"""Ground-truth check of Lemma 3 (ratio-test adjacency) and Lemma 4 (representative-only orbit state).

Specimen: the cone over the box with vertices (+-1,+-1,+-2), i.e. rows (1, x1, x2, x3) in R^4.
It has 8 rays, 6 facets, 1 ray orbit, 2 facet orbits under the 16-element stabilizer generated by
sign changes of the three coordinates and the swap of coordinates 1,2.  Ground truth: PPL.

This script does NOT run the port (the installed Sage cannot import sage_extensions); it validates the two
lemmas and the Schreier/orbit bookkeeping on data where exact ground truth is available.
"""
from itertools import product
from math import gcd

from sage.all import QQ, ZZ, matrix, vector
from sage.geometry.polyhedron.constructor import Polyhedron

ROWS = [(1, x1, x2, x3) for x1, x2, x3 in product((1, -1), repeat=3) if True]
ROWS = [(1, x1, x2, x3) for (x1, x2, x3) in [(a, b, 2 * c) for a, b, c in product((1, -1), repeat=3)]]
M = len(ROWS)
N = 4


def dot(u, y):
    return sum(QQ(u[i]) * QQ(y[i]) for i in range(N))


def primitive(values):
    values = [QQ(v) for v in values]
    den = ZZ.one()
    for value in values:
        den = den.lcm(ZZ(value.denominator()))
    scaled = [ZZ(value * den) for value in values]
    content = ZZ(0)
    for s in scaled:
        content = ZZ(gcd(int(content), int(abs(s))))
    if content == 0:
        return tuple(scaled)
    return tuple(s // content for s in scaled)


def incidence(u):
    return frozenset(i for i in range(M) if dot(u, ROWS[i]) == 0)


def rank_of(indices):
    return matrix(QQ, [ROWS[i] for i in indices]).rank()


def certify(u):
    """Lemma 1 certificate: nonnegative on all rows and tight set of rank n-1."""
    values = [dot(u, ROWS[i]) for i in range(M)]
    assert all(v >= 0 for v in values), ("not nonnegative", u, values)
    tight = incidence(u)
    assert rank_of(tight) == N - 1, ("tight rank", u, rank_of(tight))
    return tight


# ---------------------------------------------------------------- ground truth
cone = Polyhedron(rays=ROWS, backend="ppl")
facets = []
for ineq in cone.inequalities():
    assert QQ(ineq.b()) == 0, "a cone facet inequality must be homogeneous"
    u = primitive([QQ(a) for a in ineq.A()])
    if dot(u, ROWS[0]) < 0:
        u = tuple(-a for a in u)
    if incidence(u) in facets:
        continue
    facets.append(certify(u))
print("ground truth: rays", cone.n_rays(), "facets", cone.n_facets(), "distinct incidences", len(facets),
      "incidence sizes", sorted(len(f) for f in facets))

# ---------------------------------------------------------------- stabilizer
def swap12(row):
    return (row[0], row[2], row[1], row[3])


def flip(k):
    def act(row):
        out = list(row)
        out[1 + k] = -out[1 + k]
        return tuple(out)
    return act


GENERATORS = [swap12] + [flip(k) for k in range(3)]
positions = {row: i for i, row in enumerate(ROWS)}
assert len(positions) == M
PERMS = []
for g in GENERATORS:
    perm = tuple(positions[g(row)] for row in ROWS)
    assert sorted(perm) == list(range(M))
    PERMS.append(perm)
def closure_size():
    identity = tuple(range(M))
    seen = {identity}
    frontier = [identity]
    while frontier:
        perm = frontier.pop()
        for gen in PERMS:
            composed = tuple(gen[perm[i]] for i in range(M))
            if composed not in seen:
                seen.add(composed)
                frontier.append(composed)
    return len(seen)


print("generators", len(PERMS), "closure order", closure_size())


def permute_incidence(mask, perm):
    return frozenset(perm[i] for i in mask)


# ---------------------------------------------------------------- Lemma 3
def nullspace_basis(rows):
    # vectors v with row * v = 0 for every row: the right kernel of the row matrix
    return matrix(QQ, rows).right_kernel_matrix()


def proportional(a, b):
    ratios = set()
    for x, y in zip(a, b):
        if x == 0 and y == 0:
            continue
        if x == 0 or y == 0:
            return False
        ratios.add(QQ(x) / QQ(y))
    return len(ratios) <= 1


def ratio_test(u, ridge_incidence):
    """Lemma 3: the unique other facet normal through this ridge, or None if no second facet exists.

    The normal cone of C along R is  S = {alpha u + beta w : alpha p_y + beta q_y >= 0 for all rows y},
    with p_y = u.y >= 0 and q_y = w.y.  In the chart alpha = 1 the feasible s = beta/alpha form the
    interval [s_lo, s_hi] (endpoints possibly infinite); its two endpoints are the two extreme rays.
    """
    basis = nullspace_basis([ROWS[i] for i in ridge_incidence]).rows()
    assert len(basis) == 2, ("ridge nullspace not 2-dim", len(basis))
    w = None
    for candidate in basis:
        primitive_candidate = primitive([QQ(x) for x in candidate])
        if not proportional(primitive_candidate, u):
            w = primitive_candidate
            break
    assert w is not None, "no second generator"
    s_lo = None   # max of -(p_y)/(q_y) over q_y > 0, else -infinity
    s_hi = None   # min of -(p_y)/(q_y) over q_y < 0, else +infinity
    for y in range(M):
        if y in ridge_incidence:
            continue
        qy, py = QQ(dot(w, ROWS[y])), QQ(dot(u, ROWS[y]))
        if qy > 0:
            bound = -py / qy
            s_lo = bound if s_lo is None or bound > s_lo else s_lo
        elif qy < 0:
            bound = -py / qy
            s_hi = bound if s_hi is None or bound < s_hi else s_hi
    assert s_lo is None or s_lo <= 0, ("u is not supporting", s_lo)
    assert s_hi is None or s_hi >= 0, ("u is not supporting", s_hi)
    if s_hi is None:                      # second extreme ray is w itself
        assert s_lo == 0, ("u would not be extreme in the normal cone", s_lo, s_hi)
        return primitive([QQ(x) for x in w]), None, (s_lo, s_hi)
    if s_lo is None:                      # second extreme ray is -w
        assert s_hi == 0, ("u would not be extreme in the normal cone", s_lo, s_hi)
        return primitive([-QQ(x) for x in w]), None, (s_lo, s_hi)
    nonzero = [s for s in (s_lo, s_hi) if s != 0]
    if len(nonzero) != 1:
        return None, s_lo, s_hi        # normal cone is a single ray: no second facet
    s_star = nonzero[0]
    u_prime = primitive([QQ(u[i]) + s_star * QQ(w[i]) for i in range(N)])
    return u_prime, s_star, (s_lo, s_hi)


# ridge computation for a facet: the facets of the facet's own sub-cone
def ridges_of(facet_incidence):
    sub = Polyhedron(rays=[ROWS[i] for i in facet_incidence], backend="ppl")
    out = set()
    for ineq in sub.inequalities():
        if QQ(ineq.b()) != 0:
            continue
        v = primitive([QQ(a) for a in ineq.A()])
        zero = frozenset(i for i in facet_incidence if dot(v, ROWS[i]) == 0)
        if zero and rank_of(zero) == N - 2 and zero != facet_incidence:
            out.add(zero)
    return sorted(out, key=lambda s: (len(s), sorted(s)))


# ---------------------------------------------------------------- orbit machinery (Lemma 4)
SEEN = []
EMITTED = []


def orbit_bfs(start):
    """Generator BFS with Schreier words; mirrors _iter_facet_mask_orbits' word construction."""
    orbit = [(start, None)]
    index = 0
    while index < len(orbit):
        key, word = orbit[index]
        index += 1
        for gi, perm in enumerate(PERMS):
            image = permute_incidence(key, perm)
            if any(image == other for other, _ in orbit):
                continue
            orbit.append((image, (word, gi)))
    return orbit


def orbit_meets_seen(orbit):
    return any(member in SEEN for member, _ in orbit)


def word_indices(word):
    out = []
    while word is not None:
        word, gi = word
        out.append(gi)
    return list(reversed(out))


def apply_word(start, word):
    mask = start
    for gi in word_indices(word):
        mask = permute_incidence(mask, PERMS[gi])
    return mask


# ---------------------------------------------------------------- the enumeration
def normal_of(facet_incidence):
    basis = nullspace_basis([ROWS[i] for i in facet_incidence]).rows()
    assert len(basis) == 1, len(basis)
    u = primitive([QQ(x) for x in basis[0]])
    if dot(u, ROWS[0]) < 0:
        u = tuple(-a for a in u)
    return u


seed = facets[0]
seed_normal = normal_of(seed)
assert certify(seed_normal) == seed

pending = [seed]
QUEUED = []
adjacency_records = []
while pending:
    key = pending.pop(0)
    assert key not in SEEN
    orbit = orbit_bfs(key)
    canonical = min(orbit, key=lambda entry: (0, tuple(sorted(entry[0]))))
    assert canonical[0] == key
    SEEN.append(key)
    EMITTED.append(orbit)
    u = normal_of(key)
    for ridge in ridges_of(key):
        u_prime, s_star, bounds = ratio_test(u, ridge)
        if u_prime is None:
            adjacency_records.append((key, ridge, None))
            continue
        tight = certify(u_prime)
        assert ridge <= tight, ("ridge not inside the new facet", ridge, tight)
        assert tight != key
        assert tight in facets, ("ratio test produced a non-facet", u_prime, tight)
        assert key & tight == ridge, ("intersection is not the ridge", key & tight, ridge)
        adjacency_records.append((key, ridge, tight))
        partner_orbit = orbit_bfs(tight)
        partner_canonical = min(partner_orbit, key=lambda entry: (0, tuple(sorted(entry[0]))))[0]
        if partner_canonical in SEEN or partner_canonical in QUEUED:
            continue
        QUEUED.append(partner_canonical)
        pending.append(partner_canonical)

print("enumerated facet orbits:", len(EMITTED))
print("orbit sizes:", [len(o) for o in EMITTED])
covered = set()
for orbit in EMITTED:
    for member, _ in orbit:
        assert member not in covered
        covered.add(member)
assert covered == set(facets), (sorted(covered), sorted(facets))
print("coverage: every one of the", len(facets), "facets in exactly one orbit")

# word correctness: each member's word composes to the recorded permutation
for orbit in EMITTED:
    start = orbit[0][0]
    for member, word in orbit:
        assert apply_word(start, word) == member, (sorted(member), sorted(apply_word(start, word)))
print("Schreier words reproduce every member:", sum(len(o) for o in EMITTED), "members")

# adjacency: every ridge of every facet has exactly 2 facets, both enumerated
ridges_ok = 0
for facet in facets:
    u = normal_of(facet)
    for ridge in ridges_of(facet):
        u_prime, s_star, bounds = ratio_test(u, ridge)
        if u_prime is None:
            continue
        partner = certify(u_prime)
        assert facet & partner == ridge
        assert partner in facets
        ridges_ok += 1
print("adjacency witnesses verified:", ridges_ok, "of", sum(len(ridges_of(f)) for f in facets))

# Lemma A: affine/homogeneous dictionary
augmented = matrix(QQ, [[1, *row] for row in ROWS])
base = augmented.right_kernel_matrix().rows()
assert len(base) == 1
alpha, h = QQ(base[0][0]), tuple(QQ(x) for x in base[0][1:])
c0 = -alpha
assert all(dot(h, ROWS[i]) == c0 for i in range(M))
for facet in facets:
    sel = matrix(QQ, [[1, *ROWS[i]] for i in facet])
    fbase = sel.right_kernel_matrix().rows()
    assert len(fbase) == 1
    beta, w = QQ(fbase[0][0]), tuple(QQ(x) for x in fbase[0][1:])
    u = tuple(w[k] - (beta / alpha) * h[k] for k in range(N))
    got = primitive(u)
    reference = normal_of(facet)
    assert proportional(got, reference), (got, reference)
print("Lemma A dictionary verified on all", len(facets), "facets")
