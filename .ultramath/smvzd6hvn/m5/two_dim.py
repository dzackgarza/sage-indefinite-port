"""Two-dimensional reduction primitives: the pivot across a ridge and the facet descent.

Both are instances of one exact operation.  Given a two-dimensional subspace W of the dual
space and the images q_r = (w_1.r, w_2.r) of every ray under a basis (w_1, w_2) of W, the
supporting covectors of cone(rows) inside W are the polar of the two-dimensional cone
cone{q_r}; the *extreme* ones are the polar of its two extreme rays.  Everything here is exact
rational arithmetic, and `_extremes_2d` returns the two extreme rays of a generated
two-dimensional cone given a candidate set that is guaranteed to contain them.
"""
from __future__ import annotations

from fractions import Fraction


def _parallel_same_direction(u, v) -> bool:
    cross = u[0] * v[1] - u[1] * v[0]
    return cross == 0 and (u[0] * v[0] + u[1] * v[1]) > 0


def _in_cone_2d(c, u, v) -> bool:
    """Whether c lies in the closed cone generated by u and v, exactly."""
    determinant = u[0] * v[1] - u[1] * v[0]
    if determinant == 0:
        # u and v are parallel or antiparallel: the cone is a ray, a half-line or a line.
        if _parallel_same_direction(c, u) or _parallel_same_direction(c, v):
            return True
        if _parallel_same_direction(u, v):
            return False
        # antiparallel pair: the cone is the whole line through u
        return u[0] * c[1] - u[1] * c[0] == 0
    first = Fraction(c[0] * v[1] - c[1] * v[0], determinant)
    second = Fraction(u[0] * c[1] - u[1] * c[0], determinant)
    return first >= 0 and second >= 0


def extremes_2d(candidates):
    """The extreme rays of cone(candidates) for a pointed two-dimensional candidate set.

    Every extreme ray of a two-dimensional pointed cone is generated by one of its generators, so
    testing each candidate against the cone of the others is exact and complete.
    """
    unique = []
    for candidate in candidates:
        if candidate[0] == 0 and candidate[1] == 0:
            continue
        if not any(_parallel_same_direction(candidate, other) for other in unique):
            unique.append(candidate)
    if not unique:
        raise ArithmeticError("the two-dimensional reduction has no nonzero generator")
    extremes = []
    for candidate in unique:
        others = [other for other in unique if not _parallel_same_direction(other, candidate)]
        if len(others) < 2:
            extremes.append(candidate)
            continue
        contained = any(
            _in_cone_2d(candidate, others[i], others[j])
            for i in range(len(others))
            for j in range(i + 1, len(others))
        )
        if not contained:
            extremes.append(candidate)
    if len(extremes) != 2:
        raise ArithmeticError(
            f"a pointed two-dimensional cone must have exactly two extreme rays, found {len(extremes)}"
        )
    return extremes
