"""The Li–Margulis finite box must return actual owned isometries."""

from sage_extensions.all import Lattices, ZZ

from sage_indefinite_port.indefinite.li_margulis import (
    _vectors_in_box,
    isometries_in_box,
    is_isometric_in_box,
    primitive_tuples_in_box,
)


def test_theorem_one_determinant_factor_matches_primary_published_formula():
    r"""Exact Theorem 1(3) oracle, not an expectation inferred from the port.

    ORACLE-FILE: references/oracles/li_margulis_theorem_bounds.md
    ORACLE-LOCATOR: Li–Margulis 2016, Theorem 1 equation (3), printed p.2
    ORACLE-EXCERPT: Equation (3) prints the determinant factor with no leading minus before its exponent.
    ORACLE-HYPOTHESES: n=3, A=B=diag(2,-2,6), symmetric nonsingular integral forms with identity equivalence
    ORACLE-EXPECTED: Unit-constant strict upper bound is 24^3 times 6^22 plus one
    ORACLE-DERIVATION: Positive determinant exponent 8/3 rounds to 3, the A and B exponents 41/4 and 43/4 round to 11 each, determinant is 24 and coefficient norm 6; C3=1 tests the algebra, not a claimed published constant
    """
    from sage.matrix.constructor import matrix
    from sage.rings.integer_ring import ZZ as SageZZ
    from sage_indefinite_port.indefinite.li_margulis import isometry_box_bound

    gram = matrix(SageZZ, [[2, 0, 0], [0, -2, 0], [0, 0, 6]])
    assert abs(gram.det()) == 24
    assert isometry_box_bound(gram, gram, 1) == 24**3 * 6**22 + 1


def test_primitive_embedding_completion_uses_primary_theorem_determinant_factor():
    r"""Complete a primitive embedding using the independent source-bound oracle.

    ORACLE-FILE: references/oracles/li_margulis_theorem_bounds.md
    ORACLE-LOCATOR: Li–Margulis 2016, Lemma 20 equation (31) p.18 and Theorem 1 equation (3) p.2
    ORACLE-EXCERPT: a unimodular completion exists with Gram norm
    ORACLE-HYPOTHESES: n=3 and m=1, primitive vector with Gram A=[2] in B=diag(2,-2,6); constant placeholders are one to isolate exponent arithmetic
    ORACLE-EXPECTED: Completion bound is 24^3 times (4 times 24 plus 2)^11 times 6^11 plus one
    ORACLE-DERIVATION: Lemma 20 bounds the completed Gram by 4 times 24 plus 2; Theorem 1(3) has positive determinant exponent 8/3 rounded to 3 and the A,B exponents round to 11
    """
    from sage.matrix.constructor import matrix
    from sage.rings.integer_ring import ZZ as SageZZ
    from sage_indefinite_port.indefinite.li_margulis import (
        LiMargulisConstants, embedding_orbit_bound, theorem_one_constant,
    )

    gram = matrix(SageZZ, [[2, 0, 0], [0, -2, 0], [0, 0, 6]])
    embedded = matrix(SageZZ, [[2]])
    constants = LiMargulisConstants(3, *(1 for _ in range(7)))
    completed_norm_bound = 2**2 * abs(gram.det()) + 2
    expected = theorem_one_constant(constants) * 24**3 * completed_norm_bound**11 * 6**11 + 1
    assert embedding_orbit_bound(gram, embedded, constants) == expected


def test_theorem_two_exponent_dominates_verified_theorem_one_determinant_factor():
    r"""Theorem 2's n^6 exponent dominates the *positive* Theorem 1(3) factor.

    ORACLE-FILE: references/oracles/li_margulis_theorem_bounds.md
    ORACLE-LOCATOR: Li–Margulis 2016, Theorem 1(3) printed p.2 and Theorem 2 printed p.3
    ORACLE-EXCERPT: orthogonal group is generated by matrices of size strictly less than
    ORACLE-HYPOTHESES: n is any integer at least three, source forms nonsingular integral, with exact rational exponent comparisons
    ORACLE-EXPECTED: For n>=3, the determinant exponent n times d plus n times (n+1)b is at most n^6
    ORACLE-DERIVATION: d=(13n^3-39n^2+36n+52)/(20n) and b=(13n^3-13n^2+72n-20)/40; the source proof gives a positive polynomial difference 40n^6-13n^5-85n^3+26n^2-52n-104 for n>=3
    """
    from sage.rings.rational_field import QQ as SageQQ

    for n in (3, 4, 5, 6):
        d = SageQQ(13*n**3 - 39*n**2 + 36*n + 52) / (20*n)
        b = SageQQ(13*n**3 - 13*n**2 + 72*n - 20) / 40
        exponent = n * (d + (n + 1)*b)
        assert d > 0 and exponent > n*(n+1)*b
        assert exponent <= n**6


def test_bounded_search_returns_owned_orthogonal_and_isom_arrows():
    r"""A checked Gram identity is not a substitute for the O(L)/Isom parent."""
    source = Lattices(ZZ)("U")
    target = Lattices(ZZ)([[0, 1], [1, 0]])
    found = tuple(isometries_in_box(source, 1))
    assert len(found) == 4
    assert all(g.parent() is source.O() for g in found)
    assert all(g.domain() is source and g.codomain() is source for g in found)
    witness = is_isometric_in_box(source, target, 1)
    assert witness is not None
    assert witness.parent() is source.Isom(target)
    assert witness.domain() is source and witness.codomain() is target


def test_theorem_bounds_allow_unbounded_integer_magnitude_without_materializing_box():
    r"""An arbitrary-precision finite bound must not be converted to a C-sized product pool.

    The Li–Margulis theorem gives numerically finite but enormous upper
    bounds. A finite algorithm is not executable if range/product overflows
    or if it must construct the whole box before emitting its first witness.
    """
    from itertools import islice

    ambient = Lattices(ZZ)("U")
    bound = ZZ(2)**100
    prefix = tuple(islice(_vectors_in_box(ambient, bound), 6))
    assert len(prefix) == 6 and prefix[0] == ambient.zero()
    assert len({tuple(v) for v in prefix}) == 6

    complete_small_box = tuple(_vectors_in_box(ambient, 2))
    assert len(complete_small_box) == 25
    assert {tuple(v) for v in complete_small_box} == {
        (a, b) for a in range(-2, 3) for b in range(-2, 3)
    }

    first_null = next(primitive_tuples_in_box(ambient, ((0,),), bound))
    assert len(first_null) == 1
    assert first_null[0].q() == 0 and first_null[0].content() == 1
    assert len(tuple(primitive_tuples_in_box(ambient, ((0,),), 2))) == 4

    ternary = Lattices(ZZ)([[1, 0, 0], [0, 1, 0], [0, 0, -1]])
    ternary_box = tuple(_vectors_in_box(ternary, 1))
    assert len(ternary_box) == 27
    assert len({tuple(v) for v in ternary_box}) == 27
