"""`_gram_in_label_order` is memoized per lattice, and the memo returns the same, correct matrix.

One call on the rank-22 K3 rational envelope costs 25 s (the rational branch converts every pairing's
numerator and denominator), and `_isometry_from_row_matrix` asks for the Gram on every generator it builds —
twice, source and target — for a group generated by 136 approximate generators. Without the memo that is about
6 800 s of recomputing identical matrices, which is why the A_VECTORS K3 nodes could not finish inside their cap.
"""
from sage.all import ZZ, matrix

from sage_indefinite_port.indefinite.groupoid_cache import _gram_in_label_order
from tests.acceptance.consumer import lattice


def _direct_gram(lattice_):
    """The Gram in declared label order, computed without the cache."""
    labels = tuple(lattice_.module_generating_set())
    basis = tuple(lattice_.module_generator(label) for label in labels)
    return matrix(ZZ, [[int(lattice_.b(left, right)) for right in basis] for left in basis])


def test_gram_in_label_order_is_memoized_and_correct() -> None:
    lattice_ = lattice([[2, 1], [1, 2]])

    first = _gram_in_label_order(lattice_)
    second = _gram_in_label_order(lattice_)

    assert first is second, "the memo must return the same matrix, not recompute it"
    assert first == _direct_gram(lattice_), "the memo must not change the value"


def test_memo_is_per_lattice_not_per_gram() -> None:
    """Two lattices with equal Gram matrices each get their own correct entry."""
    left = lattice([[2, 0], [0, 0]])
    right = lattice([[2, 0], [0, 0]])

    assert _gram_in_label_order(left) == _direct_gram(left)
    assert _gram_in_label_order(right) == _direct_gram(right)
    assert _gram_in_label_order(left) == _gram_in_label_order(right)
    # Different label orders must not be conflated: the cache is keyed per lattice object.
    permuted = lattice([[0, 0], [0, 2]])
    assert _gram_in_label_order(permuted) == _direct_gram(permuted) == matrix(ZZ, [[0, 0], [0, 2]])
