"""Index and stabilizer data of Dawes arXiv:2205.10601 section 5 for L = U ⊕ U + <-2> + <-6> (#18).

Source: references/vendor/arxiv/2205.10601/orbits_in_lattices.tex:1366-1444.

- :1395 (citing Dawes's Lemma 2.4): O^+(L) = <stable O^+(L), sigma_w>, w the generator
  of <-6>. The stable group is the kernel of O^+(L) -> O(q_L), so the image of O^+(L)
  in O(q_L) is generated by the image of sigma_w.
- :1396-1401 and Figure gkbuilding: O^+(L) and the stable group have the same two points
  and two curves. Hence for each such line or plane I, O^+(L) = stable * Stab_{O^+}(I),
  and Stab_{O^+}(I) has the full image of O^+(L) in O(q_L).

Hand calculation of O(q_L), in the fixture order e1, f1, e2, f2, v, w (v^2 = -2,
w^2 = -6): D(L) = Z/2 + Z/6 with q(a, b) = -a^2/2 - b^2/6 mod 2. The three elements
of order 2, (1, 0), (0, 3), (1, 3), have the distinct values 3/2, 1/2, 0, so an
isometry fixes them all; on the 3-part Z/3 the isometries are +-1. So |O(q_L)| = 2,
and sigma_w acts as -1 on the 3-part. The lines and planes are those of
references/dawes-L2-boundary.md: Ze1, Zl with l = 2e2 + 2f2 + v + w, E1 = <e1, e2>,
E2 = <e1, l>.
"""

from tests.acceptance.consumer import basis, discriminant_image_order, isometry_from_rows, lattice
from tests.fixtures.oracle_fixtures import load_dawes_buildings


def _lattice():
    (case,) = (case for case in load_dawes_buildings()["buildings"] if case["id"] == "dawes_2U_minus2_minus6")
    return lattice(case["gram"])


def _sigma_w(lattice_):
    rows = [[1 if j == i else 0 for j in range(6)] for i in range(6)]
    rows[5][5] = -1
    return isometry_from_rows(lattice_, rows)


def test_discriminant_orthogonal_group_has_order_two():
    lattice_ = _lattice()

    assert int(lattice_.discriminant_group().orthogonal_group().cardinality()) == 2


def test_stable_group_has_index_two_in_o_plus_generated_by_sigma_w():
    lattice_ = _lattice()

    assert discriminant_image_order(lattice_, [_sigma_w(lattice_)]) == 2
    assert discriminant_image_order(lattice_, lattice_.O_plus().group_generators()) == 2


def test_line_and_plane_stabilizers_surject_onto_the_discriminant_image():
    lattice_ = _lattice()
    e1, f1, e2, f2, v, w = basis(lattice_)
    null = e2 + e2 + f2 + f2 + v + w
    assert null.q() == 0 and int(null.div()) == 2
    target = lattice_.discriminant_group().orthogonal_group()

    for vectors in ((e1,), (null,), (e1, e2), (e1, null)):
        sublattice = lattice_.subobject_on(list(vectors))
        stabilizer = lattice_.O_plus().stabilizer(sublattice, action="setwise")
        image = target.subgroup_on(tuple(generator.discriminant_morphism() for generator in stabilizer.group_generators()))
        assert int(image.cardinality()) == 2, vectors
