"""Exact arithmetic-preimage oracles, independent of the Sage port.

The finite-group calculation for these tests is elementary. For the
hyperbolic plane U with Gram [[0,1],[1,0]], AUA^t=U is equivalent to
ac=bd=0, ad+bc=1 for A=[[a,b],[c,d]]. Thus O(U) consists *exactly*
of I,-I,S,-S, where S exchanges the coordinates. In particular, there
are no other integral maps potentially transporting the markings below.

For the positive-definite lattice I_3, every orthogonal integral matrix
is a signed permutation: an integral column of norm one is necessarily
one of the six signed coordinate vectors, and different columns must be
perpendicular. The coordinate permutations form G=S_3, generated by
a=(12) and b=(23), and reduction modulo 3 is injective on G. For
H=<a>, |H|=2, [G:H]=3, H is nonnormal, and H\\G/H has precisely two
double cosets, H (size 2) and HbH (size 4). Consequently the two
intersections H cap xHx^-1 have orders 2 and 1, respectively, and
their preimages in the six-element integral ambient group have indices
3 and 6. These facts follow from the three-letter permutation action,
not from any implementation output.

The identical U and S_3 arguments are recorded in the previously pinned
independent proof references/oracles/hyperbolic_plane_residue_modules.md,
paragraphs "For simultaneous different-level transport", "For full-rank
sublattices" and "For the positive definite standard rank-three lattice".
This module independently rederives the expected claims above instead of
reusing the expectations in the retired regression tests.
"""

from itertools import permutations

from sage.all import ZZ, matrix

from sage_indefinite_port.indefinite.recursive import EichlerRecursion
from tests.acceptance.consumer import isometry_from_rows, lattice


def _identity_three():
    return matrix(ZZ, 3, 3, 1)


def _coordinate_permutation(rows):
    return matrix(ZZ, rows)


def _standard_permutation_ambient():
    ambient = lattice(((1, 0, 0), (0, 1, 0), (0, 0, 1)))
    swap_first = _coordinate_permutation(((0, 1, 0), (1, 0, 0), (0, 0, 1)))
    swap_second = _coordinate_permutation(((1, 0, 0), (0, 0, 1), (0, 1, 0)))
    a = isometry_from_rows(ambient, swap_first)
    b = isometry_from_rows(ambient, swap_second)
    return ambient, (a, b), swap_first


def test_nonnormal_s3_arithmetic_preimage_has_exact_integral_membership():
    """Coordinate S_3, mod 3: H=<swap(1,2)> has index three."""
    ambient, generators, a = _standard_permutation_ambient()
    engine = EichlerRecursion()
    finite = engine.congruence_image(ambient, 3, ambient_generators=generators)
    assert len(finite.image_keys()) == 6
    selected = (finite.image_one, finite.reduce(a))
    group = engine.congruence_preimage_subgroup(
        ambient, 3, selected, ambient_generators=generators
    )
    assert int(group.index()) == 3

    # All six coordinate permutations are distinct integral isometries.
    # Exactly the identity and (12) belong to the inverse image of H.
    expected = {tuple(_identity_three().list()), tuple(a.list())}
    seen = set()
    for p in permutations(range(3)):
        rows = [[int(p[i] == j) for j in range(3)] for i in range(3)]
        candidate = matrix(ZZ, rows)
        seen.add(tuple(candidate.list()))
        owned = isometry_from_rows(ambient, candidate)
        assert (owned in group) == (tuple(candidate.list()) in expected)
    assert len(seen) == 6

    # The full signed-permutation group also contains this reflection,
    # but the specified *ambient* subgroup G=S_3 does not.
    sign_change = isometry_from_rows(
        ambient, ((-1, 0, 0), (0, 1, 0), (0, 0, 1))
    )
    assert sign_change not in group


def test_nonnormal_s3_has_two_exact_integral_double_cosets():
    """H\\S3/H = {H,H(23)H}; intersections have orders 2 and 1."""
    ambient, generators, a = _standard_permutation_ambient()
    engine = EichlerRecursion()
    finite = engine.congruence_image(ambient, 3, ambient_generators=generators)
    H = (finite.image_one, finite.reduce(a))
    representatives = engine.congruence_double_coset_representatives(
        ambient, 3, H, H, ambient_generators=generators
    )
    assert len(representatives) == 2
    assert all(witness.domain() is ambient and witness.codomain() is ambient
               for _, witness in representatives)
    assert all(finite.contains(residue) for residue, _ in representatives)
    intersections = engine.congruence_double_coset_stabilizers(
        ambient, 3, H, H, ambient_generators=generators
    )
    assert len(intersections) == 2
    assert sorted(int(index) for _, index, _ in intersections) == [3, 6]
    assert all(witness.domain() is ambient and witness.codomain() is ambient
               and all(g.domain() is ambient and g.codomain() is ambient
                       for g in stabilizer_generators)
               for witness, _, stabilizer_generators in intersections)


def test_two_level_u_residue_transport_detects_incompatible_constraints():
    """No element of {I,-I,S,-S} swaps e mod 2 while fixing e mod 4."""
    plane = lattice(((0, 1), (1, 0)))
    engine = EichlerRecursion()
    source = {"vectors": ((1, 0),)}
    exchanged = {"vectors": ((0, 1),)}
    unchanged = {"vectors": ((1, 0),)}
    positive = engine.multilevel_congruence_transporter(
        plane, ((2, source, exchanged), (4, source, exchanged))
    )
    assert positive is not None
    assert positive.domain() is plane and positive.codomain() is plane
    assert tuple(int(c) % 4 for c in positive(plane.module_generators()[0])) == (0, 1)
    assert engine.multilevel_congruence_transporter(
        plane, ((2, source, exchanged), (4, source, unchanged))
    ) is None


def test_full_rank_index_eight_u_sublattices_have_exact_negative_transporter():
    r"""The diagonal congruence lattice P is fixed by O(U), unlike M/N.

    Set M=2Ze+4Zf, N=4Ze+2Zf and P=<2e+2f,4f>. All three have
    index eight and contain 4U. The swap S exchanges M and N. But
    P={(x,y): x,y even, x=y (mod 4)} is fixed by all four members of
    O(U), while 2e belongs to M and not P; hence no transporter P->M.
    """
    plane = lattice(((0, 1), (1, 0)))
    e, f = plane.module_generators()
    engine = EichlerRecursion()
    M = matrix(ZZ, ((2, 0), (0, 4)))
    N = matrix(ZZ, ((4, 0), (0, 2)))
    P = matrix(ZZ, ((2, 2), (0, 4)))
    assert abs(M.det()) == abs(N.det()) == abs(P.det()) == 8
    witness = engine.finite_index_sublattice_transporter(plane, 4, M, N)
    assert witness is not None
    images = matrix(ZZ, (witness(2 * e), witness(4 * f)))
    assert images.hermite_form() == N.hermite_form()
    assert engine.finite_index_sublattice_transporter(plane, 4, P, M) is None
