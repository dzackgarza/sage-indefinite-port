"""Independent finite-image residue stabilizer oracles for O(U)."""

from sage.all import ZZ, matrix
from sage_extensions.all import Lattices, ZZ as OwnedZZ

from sage_indefinite_port.indefinite.recursive import EichlerRecursion


def _column_matrix(g, frame):
    return matrix(ZZ, [[int(c) for c in g(v)] for v in frame]).transpose()


def test_mod_three_vector_stabilizer_in_full_hyperbolic_group():
    # Solving ac=bd=0 and ad+bc=1 gives O(U)={I,-I,S,-S}.
    # Modulo three these four matrices remain distinct. Since -e != e
    # modulo three, only I fixes e=(1,0), so the actual-image stabilizer
    # has index four.
    lattice = Lattices(OwnedZZ)([[0, 1], [1, 0]])
    e, f = lattice.module_generators()
    recursion = EichlerRecursion()
    image = recursion.congruence_image(lattice, 3)
    assert len(image.image_keys()) == 4
    index, generators = recursion.congruence_stabilizer_generators(
        lattice, 3, (1, 0)
    )
    assert index == 4
    for g in generators:
        reduced = _column_matrix(g, (e, f)).change_ring(image.ring)
        assert reduced * matrix(image.ring, [[1], [0]]) == matrix(image.ring, [[1], [0]])


def test_mod_three_residue_vector_transporter_and_negative_decision():
    # The exchange carries e to f. No element of O(U) carries e to e+f:
    # its four possible images are ±e and ±f.
    lattice = Lattices(OwnedZZ)([[0, 1], [1, 0]])
    recursion = EichlerRecursion()
    witness = recursion.congruence_vector_transporter(lattice, 3, (1, 0), (0, 1))
    assert witness is not None
    assert tuple(int(c) % 3 for c in witness(lattice.module_generators()[0])) == (0, 1)
    assert recursion.congruence_vector_transporter(lattice, 3, (1, 0), (1, 1)) is None


def test_composite_modulus_submodule_stabilizer_is_not_vector_stabilizer():
    # In Z/4, the line generated by e is preserved by I and -I, whereas
    # the vector e itself is fixed only by I. The exact setwise subgroup
    # therefore has index two in the four-element actual O(U) image.
    lattice = Lattices(OwnedZZ)([[0, 1], [1, 0]])
    recursion = EichlerRecursion()
    image = recursion.congruence_image(lattice, 4)
    assert len(image.image_keys()) == 4
    index, generators = recursion.congruence_submodule_stabilizer_generators(
        lattice, 4, ((1, 0),)
    )
    assert index == 2
    for g in generators:
        moved = _column_matrix(g, lattice.module_generators()).change_ring(image.ring)
        image_e = moved * matrix(image.ring, [[1], [0]])
        assert image_e[1, 0] == 0


def test_composite_modulus_submodule_transporters_are_exact():
    # The swap exchanges the rank-one coordinate summands of (Z/4)^2.
    # No integral isometry can carry <e> to <e+f>: the complete O(U)
    # consists of signed diagonal and signed exchange matrices, so all
    # possible images of e lie on a coordinate axis.
    lattice = Lattices(OwnedZZ)([[0, 1], [1, 0]])
    recursion = EichlerRecursion()
    witness = recursion.congruence_submodule_transporter(
        lattice, 4, ((1, 0),), ((0, 1),)
    )
    assert witness is not None
    e = lattice.module_generators()[0]
    assert tuple(int(c) % 4 for c in witness(e)) in ((0, 1), (0, 3))
    assert recursion.congruence_submodule_transporter(
        lattice, 4, ((1, 0),), ((1, 1),)
    ) is None


def test_nonfree_composite_level_flag_transporter():
    # In (Z/4)^2, the flag <2e> subset <e> is nonfree at its first
    # stage. The exchange maps it to <2f> subset <f>. No O(U) element
    # maps it to <2(e+f)> subset <e+f>, since all images of e are ±e,±f.
    lattice = Lattices(OwnedZZ)([[0, 1], [1, 0]])
    recursion = EichlerRecursion()
    source = (((2, 0),), ((1, 0),))
    target = (((0, 2),), ((0, 1),))
    witness = recursion.congruence_flag_transporter(lattice, 4, source, target)
    assert witness is not None
    assert tuple(int(c) % 4 for c in witness(lattice.module_generators()[0])) in ((0, 1), (0, 3))
    impossible = (((2, 2),), ((1, 1),))
    assert recursion.congruence_flag_transporter(lattice, 4, source, impossible) is None
