r"""Line-stabilizer generators of the Enriques lattice N = U + U(2) + E8(-2) (#70).

The public setwise stabilizer of each published O^+(N) line representative
must be generated by elements of O^+(N) that preserve the line, and the image of
the generated group in O(q_N) must have the published index: 1 for Z e1 (from U)
and 527 for Z e3 (from U(2)) (Dutour Sikirić--Hulek, arXiv:2302.01679).
"""
import pytest

from tests.acceptance.consumer import element, lattice, marked_sublattice, sublattice_of
from tests.fixtures.oracle_fixtures import load_unpolarized_enriques

_N = load_unpolarized_enriques()


@pytest.mark.parametrize("representative", _N["component_preserving_group"]["line_representatives"], ids=lambda rep: rep["id"])
def test_line_stabilizer_generators_generate_the_stabilizer(representative):
    n = lattice(_N["lattice"]["gram"])
    (vector,) = (element(n, coordinates) for coordinates in representative["basis"])
    line = sublattice_of(marked_sublattice(n, [vector]))
    group = n.O_plus()

    generators = tuple(group.stabilizer(line, action="setwise").group_generators())

    assert generators
    for generator in generators:
        assert generator in group
        assert generator(vector) in (vector, -vector)
    target = n.discriminant_group().orthogonal_group()
    image = target.subgroup_on(tuple(generator.discriminant_morphism() for generator in generators))
    assert int(target.cardinality()) // int(image.cardinality()) == representative["discriminant_stabilizer_index"]
