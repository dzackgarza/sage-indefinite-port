"""Exact elementary GL_2(Z) oracles for the zero rank-two lattice.

Independent proof: For L=(Z^2,0), every unimodular integral matrix
preserves the zero bilinear form, and every lattice automorphism is
unimodular. Hence O(L)=GL_2(Z). The Euclidean algorithm produces a
unimodular matrix taking any primitive vector (a,b), gcd(a,b)=1, to
e_1. Multiplying by d gives one orbit of nonzero vectors of content d;
content is invariant under GL_2(Z), so different contents cannot mix.
The pointwise stabilizer of e_1 consists precisely of column matrices
[[1,k],[0,epsilon]], k in Z, epsilon in {1,-1}. It is generated by
the shear k=1 and the sign epsilon=-1. Finally ordered unimodular
frames are the columns of GL_2(Z), so form a single orbit.

These assertions are proved here independently of the implementation
and do not depend on any retired test's expected output.
"""

from math import gcd

from sage_extensions.all import Lattices, ZZ


def _zero_plane():
    return Lattices(ZZ)([[0, 0], [0, 0]])


def test_zero_plane_has_exactly_one_nonzero_vector_orbit_per_content():
    lattice = _zero_plane()
    e, _ = tuple(lattice.module_generators())
    group = lattice.O()
    for d in (1, 2, 3):
        representatives = tuple(group.vector_orbit_representatives(0, content=d))
        # The theorem specifies a single orbit, not which orbit member a
        # particular enumeration is obliged to choose as its representative.
        assert len(representatives) == 1
        assert gcd(*(int(c) for c in representatives[0])) == d
        transporter = group.transporter(d * e, representatives[0])
        assert transporter is not None and transporter(d * e) == representatives[0]


def test_zero_plane_transporter_preserves_content_and_reaches_primitive_vectors():
    lattice = _zero_plane()
    e, f = tuple(lattice.module_generators())
    group = lattice.O()
    for vector in (e + f, 2 * e + 3 * f, -3 * e + 2 * f):
        transporter = group.transporter(e, vector)
        assert transporter is not None
        assert transporter(e) == vector
    assert group.transporter(e, 2 * e) is None
    assert group.transporter(2 * e, 3 * e) is None


def test_zero_plane_point_stabilizer_contains_infinite_shear_and_sign():
    lattice = _zero_plane()
    e, f = tuple(lattice.module_generators())
    group = lattice.O()
    stabilizer = group.stabilizer(e)
    generators = tuple(stabilizer.group_generators())
    assert generators
    assert all(g(e) == e for g in generators)
    # An element of the stabilizer is determined by f -> k*e + eps*f.
    # Exact shear/sign membership is a group property, independently of
    # which alternative complete generating family a provider may select.
    shear = group((e, e + f))
    sign = group((e, -f))
    assert shear in stabilizer and sign in stabilizer
    assert all((shear**k)(f) == k * e + f for k in (1, 2, 3, 4))
