"""The glued lattice marks one isotropic discriminant class of U(2).

For the line generated by the first basis vector in the Gram matrix below,
K=I-perp/I is U(2). The gluing distinguishes its two primitive null lines.
The quotient action is {+1,-1}; O(U(2)) also swaps the null lines.
"""
from sage.all import GF, MatrixGroup, matrix

from sage_indefinite_port.indefinite.isotropic_induction import IsotropicInduction
from sage_indefinite_port.indefinite.recursive import EichlerRecursion
from tests.acceptance.consumer import lattice


def test_glued_line_stabilizer_has_a_proper_quotient_image():
    ambient = lattice([[0, 2, 0, 0], [2, 0, 1, 0], [0, 1, 0, 2], [0, 0, 2, 0]])
    line = ambient.module_generator(tuple(ambient.module_generating_set())[0])
    induction = IsotropicInduction(EichlerRecursion())
    reduction = induction.reduction(ambient, line)
    quotient = reduction.quotient_lattice()
    labels, lifts = induction._frame_lifts(reduction)
    perpendicular = reduction.orthogonal_complement().inclusion()
    projection = reduction.projection()
    generators = induction.line_automorphism_generators(ambient, line)
    images = [matrix(GF(3), [[int(projection(perpendicular.lift(generator(lifts[label]))).to_vector()(target)) for target in labels] for label in labels]) for generator in generators]
    full = [matrix(GF(3), [[int(generator(quotient.module_generator(label)).to_vector()(target)) for target in labels] for label in labels]) for generator in induction.recursion.orthogonal_group_generators(quotient)]
    assert MatrixGroup(images).order() == 2
    assert MatrixGroup(full).order() == 4
