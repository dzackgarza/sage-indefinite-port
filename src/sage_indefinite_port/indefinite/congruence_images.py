r"""Exact finite congruence images of generated integral matrix groups (#42).

The finite image is generated by the actual reductions, not an ambient
``GL_n(Z/m)``. Schreier lifts use right multiplication throughout.
"""

from collections import deque

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.rings.finite_rings.integer_mod_ring import Integers
from sage.rings.integer_ring import ZZ


class IntegralCongruenceImage:
    r"""Construct the actual reduction image and exact inverse images of its subgroups.

    ``generators`` are invertible integral square matrices. The image is finite
    for every integer modulus >= 2, including composite moduli.
    """

    def __init__(self, generators, modulus, rank=None):
        modulus = ZZ(modulus)
        if modulus < 2:
            raise ValueError("congruence modulus must be at least two")
        self.modulus = modulus
        self.generators = tuple(matrix(ZZ, g) for g in generators)
        rank = ZZ(rank) if rank is not None else (self.generators[0].nrows() if self.generators else None)
        if rank is None or rank < 0:
            raise ValueError("rank is required for an empty generating family")
        self.rank = int(rank)
        for g in self.generators:
            if g.dimensions() != (rank, rank) or g.det() not in (1, -1):
                raise ValueError("generators must be integral unimodular square matrices")
        self.one = identity_matrix(ZZ, rank)
        self.ring = Integers(modulus)
        self.image_one = identity_matrix(self.ring, rank)
        self.image_generators = tuple(g.change_ring(self.ring) for g in self.generators)
        identity_key = self._key(self.image_one)
        self._lifts = {identity_key: self.one}
        self._words = {identity_key: ()}
        queue = deque([self.image_one])
        while queue:
            current = queue.popleft()
            current_key = self._key(current)
            lift = self._lifts[current_key]
            word = self._words[current_key]
            for position, (g, image) in enumerate(zip(self.generators, self.image_generators)):

                moved = current * image
                key = self._key(moved)
                if key not in self._lifts:
                    self._lifts[key] = lift * g
                    self._words[key] = word + (position,)
                    queue.append(moved)

    @staticmethod
    def _key(g):
        return tuple(int(x) for x in g.list())

    def reduce(self, g):
        return matrix(ZZ, g).change_ring(self.ring)

    def image_keys(self):
        return frozenset(self._lifts)

    def lift(self, image):
        return self._lifts[self._key(image)]

    def contains(self, image):
        """Whether ``image`` belongs to the actual finite reduction image."""
        return self._key(image) in self._lifts

    def section_word(self, image):
        """Generator-index word lifting an element of the actual image."""
        return self._words[self._key(image)]

    def section(self, image):
        """A chosen integral lift of an element of the actual image."""
        return self.lift(image)

    def inclusion(self, other):
        r"""Whether this finite image embeds in ``other`` at the *same level*.

        Reduction images at distinct moduli are not subgroups of a common
        matrix group. In particular, reducing representatives modulo the
        wrong modulus can falsely certify containment. Compare images of
        generators only after checking that both act on the same module.
        """
        if not isinstance(other, IntegralCongruenceImage):
            raise TypeError("finite-image inclusion requires another congruence image")
        if self.modulus != other.modulus or self.rank != other.rank:
            raise ValueError("finite-image inclusion requires identical modulus and rank")
        return all(other.contains(g) for g in self.image_generators)

    def project_to_level(self, divisor):
        r"""Actual image at a quotient level, with its exact reduction map.

        For ``d | m`` the canonical reduction ``Z/m -> Z/d`` induces a
        surjection from the generated image at level m to its image at
        level d. Return that image and a function on level-m image matrices.
        """
        divisor = ZZ(divisor)
        if divisor < 2 or self.modulus % divisor:
            raise ValueError("target level must be a divisor >= 2 of the source level")
        target = IntegralCongruenceImage(self.generators, divisor, rank=self.rank)

        def projection(g):
            if not self.contains(g):
                raise ValueError("matrix is outside the actual source image")
            reduced = matrix(target.ring, g)
            if not target.contains(reduced):
                raise ArithmeticError("image reduction failed to land in the actual quotient")
            return reduced

        assert {target._key(projection(self.reduce(lift))) for lift in self._lifts.values()} == target.image_keys()
        return target, projection

    def relative_level_kernel(self, divisor):
        r"""Generators of ``ker(G -> GL(L/dL))`` using the level-m image.

        The source group G is specified by this image's integral generators
        at level m, with d dividing m. The returned subgroup is an actual
        preimage of the kernel of the canonical level-m to level-d map,
        rather than a nominal full matrix congruence subgroup.
        """
        target, projection = self.project_to_level(divisor)
        identity = target._key(target.image_one)
        allowed = (self.reduce(lift) for lift in self._lifts.values()
                   if target._key(projection(self.reduce(lift))) == identity)
        index, generators = self.preimage_generators(allowed)
        if index != len(target.image_keys()):
            raise ArithmeticError("relative congruence kernel has incorrect index")
        return index, generators

    def residue_vector_stabilizer(self, coordinates):
        r"""Exact preimage of the stabilizer of a residue column vector.

        The stabilizer is taken inside the computed image, never the nominal
        general linear group over the residue ring.
        """
        from sage.modules.free_module_element import vector

        point = vector(self.ring, coordinates)
        if len(point) != self.rank:
            raise ValueError("residue vector has the wrong rank")
        allowed = (self.reduce(lift) for lift in self._lifts.values()
                   if self.reduce(lift) * point == point)
        return self.preimage_generators(allowed)

    def residue_colouring_stabilizer(self, colour_classes):
        r"""Preimage preserving every named colour class of residue vectors.

        ``colour_classes`` maps colour labels to finite collections of vectors.
        Each colour is preserved setwise, with no permitted permutation of
        labels. Membership is tested in the *actual* finite reduction image.
        """
        from sage.modules.free_module_element import vector

        classes = []
        for points in colour_classes.values():
            entries = frozenset(tuple(vector(self.ring, point)) for point in points)
            if any(len(point) != self.rank for point in entries):
                raise ValueError("coloured residue vector has the wrong rank")
            classes.append(entries)
        allowed = []
        for lift in self._lifts.values():
            image = self.reduce(lift)
            if all({tuple(image * vector(self.ring, point)) for point in points} == points
                   for points in classes):
                allowed.append(image)
        return self.preimage_generators(allowed)

    def residue_submodule_stabilizer(self, generators):
        r"""Exact inverse image of the setwise stabilizer of a residue submodule.

        The finite submodule is generated additively in ``(Z/m)^rank``;
        testing its full image avoids assuming it is a free summand.
        """
        from sage.modules.free_module_element import vector

        rows = tuple(vector(self.ring, x) for x in generators)
        if any(len(x) != self.rank for x in rows):
            raise ValueError("residue submodule generator has the wrong rank")
        zero = vector(self.ring, [0] * self.rank)
        elements = {tuple(zero)}
        queue = deque([zero])
        while queue:
            x = queue.popleft()
            for y in rows:
                z = x + y
                key = tuple(z)
                if key not in elements:
                    elements.add(key)
                    queue.append(z)
        allowed = []
        for lift in self._lifts.values():
            image = self.reduce(lift)
            if all(tuple(image * row) in elements for row in rows):
                allowed.append(image)
        return self.preimage_generators(allowed)

    def simultaneous_residue_stabilizer(self, *, vectors=(), submodules=(), flags=(), colour_classes=None):
        """Schreier preimage of the exact simultaneous residue stabilizer."""
        keys = self.simultaneous_residue_stabilizer_keys(
            vectors=vectors, submodules=submodules, flags=flags, colour_classes=colour_classes
        )
        return self.preimage_generators(self.reduce(self._lifts[key]) for key in keys)

    def simultaneous_residue_stabilizer_keys(self, *, vectors=(), submodules=(), flags=(), colour_classes=None):
        r"""Preimage of the intersection of any finite family of residue stabilizers.

        All constraints are tested against each element of the same actual
        reduction image before a single Schreier preimage is constructed.
        """
        from sage.modules.free_module_element import vector

        fixed_vectors = tuple(vector(self.ring, x) for x in vectors)
        if any(len(x) != self.rank for x in fixed_vectors):
            raise ValueError("residue vector has the wrong rank")

        def generated(rows):
            rows = tuple(vector(self.ring, x) for x in rows)
            if any(len(x) != self.rank for x in rows):
                raise ValueError("residue submodule generator has the wrong rank")
            zero = vector(self.ring, [0] * self.rank)
            members = {tuple(zero)}
            queue = deque([zero])
            while queue:
                x = queue.popleft()
                for y in rows:
                    z = x + y
                    if tuple(z) not in members:
                        members.add(tuple(z))
                        queue.append(z)
            return rows, members

        modules = tuple(generated(rows) for rows in submodules)
        flag_data = tuple(tuple(generated(stage) for stage in stages) for stages in flags)
        for flag in flag_data:
            if any(not left[1] <= right[1] for left, right in zip(flag, flag[1:])):
                raise ValueError("residue flag stages must be nested")
        colours = []
        for points in (colour_classes or {}).values():
            values = frozenset(tuple(vector(self.ring, x)) for x in points)
            if any(len(x) != self.rank for x in values):
                raise ValueError("coloured residue vector has the wrong rank")
            colours.append(values)

        allowed = []
        for lift in self._lifts.values():
            image = self.reduce(lift)
            if not all(image * x == x for x in fixed_vectors):
                continue
            if not all(all(tuple(image * x) in members for x in rows) for rows, members in modules):
                continue
            if not all(all(all(tuple(image * x) in members for x in rows) for rows, members in flag)
                       for flag in flag_data):
                continue
            if not all({tuple(image * vector(self.ring, x)) for x in points} == points for points in colours):
                continue
            allowed.append(image)
        return frozenset(self._key(g) for g in allowed)

    def finite_index_sublattice_stabilizer(self, basis):
        r"""Preimage stabilizing a full-rank sublattice ``M`` of ``Z^rank``.

        Requires ``modulus * Z^rank <= M``; then ``M`` is precisely the
        inverse image of ``M / modulus * Z^rank``. The return is exact.
        """
        rows = matrix(ZZ, basis)
        if rows.dimensions() != (self.rank, self.rank) or rows.det() == 0:
            raise ValueError("sublattice basis must be square and full rank")
        if any(x not in ZZ for x in (self.modulus * rows.inverse()).list()):
            raise ValueError("modulus times the ambient lattice must lie in the sublattice")
        return self.residue_submodule_stabilizer(rows.rows())

    def residue_flag_stabilizer(self, stages):
        r"""Exact inverse image of the stabilizer of a nested residue-module flag.

        Each stage is an iterable of generators. No freeness or direct-summand
        assumption is made, including at composite level.
        """
        from sage.modules.free_module_element import vector

        flags = []
        for stage in stages:
            rows = tuple(vector(self.ring, x) for x in stage)
            if any(len(x) != self.rank for x in rows):
                raise ValueError("residue flag generator has the wrong rank")
            zero = vector(self.ring, [0] * self.rank)
            members = {tuple(zero)}
            queue = deque([zero])
            while queue:
                x = queue.popleft()
                for y in rows:
                    z = x + y
                    if tuple(z) not in members:
                        members.add(tuple(z))
                        queue.append(z)
            flags.append((rows, members))
        if any(not left <= right for (_, left), (_, right) in zip(flags, flags[1:])):
            raise ValueError("residue flag stages must be nested")
        allowed = []
        for lift in self._lifts.values():
            image = self.reduce(lift)
            if all(all(tuple(image * x) in members for x in rows) for rows, members in flags):
                allowed.append(image)
        return self.preimage_generators(allowed)

    def preimage_generators(self, allowed):
        r"""Generators of the inverse image of a subgroup of the actual image.

        ``allowed`` is an iterable of its image matrices, required to form a
        subgroup. Return ``(index, generators)``. The transversal consists of
        right cosets ``H f``; its Schreier words are ``t g t'^{-1}``.
        """
        subgroup = {self._key(x) for x in allowed}
        if self._key(self.image_one) not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must be a subgroup of the actual image")
        images = {key: self.reduce(lift) for key, lift in self._lifts.items()}
        if any(self._key(images[a] * images[b]) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not closed under multiplication")

        def coset_key(image):
            return min(self._key(images[h] * image) for h in subgroup)

        first = coset_key(self.image_one)
        transversal = {first: self.one}
        queue = deque([first])
        result = []
        while queue:
            key = queue.popleft()
            t = transversal[key]
            for g in self.generators:
                moved = t * g
                target = coset_key(self.reduce(moved))
                if target not in transversal:
                    transversal[target] = moved
                    queue.append(target)
                word = moved * transversal[target].inverse()
                if word != self.one:
                    result.append(word)
        assert len(transversal) * len(subgroup) == len(self._lifts)
        assert all(self._key(self.reduce(g)) in subgroup for g in result)
        return len(transversal), tuple(result)


class JointDeterminantCongruenceImage:
    r"""Actual joint image of reduction modulo ``m`` and determinant sign.

    The determinant is retained independently of reduction: at level two,
    ``-I`` may reduce to ``I`` while having determinant ``-1`` in odd rank.
    The finite target is the subgroup of ``GL_n(Z/m) x {+-1}`` generated by
    the *paired* images, not the product of their separate images.
    """

    def __init__(self, generators, modulus, rank=None):
        self.reduction = IntegralCongruenceImage(generators, modulus, rank=rank)
        self.generators = self.reduction.generators
        self.one = self.reduction.one
        self.identity = (self.reduction._key(self.reduction.image_one), 1)
        self._lifts = {self.identity: self.one}
        queue = deque([self.identity])
        images = tuple(self.image(g) for g in self.generators)
        while queue:
            key = queue.popleft()
            lift = self._lifts[key]
            for g, image in zip(self.generators, images):
                moved = self._multiply(key, image)
                if moved not in self._lifts:
                    self._lifts[moved] = lift * g
                    queue.append(moved)

    def image(self, g):
        g = matrix(ZZ, g)
        if g.det() not in (1, -1):
            raise ValueError("image requires an integral unimodular matrix")
        return (self.reduction._key(self.reduction.reduce(g)), int(g.det()))

    def _multiply(self, left, right):
        ring, rank = self.reduction.ring, self.reduction.rank
        a = matrix(ring, rank, rank, left[0])
        b = matrix(ring, rank, rank, right[0])
        return (self.reduction._key(a * b), left[1] * right[1])

    def image_keys(self):
        return frozenset(self._lifts)

    def lift(self, image):
        return self._lifts[image]

    def preimage_generators(self, allowed):
        r"""Exact Schreier generators of the inverse image of a joint subgroup."""
        subgroup = set(allowed)
        if self.identity not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must contain the identity and lie in the joint image")
        if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not a subgroup")

        def coset_key(image):
            return min(self._multiply(h, image) for h in subgroup)

        first = coset_key(self.identity)
        transversal = {first: self.one}
        queue = deque([first])
        result = []
        while queue:
            t = transversal[queue.popleft()]
            for g in self.generators:
                moved = t * g
                key = coset_key(self.image(moved))
                if key not in transversal:
                    transversal[key] = moved
                    queue.append(key)
                word = moved * transversal[key].inverse()
                if word != self.one:
                    result.append(word)
        assert len(transversal) * len(subgroup) == len(self._lifts)
        assert all(self.image(g) in subgroup for g in result)
        return len(transversal), tuple(result)


class JointSignCongruenceImage(JointDeterminantCongruenceImage):
    r"""Joint reduction image with an explicitly supplied sign homomorphism.

    ``sign`` must evaluate on integral matrices and return ``+1`` or ``-1``.
    This covers the normalized real-spinor sign without conflating it with
    determinant or the positive-cone component character.
    """

    def __init__(self, generators, modulus, sign, rank=None):
        self.sign = sign
        super().__init__(generators, modulus, rank=rank)
        if self.image(self.one) != self.identity:
            raise ValueError("sign must send identity to +1")
        # Check the character law on every edge of the finite image graph.
        for lift in self._lifts.values():
            for generator in self.generators:
                if self.image(lift * generator) != self._multiply(self.image(lift), self.image(generator)):
                    raise ValueError("sign is not multiplicative on the generated image")

    def image(self, g):
        g = matrix(ZZ, g)
        if g.det() not in (1, -1):
            raise ValueError("image requires an integral unimodular matrix")
        value = self.sign(g)
        if value not in (1, -1):
            raise ValueError("sign must take values in {+1,-1}")
        return (self.reduction._key(self.reduction.reduce(g)), int(value))


class JointTwoSignsCongruenceImage(JointSignCongruenceImage):
    r"""Actual joint image of level reduction and two independent sign characters.

    The image lies in ``GL_n(Z/m) x C2 x C2`` but is *not* assumed to
    equal the product of the separate images.
    """

    def __init__(self, generators, modulus, first_sign, second_sign, rank=None):
        self.second_sign = second_sign
        super().__init__(generators, modulus, first_sign, rank=rank)

    @property
    def identity(self):
        return (self.reduction._key(self.reduction.image_one), 1, 1)

    @identity.setter
    def identity(self, value):
        # The parent initializes its two-factor identity; the third sign is
        # supplied by this subclass's read-only three-factor identity.
        if value != self.identity[:2]:
            raise ValueError("invalid identity in joint sign image")

    def image(self, g):
        reduced, first = super().image(g)
        second = self.second_sign(matrix(ZZ, g))
        if second not in (1, -1):
            raise ValueError("second sign must take values in {+1,-1}")
        return (reduced, first, int(second))

    def _multiply(self, left, right):
        ring, rank = self.reduction.ring, self.reduction.rank
        a = matrix(ring, rank, rank, left[0])
        b = matrix(ring, rank, rank, right[0])
        return (self.reduction._key(a * b), left[1] * right[1], left[2] * right[2])


class JointFieldSpinorCongruenceImage:
    r"""Actual finite generated joint image of level and field-spinor square classes.

    ``spinor`` evaluates integral matrices into a multiplicative square-class
    group. Its image is enumerated jointly with reduction, rather than using
    the (possibly infinite) ambient square-class group as the finite target.
    """

    def __init__(self, generators, modulus, spinor, one_class, rank=None):
        self.reduction = IntegralCongruenceImage(generators, modulus, rank=rank)
        self.generators = self.reduction.generators
        self.one = self.reduction.one
        self.spinor = spinor
        self.identity = (self.reduction._key(self.reduction.image_one), one_class)
        if self.image(self.one) != self.identity:
            raise ValueError("spinor must map identity to the unit square class")
        self._lifts = {self.identity: self.one}
        queue = deque([self.identity])
        images = tuple(self.image(g) for g in self.generators)
        while queue:
            key = queue.popleft()
            lift = self._lifts[key]
            for g, image in zip(self.generators, images):
                moved = self._multiply(key, image)
                if moved not in self._lifts:
                    self._lifts[moved] = lift * g
                    queue.append(moved)
        for lift in self._lifts.values():
            for g in self.generators:
                if self.image(lift * g) != self._multiply(self.image(lift), self.image(g)):
                    raise ValueError("spinor is not multiplicative on the generated image")

    def image(self, g):
        g = matrix(ZZ, g)
        if g.det() not in (1, -1):
            raise ValueError("image requires an integral unimodular matrix")
        return (self.reduction._key(self.reduction.reduce(g)), self.spinor(g))

    def _multiply(self, a, b):
        ring, rank = self.reduction.ring, self.reduction.rank
        left = matrix(ring, rank, rank, a[0])
        right = matrix(ring, rank, rank, b[0])
        return (self.reduction._key(left * right), a[1] * b[1])

    def image_keys(self):
        return frozenset(self._lifts)

    def lift(self, image):
        return self._lifts[image]

    def preimage_generators(self, allowed):
        r"""Exact inverse-image generators for a subgroup of the joint image."""
        subgroup = set(allowed)
        if self.identity not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must contain identity and lie in the actual joint image")
        if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not a subgroup")
        # Square classes need not admit a total ordering; use the image's
        # deterministic BFS enumeration order as coset representative order.
        order = {key: i for i, key in enumerate(self._lifts)}

        def coset_key(image):
            return min((self._multiply(h, image) for h in subgroup), key=order.__getitem__)

        first = coset_key(self.identity)
        transversal = {first: self.one}
        queue = deque([first])
        result = []
        while queue:
            t = transversal[queue.popleft()]
            for g in self.generators:
                moved = t * g
                key = coset_key(self.image(moved))
                if key not in transversal:
                    transversal[key] = moved
                    queue.append(key)
                word = moved * transversal[key].inverse()
                if word != self.one:
                    result.append(word)
        assert len(transversal) * len(subgroup) == len(self._lifts)
        assert all(self.image(g) in subgroup for g in result)
        return len(transversal), tuple(result)


