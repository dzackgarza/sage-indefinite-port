r"""Exact finite congruence images of generated integral matrix groups (#42).

The finite image is generated by the actual reductions, not an ambient
``GL_n(Z/m)``. Schreier lifts use right multiplication throughout.
"""

from collections import deque

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.rings.finite_rings.integer_mod_ring import Integers
from sage.rings.integer_ring import ZZ


class IntegralCongruenceImage:
    r"""Construct the actual reduction image and exact inverse images of its subgroups.

    ``generators`` are invertible integral square matrices. The image is finite
    for every integer modulus >= 2, including composite moduli.
    """

    def __init__(self, generators, modulus, rank=None):
        modulus = ZZ(modulus)
        if modulus < 2:
            raise ValueError("congruence modulus must be at least two")
        self.modulus = modulus
        self.generators = tuple(matrix(ZZ, g) for g in generators)
        rank = ZZ(rank) if rank is not None else (self.generators[0].nrows() if self.generators else None)
        if rank is None or rank < 0:
            raise ValueError("rank is required for an empty generating family")
        self.rank = int(rank)
        for g in self.generators:
            if g.dimensions() != (rank, rank) or g.det() not in (1, -1):
                raise ValueError("generators must be integral unimodular square matrices")
        self.one = identity_matrix(ZZ, rank)
        self.ring = Integers(modulus)
        self.image_one = identity_matrix(self.ring, rank)
        self.image_generators = tuple(g.change_ring(self.ring) for g in self.generators)
        self._lifts = {self._key(self.image_one): self.one}
        queue = deque([self.image_one])
        while queue:
            current = queue.popleft()
            lift = self._lifts[self._key(current)]
            for g, image in zip(self.generators, self.image_generators):
                moved = current * image
                key = self._key(moved)
                if key not in self._lifts:
                    self._lifts[key] = lift * g
                    queue.append(moved)

    @staticmethod
    def _key(g):
        return tuple(int(x) for x in g.list())

    def reduce(self, g):
        return matrix(ZZ, g).change_ring(self.ring)

    def image_keys(self):
        return frozenset(self._lifts)

    def lift(self, image):
        return self._lifts[self._key(image)]

    def residue_vector_stabilizer(self, coordinates):
        r"""Exact preimage of the stabilizer of a residue column vector.

        The stabilizer is taken inside the computed image, never the nominal
        general linear group over the residue ring.
        """
        from sage.modules.free_module_element import vector

        point = vector(self.ring, coordinates)
        if len(point) != self.rank:
            raise ValueError("residue vector has the wrong rank")
        allowed = (self.reduce(lift) for lift in self._lifts.values()
                   if self.reduce(lift) * point == point)
        return self.preimage_generators(allowed)

    def residue_submodule_stabilizer(self, generators):
        r"""Exact inverse image of the setwise stabilizer of a residue submodule.

        The finite submodule is generated additively in ``(Z/m)^rank``;
        testing its full image avoids assuming it is a free summand.
        """
        from sage.modules.free_module_element import vector

        rows = tuple(vector(self.ring, x) for x in generators)
        if any(len(x) != self.rank for x in rows):
            raise ValueError("residue submodule generator has the wrong rank")
        zero = vector(self.ring, [0] * self.rank)
        elements = {tuple(zero)}
        queue = deque([zero])
        while queue:
            x = queue.popleft()
            for y in rows:
                z = x + y
                key = tuple(z)
                if key not in elements:
                    elements.add(key)
                    queue.append(z)
        allowed = []
        for lift in self._lifts.values():
            image = self.reduce(lift)
            if all(tuple(image * row) in elements for row in rows):
                allowed.append(image)
        return self.preimage_generators(allowed)

    def preimage_generators(self, allowed):
        r"""Generators of the inverse image of a subgroup of the actual image.

        ``allowed`` is an iterable of its image matrices, required to form a
        subgroup. Return ``(index, generators)``. The transversal consists of
        right cosets ``H f``; its Schreier words are ``t g t'^{-1}``.
        """
        subgroup = {self._key(x) for x in allowed}
        if self._key(self.image_one) not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must be a subgroup of the actual image")
        images = {key: self.reduce(lift) for key, lift in self._lifts.items()}
        if any(self._key(images[a] * images[b]) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not closed under multiplication")

        def coset_key(image):
            return min(self._key(images[h] * image) for h in subgroup)

        first = coset_key(self.image_one)
        transversal = {first: self.one}
        queue = deque([first])
        result = []
        while queue:
            key = queue.popleft()
            t = transversal[key]
            for g in self.generators:
                moved = t * g
                target = coset_key(self.reduce(moved))
                if target not in transversal:
                    transversal[target] = moved
                    queue.append(target)
                word = moved * transversal[target].inverse()
                if word != self.one:
                    result.append(word)
        assert len(transversal) * len(subgroup) == len(self._lifts)
        assert all(self._key(self.reduce(g)) in subgroup for g in result)
        return len(transversal), tuple(result)
