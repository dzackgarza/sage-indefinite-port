class JointDiscriminantCharacterImage:
    r"""Actual joint image of a discriminant action and finite characters.

    ``discriminant`` evaluates an integral matrix as an element of the
    provider's discriminant orthogonal group; ``characters`` are additional
    homomorphisms to finite groups, including real spinor and determinant.
    The target is their *generated joint image*, not the direct product.
    """

    def __init__(self, generators, discriminant, characters, identity, *, level_modulus=None, rank=None, ambient_contains=None):
        self.generators = tuple(matrix(ZZ, g) for g in generators)
        if rank is None:
            rank = self.generators[0].nrows() if self.generators else None
        if rank is None:
            raise ValueError("rank must be known for an empty generating family")
        self.one = identity_matrix(ZZ, rank)
        if any(g.dimensions() != (rank, rank) or g.det() not in (1, -1) for g in self.generators):
            raise ValueError("ambient generators must be unimodular square matrices")
        self.discriminant = discriminant
        self.characters = tuple(characters)
        # The finite quotient alone never decides membership in a *proper*
        # generated ambient subgroup: its kernel can contain elements outside
        # that subgroup. The owned group must supply the exact decision.
        self.ambient_contains = ambient_contains
        self.identity = tuple(identity)
        self.level_modulus = ZZ(level_modulus) if level_modulus is not None else None
        if self.level_modulus is not None:
            if self.level_modulus < 2:
                raise ValueError("congruence level must be at least two")
            self.level_ring = Integers(self.level_modulus)
            self.rank = self.one.nrows()
            self.identity = (tuple(int(x) for x in identity_matrix(self.level_ring, self.rank).list()), *self.identity)
        if self.image(self.one) != self.identity:
            raise ValueError("joint character identity mismatch")
        self._lifts = {self.identity: self.one}
        self._words = {self.identity: ()}
        queue = deque([self.identity])
        generator_images = tuple(self.image(g) for g in self.generators)
        while queue:
            key = queue.popleft()
            for i, (g, value) in enumerate(zip(self.generators, generator_images)):
                next_key = self._multiply(key, value)
                if next_key not in self._lifts:
                    self._lifts[next_key] = self._lifts[key] * g
                    self._words[next_key] = self._words[key] + (i,)
                    queue.append(next_key)
        for lift in self._lifts.values():
            for g, value in zip(self.generators, generator_images):
                if self.image(lift * g) != self._multiply(self.image(lift), value):
                    raise ValueError("a supplied joint character is not multiplicative")

    def image(self, matrix_value):
        g = matrix(ZZ, matrix_value)
        if g.det() not in (1, -1):
            raise ValueError("joint character requires an integral unimodular matrix")
        values = (self.discriminant(g), *(character(g) for character in self.characters))
        if self.level_modulus is None:
            return values
        return (tuple(int(x) for x in g.change_ring(self.level_ring).list()), *values)

    def _multiply(self, a, b):
        if self.level_modulus is None:
            return tuple(x * y for x, y in zip(a, b, strict=True))
        left = matrix(self.level_ring, self.rank, self.rank, a[0])
        right = matrix(self.level_ring, self.rank, self.rank, b[0])
        level = tuple(int(x) for x in (left * right).list())
        return (level, *(x * y for x, y in zip(a[1:], b[1:], strict=True)))

    def image_keys(self):
        return frozenset(self._lifts)

    def section(self, key):
        return self._lifts[key]

    def section_word(self, key):
        return self._words[key]

    def subgroup_from_generators(self, generators):
        r"""Exact finite subgroup generated inside the computed joint image."""
        generators = tuple(generators)
        if any(g not in self._lifts for g in generators):
            raise ValueError("subgroup generator is outside the actual image")
        elements = {self.identity}
        queue = deque([self.identity])
        while queue:
            current = queue.popleft()
            for generator in generators:
                moved = self._multiply(current, generator)
                if moved not in elements:
                    elements.add(moved)
                    queue.append(moved)
        return frozenset(elements)

    def subgroup_from_membership(self, predicate):
        r"""Exact subgroup of the actual joint image selected by a predicate."""
        elements = frozenset(key for key in self._lifts if predicate(key))
        if self.identity not in elements:
            raise ValueError("subgroup membership must contain identity")
        if any(self._multiply(a, b) not in elements for a in elements for b in elements):
            raise ValueError("membership criterion does not define a subgroup")
        return elements

    def preimage_membership(self, matrix_value, allowed):
        r"""Exact membership in the preimage of a subgroup of the actual image."""
        subgroup = set(allowed)
        if self.identity not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must be contained in the actual joint image")
        if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not a subgroup")
        if self.ambient_contains is None:
            raise ValueError("exact ambient subgroup membership must be supplied to decide preimage membership")
        if not self.ambient_contains(matrix_value):
            return False
        return self.image(matrix_value) in subgroup

    def image_witness(self, key):
        r"""Integral isometry-matrix witness lifting the specified joint image."""
        witness = self.section(key)
        assert self.image(witness) == key
        return witness

    def right_coset_action(self, allowed):
        r"""Exact right action of the actual image on ``H\F``.

        Return an ordered tuple of left cosets ``H*f`` (represented by
        canonical image keys), and an action function taking a coset index
        and an integral ambient matrix to the index of its right translate.
        The action is a *right* action, so ``act(act(i,g),h)=act(i,g*h)``.
        """
        subgroup = set(allowed)
        if self.identity not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must lie in the actual joint image and contain identity")
        if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not a subgroup")
        order = {key: i for i, key in enumerate(self._lifts)}

        def representative(key):
            return min((self._multiply(h, key) for h in subgroup), key=order.__getitem__)

        cosets = tuple(dict.fromkeys(representative(key) for key in self._lifts))
        positions = {key: i for i, key in enumerate(cosets)}
        assert len(cosets) * len(subgroup) == len(self._lifts)

        def act(index, matrix_value):
            if not 0 <= index < len(cosets):
                raise IndexError("coset index out of range")
            if self.ambient_contains is not None and not self.ambient_contains(matrix_value):
                raise ValueError("matrix is not in the specified ambient subgroup")
            image = self.image(matrix_value)
            if image not in self._lifts:
                raise ValueError("matrix image is outside the generated ambient group")
            return positions[representative(self._multiply(cosets[index], image))]

        return cosets, act

    def right_coset_transporter(self, allowed, source_index, target_index):
        r"""An integral ambient witness carrying one right coset to another.

        For left cosets ``H*a`` and ``H*b``, the element ``a^-1*b`` acts
        on the right and carries the former to the latter. The returned
        witness is verified using the exact finite action.
        """
        cosets, act = self.right_coset_action(allowed)
        if not 0 <= source_index < len(cosets) or not 0 <= target_index < len(cosets):
            raise IndexError("coset index out of range")
        source = self.section(cosets[source_index])
        target = self.section(cosets[target_index])
        witness = source.inverse() * target
        assert act(source_index, witness) == target_index
        return matrix(ZZ, witness)

    def double_coset_representatives(self, left_subgroup, right_subgroup):
        r"""Exact representatives and integral lifts of ``H\F/K``.

        Both subgroups must lie in the actual joint image ``F``. Every
        double coset is enumerated using multiplication in ``F``, not in
        the nominal product of the character targets. Return pairs of
        an image key and a certified integral lift.
        """
        left = frozenset(left_subgroup)
        right = frozenset(right_subgroup)
        actual = self.image_keys()
        for subgroup in (left, right):
            if self.identity not in subgroup or not subgroup <= actual:
                raise ValueError("double-coset subgroup is not in the actual image")
            if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
                raise ValueError("double-coset argument is not a subgroup")
        unseen = set(actual)
        result = []
        for representative in self._lifts:
            if representative not in unseen:
                continue
            orbit = {self._multiply(self._multiply(h, representative), k)
                     for h in left for k in right}
            if not orbit <= unseen:
                raise ArithmeticError("double cosets do not partition the actual image")
            unseen.difference_update(orbit)
            witness = self.section(representative)
            assert self.image(witness) == representative
            result.append((representative, witness))
        assert not unseen
        return tuple(result)

    def double_coset_intersection(self, left_subgroup, right_subgroup, representative):
        r"""Exact subgroup ``H intersect r*K*r^-1`` in the actual image."""
        left = self.subgroup_from_generators(tuple(left_subgroup))
        right = self.subgroup_from_generators(tuple(right_subgroup))
        if representative not in self._lifts:
            raise ValueError("representative is outside the actual image")
        r = self.section(representative)
        inverse = self.image(r.inverse())
        return frozenset(h for h in left
                         if self._multiply(self._multiply(inverse, h), representative) in right)

    def double_coset_stabilizer_preimage(self, left_subgroup, right_subgroup, representative):
        r"""Exact integral generators of ``rho^-1(H intersect r*K*r^-1)``.

        This is the preimage of the *finite intersection*, not in general
        the stabilizer of a marked object: ``ker(rho)`` need not preserve
        that object. For the actual marked stabilizer use
        ``conjugate_stabilizer_generators`` with generators of its ambient
        stabilizer ``P``. The index here is measured in the ambient group.
        """
        intersection = self.double_coset_intersection(
            left_subgroup, right_subgroup, representative
        )
        index, generators = self.preimage_generators(intersection)
        assert index * len(intersection) == len(self._lifts)
        return index, generators

    def conjugate_stabilizer_generators(self, left_subgroup, stabilizer_generators, representative):
        r"""Generators of ``rho^-1(H) intersect r*P*r^-1`` inside ``r*P*r^-1``.

        ``P`` must be generated by the supplied *integral* stabilizer
        generators. Schreier is performed inside P, not the full ambient
        group: the ambient congruence kernel need not stabilize the mark.
        The returned index is ``[P : P intersect r^-1*Gamma*r]``.
        """
        left = frozenset(left_subgroup)
        if self.identity not in left or not left <= self.image_keys():
            raise ValueError("left subgroup must lie in the actual image")
        if any(self._multiply(a, b) not in left for a in left for b in left):
            raise ValueError("left subgroup is not closed")
        if representative not in self._lifts:
            raise ValueError("representative is outside the actual image")
        r = self.section(representative)
        r_inverse = r.inverse()
        generators = tuple(matrix(ZZ, g) for g in stabilizer_generators)
        for g in generators:
            if self.ambient_contains is not None and not self.ambient_contains(g):
                raise ValueError("stabilizer generator lies outside ambient group")
            if self.image(g) not in self._lifts:
                raise ValueError("stabilizer generator lies outside generated image")
        right_image = {self.identity}
        queue = deque([self.identity])
        generator_images = tuple(self.image(g) for g in generators)
        while queue:
            key = queue.popleft()
            for g in generator_images:
                moved = self._multiply(key, g)
                if moved not in right_image:
                    right_image.add(moved)
                    queue.append(moved)
        inverse_key = self.image(r_inverse)
        allowed = frozenset(key for key in right_image
            if self._multiply(self._multiply(representative, key), inverse_key) in left)
        order = {key: i for i, key in enumerate(self._lifts)}
        def coset_key(key):
            return min((self._multiply(h, key) for h in allowed), key=order.__getitem__)
        first = coset_key(self.identity)
        transversal = {first: self.one}
        queue = deque([first])
        words = []
        while queue:
            t = transversal[queue.popleft()]
            for g in generators:
                moved = t * g
                key = coset_key(self.image(moved))
                if key not in transversal:
                    transversal[key] = moved
                    queue.append(key)
                word = moved * transversal[key].inverse()
                if word != self.one:
                    words.append(matrix(ZZ, r * word * r_inverse))
        assert len(transversal) * len(allowed) == len(right_image)
        assert all(self.image(g) in left for g in words)
        return len(transversal), tuple(words)

    def restricted_transporter(self, allowed, ambient_transporter, stabilizer_generators):
        r"""Find a transporter in ``rho^-1(H)`` inside the coset ``t*P``.

        ``ambient_transporter`` is an actual ambient witness ``t`` from a
        marked object to its target, and ``stabilizer_generators`` generate
        the target-preserving right correction group ``P``. Return ``t*p``
        with ``p in P`` and image in H, or ``None`` if none exists. The
        finite search is complete because it enumerates the actual image
        of P and retains integral words lifting every image element.
        """
        allowed = frozenset(allowed)
        if self.identity not in allowed or not allowed <= self.image_keys():
            raise ValueError("allowed must be a subgroup of the actual image")
        if any(self._multiply(a, b) not in allowed for a in allowed for b in allowed):
            raise ValueError("allowed is not a subgroup")
        t = matrix(ZZ, ambient_transporter)
        if self.ambient_contains is not None and not self.ambient_contains(t):
            raise ValueError("ambient transporter is not in the generated ambient group")
        t_image = self.image(t)
        if t_image not in self._lifts:
            raise ValueError("ambient transporter image is outside the generated group")
        generators = tuple(matrix(ZZ, g) for g in stabilizer_generators)
        if self.ambient_contains is not None and any(
            not self.ambient_contains(g) for g in generators
        ):
            raise ValueError("stabilizer generator is outside the specified ambient subgroup")
        images = tuple(self.image(g) for g in generators)
        if any(key not in self._lifts for key in images):
            raise ValueError("stabilizer generator image lies outside the generated group")
        lifts = {self.identity: self.one}
        queue = deque([self.identity])
        while queue:
            key = queue.popleft()
            candidate = t * lifts[key]
            if self._multiply(t_image, key) in allowed:
                assert self.image(candidate) in allowed
                return matrix(ZZ, candidate)
            for g, image in zip(generators, images):
                moved = self._multiply(key, image)
                if moved not in lifts:
                    lifts[moved] = lifts[key] * g
                    queue.append(moved)
        return None

    def preimage_generators(self, allowed):
        subgroup = set(allowed)
        if self.identity not in subgroup or not subgroup <= self.image_keys():
            raise ValueError("allowed must be contained in the actual joint image")
        if any(self._multiply(a, b) not in subgroup for a in subgroup for b in subgroup):
            raise ValueError("allowed is not a subgroup")
        order = {key: i for i, key in enumerate(self._lifts)}

        def coset_key(image):
            return min((self._multiply(h, image) for h in subgroup), key=order.__getitem__)

        transversal = {coset_key(self.identity): self.one}
        queue = deque(transversal)
        result = []
        while queue:
            t = transversal[queue.popleft()]
            for g in self.generators:
                moved = t * g
                key = coset_key(self.image(moved))
                if key not in transversal:
                    transversal[key] = moved
                    queue.append(key)
                schreier = moved * transversal[key].inverse()
                if schreier != self.one:
                    result.append(schreier)
        assert len(transversal) * len(subgroup) == len(self._lifts)
        assert all(self.image(g) in subgroup for g in result)
        return len(transversal), tuple(result)
