r"""Voronoi's algorithm for the unit group of an order in a semisimple `Q`-algebra (#54).

Let `A` be a finite-dimensional semisimple `Q`-algebra given inside `M_k(Q)` by a `Z`-basis `o_1, \ldots, o_m` of an order `O`. By
Wedderburn, `A \otimes R \cong \prod_v M_{n_v}(R), M_{n_v}(C), M_{n_v}(H)`; a positive involution `*` of `A \otimes R` is the standard
(conjugate) transpose on each factor. The cone is the set of positive elements of `\mathrm{Herm}(A \otimes R) = \{s : s^* = s\}`, with the forms
`\varphi_s(x) = \mathrm{Tr}(x^* s x) = \langle s, x x^* \rangle` on `O`, `\langle s, r \rangle = \mathrm{Tr}(s r)` (Braun, Coulangeon, Nebe,
Schoennenbeck, *Computing in arithmetic groups with Voronoi's algorithm*, J. Algebra 435 (2015), arXiv:1407.6234, Sec. 2-4). A unit `u`
acts by `u \cdot s = u^* s u`, with `\varphi_{u \cdot s}(x) = \varphi_s(u x)` and `\mathrm{Min}(u \cdot s) = u^{-1} \mathrm{Min}(s)`. Perfect forms,
their Voronoi domains `\mathrm{cone}\{x x^* : x \in \mathrm{Min}(s)\}` and the neighbours across facets tile the cone, there are finitely many
perfect forms up to `O^\times` and positive scalars, and `O^\times` is generated by `-1`, the stabilizers of representatives and the elements
carrying each neighbour to its representative (BCNS Thm. 3.4; Opgenorth, *Dual cones and the Voronoi algorithm*, Experiment. Math. 10
(2001)).

Two models of the cone, both exact.

Rational. When `A` is stable under the transpose of `M_k(Q)`, `x \mapsto x^T` is a positive involution of `A` (`\mathrm{Tr}(x x^T) > 0`),
and `\mathrm{Herm} = \{s \in A : s^T = s\}` is a `Q`-form of `\mathrm{Herm}(A \otimes R)`.

Split (Opgenorth's version). An algebra need not have a positive involution over `Q`: a central division algebra of degree three over a
totally real `K` has none, since an involution of the first kind needs exponent two and one of the second kind needs a CM centre. Then the
cone is defined through `A \otimes R \cong \prod_v M_n(R)` with the transpose: the caller gives a totally real number field `N` with a real
embedding and `Q`-algebra homomorphisms `h_v : A \to M_n(N)`, one for each real place `v`, with `A \otimes R \cong \prod_v M_n(R)` through
them. The forms are `s = (s_v) \in \prod_v \mathrm{Sym}_n(N)`, an `N`-form of the real cone, and every perfect form lies in it because it solves
linear equations with coefficients `(h_v(x) h_v(x)^T)_v` in `N`. Positivity and comparisons are exact in the embedded `N`.

Minimal vectors. The Gram matrix of `\varphi_s` on the order basis has entries in `N`; a rational minorant `R \preceq` Gram (interval centre
minus `m \cdot` radius times the identity) bounds the enumeration, PARI ``qfminim(..., flag=2)`` lists the candidates, and exact values filter
them.

Neighbours. For a facet of the Voronoi domain of a perfect `s` with inner normal `r`, the neighbour is `s + \rho r` with the least `\rho > 0`
at which a new minimal vector appears (Schuermann, *Computational geometry of positive definite quadratic forms*, AMS Univ. Lecture Ser.
48 (2009), Alg. 2).

Equivalence. `u \cdot s = s'` forces `u x \in \mathrm{Min}(s)` for `x \in \mathrm{Min}(s')`. The minimal vectors of a perfect `s'` generate `A`
as a right `A`-module (otherwise they lie in a proper right ideal `e A` and their rays in `e \,\mathrm{Herm}\, e`), so for `x_1, \ldots, x_r \in
\mathrm{Min}(s')` with `\sum x_i A = A` and `\sum x_i a_i = 1`, `u = \sum (u x_i) a_i` runs over the finite set `\sum m_i a_i`,
`m_i \in \pm \mathrm{Min}(s)`. For a division algebra `r = 1` and `u = m x_1^{-1}`.

Ideal generators. For a simple `A` with centre `K` and `\dim_K A = n^2`, an element `x` of an invertible ideal `I` of a maximal order
generates it exactly when `\mathrm{nrd}(x) O_K = \mathrm{nrd}(I)`, i.e. `N_{A/K}(x) O_K = \mathrm{nrd}(I)^n`. Unless `A` is a totally definite
quaternion algebra, the Eichler condition holds and `I` is principal exactly when `\mathrm{nrd}(I)` has a generator positive at the real places
where `A` ramifies (Reiner, *Maximal Orders*, Thm. 34.9 and 35.14); for odd `n` no real place ramifies and the condition is the class of
`\mathrm{nrd}(I)` in `\mathrm{Cl}(K)`. The generator is then found by enumeration in the Frobenius form `\varphi_1`. A totally definite quaternion
algebra is decided by the exact enumeration of Kirschmer and Voight (*Algorithmic enumeration of ideal classes for quaternion orders*,
SIAM J. Comput. 39 (2010), Sec. 6).
"""

from copy import copy
from itertools import combinations, product

from sage.geometry.polyhedron.constructor import Polyhedron
from sage.libs.pari import pari
from sage.matrix.constructor import block_matrix, matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.integer_ring import ZZ
from sage.rings.qqbar import AA
from sage.rings.rational_field import QQ
from sage.rings.real_mpfi import RealIntervalField


def _definiteness(gram):
    r"""Return ``"definite"``, ``"semidefinite"`` or ``None`` for the symmetric ``gram`` over an exactly ordered field (symmetric Gaussian
    elimination: a zero pivot needs a zero row in the Schur complement)."""
    a = copy(gram)
    m = a.nrows()
    strict = True
    for i in range(m):
        pivot = a[i, i]
        if pivot < 0:
            return None
        if pivot == 0:
            if any(a[i, j] != 0 for j in range(i + 1, m)):
                return None
            strict = False
            continue
        for r in range(i + 1, m):
            if a[r, i] != 0:
                a.add_multiple_of_row(r, i, -a[r, i] / pivot)
    return "definite" if strict else "semidefinite"


def _rational_minorant(gram):
    r"""Return a rational positive definite `R` with `\mathrm{gram} - R` positive semidefinite (module docstring, Minimal vectors)."""
    if gram.base_ring() is QQ:
        return gram
    m = gram.nrows()
    precision = 64
    while True:
        field = RealIntervalField(precision)
        intervals = [field(e) for e in gram.list()]
        centres = [QQ(z.center()) for z in intervals]
        radius = max(QQ((z - c).abs().upper()) for z, c in zip(intervals, centres))
        lower = matrix(QQ, m, m, centres) - m * radius * identity_matrix(QQ, m)
        if lower.is_positive_definite():
            return lower
        precision *= 2


def _short_vectors(gram, bound):
    r"""Return the pairs `(v, v^T G v)`, one `v` of each pair `\pm v \ne 0` in `Z^m`, with `v^T G v \le` ``bound`` for the positive definite `G`."""
    lower = _rational_minorant(gram)
    ceiling = QQ(bound) if gram.base_ring() is QQ else QQ(RealIntervalField(64)(bound).upper())
    scale = lower.denominator()
    found = pari(matrix(ZZ, scale * lower)).qfminim(scale * ceiling, flag=2)[2].sage()
    result = []
    for column in found.columns():
        v = vector(ZZ, column)
        value = v * gram * v
        if value <= bound:
            result.append((v, value))
    return result


class SemisimpleOrderVoronoi:
    r"""Perfect forms, Voronoi neighbours and unit generators of the order with `Z`-basis ``order_basis`` (matrices in `M_k(Q)`).

    ``splitting`` is ``None`` for the rational model, or ``(N, places)`` for the split model (module docstring). ``center`` is ``(K, embed)``,
    the centre `K` of a simple `A` with ``embed`` `: K \to A`; it is needed only by :meth:`norm_generator` and defaults to `Q` for central `A`."""

    def __init__(self, order_basis, splitting=None, center=None):
        self.order = tuple(matrix(QQ, b) for b in order_basis)
        self._order_rows = matrix(QQ, [b.list() for b in self.order])
        assert self._order_rows.rank() == len(self.order)
        self.one = self._unit()
        if splitting is None:
            assert all(self.in_algebra(b.transpose()) for b in self.order), "the algebra is not stable under the transpose: give a splitting"
            self.field = QQ
            self.places = (lambda x: x,)
            kernel = matrix(QQ, [(b.transpose() - b).list() for b in self.order]).left_kernel().basis()
            self.herm = [(self._combination(row),) for row in kernel]
        else:
            self.field, places = splitting
            self.places = tuple(places)
            n = self.places[0](self.one).nrows()
            assert len(self.order) == len(self.places) * n * n
            assert all(h(self.one) == identity_matrix(self.field, n) for h in self.places)
            zero = matrix(self.field, n, n)
            self.herm = []
            for v in range(len(self.places)):
                for i in range(n):
                    for j in range(i, n):
                        e = matrix(self.field, n, n)
                        e[i, j] = 1
                        e[j, i] = 1
                        self.herm.append(tuple(e if w == v else zero for w in range(len(self.places))))
        self.center = center
        self._images = [self._image(b) for b in self.order]
        self._herm_rows = matrix(self.field, [self._flat(s) for s in self.herm])
        self._pairing = matrix(self.field, [[self._inner(s, r) for r in self.herm] for s in self.herm])
        assert _definiteness(self._pairing) == "definite"

    # The algebra.
    def _combination(self, coefficients):
        return sum((c * b for c, b in zip(coefficients, self.order)), 0 * self.order[0])

    def _unit(self):
        r"""Return the unit `e` of `A`: the solution of `e o_i = o_i e = o_i`."""
        system = block_matrix([[matrix(QQ, [(b * c).list() + (c * b).list() for b in self.order]) for c in self.order]], subdivide=False)
        target = vector(QQ, [t for c in self.order for t in c.list() + c.list()])
        one = self._combination(system.solve_left(target))
        assert all(one * b == b and b * one == b for b in self.order)
        return one

    def order_coordinates(self, x):
        r"""Return the coordinates of ``x`` `\in A` in the order basis (rational; integral exactly when ``x`` is in the order)."""
        return self._order_rows.solve_left(vector(QQ, x.list()))

    def in_algebra(self, x):
        return self._order_rows.stack(matrix(QQ, [x.list()])).rank() == len(self.order)

    def in_order(self, x):
        return all(c in ZZ for c in self.order_coordinates(x))

    def from_order(self, coordinates):
        return sum((ZZ(c) * o for c, o in zip(coordinates, self.order)), 0 * self.one)

    def inverse(self, x):
        r"""Return `x^{-1}` in `A`, or ``None`` when ``x`` is not invertible (left multiplication is singular)."""
        system = matrix(QQ, [(x * b).list() for b in self.order])
        if system.rank() < len(self.order):
            return None
        y = self._combination(system.solve_left(vector(QQ, self.one.list())))
        assert x * y == self.one and y * x == self.one
        return y

    def is_unit(self, x):
        if not self.in_order(x):
            return False
        y = self.inverse(x)
        return y is not None and self.in_order(y)

    # Hermitian forms: tuples `(s_v)` over the places.
    def _image(self, x):
        return tuple(h(x) for h in self.places)

    def _flat(self, s):
        return [c for t in s for c in t.list()]

    def _inner(self, s, r):
        return sum(((a * b).trace() for a, b in zip(s, r)), self.field(0))

    def form(self, coordinates):
        r"""Return `\sum_t c_t h_t` for the basis `h_t` of `\mathrm{Herm}`."""
        return tuple(sum((c * s[v] for c, s in zip(coordinates, self.herm)), 0 * self.herm[0][v]) for v in range(len(self.places)))

    def herm_coordinates(self, s):
        return self._herm_rows.solve_left(vector(self.field, self._flat(s)))

    def act(self, u, s):
        r"""Return `u \cdot s = u^* s u`."""
        return tuple(U.transpose() * t * U for U, t in zip(self._image(u), s))

    def _move(self, s, rho, r):
        return tuple(a + rho * b for a, b in zip(s, r))

    def _gram_on(self, s, images):
        return matrix(
            self.field,
            [[sum(((X.transpose() * t * Y).trace() for X, t, Y in zip(I, s, J)), self.field(0)) for J in images] for I in images],
        )

    def gram(self, s):
        r"""Return the Gram matrix of `\varphi_s` in the order basis."""
        return self._gram_on(s, self._images)

    def value(self, s, x):
        return sum(((X.transpose() * t * X).trace() for X, t in zip(self._image(x), s)), self.field(0))

    def ray(self, x):
        return self.herm_coordinates(tuple(X * X.transpose() for X in self._image(x)))

    def is_positive(self, s):
        return _definiteness(self.gram(s)) == "definite"

    def _below(self, s, bound):
        r"""Return the order elements `x \ne 0` (up to sign) with `\varphi_s(x) <` ``bound``, `s` positive."""
        return [self.from_order(v) for v, value in _short_vectors(self.gram(s), bound) if value < bound]

    def minimum(self, s):
        r"""Return `\mu(s)` and `\mathrm{Min}(s)` up to sign."""
        gram = self.gram(s)
        vectors = _short_vectors(gram, min(gram.diagonal()))
        mu = min(value for _v, value in vectors)
        return mu, [self.from_order(v) for v, value in vectors if value == mu]

    def is_perfect(self, s):
        _mu, minimal = self.minimum(s)
        return matrix(self.field, [self.ray(x) for x in minimal]).rank() == len(self.herm)

    def _step(self, s, r):
        r"""Return the least `\rho > 0` at which `s + \rho r` has a new minimal vector (Schuermann, Alg. 2)."""
        mu, _minimal = self.minimum(s)
        low, high = self.field(0), self.field(1)
        while True:
            moved = self._move(s, high, r)
            if not self.is_positive(moved):
                high = (low + high) / 2
                continue
            below = self._below(moved, mu)
            if below:
                break
            low, high = high, 2 * high
        while below:
            high = min((self.value(s, x) - mu) / (-self.value(r, x)) for x in below)
            below = self._below(self._move(s, high, r), mu)
        return high

    def _normalized(self, s):
        mu, _minimal = self.minimum(s)
        return tuple(t / mu for t in s)

    def perfect_form(self):
        r"""Return a perfect form, from `s = 1` by moves orthogonal to the rays of the minimal vectors."""
        s = self._image(self.one)
        while not self.is_perfect(s):
            _mu, minimal = self.minimum(s)
            rays = matrix(self.field, [self.ray(x) for x in minimal])
            r = self.form((rays * self._pairing).right_kernel().basis()[0])
            if _definiteness(self.gram(r)) is not None:
                r = tuple(-t for t in r)
            assert _definiteness(self.gram(r)) is None
            s = self._normalized(self._move(s, self._step(s, r), r))
        return self._normalized(s)

    def facet_normals(self, s):
        r"""Return the inner normals `r \in \mathrm{Herm}` of the facets of the Voronoi domain of the perfect ``s``."""
        _mu, minimal = self.minimum(s)
        backend = "ppl" if self.field is QQ else "field"
        cone = Polyhedron(rays=[self.ray(x) for x in minimal], base_ring=self.field, backend=backend)
        assert cone.dim() == len(self.herm)
        inverse = self._pairing.inverse()
        normals = []
        for inequality in cone.inequalities():
            assert inequality.b() == 0
            normals.append(self.form(inverse * vector(self.field, inequality.A())))
        return normals

    def neighbour(self, s, r):
        r"""Return the normalized Voronoi neighbour of the perfect ``s`` across the facet with inner normal ``r``."""
        assert _definiteness(self.gram(r)) is None, f"the facet normal {r} of the perfect form {s} is positive semidefinite"
        return self._normalized(self._move(s, self._step(s, r), r))

    def _candidates(self, source, target):
        r"""Return the finite set of `u` with `u \cdot` ``target`` possibly equal to ``source`` (module docstring, Equivalence)."""
        _mu, minimal = self.minimum(source)
        _nu, target_minimal = self.minimum(target)
        if len(minimal) != len(target_minimal):
            return []
        chosen, rows, rank = [], [], 0
        for x in target_minimal:
            block = [(x * b).list() for b in self.order]
            grown = matrix(QQ, rows + block).rank()
            if grown > rank:
                chosen.append(x)
                rows.extend(block)
                rank = grown
            if rank == len(self.order):
                break
        assert rank == len(self.order), "the minimal vectors of a perfect form generate A as a right module"
        solution = matrix(QQ, rows).solve_left(vector(QQ, self.one.list()))
        size = len(self.order)
        multipliers = [self._combination(solution[t * size : (t + 1) * size]) for t in range(len(chosen))]
        signed = [*minimal, *(-m for m in minimal)]
        result = []
        for first in minimal:
            for rest in product(signed, repeat=len(chosen) - 1):
                result.append(sum((m * a for m, a in zip((first, *rest), multipliers)), 0 * self.one))
        return result

    def transporter(self, source, target):
        r"""Return a unit `u` with `u \cdot` ``source`` `=` ``target`` (both normalized), or ``None``."""
        for u in self._candidates(source, target):
            if self.is_unit(u) and self.act(u, source) == target:
                return u
        return None

    def stabilizer(self, s):
        result = []
        for u in self._candidates(s, s):
            if u not in result and self.is_unit(u) and self.act(u, s) == s:
                result.append(u)
        return result

    def perfect_forms(self):
        r"""Return representatives of the perfect forms up to `O^\times`, with the transports of their neighbours."""
        if not hasattr(self, "_perfect"):
            forms, transports = [self.perfect_form()], []
            position = 0
            while position < len(forms):
                s = forms[position]
                position += 1
                for r in self.facet_normals(s):
                    neighbour = self.neighbour(s, r)
                    found = next((u for known in forms for u in [self.transporter(known, neighbour)] if u is not None), None)
                    if found is None:
                        forms.append(neighbour)
                    else:
                        transports.append(found)
            self._perfect = (tuple(forms), tuple(transports))
        return self._perfect[0]

    def unit_generators(self):
        r"""Return generators of `O^\times`: `-1`, the stabilizers of the perfect representatives and the transports of their neighbours."""
        forms = self.perfect_forms()
        result = [-self.one]
        for s in forms:
            result.extend(self.stabilizer(s))
        result.extend(self._perfect[1])
        assert all(self.is_unit(u) for u in result)
        return tuple(result)

    # Ideal generators (module docstring).
    def _center(self):
        if self.center is None:
            commutators = matrix(QQ, [[c for b in self.order for c in (a * b - b * a).list()] for a in self.order])
            assert commutators.left_kernel().dimension() == 1, "a noncentral algebra needs its centre (K, embed)"
            self.center = (QQ, lambda c: QQ(c) * self.one)
        return self.center

    def _ideal(self, value):
        K, _embed = self._center()
        return (ZZ if K is QQ else K).ideal(value)

    def _k_matrix(self, x):
        r"""Return the matrix over `K` of left multiplication by ``x`` on the `K`-space `A`."""
        K, embed = self._center()
        if not hasattr(self, "_k_frame"):
            powers = [embed(K.gen() ** j) for j in range(K.degree())]
            basis, rows = [], []
            for b in self.order:
                block = [(p * b).list() for p in powers]
                if matrix(QQ, rows + block).rank() == len(rows) + len(block):
                    basis.append(b)
                    rows.extend(block)
            assert len(rows) == len(self.order)
            self._k_frame = (basis, matrix(QQ, rows))
        basis, span = self._k_frame
        d = K.degree()
        columns = []
        for b in basis:
            c = span.solve_left(vector(QQ, (x * b).list()))
            columns.append([sum((c[s * d + j] * K.gen() ** j for j in range(d)), K(0)) for s in range(len(basis))])
        return matrix(K, columns).transpose()

    def degree(self):
        r"""Return `n` with `\dim_K A = n^2`."""
        self._k_matrix(self.one)
        return ZZ(len(self._k_frame[0])).isqrt()

    def generates(self, x, target):
        r"""Decide `\mathrm{nrd}(x) O_K =` ``target`` through `N_{A/K}(x) O_K = ` ``target`` `^n`."""
        norm = self._k_matrix(x).det()
        return norm != 0 and self._ideal(norm) == target ** self.degree()

    def _real_embeddings(self):
        K, _embed = self._center()
        if K is QQ:
            return [lambda c: AA(c)]
        return list(K.embeddings(AA))

    def _ramified_places(self):
        r"""Return the real embeddings of `K` at which `A \otimes R \cong M_{n/2}(H)`: the trace form has negative signature there."""
        if self.degree() % 2 == 1 or self.field is not QQ:
            return []
        K, embed = self._center()
        size = len(self.order)
        trace = matrix(QQ, size, size, [(b * c).trace() for b in self.order for c in self.order]).change_ring(AA)
        theta = matrix(QQ, [self.order_coordinates(embed(K.gen()) * b) for b in self.order]).change_ring(AA)
        result = []
        for phi in self._real_embeddings():
            space = (theta - phi(K.gen()) * identity_matrix(AA, size)).left_kernel().basis_matrix()
            eigenvalues = (space * trace * space.transpose()).charpoly().roots(AA)
            if sum(m for r, m in eigenvalues if r > 0) < sum(m for r, m in eigenvalues if r < 0):
                result.append(phi)
        return result

    def _unit_classes(self):
        r"""Return representatives of `O_K^\times / (O_K^\times)^2`."""
        K, _embed = self._center()
        generators = [QQ(-1)] if K is QQ else [K(u) for u in K.unit_group().gens_values()]
        result = []
        for size in range(len(generators) + 1):
            for chosen in combinations(generators, size):
                value = K(1)
                for u in chosen:
                    value *= u
                result.append(value)
        return result

    def _principal_generator(self, target):
        K, _embed = self._center()
        if K is QQ:
            return QQ(target.gen())
        return K(target.gens_reduced()[0]) if target.is_principal() else None

    def _lattice(self, elements):
        r"""Return a `Z`-basis (matrices) of the `Z`-span of ``elements``."""
        rows = matrix(QQ, [x.list() for x in elements])
        scale = rows.denominator()
        hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
        k = self.one.nrows()
        return [matrix(QQ, k, k, list(row)) for row in hermite.rows()]

    def norm_generator(self, elements, target):
        r"""Return `x` in the `Z`-span of ``elements`` (an invertible ideal of a maximal order) with `\mathrm{nrd}(x) O_K =` ``target``, or ``None``
        when there is none (module docstring, Ideal generators)."""
        K, _embed = self._center()
        lattice = self._lattice(elements)
        assert len(lattice) == len(self.order)
        ramified = self._ramified_places()
        units = self._unit_classes()
        g = self._principal_generator(target)
        if g is None:
            return None
        if self.degree() == 2 and len(ramified) == K.degree():
            return self._definite_norm_generator(lattice, g, ramified, units)
        if not any(all(phi(g * u) > 0 for phi in ramified) for u in units):
            return None
        gram = self._gram_on(self._image(self.one), [self._image(x) for x in lattice])
        bound = max(gram.diagonal())
        while True:
            for v, _value in _short_vectors(gram, bound):
                x = sum((ZZ(c) * b for c, b in zip(v, lattice)), 0 * self.one)
                if self.generates(x, target):
                    return x
            bound *= 2

    def _definite_norm_generator(self, lattice, g, places, units):
        r"""Return `x` in ``lattice`` with `\mathrm{nrd}(x) = g' u`, `g'` a totally positive generator and `u` a totally positive unit class,
        or ``None``: the positive definite `\mathrm{Tr}_{K/Q} \mathrm{nrd}` takes the value `\mathrm{Tr}(g' u)` there, so the enumeration to
        that bound decides (Kirschmer-Voight, Sec. 6)."""
        K, _embed = self._center()
        positive = [g * u for u in units if all(phi(g * u) > 0 for phi in places)]
        if not positive:
            return None
        generator = positive[0]
        trace = (lambda c: QQ(c)) if K is QQ else (lambda c: QQ(K(c).trace()))

        def nrd(x):
            t = self._k_matrix(x).trace() / 2
            return (t * t - self._k_matrix(x * x).trace() / 2) / 2

        q = lambda x: trace(nrd(x))
        gram = matrix(QQ, [[(q(x + y) - q(x) - q(y)) / 2 for y in lattice] for x in lattice])
        for u in units:
            if not all(phi(u) > 0 for phi in places):
                continue
            norm = generator * u
            for v, _value in _short_vectors(gram, trace(norm)):
                x = sum((ZZ(c) * b for c, b in zip(v, lattice)), 0 * self.one)
                if nrd(x) == norm:
                    return x
        return None
