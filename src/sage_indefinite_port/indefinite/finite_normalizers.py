def _frame_matrix(lattice, isometry):
    return matrix(QQ, [[int(c) for c in isometry(g)] for g in lattice.module_generators()])


def _key(m):
    return tuple(m.list())


def _group_elements(generators):
    identity = matrix.identity(QQ, generators[0].nrows())
    elements = {_key(identity): identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in generators:
            following = current * generator
            if _key(following) not in elements:
                elements[_key(following)] = following
                frontier.append(following)
    return tuple(elements.values())


def _automorphisms(generators):
    r"""Yield the tuples `(\varphi(F_1), \dots, \varphi(F_s))` for `\varphi \in \mathrm{Aut}(H)`.

    A tuple of images defines an automorphism exactly when the assignment along a spanning
    tree of the Cayley graph is a well-defined bijective homomorphism.
    """
    elements = _group_elements(generators)
    identity = matrix.identity(QQ, generators[0].nrows())
    for images in product(elements, repeat=len(generators)):
        assignment = {_key(identity): identity}
        frontier = [identity]
        consistent = True
        while frontier and consistent:
            current = frontier.pop()
            source_image = assignment[_key(current)]
            for generator, image in zip(generators, images, strict=True):
                following = current * generator
                moved = source_image * image
                known = assignment.get(_key(following))
                if known is None:
                    assignment[_key(following)] = moved
                    frontier.append(following)
                elif known != moved:
                    consistent = False
                    break
        if consistent and len(set(_key(value) for value in assignment.values())) == len(elements):
            yield images


def _saturated_kernel(rows):
    return matrix(ZZ, rows).left_kernel().basis_matrix().change_ring(QQ)


def _components(gram, isometries):
    r"""Return the sign vectors and bases of the nonzero `L_\epsilon`, then a basis of `R`."""
    rank = gram.nrows()
    identity = matrix.identity(QQ, rank)
    pieces = []
    for signs in product((1, -1), repeat=len(isometries)):
        stacked = matrix.block([[F - sign * identity for F, sign in zip(isometries, signs, strict=True)]], subdivide=False)
        basis = _saturated_kernel(stacked)
        if basis.nrows():
            pieces.append((signs, basis))
    scalar = matrix.block([[basis] for _signs, basis in pieces], subdivide=False) if pieces else matrix(QQ, 0, rank)
    rest = matrix(ZZ, scalar * gram).right_kernel().basis_matrix().change_ring(QQ)
    return pieces, rest


def _classes(gram, start, generators):
    r"""Return `\{s M_0\}` for `s` in the group generated by ``generators``, one per class on `S^\vee/S`."""
    dual = gram.inverse()
    key = lambda m: tuple(c - c.floor() for c in (dual * m).list())
    identity = matrix.identity(QQ, gram.nrows())
    seen = {key(identity * start): identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for step in generators:
            following = current * step
            if key(following * start) not in seen:
                seen[key(following * start)] = following
                frontier.append(following)
    return tuple(s * start for s in seen.values())


def _abstract(gram):
    return Lattices(ZZ)([[int(c) for c in row] for row in gram])


def _component_isometry(gram, target_gram):
    r"""Return the matrix of an isometry between two Gram lattices, or ``None``."""
    source, target = _abstract(gram), _abstract(target_gram)
    morphisms = source.Isom(target)
    if morphisms.is_empty() is True:
        return None
    witness = morphisms.an_element()
    return matrix(QQ, [[int(c) for c in witness(g)] for g in source.module_generators()])


def _orthogonal_generators(gram):
    abstract = _abstract(gram)
    frame = tuple(abstract.module_generators())
    return tuple(matrix(QQ, [[int(c) for c in s(g)] for g in frame]) for s in abstract.O().group_generators())


class FiniteSubgroupNormalizer:
    r"""`N_{O(L)}(H)` and `C_{O(L)}(H)` for a finite `H \le O(L)`."""

    def __init__(self, lattice, generators):
        self.lattice = lattice
        self.frame = tuple(lattice.module_generators())
        self.gram = matrix(QQ, [[int(lattice.b(x, y)) for y in self.frame] for x in self.frame])
        self.generators = tuple(generators)
        self.matrices = tuple(_frame_matrix(lattice, F) for F in self.generators)
        self.pieces, self.rest = _components(self.gram, self.matrices)
        self.rest_definite = not self.rest.nrows() or _abstract(self._gram_of(self.rest)).is_definite()
        self.basis = matrix.block([[basis] for _signs, basis in self.pieces] + [[self.rest]], subdivide=False)
        self.inverse = self.basis.inverse()

    def _gram_of(self, rows):
        return rows * self.gram * rows.transpose()

    def _on_rest(self, F):
        return self.rest.solve_left(self.rest * F)

    def _rest_commutant(self):
        r"""Return the commutant of `H` on `R`, in column convention: `F_{col} = F^t`."""
        gram = matrix(ZZ, self._gram_of(self.rest))
        return IsometryCommutant(gram, [matrix(ZZ, self._on_rest(F)).transpose() for F in self.matrices])

    def _rest_centralizer(self):
        r"""Return generators of `C_{O(R)}(H)` on `R`, in its basis and row convention."""
        if self.rest_definite:
            return self._rest_twisted(self.matrices)
        return tuple(matrix(QQ, g).transpose() for g in centralizer_generators(self._rest_commutant()))

    def _rest_choices(self, images):
        r"""Return equivariant isometries `h` of `R` with `F h = h \varphi(F)`, one per discriminant class.

        For indefinite `R` they are `C_{O(R)}(H) h_0` for one transporter `h_0`. In column convention
        `t = h^t` satisfies `t F^t = \varphi(F)^t t` and `t^t B t = B`.
        """
        if not self.rest.nrows():
            return (matrix(QQ, 0, 0),)
        if self.rest_definite:
            return self._rest_twisted(images)
        gram = self._gram_of(self.rest)
        targets = tuple(self._on_rest(T) for T in images)
        if all(self._on_rest(F) == T for F, T in zip(self.matrices, targets, strict=True)):
            start = matrix.identity(QQ, self.rest.nrows())
        else:
            commutant = self._rest_commutant()
            columns = tuple(matrix(ZZ, T).transpose() for T in targets)
            witness = equivariant_transporter(commutant, matrix(ZZ, gram), columns)
            if witness is None:
                return ()
            start = matrix(QQ, witness).transpose()
        return _classes(gram, start, self._rest_centralizer())

    def _rest_twisted(self, images):
        r"""Return the matrices on `R` (in its basis) of all `h \in O(R)` with `F h = h \varphi(F)`, for definite `R`."""
        if not self.rest.nrows():
            return (matrix(QQ, 0, 0),)
        rest_lattice = _abstract(self._gram_of(self.rest))
        frame = tuple(rest_lattice.module_generators())
        sources = tuple(self._on_rest(F) for F in self.matrices)
        targets = tuple(self._on_rest(F) for F in images)
        result = []
        for element in rest_lattice.O():
            h = matrix(QQ, [[int(c) for c in element(g)] for g in frame])
            if all(F * h == h * T for F, T in zip(sources, targets, strict=True)):
                result.append(h)
        return tuple(result)

    def _assemble(self, blocks, target_basis):
        return self.inverse * matrix.block_diagonal(list(blocks), subdivide=False) * target_basis

    def _isometry(self, moved):
        labels = tuple(self.lattice.module_generating_set())
        images = {
            label: sum(
                (self.lattice.scalar_multiple(int(c), g) for c, g in zip(moved.row(i), self.frame, strict=True)),
                self.lattice.zero(),
            )
            for i, label in enumerate(labels)
        }
        return self.lattice.O()(images)

    def twisted_transporter(self, images):
        r"""Return `g \in O(L)` with `g F_i g^{-1} = ` ``images[i]``, or ``None``."""
        return self._twisted(tuple(_frame_matrix(self.lattice, F) for F in images))

    def _twisted(self, image_matrices):
        target_pieces, _rest = _components(self.gram, image_matrices)
        targets = dict((signs, basis) for signs, basis in target_pieces)
        choices = []
        target_rows = []
        for signs, basis in self.pieces:
            target = targets.get(signs)
            if target is None or target.nrows() != basis.nrows():
                return None
            start = _component_isometry(self._gram_of(basis), self._gram_of(target))
            if start is None:
                return None
            choices.append(_classes(self._gram_of(basis), start, _orthogonal_generators(self._gram_of(basis))))
            target_rows.append(target)
        choices.append(self._rest_choices(image_matrices))
        target_basis = matrix.block([[rows] for rows in target_rows] + [[self.rest]], subdivide=False)
        for blocks in product(*choices):
            moved = self._assemble(blocks, target_basis)
            if moved.denominator() != 1:
                continue
            assert all(F * moved == moved * T for F, T in zip(self.matrices, image_matrices, strict=True))
            return self._isometry(moved)
        return None

    def centralizer_generators(self):
        r"""Return generators of `C_{O(L)}(H)`.

        `\prod O(L_\epsilon) \times C_{O(R)}(H)` acts on `L_Q`, and `C_{O(L)}(H)` is the
        finite-index subgroup of elements that map `L` into `L`; Schreier generators follow.
        """
        sizes = [basis.nrows() for _signs, basis in self.pieces] + [self.rest.nrows()]
        offsets = [sum(sizes[:i]) for i in range(len(sizes))]
        total = sum(sizes)

        def embed(index, block):
            result = matrix.identity(QQ, total)
            result.set_block(offsets[index], offsets[index], block)
            return result

        generators = []
        for index, (_signs, basis) in enumerate(self.pieces):
            generators.extend(embed(index, s) for s in _orthogonal_generators(self._gram_of(basis)))
        if self.rest.nrows():
            generators.extend(embed(len(self.pieces), h) for h in self._rest_centralizer())
        generators.append(matrix.identity(QQ, total))
        integral = lambda m: (self.inverse * m * self.basis).denominator() == 1
        schreier, _index = finite_preimage_generators(generators, lambda m: m, integral)
        result = [self._isometry(self.inverse * m * self.basis) for m in schreier]
        return tuple(result) if result else (self.lattice.O().one(),)

    def normalizer_generators(self):
        r"""Return generators of `N_{O(L)}(H)`: `C(H)` and one transporter for each realized `\varphi`."""
        result = list(self.centralizer_generators())
        for images in _automorphisms(self.matrices):
            witness = self._twisted(images)
            if witness is not None:
                result.append(witness)
        return tuple(result)


def _column_matrix(lattice, isometry):
    return matrix(ZZ, [[int(c) for c in isometry(g)] for g in lattice.module_generators()]).transpose()


def _from_columns(lattice, columns):
    frame = tuple(lattice.module_generators())
    images = {
        label: sum(
            (lattice.scalar_multiple(int(c), g) for c, g in zip(columns.column(j), frame, strict=True)),
            lattice.zero(),
        )
        for j, label in enumerate(lattice.module_generating_set())
    }
    return lattice.O()(images)


def has_finite_order(columns):
    r"""Decide whether an integer matrix has finite order: its minimal polynomial is squarefree with cyclotomic factors."""
    polynomial = columns.change_ring(QQ).minimal_polynomial().change_ring(ZZ)
    factors = polynomial.factor()
    return all(e == 1 and f.is_cyclotomic() for f, e in factors)


def infinite_cyclic_normalizer(lattice, isometry):
    r"""Return ``(centralizer_generators, inversion)`` for `N_{O(L)}(\langle f \rangle)`, `f` of infinite order.

    ``inversion`` is `t` with `t f t^{-1} = f^{-1}`, or ``None`` as a proof that no element inverts `f`;
    the normalizer is then `C(f)`.
    """
    frame = tuple(lattice.module_generators())
    gram = matrix(ZZ, [[int(lattice.b(x, y)) for y in frame] for x in frame])
    columns = _column_matrix(lattice, isometry)
    assert not has_finite_order(columns), f"{isometry} has finite order"
    commutant = IsometryCommutant(gram, [columns])
    centralizer = tuple(_from_columns(lattice, g) for g in centralizer_generators(commutant))
    witness = equivariant_transporter(commutant, gram, [matrix(ZZ, columns.inverse())])
    inversion = None if witness is None else _from_columns(lattice, witness)
    assert inversion is None or inversion * isometry == ~isometry * inversion
    return centralizer, inversion


def _joint_characters(columns):
    r"""Return the joint eigencharacters `(\lambda_1, \dots, \lambda_m)` of commuting semisimple matrices with their multiplicities."""
    size = columns[0].nrows()
    spaces = [(QQbar**size, ())]
    for F in columns:
        G = F.change_ring(QQbar)
        roots = [r for r, _e in F.charpoly().roots(QQbar)]
        spaces = [(V.intersection((G - r).right_kernel()), chi + (r,)) for V, chi in spaces for r in roots]
        spaces = [(V, chi) for V, chi in spaces if V.dimension() > 0]
    assert sum(V.dimension() for V, _chi in spaces) == size, "the isometries are not simultaneously diagonalizable"
    return [(chi, V.dimension()) for V, chi in spaces]


def _power_word(columns, row):
    result = identity_matrix(QQ, columns[0].nrows())
    for F, e in zip(columns, row, strict=True):
        result = result * F.change_ring(QQ) ** int(e)
    return matrix(ZZ, result)


def _candidate_automorphisms(columns):
    r"""Return the `\Phi \ne 1` in `GL_m(Z)` that permute the multiset `\ell(X)` of the joint characters of `H`."""
    field = RealField(200)
    tolerance = field(2) ** -120
    m = len(columns)
    distinct = []
    for chi, multiplicity in _joint_characters(columns):
        point = vector(field, [field(abs(value)).log() for value in chi])
        known = next((entry for entry in distinct if max(abs(c) for c in entry[0] - point) < tolerance), None)
        if known is None:
            distinct.append([point, multiplicity])
        else:
            known[1] += multiplicity
    basis = next(
        (
            rows
            for rows in combinations(range(len(distinct)), m)
            if abs(matrix(field, [distinct[i][0] for i in rows]).det()) > tolerance
        ),
        None,
    )
    if basis is None:
        raise NotImplementedError(
            f"the logarithms of the joint characters of {columns} span less than R^{m}: H is not free abelian on its "
            f"generators, so N(H) / C(H) is not decided by its permutation of characters (#50)"
        )
    inverse = matrix(field, [distinct[i][0] for i in basis]).transpose().inverse()
    result = []
    for targets in product(range(len(distinct)), repeat=m):
        approximate = matrix(field, [distinct[j][0] for j in targets]).transpose() * inverse
        candidate = matrix(ZZ, m, m, [c.round() for c in approximate.list()])
        if max(abs(c - d) for c, d in zip(approximate.list(), candidate.list())) > tolerance:
            continue
        if candidate.det() not in (1, -1) or candidate == identity_matrix(ZZ, m):
            continue
        permutes = all(
            any(
                multiplicity == other and max(abs(c) for c in candidate.change_ring(field) * point - image) < tolerance
                for image, other in distinct
            )
            for point, multiplicity in distinct
        )
        if permutes and all(str(candidate) != str(known) for known in result):
            result.append(candidate)
    return result


def free_abelian_normalizer(lattice, generators):
    r"""Return generators of `N_{O(L)}(H)` for `H` free abelian on commuting semisimple isometries of infinite order."""
    frame = tuple(lattice.module_generators())
    gram = matrix(ZZ, [[int(lattice.b(x, y)) for y in frame] for x in frame])
    columns = tuple(_column_matrix(lattice, g) for g in generators)
    assert all(F * G == G * F for F in columns for G in columns), "the isometries do not commute"
    if not all(F.change_ring(QQ).minimal_polynomial().is_squarefree() for F in columns):
        raise NotImplementedError(
            f"the commuting isometries {columns} are not all semisimple: N(H) / C(H) is not decided by the joint "
            f"characters (#50)"
        )
    commutant = IsometryCommutant(gram, columns)
    result = [_from_columns(lattice, g) for g in centralizer_generators(commutant)]
    for candidate in _candidate_automorphisms(columns):
        images = [_power_word(columns, row) for row in candidate.rows()]
        if any(F.charpoly() != image.charpoly() for F, image in zip(columns, images, strict=True)):
            continue
        witness = equivariant_transporter(commutant, gram, images)
        if witness is None:
            continue
        assert all(witness * F == image * witness for F, image in zip(columns, images, strict=True))
        result.append(_from_columns(lattice, witness))
    return tuple(result)


_FIELD = RealField(200)
_TOLERANCE = _FIELD(2) ** -100


class _Characters:
    r"""The joint eigenlines of commuting semisimple integer matrices and the logarithmic embedding `\ell`.

    For each joint eigenspace `V_\chi` one vector `v_\chi` is kept; `\ell(g) = (\log |\lambda_\chi(g)|)_\chi` for an
    element `g` acting on `v_\chi` by `\lambda_\chi(g)`. On a group of commuting semisimple integral matrices `\ell` is a
    homomorphism whose kernel consists of the elements of finite order (Kronecker), so it is injective on a
    torsion-free group, and its values only select candidates that are then verified exactly.
    """

    def __init__(self, columns):
        size = columns[0].nrows()
        spaces = [QQbar**size]
        for F in columns:
            G = F.change_ring(QQbar)
            roots = [r for r, _e in F.charpoly().roots(QQbar)]
            spaces = [V.intersection((G - r).right_kernel()) for V in spaces for r in roots]
            spaces = [V for V in spaces if V.dimension() > 0]
        assert sum(V.dimension() for V in spaces) == size, f"{columns} are not simultaneously diagonalizable"
        self.vectors = [V.basis()[0] for V in spaces]

    def log_vector(self, g):
        G = g.change_ring(QQbar)
        values = []
        for v in self.vectors:
            index = next(i for i, c in enumerate(v) if c != 0)
            value = (G * v)[index] / v[index]
            assert value != 0
            values.append(_FIELD(abs(value)).log())
        return vector(_FIELD, values)


class _FreeAbelian:
    r"""A basis of the free abelian group generated by commuting semisimple integer matrices, and exact exponents.

    The coordinates of `\ell(g_i)` in a maximal independent subset are rational, since the image of a torsion-free
    finitely generated abelian group under `\ell` is a lattice; the Hermite form of their common-denominator matrix,
    with its unimodular transformation, gives a basis as words in the `g_i` (Cohen, *A Course in Computational
    Algebraic Number Theory*, Alg. 2.4.5). Every claimed basis word and exponent vector is verified by exact products,
    so a torsion element (`\ell = 0`, `g \ne 1`) fails loudly.
    """

    def __init__(self, elements):
        elements = [matrix(ZZ, g) for g in elements]
        self.size = elements[0].nrows()
        self.characters = _Characters(elements)
        logs = [self.characters.log_vector(g) for g in elements]
        independent, orthonormal = [], []
        for v in logs:
            residual = v - sum((v.dot_product(q) * q for q in orthonormal), vector(_FIELD, len(v)))
            if residual.norm() > _FIELD(2) ** -60:
                independent.append(v)
                orthonormal.append(residual / residual.norm())
        self.independent = matrix(_FIELD, independent)
        coordinates = [self._coordinates(v) for v in logs]
        denominator = lcm([c.denominator() for row in coordinates for c in row] + [1])
        integral = matrix(ZZ, [[denominator * c for c in row] for row in coordinates])
        echelon, transformation = integral.echelon_form(transformation=True)
        rank = len(independent)
        self.echelon = echelon.matrix_from_rows(range(rank))
        self.denominator = denominator
        self.basis = tuple(_power_word(elements, row) for row in transformation.rows()[:rank])
        for g in elements:
            assert self.exponents(g) is not None, f"{g} is not a word in the claimed basis: the group has torsion"

    def _coordinates(self, v):
        M = self.independent
        real = (M * M.transpose()).inverse() * (M * v)
        return [QQ(c.nearby_rational(max_error=_FIELD(2) ** -80)) for c in real]

    def exponents(self, g):
        r"""Return `e \in Z^m` with `g = \prod b_i^{e_i}`, or ``None`` when `g` is not in the group."""
        g = matrix(ZZ, g)
        if not self.basis:
            return vector(ZZ, []) if g == identity_matrix(ZZ, self.size) else None
        target = vector(QQ, [self.denominator * c for c in self._coordinates(self.characters.log_vector(g))])
        try:
            solution = self.echelon.change_ring(QQ).solve_left(target)
        except ValueError:
            return None
        if solution.denominator() != 1:
            return None
        exponents = vector(ZZ, solution)
        return exponents if _power_word(self.basis, exponents) == g else None

    def action(self, g):
        r"""Return the matrix `\rho(g)` with `g t^e g^{-1} = t^{\rho(g) e}`, columns the exponents of `g b_i g^{-1}`."""
        g = matrix(ZZ, g)
        inverse = matrix(ZZ, g.inverse())
        columns = [self.exponents(g * b * inverse) for b in self.basis]
        assert all(c is not None for c in columns), f"{g} does not normalize the abelian subgroup {self.basis}"
        return matrix(ZZ, columns).transpose() if columns else matrix(ZZ, 0, 0)


def _congruence_kernel(columns, prime=3):
    r"""Return Schreier generators of `H \cap \Gamma(p)`, of finite index; torsion-free for `p \ge 3` (Minkowski)."""
    field = GF(prime)
    reduce = lambda g: matrix(field, g)
    found, _index = finite_preimage_generators(list(columns), reduce, lambda m: m.is_one())
    return [matrix(ZZ, g) for g in found]


def _kernel(columns, action):
    found, _index = finite_preimage_generators(list(columns), action, lambda m: m.is_one())
    return [matrix(ZZ, g) for g in found]


def _translation_subgroup(columns):
    r"""Return the unique maximal abelian normal subgroup `T^*` of finite index of `H`, as a :class:`_FreeAbelian`.

    `T_0 = H \cap \Gamma(3)` is torsion-free of finite index. When it is abelian, `H` acts on it through the finite
    image `\rho_{T_0}(H) \le GL(T_0)`, and `T^* = C_H(T_0) = \ker \rho_{T_0}`. When `T^*` is abelian and torsion-free,
    every `h \in C_H(T^*)` fixes `T^* \otimes Q` and so centralizes `T_0`; hence `C_H(T^*) = T^*`, any abelian `T_1` of
    finite index lies in `C_H(T_1 \cap T^*) = T^*`, and `T^*` is characteristic (as for the translation subgroup of a
    crystallographic group: Charlap, *Bieberbach Groups and Flat Manifolds*, I.4).
    """
    kernel = _congruence_kernel(columns)
    if not all(x * y == y * x for x in kernel for y in kernel):
        raise NotImplementedError(
            f"the congruence kernel of the infinite group generated by {columns} is not abelian: H is not virtually "
            f"abelian, and its normalizer is decided by congruence_normalizer_generators once a level m with "
            f"H containing Gamma_L(m) is supplied; finite index of a finitely generated subgroup is not decidable from "
            f"its generators (Grunewald-Segal, Ann. of Math. 112 (1980); Sarnak, Notes on thin matrix groups) (#50)"
        )
    if not all(F.change_ring(QQ).minimal_polynomial().is_squarefree() for F in kernel):
        raise NotImplementedError(
            f"the abelian congruence kernel of the group generated by {columns} is not semisimple: N(H) is not decided "
            f"by the joint characters (#50)"
        )
    first = _FreeAbelian(kernel)
    translations = _kernel(columns, first.action)
    if not all(x * y == y * x for x in translations for y in translations):
        raise NotImplementedError(
            f"the centralizer of the congruence kernel in the group generated by {columns} is not abelian: the "
            f"maximal abelian normal subgroup is not self-centralizing, and N(H) needs the Grunewald-Segal "
            f"normalizer algorithm (#50)"
        )
    return _FreeAbelian([*translations, *first.basis])


def _fp_relators(images):
    r"""Return the relators of a presentation of the finite matrix group on ``images``, as letter lists (GAP)."""
    generators = [libgap(matrix(ZZ, g)) for g in images]
    isomorphism = libgap.Group(generators).IsomorphismFpGroupByGenerators(generators)
    return [[int(c) for c in relator.LetterRepAssocWord()] for relator in isomorphism.Range().RelatorsOfFpGroup()]


def _word(columns, letters):
    result = identity_matrix(ZZ, columns[0].nrows())
    for letter in letters:
        g = columns[abs(letter) - 1]
        result = result * (g if letter > 0 else matrix(ZZ, g.inverse()))
    return result


def virtually_abelian_normalizer(lattice, generators):
    r"""Return generators of `N_{O(L)}(H)` for `H` infinite with a semisimple abelian maximal normal subgroup `T^*`.

    `T^*` (:func:`_translation_subgroup`) is characteristic, so `N(H) \le N(T^*)`, and `g \in N(H)` induces
    `\alpha \in \mathrm{Aut}(H)` with `\alpha|_{T^*} = \Phi` among the finitely many candidates permuting the joint
    characters (:func:`_candidate_automorphisms`). `Q = H / T^*` acts faithfully on `T^*` by `\rho`, and
    `\rho(\alpha(h)) = \Phi \rho(h) \Phi^{-1}`, so `\Phi` must normalize `\rho(Q)`, and `\alpha(h_j) = t^{\tau_j} r_j` for a
    fixed lift `r_j`. `H` is presented by `T^*`, the `h_j`, the conjugation relations (preserved automatically) and
    the lifted relators `w(h) = t^{c_w}` of `Q`, so `\alpha` is a homomorphism exactly when the `\tau_j` solve the
    linear system `w(t^{\tau} r) = t^{\Phi c_w}` (Fox calculus: Brown, *Cohomology of Groups*, IV.2). Inner
    automorphisms by `T^*` shift `\tau_j` by `(1 - \rho(r_j)) \sigma`, and the solutions modulo these form the finite
    group `H^1(Q, T^*)` up to a translate. One twisted transporter of the commutant of `T^* \cup \{h_j\}`
    (:func:`commutant_groups.equivariant_transporter`, #54) decides each class, and `N(H)` is generated by `C(H)`,
    `H` and these transporters.
    """
    frame = tuple(lattice.module_generators())
    gram = matrix(ZZ, [[int(lattice.b(x, y)) for y in frame] for x in frame])
    columns = tuple(_column_matrix(lattice, g) for g in generators)
    torus = _translation_subgroup(columns)
    basis = torus.basis
    m = len(basis)
    assert m > 0, f"the group generated by {columns} is finite"
    one = identity_matrix(ZZ, gram.nrows())
    transversal = {torus.action(one).str(): one}
    frontier = [one]
    while frontier:
        current = frontier.pop()
        for h in columns:
            following = current * h
            key = torus.action(following).str()
            if key not in transversal:
                transversal[key] = following
                frontier.append(following)
    images = [torus.action(h) for h in columns]
    relators = _fp_relators(images)
    values = [torus.exponents(_word(columns, w)) for w in relators]
    assert all(v is not None for v in values), "a lifted relator of H / T* is not in T*"
    commutant = IsometryCommutant(gram, [*basis, *columns])
    result = [_from_columns(lattice, g) for g in centralizer_generators(commutant)]
    result.extend(generators)
    candidates = [identity_matrix(ZZ, m), *(Phi.transpose() for Phi in _candidate_automorphisms(basis))]
    s = len(columns)
    for P in candidates:
        lifts = []
        for image in images:
            moved = P * image * P.inverse()
            if moved.denominator() != 1 or matrix(ZZ, moved).str() not in transversal:
                break
            lifts.append(transversal[matrix(ZZ, moved).str()])
        if len(lifts) != s:
            continue
        rows, targets = [], []
        for w, c in zip(relators, values, strict=True):
            linear = matrix(ZZ, m, m * s)
            g = one
            for letter in w:
                j = abs(letter) - 1
                if letter > 0:
                    linear.set_block(0, m * j, linear.submatrix(0, m * j, m, m) + torus.action(g))
                    g = g * lifts[j]
                else:
                    inverse = matrix(ZZ, lifts[j].inverse())
                    linear.set_block(0, m * j, linear.submatrix(0, m * j, m, m) - torus.action(g) * torus.action(inverse))
                    g = g * inverse
            constant = torus.exponents(g)
            assert constant is not None
            rows.append(linear)
            targets.extend(P * c - constant)
        system = matrix.block([[r] for r in rows], subdivide=False) if rows else matrix(ZZ, 0, m * s)
        particular = _integer_solution(system, vector(ZZ, targets))
        if particular is None:
            continue
        kernel = system.right_kernel_matrix()
        coboundary = matrix.block([[identity_matrix(ZZ, m) - torus.action(r)] for r in lifts], subdivide=False)
        if kernel.nrows():
            coordinates = matrix(ZZ, kernel.change_ring(QQ).solve_left(coboundary.transpose().change_ring(QQ)))
            diagonal, _left, right = coordinates.smith_form()
            sizes = [diagonal[i, i] if i < diagonal.nrows() else 0 for i in range(kernel.nrows())]
            assert all(d != 0 for d in sizes), "H^1(H / T*, T*) is infinite: the relators do not present H / T*"
            inverse = right.inverse()
            classes = [
                particular + (vector(ZZ, point) * inverse) * kernel for point in product(*(range(abs(d)) for d in sizes))
            ]
        else:
            classes = [particular]
        torus_targets = [_power_word(basis, P.column(i)) for i in range(m)]
        for tau in classes:
            h_targets = [_power_word(basis, tau[m * j : m * (j + 1)]) * lifts[j] for j in range(s)]
            targets_all = [*torus_targets, *h_targets]
            witness = equivariant_transporter(commutant, gram, targets_all)
            if witness is None:
                continue
            assert all(witness * F == T * witness for F, T in zip([*basis, *columns], targets_all, strict=True))
            result.append(_from_columns(lattice, witness))
    result.extend(_from_columns(lattice, t) for t in basis)
    return tuple(result)


class _ResidueAction:
    r"""The faithful right action `v \mapsto v \bar g` of `GL_n(Z/m)` on the `m^n` row vectors, as GAP permutations.

    An element is read back from the images of the unit vectors, so permutations of the image group and reduced
    matrices correspond exactly.
    """

    def __init__(self, size, level):
        self.ring = Zmod(level)
        self.points = [vector(self.ring, p) for p in product(range(level), repeat=size)]
        for p in self.points:
            p.set_immutable()
        self.index = {p: i for i, p in enumerate(self.points)}

    def permutation(self, columns):
        g = matrix(self.ring, columns).transpose()
        images = []
        for p in self.points:
            q = p * g
            q.set_immutable()
            images.append(self.index[q] + 1)
        return libgap.PermList(images)


def congruence_normalizer_generators(lattice, generators, level):
    r"""Return generators of `N_{O(L)}(H)` for the congruence subgroup `H = \langle` ``generators`` `\rangle \Gamma_L(m)`.

    `\Gamma_L(m) = \ker(O(L) \to GL(L / mL))` is normal in `O(L)`, so `H = \pi^{-1}(\pi(H))` for the reduction `\pi`
    modulo `m = ` ``level``, and `g \in O(L)` normalizes `H` exactly when `\pi(g)` normalizes the finite group `\pi(H)`:
    `N_{O(L)}(H) = \pi^{-1}(N_{\pi O(L)}(\pi H))`. This is the congruence case of the normalizer algorithm of
    Grunewald and Segal (*Some general algorithms II: Nilpotent groups* and *I: Arithmetic groups*, Ann. of Math. 112
    (1980), 531-583 and 585-617, \S 4): for `H` of finite index the normalizer is read off a finite quotient. The finite
    normalizer is computed by GAP on the faithful permutation action on `(Z/m)^n`, and its preimage in `O(L)` by
    Schreier generators over the generators of `O(L)` (``lattice.O().group_generators()``).

    The level is part of the input because `H \supseteq \Gamma_L(m)` cannot be decided from generators of `H` alone:
    whether a finitely generated subgroup of an arithmetic group has finite index is open in general (Sarnak, *Notes
    on thin matrix groups*, 2014, \S 1).
    """
    assert int(level) >= 2, f"the level {level} of a congruence subgroup is at least 2"
    frame = tuple(lattice.module_generators())
    action = _ResidueAction(len(frame), int(level))
    ambient = [_column_matrix(lattice, g) for g in lattice.O().group_generators()]
    one = action.permutation(identity_matrix(ZZ, len(frame)))
    image = libgap.Group([one, *(action.permutation(g) for g in ambient)])
    subgroup = libgap.Group([one, *(action.permutation(_column_matrix(lattice, g)) for g in generators)])
    assert libgap.IsSubgroup(image, subgroup), f"{generators} do not reduce into the image of O(L) modulo {level}"
    normalizer = libgap.Normalizer(image, subgroup)
    found, _index = finite_preimage_generators(ambient, action.permutation, lambda p: bool(libgap.IsSubset(normalizer, [p])))
    return tuple(_from_columns(lattice, matrix(ZZ, g)) for g in found)


def normalizer_generators(lattice, generators):
    r"""Return generators of `N_{O(L)}(H)` for `H = \langle` ``generators`` `\rangle`.

    A finite `H` is decided by :class:`FiniteSubgroupNormalizer`. One generator of infinite order
    is decided by :func:`infinite_cyclic_normalizer`. Commuting generators are decided by
    :func:`free_abelian_normalizer`, which raises outside free abelian semisimple `H`. A non-abelian
    infinite `H` is decided by :func:`virtually_abelian_normalizer`, which raises a precise error when `H` is not
    virtually abelian with a semisimple self-centralizing translation subgroup; a congruence `H` that is not virtually
    abelian is decided by :func:`congruence_normalizer_generators` from its level.
    """
    generators = tuple(generators)
    columns = tuple(_column_matrix(lattice, g) for g in generators)
    if all(has_finite_order(m) for m in columns):
        if MatrixGroup(list(columns)).is_finite():
            return FiniteSubgroupNormalizer(lattice, generators).normalizer_generators()
    if len(generators) == 1:
        centralizer, inversion = infinite_cyclic_normalizer(lattice, generators[0])
        return centralizer if inversion is None else (*centralizer, inversion)
    if all(F * G == G * F for F in columns for G in columns):
        return free_abelian_normalizer(lattice, generators)
    return virtually_abelian_normalizer(lattice, generators)
