r"""Normalizers and centralizers of finite subgroups of `O(L)` for indefinite `L` (#50).

Let `H = \langle F_1, \dots, F_s \rangle` be finite. For a sign vector `\epsilon`, let
`L_\epsilon = \{x : F_i x = \epsilon_i x\}`, a primitive sublattice on which `H` acts by scalars,
and let `R` be the orthogonal complement of their sum. When `R` is definite, `O(R)` is finite and
is enumerated. When `R` is indefinite, the equivariant isometries of `R` are a coset of the
centralizer `C_{O(R)}(H)`, computed by the commutant algebra of `H` on `R`
(:class:`sage_extensions.algebras.isometry_commutant.IsometryCommutant`), and a transporter;
only the discriminant classes of that coset enter the gluing.

`N(H) / C(H)` embeds in `\mathrm{Aut}(H)`. For `\varphi \in \mathrm{Aut}(H)`, an isometry `g` with
`g F g^{-1} = \varphi(F)` for all `F \in H` maps `L_\epsilon` onto
`L'_\epsilon = \{x : \varphi(F_i) x = \epsilon_i x\}` by an arbitrary isometry, and maps `R` to `R`
with `g F = \varphi(F) g`. Conversely such component maps define `g` on
`\bigoplus L_\epsilon \oplus R`, and `g \in O(L)` exactly when it maps `L` into `L`. That depends
only on the classes of the component maps on the finite discriminant groups (Nikulin,
*Integral symmetric bilinear forms*, Prop. 1.5.1), so finitely many classes decide.

Matrices act on coefficient rows from the right: `p \mapsto p M`, so `g \circ F` has matrix `F G`.

For `f` of infinite order, `\mathrm{Aut}(\langle f \rangle) = \{\pm 1\}`, so `N(\langle f \rangle)` is `C(f)`,
extended by one `t` with `t f t^{-1} = f^{-1}` when such `t` exists. Both come from the commutant of
`f` (:mod:`commutant_groups`, #54), in column convention: the columns of `f` are the images of the
module generators.

For `H` free abelian on commuting semisimple `F_1, \dots, F_m` of infinite order, `g F_i g^{-1} = \varphi(F_i)`
with `\varphi(F_i) = \prod_j F_j^{\Phi_{ij}}`, `\Phi \in GL_m(Z)`. A joint eigencharacter `\chi` of `H` has the
vector `\ell(\chi) = (\log |\chi(F_i)|)_i`, and the characters of `\varphi(F)` are `\chi \circ \varphi`, so `\Phi`
permutes the finite multiset `\ell(X)` of the joint characters. By Kronecker's theorem an integral matrix with
all eigenvalues of modulus one is of finite order when semisimple, so `\ell` is injective on `H` exactly when
`\ell(X)` spans `R^m`; then `\Phi` is determined by the images of `m` independent vectors of `\ell(X)`, and only
finitely many `\Phi` are candidates. Each candidate is decided by the twisted transporter of the commutant
(:func:`commutant_groups.equivariant_transporter`), and `N(H)` is generated by `C(H)` and one transporter for
each realized `\varphi`. The characters are exact algebraic numbers; their logarithms at 200 bits only
select the candidate `\Phi`, whose action is then verified exactly.
"""

