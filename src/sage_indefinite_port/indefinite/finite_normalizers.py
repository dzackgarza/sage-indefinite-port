def _frame_matrix(lattice, isometry):
    return matrix(QQ, [[int(c) for c in isometry(g)] for g in lattice.module_generators()])


def _key(m):
    return tuple(m.list())


def _group_elements(generators):
    identity = matrix.identity(QQ, generators[0].nrows())
    elements = {_key(identity): identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in generators:
            following = current * generator
            if _key(following) not in elements:
                elements[_key(following)] = following
                frontier.append(following)
    return tuple(elements.values())


def _automorphisms(generators):
    r"""Yield the tuples `(\varphi(F_1), \dots, \varphi(F_s))` for `\varphi \in \mathrm{Aut}(H)`.

    A tuple of images defines an automorphism exactly when the assignment along a spanning
    tree of the Cayley graph is a well-defined bijective homomorphism.
    """
    elements = _group_elements(generators)
    identity = matrix.identity(QQ, generators[0].nrows())
    for images in product(elements, repeat=len(generators)):
        assignment = {_key(identity): identity}
        frontier = [identity]
        consistent = True
        while frontier and consistent:
            current = frontier.pop()
            source_image = assignment[_key(current)]
            for generator, image in zip(generators, images, strict=True):
                following = current * generator
                moved = source_image * image
                known = assignment.get(_key(following))
                if known is None:
                    assignment[_key(following)] = moved
                    frontier.append(following)
                elif known != moved:
                    consistent = False
                    break
        if consistent and len(set(_key(value) for value in assignment.values())) == len(elements):
            yield images


def _saturated_kernel(rows):
    return matrix(ZZ, rows).left_kernel().basis_matrix().change_ring(QQ)


def _components(gram, isometries):
    r"""Return the sign vectors and bases of the nonzero `L_\epsilon`, then a basis of `R`."""
    rank = gram.nrows()
    identity = matrix.identity(QQ, rank)
    pieces = []
    for signs in product((1, -1), repeat=len(isometries)):
        stacked = matrix.block([[F - sign * identity for F, sign in zip(isometries, signs, strict=True)]], subdivide=False)
        basis = _saturated_kernel(stacked)
        if basis.nrows():
            pieces.append((signs, basis))
    scalar = matrix.block([[basis] for _signs, basis in pieces], subdivide=False) if pieces else matrix(QQ, 0, rank)
    rest = matrix(ZZ, scalar * gram).right_kernel().basis_matrix().change_ring(QQ)
    return pieces, rest


def _classes(gram, start, generators):
    r"""Return `\{s M_0\}` for `s` in the group generated by ``generators``, one per class on `S^\vee/S`."""
    dual = gram.inverse()
    key = lambda m: tuple(c - c.floor() for c in (dual * m).list())
    identity = matrix.identity(QQ, gram.nrows())
    seen = {key(identity * start): identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for step in generators:
            following = current * step
            if key(following * start) not in seen:
                seen[key(following * start)] = following
                frontier.append(following)
    return tuple(s * start for s in seen.values())


def _abstract(gram):
    return Lattices(ZZ)([[int(c) for c in row] for row in gram])


def _component_isometry(gram, target_gram):
    r"""Return the matrix of an isometry between two Gram lattices, or ``None``."""
    source, target = _abstract(gram), _abstract(target_gram)
    morphisms = source.Isom(target)
    if morphisms.is_empty() is True:
        return None
    witness = morphisms.an_element()
    return matrix(QQ, [[int(c) for c in witness(g)] for g in source.module_generators()])


def _orthogonal_generators(gram):
    abstract = _abstract(gram)
    frame = tuple(abstract.module_generators())
    return tuple(matrix(QQ, [[int(c) for c in s(g)] for g in frame]) for s in abstract.O().group_generators())


class FiniteSubgroupNormalizer:
    r"""`N_{O(L)}(H)` and `C_{O(L)}(H)` for a finite `H \le O(L)`."""

    def __init__(self, lattice, generators):
        self.lattice = lattice
        self.frame = tuple(lattice.module_generators())
        self.gram = matrix(QQ, [[int(lattice.b(x, y)) for y in self.frame] for x in self.frame])
        self.generators = tuple(generators)
        self.matrices = tuple(_frame_matrix(lattice, F) for F in self.generators)
        self.pieces, self.rest = _components(self.gram, self.matrices)
        self.rest_definite = not self.rest.nrows() or _abstract(self._gram_of(self.rest)).is_definite()
        self.basis = matrix.block([[basis] for _signs, basis in self.pieces] + [[self.rest]], subdivide=False)
        self.inverse = self.basis.inverse()

    def _gram_of(self, rows):
        return rows * self.gram * rows.transpose()

    def _on_rest(self, F):
        return self.rest.solve_left(self.rest * F)

    def _rest_commutant(self):
        r"""Return the commutant of `H` on `R`, in column convention: `F_{col} = F^t`."""
        gram = matrix(ZZ, self._gram_of(self.rest))
        return IsometryCommutant(gram, [matrix(ZZ, self._on_rest(F)).transpose() for F in self.matrices])

    def _rest_centralizer(self):
        r"""Return generators of `C_{O(R)}(H)` on `R`, in its basis and row convention."""
        if self.rest_definite:
            return self._rest_twisted(self.matrices)
        return tuple(matrix(QQ, g).transpose() for g in centralizer_generators(self._rest_commutant()))

    def _rest_choices(self, images):
        r"""Return equivariant isometries `h` of `R` with `F h = h \varphi(F)`, one per discriminant class.

        For indefinite `R` they are `C_{O(R)}(H) h_0` for one transporter `h_0`. In column convention
        `t = h^t` satisfies `t F^t = \varphi(F)^t t` and `t^t B t = B`.
        """
        if not self.rest.nrows():
            return (matrix(QQ, 0, 0),)
        if self.rest_definite:
            return self._rest_twisted(images)
        gram = self._gram_of(self.rest)
        targets = tuple(self._on_rest(T) for T in images)
        if all(self._on_rest(F) == T for F, T in zip(self.matrices, targets, strict=True)):
            start = matrix.identity(QQ, self.rest.nrows())
        else:
            commutant = self._rest_commutant()
            columns = tuple(matrix(ZZ, T).transpose() for T in targets)
            witness = equivariant_transporter(commutant, matrix(ZZ, gram), columns)
            if witness is None:
                return ()
            start = matrix(QQ, witness).transpose()
        return _classes(gram, start, self._rest_centralizer())

    def _rest_twisted(self, images):
        r"""Return the matrices on `R` (in its basis) of all `h \in O(R)` with `F h = h \varphi(F)`, for definite `R`."""
        if not self.rest.nrows():
            return (matrix(QQ, 0, 0),)
        rest_lattice = _abstract(self._gram_of(self.rest))
        frame = tuple(rest_lattice.module_generators())
        sources = tuple(self._on_rest(F) for F in self.matrices)
        targets = tuple(self._on_rest(F) for F in images)
        result = []
        for element in rest_lattice.O():
            h = matrix(QQ, [[int(c) for c in element(g)] for g in frame])
            if all(F * h == h * T for F, T in zip(sources, targets, strict=True)):
                result.append(h)
        return tuple(result)

    def _assemble(self, blocks, target_basis):
        return self.inverse * matrix.block_diagonal(list(blocks), subdivide=False) * target_basis

    def _isometry(self, moved):
        labels = tuple(self.lattice.module_generating_set())
        images = {
            label: sum(
                (self.lattice.scalar_multiple(int(c), g) for c, g in zip(moved.row(i), self.frame, strict=True)),
                self.lattice.zero(),
            )
            for i, label in enumerate(labels)
        }
        return self.lattice.O()(images)

    def twisted_transporter(self, images):
        r"""Return `g \in O(L)` with `g F_i g^{-1} = ` ``images[i]``, or ``None``."""
        return self._twisted(tuple(_frame_matrix(self.lattice, F) for F in images))

    def _twisted(self, image_matrices):
        target_pieces, _rest = _components(self.gram, image_matrices)
        targets = dict((signs, basis) for signs, basis in target_pieces)
        choices = []
        target_rows = []
        for signs, basis in self.pieces:
            target = targets.get(signs)
            if target is None or target.nrows() != basis.nrows():
                return None
            start = _component_isometry(self._gram_of(basis), self._gram_of(target))
            if start is None:
                return None
            choices.append(_classes(self._gram_of(basis), start, _orthogonal_generators(self._gram_of(basis))))
            target_rows.append(target)
        choices.append(self._rest_choices(image_matrices))
        target_basis = matrix.block([[rows] for rows in target_rows] + [[self.rest]], subdivide=False)
        for blocks in product(*choices):
            moved = self._assemble(blocks, target_basis)
            if moved.denominator() != 1:
                continue
            assert all(F * moved == moved * T for F, T in zip(self.matrices, image_matrices, strict=True))
            return self._isometry(moved)
        return None

    def centralizer_generators(self):
        r"""Return generators of `C_{O(L)}(H)`.

        `\prod O(L_\epsilon) \times C_{O(R)}(H)` acts on `L_Q`, and `C_{O(L)}(H)` is the
        finite-index subgroup of elements that map `L` into `L`; Schreier generators follow.
        """
        sizes = [basis.nrows() for _signs, basis in self.pieces] + [self.rest.nrows()]
        offsets = [sum(sizes[:i]) for i in range(len(sizes))]
        total = sum(sizes)

        def embed(index, block):
            result = matrix.identity(QQ, total)
            result.set_block(offsets[index], offsets[index], block)
            return result

        generators = []
        for index, (_signs, basis) in enumerate(self.pieces):
            generators.extend(embed(index, s) for s in _orthogonal_generators(self._gram_of(basis)))
        if self.rest.nrows():
            generators.extend(embed(len(self.pieces), h) for h in self._rest_centralizer())
        generators.append(matrix.identity(QQ, total))
        integral = lambda m: (self.inverse * m * self.basis).denominator() == 1
        schreier, _index = finite_preimage_generators(generators, lambda m: m, integral)
        result = [self._isometry(self.inverse * m * self.basis) for m in schreier]
        return tuple(result) if result else (self.lattice.O().one(),)

    def normalizer_generators(self):
        r"""Return generators of `N_{O(L)}(H)`: `C(H)` and one transporter for each realized `\varphi`."""
        result = list(self.centralizer_generators())
        for images in _automorphisms(self.matrices):
            witness = self._twisted(images)
            if witness is not None:
                result.append(witness)
        return tuple(result)


def _column_matrix(lattice, isometry):
    return matrix(ZZ, [[int(c) for c in isometry(g)] for g in lattice.module_generators()]).transpose()


def _from_columns(lattice, columns):
    frame = tuple(lattice.module_generators())
    images = {
        label: sum(
            (lattice.scalar_multiple(int(c), g) for c, g in zip(columns.column(j), frame, strict=True)),
            lattice.zero(),
        )
        for j, label in enumerate(lattice.module_generating_set())
    }
    return lattice.O()(images)


def has_finite_order(columns):
    r"""Decide whether an integer matrix has finite order: its minimal polynomial is squarefree with cyclotomic factors."""
    polynomial = columns.change_ring(QQ).minimal_polynomial().change_ring(ZZ)
    factors = polynomial.factor()
    return all(e == 1 and f.is_cyclotomic() for f, e in factors)


def infinite_cyclic_normalizer(lattice, isometry):
    r"""Return ``(centralizer_generators, inversion)`` for `N_{O(L)}(\langle f \rangle)`, `f` of infinite order.

    ``inversion`` is `t` with `t f t^{-1} = f^{-1}`, or ``None`` as a proof that no element inverts `f`;
    the normalizer is then `C(f)`.
    """
    frame = tuple(lattice.module_generators())
    gram = matrix(ZZ, [[int(lattice.b(x, y)) for y in frame] for x in frame])
    columns = _column_matrix(lattice, isometry)
    assert not has_finite_order(columns), f"{isometry} has finite order"
    commutant = IsometryCommutant(gram, [columns])
    centralizer = tuple(_from_columns(lattice, g) for g in centralizer_generators(commutant))
    witness = equivariant_transporter(commutant, gram, [matrix(ZZ, columns.inverse())])
    inversion = None if witness is None else _from_columns(lattice, witness)
    assert inversion is None or inversion * isometry == ~isometry * inversion
    return centralizer, inversion


def _joint_characters(columns):
    r"""Return the joint eigencharacters `(\lambda_1, \dots, \lambda_m)` of commuting semisimple matrices with their multiplicities."""
    size = columns[0].nrows()
    spaces = [(QQbar**size, ())]
    for F in columns:
        G = F.change_ring(QQbar)
        roots = [r for r, _e in F.charpoly().roots(QQbar)]
        spaces = [(V.intersection((G - r).right_kernel()), chi + (r,)) for V, chi in spaces for r in roots]
        spaces = [(V, chi) for V, chi in spaces if V.dimension() > 0]
    assert sum(V.dimension() for V, _chi in spaces) == size, "the isometries are not simultaneously diagonalizable"
    return [(chi, V.dimension()) for V, chi in spaces]


def _power_word(columns, row):
    result = identity_matrix(QQ, columns[0].nrows())
    for F, e in zip(columns, row, strict=True):
        result = result * F.change_ring(QQ) ** int(e)
    return matrix(ZZ, result)


def _candidate_automorphisms(columns):
    r"""Return the `\Phi \ne 1` in `GL_m(Z)` that permute the multiset `\ell(X)` of the joint characters of `H`."""
    field = RealField(200)
    tolerance = field(2) ** -120
    m = len(columns)
    distinct = []
    for chi, multiplicity in _joint_characters(columns):
        point = vector(field, [field(abs(value)).log() for value in chi])
        known = next((entry for entry in distinct if max(abs(c) for c in entry[0] - point) < tolerance), None)
        if known is None:
            distinct.append([point, multiplicity])
        else:
            known[1] += multiplicity
    basis = next(
        (
            rows
            for rows in combinations(range(len(distinct)), m)
            if abs(matrix(field, [distinct[i][0] for i in rows]).det()) > tolerance
        ),
        None,
    )
    if basis is None:
        raise NotImplementedError(
            f"the logarithms of the joint characters of {columns} span less than R^{m}: H is not free abelian on its "
            f"generators, so N(H) / C(H) is not decided by its permutation of characters (#50)"
        )
    inverse = matrix(field, [distinct[i][0] for i in basis]).transpose().inverse()
    result = []
    for targets in product(range(len(distinct)), repeat=m):
        approximate = matrix(field, [distinct[j][0] for j in targets]).transpose() * inverse
        candidate = matrix(ZZ, m, m, [c.round() for c in approximate.list()])
        if max(abs(c - d) for c, d in zip(approximate.list(), candidate.list())) > tolerance:
            continue
        if candidate.det() not in (1, -1) or candidate == identity_matrix(ZZ, m):
            continue
        permutes = all(
            any(
                multiplicity == other and max(abs(c) for c in candidate.change_ring(field) * point - image) < tolerance
                for image, other in distinct
            )
            for point, multiplicity in distinct
        )
        if permutes and all(str(candidate) != str(known) for known in result):
            result.append(candidate)
    return result


def free_abelian_normalizer(lattice, generators):
    r"""Return generators of `N_{O(L)}(H)` for `H` free abelian on commuting semisimple isometries of infinite order."""
    frame = tuple(lattice.module_generators())
    gram = matrix(ZZ, [[int(lattice.b(x, y)) for y in frame] for x in frame])
    columns = tuple(_column_matrix(lattice, g) for g in generators)
    assert all(F * G == G * F for F in columns for G in columns), "the isometries do not commute"
    if not all(F.change_ring(QQ).minimal_polynomial().is_squarefree() for F in columns):
        raise NotImplementedError(
            f"the commuting isometries {columns} are not all semisimple: N(H) / C(H) is not decided by the joint "
            f"characters (#50)"
        )
    commutant = IsometryCommutant(gram, columns)
    result = [_from_columns(lattice, g) for g in centralizer_generators(commutant)]
    for candidate in _candidate_automorphisms(columns):
        images = [_power_word(columns, row) for row in candidate.rows()]
        if any(F.charpoly() != image.charpoly() for F, image in zip(columns, images, strict=True)):
            continue
        witness = equivariant_transporter(commutant, gram, images)
        if witness is None:
            continue
        assert all(witness * F == image * witness for F, image in zip(columns, images, strict=True))
        result.append(_from_columns(lattice, witness))
    return tuple(result)


def normalizer_generators(lattice, generators):
    r"""Return generators of `N_{O(L)}(H)` for `H = \langle` ``generators`` `\rangle`.

    A finite `H` is decided by :class:`FiniteSubgroupNormalizer`. One generator of infinite order
    is decided by :func:`infinite_cyclic_normalizer`. Commuting generators are decided by
    :func:`free_abelian_normalizer`, which raises outside free abelian semisimple `H`. A non-abelian
    infinite `H` has no implemented route.
    """
    generators = tuple(generators)
    columns = tuple(_column_matrix(lattice, g) for g in generators)
    if all(has_finite_order(m) for m in columns):
        if MatrixGroup(list(columns)).is_finite():
            return FiniteSubgroupNormalizer(lattice, generators).normalizer_generators()
    if len(generators) == 1:
        centralizer, inversion = infinite_cyclic_normalizer(lattice, generators[0])
        return centralizer if inversion is None else (*centralizer, inversion)
    if all(F * G == G * F for F in columns for G in columns):
        return free_abelian_normalizer(lattice, generators)
    raise NotImplementedError(
        f"the normalizer of the infinite non-abelian subgroup generated by {generators} has no implemented route"
    )
