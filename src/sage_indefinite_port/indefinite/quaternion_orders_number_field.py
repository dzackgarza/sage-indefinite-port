r"""Maximal orders containing a quaternion order over a number field, and the normalizer of the order (#54).

Let `A` be a quaternion algebra over a totally real field `Z` and `O` an order, given by a `Z`-basis of `4 [Z : Q]` elements. Orders are handled as `Z`-lattices in the `Q`-coordinates `z^p e_m`; a `Z`-order of `A` containing `O_Z` is an
`O_Z`-order, so maximal `Z`-orders containing `O` are the maximal `O_Z`-orders containing it.

Maximal orders. `O` is maximal exactly when `|\det \mathrm{Tr}_{A/Q}(o_i o_j)| = |d_Z|^4 N(\mathfrak D)^2`, `\mathfrak D` the product of the finite
ramified primes (Voight, *Quaternion Algebras*, Thm. 15.5.5 and Sec. 15.6, discriminants of maximal orders). If `O \subsetneq O'`, the finite
group `O'/O` has an element of prime order `p`, so `O'` contains `x \in p^{-1} O \setminus O`, and `O[x]` is an order between them. Every order
containing `O` is therefore reached from `O` by such one-element extensions at the primes `p` dividing the discriminant index, and the
breadth-first enumeration of the (finitely many, all inside `O^\sharp`) orders containing `O` lists the maximal ones. This replaces the
Bruhat-Tits neighbour step by the same finite search over `p^{-1} O / O`.

Normalizer. `N(O_1)` for a maximal `O_1 \supseteq O` is generated by `O_1^\times` (:class:`QuaternionOrderVoronoi`, or :class:`fuchsian_domain.FuchsianDomain` with real
ramification) and generators of the
two-sided ideals over the ramified primes, lifted through the class group (:func:`two_sided_generators`). `N(O_1)` acts on the finite set of
its conjugates of `O` inside `O_1`; Schreier generators of the stabilizer of `O` give `N(O) \cap N(O_1)`. An `n \in N(O)` carries `O_1` to a
maximal `O_i \supseteq O`; with `\alpha` generating the connecting ideal `O_i O_1` (`\alpha O_1 \alpha^{-1} = O_i`), `n = \alpha m` with `m` in the
`N(O_1)`-orbit transversal at `\alpha^{-1} O \alpha`. These extra elements complete `N(O)`.
"""

from itertools import combinations, product

from sage.matrix.constructor import matrix
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ


class OrderLattices:
    r"""`Q`-coordinates, Hermite keys and ring closures of lattices in the quaternion algebra ``algebra`` over a quadratic field."""

    def __init__(self, algebra):
        self.algebra = algebra
        self.field = algebra.base_ring()
        degree = self.field.degree()
        self._q_basis = [self.field.gen() ** p * g for g in algebra.basis() for p in range(degree)]

    def coordinates(self, x):
        return [c for a in self.algebra(x).coefficient_tuple() for c in self.field(a).list()]

    def element(self, row):
        return sum((QQ(c) * q for c, q in zip(row, self._q_basis)), self.algebra(0))

    def basis(self, elements):
        r"""Return the Hermite basis (as elements) of the `Z`-span of ``elements``."""
        rows = matrix(QQ, [self.coordinates(x) for x in elements])
        scale = rows.denominator()
        hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
        return [self.element(row) for row in hermite.rows()]

    def key(self, elements):
        return tuple(tuple(self.coordinates(x)) for x in self.basis(elements))

    def trace(self, x):
        return QQ(self.field(self.algebra(x).reduced_trace()).trace())

    def discriminant(self, order):
        return abs(matrix(QQ, [[self.trace(x * y) for y in order] for x in order]).det())

    def integral(self, x):
        integers = self.field.ring_of_integers()
        x = self.algebra(x)
        return x.reduced_trace() in integers and x.reduced_norm() in integers

    def closure(self, elements):
        r"""Return the `Z`-basis of the ring generated by ``elements`` (containing `1`), or ``None`` if it contains a non-integral element."""
        basis = self.basis([self.algebra(1), *elements])
        while True:
            if not all(self.integral(x) for x in basis):
                return None
            products = self.basis([*basis, *(x * y for x in basis for y in basis)])
            if self.key(products) == self.key(basis):
                return basis
            basis = products


def maximal_orders_containing(algebra, order, expected):
    r"""Return the maximal orders containing ``order`` (module docstring); ``expected`` is the discriminant of a maximal order."""
    lattices = OrderLattices(algebra)
    order = lattices.basis(order)
    seen, queue, maximal = {lattices.key(order)}, [order], []
    while queue:
        current = queue.pop(0)
        index = lattices.discriminant(current) / expected
        assert index in ZZ and index >= 1
        if index == 1:
            maximal.append(current)
            continue
        for p, _e in ZZ(index).factor():
            for coefficients in product(range(p), repeat=len(current)):
                if not any(coefficients):
                    continue
                x = sum((QQ(c) / p * b for c, b in zip(coefficients, current)), algebra(0))
                if not lattices.integral(x):
                    continue
                larger = lattices.closure([*current, x])
                if larger is None:
                    continue
                key = lattices.key(larger)
                if key not in seen:
                    seen.add(key)
                    queue.append(larger)
    return maximal


def two_sided_generators(engine, order):
    r"""Return generators of the principal two-sided ideals `\prod_{P \in T} \mathfrak P \cdot \mathfrak b^{-1}` of the maximal ``order``.

    For each set `T` of finite ramified primes, `\mathfrak b` runs over class representatives of `Z` with `\prod_T P \cdot \mathfrak b^{-2}`
    generated by an element positive at the ramified real places (Eichler's norm theorem; Voight Sec. 28.5); the generator is found in
    `\mathfrak b^{-1} O` by the enumeration of ``engine`` (:class:`QuaternionOrderVoronoi`, or :class:`fuchsian_domain.FuchsianDomain` with
    real ramification).
    """
    from sage.rings.real_mpfr import RealField

    from sage_indefinite_port.indefinite.fuchsian_domain import positive_generator, ramified_real_places

    algebra = engine.algebra
    field = algebra.base_ring()
    primes = list(algebra.ramified_places(inf=False))
    classes = [c.ideal() for c in field.class_group()]
    ramified_real = ramified_real_places(algebra, RealField(64))
    result = []
    for t in range(1, len(primes) + 1):
        for chosen in combinations(primes, t):
            product_ideal = field.ideal(1)
            for prime in chosen:
                product_ideal *= prime
            for central in classes:
                if positive_generator(field, product_ideal / central**2, ramified_real) is None:
                    continue
                elements = [algebra(g) * o for g in (central**-1).basis() for o in order]
                generator = engine.norm_generator(elements, product_ideal / central**2)
                if generator is not None:
                    result.append(generator)
                    break
    return result


def connecting_generator(engine, connecting):
    r"""Return `\alpha` with `\alpha O_1 \alpha^{-1} = O_i` for the connecting ideal `I = O_i O_1` spanned by ``connecting``, or ``None`` when
    there is none.

    Such `\alpha` generates `\mathfrak b^{-1} I \mathfrak P_T` for a central `\mathfrak b` and a set `T` of finite ramified primes (the two-sided
    ideals of `O_1` modulo principal ones are generated by central ideals and the `\mathfrak P`; Voight, *Quaternion Algebras*, Sec. 18.5);
    in a definite algebra `I` itself need not be principal. At a ramified `P` the local order has exactly one ideal of each norm, so an
    element of `\mathfrak b^{-1} I` of reduced norm `\mathfrak b^{-2} \mathrm{nrd}(I) \prod_T P` generates `\mathfrak b^{-1} I \mathfrak P_T`.
    ``engine.norm_generator`` decides each candidate, so ``None`` after all `T` and class representatives `\mathfrak b` is a proof."""
    from sage_indefinite_port.indefinite.clifford_commutant import _reduced_norm_ideal

    algebra = engine.algebra
    field = algebra.base_ring()
    norm = _reduced_norm_ideal(field, connecting)
    primes = list(algebra.ramified_places(inf=False))
    classes = [c.ideal() for c in field.class_group()]
    for t in range(len(primes) + 1):
        for chosen in combinations(primes, t):
            product_ideal = field.ideal(1)
            for prime in chosen:
                product_ideal *= prime
            for central in classes:
                lattice = [algebra(g) * x for g in (central**-1).basis() for x in connecting]
                alpha = engine.norm_generator(lattice, norm * product_ideal / central**2)
                if alpha is not None:
                    return alpha
    return None


def normalizer_generators(algebra, order, maximal):
    r"""Return generators of `N(O)` for the order ``order`` contained in the maximal orders ``maximal`` (module docstring)."""
    from sage_indefinite_port.indefinite.fuchsian_domain import quaternion_unit_engine

    lattices = OrderLattices(algebra)
    first = maximal[0]
    engine = quaternion_unit_engine(algebra, first)
    generators = [*engine.unit_generators(), *two_sided_generators(engine, first)]

    def act(n):
        return lattices.key([n * o * ~n for o in order])

    one = algebra(1)
    transversal = {act(one): one}
    queue, stabilizer = [one], []
    while queue:
        current = queue.pop(0)
        for g in generators:
            moved = g * current
            point = act(moved)
            if point in transversal:
                stabilizer.append(~transversal[point] * moved)
            else:
                transversal[point] = moved
                queue.append(moved)
    extra = []
    for other in maximal[1:]:
        connecting = [x * y for x in other for y in first]
        alpha = connecting_generator(engine, connecting)
        if alpha is None:
            continue
        assert lattices.key([~alpha * o * alpha for o in other]) == lattices.key(first)
        point = act(~alpha)
        if point in transversal:
            n = alpha * transversal[point]
            assert act(n) == act(one)
            extra.append(n)
    return [*stabilizer, *extra]
