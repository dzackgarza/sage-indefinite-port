r"""Maximal orders containing a quaternion order over a number field, and the normalizer of the order (#54).

Let `A` be a quaternion algebra over a totally real field `Z` and `O` an order, given by a `Z`-basis of `4 [Z : Q]` elements. Orders are handled as `Z`-lattices in the `Q`-coordinates `z^p e_m`; a `Z`-order of `A` containing `O_Z` is an
`O_Z`-order, so maximal `Z`-orders containing `O` are the maximal `O_Z`-orders containing it.

Maximal orders. `O` is maximal exactly when `|\det \mathrm{Tr}_{A/Q}(o_i o_j)| = |d_Z|^4 N(\mathfrak D)^2`, `\mathfrak D` the product of the finite
ramified primes (Voight, *Quaternion Algebras*, Thm. 15.5.5 and Sec. 15.6, discriminants of maximal orders); the quotient is `[O_{\max} : O]^2`.
One maximal order containing `O` comes from the local maximalization of Ivanyos and Ronyai (*Finding maximal orders in semisimple algebras
over Q*, Comput. Complexity 3 (1993); Voight Sec. 15.5) at each prime `p` dividing the index: replace `O` by the right order of its
`p`-radical `J = \mathrm{rad}(O / pO) + pO` (:func:`_p_radical`); when that does not grow, `O` is `p`-hereditary and the left or right order of
a maximal two-sided ideal `M \supseteq J` is larger (:func:`_maximal_two_sided_ideals`). The maximal orders containing `O` form, at each
split prime `P`, a connected subtree of the Bruhat-Tits tree (the intersection of two of them is the Eichler order contained in every vertex
of the geodesic; Voight Sec. 23.5); at a ramified prime the local maximal order is unique. They are therefore reached from the first one by
neighbour steps at the split `P` above the index, staying inside the set: the `N(P) + 1` neighbours of `O_1` are the right orders of the left
ideals `O_1 z y + P O_1` over the lines of `O_1 / P O_1 \cong M_2(F_q)` (:func:`_neighbours`).

Normalizer. `N(O_1)` for a maximal `O_1 \supseteq O` is generated by `O_1^\times` (:class:`QuaternionOrderVoronoi`, or :class:`fuchsian_domain.FuchsianDomain` with real
ramification) and generators of the
two-sided ideals over the ramified primes, lifted through the class group (:func:`two_sided_generators`). `N(O_1)` acts on the finite set of
its conjugates of `O` inside `O_1`; Schreier generators of the stabilizer of `O` give `N(O) \cap N(O_1)`. An `n \in N(O)` carries `O_1` to a
maximal `O_i \supseteq O`; with `\alpha` generating the connecting ideal `O_i O_1` (`\alpha O_1 \alpha^{-1} = O_i`), `n = \alpha m` with `m` in the
`N(O_1)`-orbit transversal at `\alpha^{-1} O \alpha`. These extra elements complete `N(O)`.
"""

from itertools import combinations, product

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module import VectorSpace
from sage.modules.free_module_element import vector
from sage.rings.finite_rings.finite_field_constructor import GF
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ


class OrderLattices:
    r"""`Q`-coordinates, Hermite keys and ring closures of lattices in the quaternion algebra ``algebra`` over a quadratic field."""

    def __init__(self, algebra):
        self.algebra = algebra
        self.field = algebra.base_ring()
        degree = self.field.degree()
        self._q_basis = [self.field.gen() ** p * g for g in algebra.basis() for p in range(degree)]

    def coordinates(self, x):
        return [c for a in self.algebra(x).coefficient_tuple() for c in self.field(a).list()]

    def element(self, row):
        return sum((QQ(c) * q for c, q in zip(row, self._q_basis)), self.algebra(0))

    def basis(self, elements):
        r"""Return the Hermite basis (as elements) of the `Z`-span of ``elements``."""
        rows = matrix(QQ, [self.coordinates(x) for x in elements])
        scale = rows.denominator()
        hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
        return [self.element(row) for row in hermite.rows()]

    def key(self, elements):
        return tuple(tuple(self.coordinates(x)) for x in self.basis(elements))

    def trace(self, x):
        return QQ(self.field(self.algebra(x).reduced_trace()).trace())

    def discriminant(self, order):
        return abs(matrix(QQ, [[self.trace(x * y) for y in order] for x in order]).det())

    def integral(self, x):
        integers = self.field.ring_of_integers()
        x = self.algebra(x)
        return x.reduced_trace() in integers and x.reduced_norm() in integers

    def contains(self, lattice, elements):
        r"""Decide whether the ``elements`` lie in the full-rank ``lattice`` (a `Z`-basis)."""
        inverse = matrix(QQ, [self.coordinates(b) for b in lattice]).inverse()
        return all(c in ZZ for x in elements for c in vector(QQ, self.coordinates(x)) * inverse)

    def _dual(self, rows):
        r"""Return the dual basis (as elements, standard pairing on `Q`-coordinates) of the full-rank `Z`-span of the rational ``rows``."""
        scale = rows.denominator()
        hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
        assert hermite.is_square(), "the multiplier lattice is not of full rank"
        return [self.element(row) for row in hermite.inverse().transpose().rows()]

    def _idealizer(self, lattice, act):
        r"""Return `\{x : \mathrm{act}(b, x) \in I \text{ for all } b \in I\}` for the full-rank ``lattice`` `I`: with `x = \sum_k c_k q_k`, the
        conditions are `c \cdot v_{bj} \in Z` for `(v_{bj})_k` the `j`-th `I`-coordinate of `\mathrm{act}(b, q_k)`, so it is the dual of their span."""
        inverse = matrix(QQ, [self.coordinates(b) for b in lattice]).inverse()
        rows = []
        for b in lattice:
            images = matrix(QQ, [self.coordinates(act(b, q)) for q in self._q_basis]) * inverse
            rows.extend(images.columns())
        return self._dual(matrix(QQ, rows))

    def right_order(self, lattice):
        r"""Return `O_R(I) = \{x : I x \subseteq I\}`."""
        return self._idealizer(lattice, lambda b, x: b * x)

    def left_order(self, lattice):
        r"""Return `O_L(I) = \{x : x I \subseteq I\}`."""
        return self._idealizer(lattice, lambda b, x: x * b)

    def closure(self, elements):
        r"""Return the `Z`-basis of the ring generated by ``elements`` (containing `1`), or ``None`` if it contains a non-integral element."""
        basis = self.basis([self.algebra(1), *elements])
        while True:
            if not all(self.integral(x) for x in basis):
                return None
            products = self.basis([*basis, *(x * y for x in basis for y in basis)])
            if self.key(products) == self.key(basis):
                return basis
            basis = products


class _Residue:
    r"""`R = O / pO` in the `Z`-basis ``order`` of `O`: integral coordinates, lifts with entries in `[0, p)`, and left regular matrices."""

    def __init__(self, lattices, order, p):
        self.lattices, self.order, self.p = lattices, order, p
        self.field = GF(p)
        self.inverse = matrix(QQ, [lattices.coordinates(o) for o in order]).inverse()

    def integral(self, x):
        coordinates = vector(QQ, self.lattices.coordinates(x)) * self.inverse
        assert all(c in ZZ for c in coordinates), f"{x} is not in the order"
        return vector(ZZ, coordinates)

    def reduce(self, x):
        return vector(self.field, self.integral(x))

    def lift(self, row):
        return sum((ZZ(c) * o for c, o in zip(row, self.order)), self.lattices.algebra(0))

    def regular(self, x):
        return matrix(ZZ, [self.integral(x * o) for o in self.order]).transpose()


def _p_radical(lattices, order, p):
    r"""Return a `Z`-basis of `J = \mathrm{rad}(O / pO) + pO`.

    Ronyai, *Computing the structure of finite algebras*, J. Symbolic Comput. 9 (1990), and Cohen, Ivanyos and Wales, *Finding the radical
    of an algebra of linear transformations*, J. Pure Appl. Algebra 117 (1997), Sec. 2: for the faithful left regular representation of `R`
    on `F_p^m` with integral lifts `\hat x`, `g_i(x) = \mathrm{Tr}(\hat x^{p^i}) / p^i \bmod p` is well defined and `F_p`-linear on `I_{i-1}`,
    `I_{-1} = R`, `I_i = \{x \in I_{i-1} : g_i(x y) = 0 \ \forall y \in R\}`, and `\mathrm{rad}(R) = I_l` for `p^l \le m < p^{l+1}`."""
    residue = _Residue(lattices, order, p)
    m = len(order)
    current = identity_matrix(residue.field, m)
    level = 0
    while p**level <= m and current.nrows():
        power = p**level
        values = []
        for row in current.rows():
            x = residue.lift(row)
            for o in order:
                trace = (residue.regular(x * o) ** power).trace()
                assert trace % power == 0
                values.append(residue.field(trace // power))
        current = matrix(residue.field, current.nrows(), m, values).left_kernel().basis_matrix() * current
        level += 1
    return lattices.basis([*(residue.lift(row) for row in current.rows()), *(p * o for o in order)])


def _maximal_two_sided_ideals(lattices, order, radical, p):
    r"""Return `Z`-bases of the maximal two-sided ideals `M \supseteq J` of `O`, the preimages of `S (1 - f)` for the primitive central idempotents
    `f` of the semisimple `S = O / J`.

    The centre `Z(S)` is commutative semisimple over `F_p`, and its Berlekamp subalgebra `\{z : z^p = z\} \cong F_p^s` is spanned by those
    idempotents (Cohen, *A Course in Computational Algebraic Number Theory*, Sec. 3.4.3); refining by each of its basis elements `b`, with
    `e \mapsto e (1 - (b - c)^{p - 1})` for `c \in F_p`, separates the `s` components."""
    residue = _Residue(lattices, order, p)
    m = len(order)
    space = VectorSpace(residue.field, m)
    quotient = space.quotient(space.subspace([residue.reduce(x) for x in radical]))
    to_quotient, from_quotient = quotient.quotient_map(), quotient.lift_map()

    def times(s, t):
        return to_quotient(residue.reduce(residue.lift(from_quotient(s)) * residue.lift(from_quotient(t))))

    def power(s, e):
        result = one
        for _ in range(e):
            result = times(result, s)
        return result

    basis = quotient.basis()
    one = to_quotient(residue.reduce(lattices.algebra(1)))
    commutators = matrix(residue.field, [[c for t in basis for c in times(s, t) - times(t, s)] for s in basis])
    center = [sum((c * s for c, s in zip(row, basis)), quotient(0)) for row in commutators.left_kernel().basis()]
    frobenius = matrix(residue.field, [list(power(z, p) - z) for z in center])
    berlekamp = [sum((c * z for c, z in zip(row, center)), quotient(0)) for row in frobenius.left_kernel().basis()]
    idempotents = [one]
    for b in berlekamp:
        refined = []
        for e in idempotents:
            for c in residue.field:
                f = times(e, one - power(b - c * one, p - 1))
                if not f.is_zero():
                    refined.append(f)
        idempotents = refined
    assert all(times(f, f) == f for f in idempotents) and sum(idempotents, quotient(0)) == one
    result = []
    for f in idempotents:
        complement = [residue.lift(from_quotient(times(one - f, s))) for s in basis]
        result.append(lattices.basis([*radical, *complement]))
    return result


def _local_maximal(lattices, order, p, expected):
    r"""Return a `p`-maximal order containing ``order`` (module docstring, Ivanyos-Ronyai)."""
    while ZZ(lattices.discriminant(order) / expected) % p == 0:
        radical = _p_radical(lattices, order, p)
        larger = lattices.right_order(radical)
        if lattices.key(larger) != lattices.key(order):
            order = larger
            continue
        grown = None
        for ideal in _maximal_two_sided_ideals(lattices, order, radical, p):
            for candidate in (lattices.left_order(ideal), lattices.right_order(ideal)):
                if lattices.key(candidate) != lattices.key(order):
                    grown = candidate
                    break
            if grown is not None:
                break
        assert grown is not None, f"the {p}-hereditary order {order} is not {p}-maximal, but no maximal two-sided ideal has a larger idealizer"
        order = grown
    return order


def _neighbours(lattices, maximal, prime):
    r"""Return the `N(P) + 1` maximal orders adjacent to ``maximal`` at the split prime ``prime`` in the Bruhat-Tits tree.

    `O_1 / P O_1 \cong M_2(F_q)`; a nonzero `z` with `\mathrm{nrd}(z) \in P` has rank one, found in the span of `1, x, x'` (a ternary quadratic
    form over `F_q` is isotropic, Chevalley-Warning). The left ideals of index `q^2` over `P O_1` are `O_1 z y + P O_1`, determined by the line
    `\ell_0 y` (`\ell_0` the row space of `z`); for `v` with `\ell_0 v \ne \ell_0` they are `y \in \{1\} \cup \{v + t : t \in F_q\}`, and the
    neighbours are their right orders (Voight Sec. 23.5)."""
    algebra = lattices.algebra
    residue = lattices.field.residue_field(prime)
    representatives = [residue.lift(a) for a in residue]
    reduced = lattices.basis([algebra(g) * x for g in prime.basis() for x in maximal])

    def zero_divisor():
        for x, x2 in combinations(maximal, 2):
            for a, b, c in product(representatives, repeat=3):
                z = algebra(a) + algebra(b) * x + algebra(c) * x2
                if not lattices.contains(reduced, [z]) and z.reduced_norm() in prime:
                    return z
        raise AssertionError(f"no zero divisor of the residue algebra of {maximal} at {prime}")

    z = zero_divisor()
    ideal = lambda y: lattices.basis([*(x * z * y for x in maximal), *reduced])
    base = ideal(algebra(1))
    v = next((x for x in maximal if lattices.key(ideal(x)) != lattices.key(base)), None)
    assert v is not None, f"every element of {maximal} fixes the line of {z} modulo {prime}"
    ideals = [base, *(ideal(v + algebra(t)) for t in representatives)]
    assert len({lattices.key(i) for i in ideals}) == len(representatives) + 1
    return [lattices.right_order(i) for i in ideals]


def maximal_orders_containing(algebra, order, expected):
    r"""Return the maximal orders containing ``order`` (module docstring); ``expected`` is the discriminant of a maximal order."""
    lattices = OrderLattices(algebra)
    order = lattices.basis(order)
    index = lattices.discriminant(order) / expected
    assert index in ZZ and index >= 1
    primes = ZZ(index).prime_divisors()
    first = order
    for p in primes:
        first = _local_maximal(lattices, first, p, expected)
    assert lattices.discriminant(first) == expected
    ramified = list(algebra.ramified_places(inf=False))
    split = [P for p in primes for P in lattices.field.primes_above(p) if P not in ramified]
    found = {lattices.key(first): first}
    queue = [first]
    while queue:
        current = queue.pop(0)
        for prime in split:
            for neighbour in _neighbours(lattices, current, prime):
                key = lattices.key(neighbour)
                if key not in found and lattices.contains(neighbour, order):
                    found[key] = neighbour
                    queue.append(neighbour)
    return list(found.values())


def two_sided_generators(engine, order):
    r"""Return generators of the principal two-sided ideals `\prod_{P \in T} \mathfrak P \cdot \mathfrak b^{-1}` of the maximal ``order``.

    For each set `T` of finite ramified primes, `\mathfrak b` runs over class representatives of `Z` with `\prod_T P \cdot \mathfrak b^{-2}`
    generated by an element positive at the ramified real places (Eichler's norm theorem; Voight Sec. 28.5); the generator is found in
    `\mathfrak b^{-1} O` by the enumeration of ``engine`` (:class:`QuaternionOrderVoronoi`, or :class:`fuchsian_domain.FuchsianDomain` with
    real ramification).
    """
    from sage.rings.real_mpfr import RealField

    from sage_indefinite_port.indefinite.fuchsian_domain import positive_generator, ramified_real_places

    algebra = engine.algebra
    field = algebra.base_ring()
    primes = list(algebra.ramified_places(inf=False))
    classes = [c.ideal() for c in field.class_group()]
    ramified_real = ramified_real_places(algebra, RealField(64))
    result = []
    for t in range(1, len(primes) + 1):
        for chosen in combinations(primes, t):
            product_ideal = field.ideal(1)
            for prime in chosen:
                product_ideal *= prime
            for central in classes:
                if positive_generator(field, product_ideal / central**2, ramified_real) is None:
                    continue
                elements = [algebra(g) * o for g in (central**-1).basis() for o in order]
                generator = engine.norm_generator(elements, product_ideal / central**2)
                if generator is not None:
                    result.append(generator)
                    break
    return result


def connecting_generator(engine, connecting):
    r"""Return `\alpha` with `\alpha O_1 \alpha^{-1} = O_i` for the connecting ideal `I = O_i O_1` spanned by ``connecting``, or ``None`` when
    there is none.

    Such `\alpha` generates `\mathfrak b^{-1} I \mathfrak P_T` for a central `\mathfrak b` and a set `T` of finite ramified primes (the two-sided
    ideals of `O_1` modulo principal ones are generated by central ideals and the `\mathfrak P`; Voight, *Quaternion Algebras*, Sec. 18.5);
    in a definite algebra `I` itself need not be principal. At a ramified `P` the local order has exactly one ideal of each norm, so an
    element of `\mathfrak b^{-1} I` of reduced norm `\mathfrak b^{-2} \mathrm{nrd}(I) \prod_T P` generates `\mathfrak b^{-1} I \mathfrak P_T`.
    ``engine.norm_generator`` decides each candidate, so ``None`` after all `T` and class representatives `\mathfrak b` is a proof."""
    from sage_indefinite_port.indefinite.clifford_commutant import _reduced_norm_ideal

    algebra = engine.algebra
    field = algebra.base_ring()
    norm = _reduced_norm_ideal(field, connecting)
    primes = list(algebra.ramified_places(inf=False))
    classes = [c.ideal() for c in field.class_group()]
    for t in range(len(primes) + 1):
        for chosen in combinations(primes, t):
            product_ideal = field.ideal(1)
            for prime in chosen:
                product_ideal *= prime
            for central in classes:
                lattice = [algebra(g) * x for g in (central**-1).basis() for x in connecting]
                alpha = engine.norm_generator(lattice, norm * product_ideal / central**2)
                if alpha is not None:
                    return alpha
    return None


def normalizer_generators(algebra, order, maximal):
    r"""Return generators of `N(O)` for the order ``order`` contained in the maximal orders ``maximal`` (module docstring)."""
    from sage_indefinite_port.indefinite.fuchsian_domain import quaternion_unit_engine

    lattices = OrderLattices(algebra)
    first = maximal[0]
    engine = quaternion_unit_engine(algebra, first)
    generators = [*engine.unit_generators(), *two_sided_generators(engine, first)]

    def act(n):
        return lattices.key([n * o * ~n for o in order])

    one = algebra(1)
    transversal = {act(one): one}
    queue, stabilizer = [one], []
    while queue:
        current = queue.pop(0)
        for g in generators:
            moved = g * current
            point = act(moved)
            if point in transversal:
                stabilizer.append(~transversal[point] * moved)
            else:
                transversal[point] = moved
                queue.append(moved)
    extra = []
    for other in maximal[1:]:
        connecting = [x * y for x in other for y in first]
        alpha = connecting_generator(engine, connecting)
        if alpha is None:
            continue
        assert lattices.key([~alpha * o * alpha for o in other]) == lattices.key(first)
        point = act(~alpha)
        if point in transversal:
            n = alpha * transversal[point]
            assert act(n) == act(one)
            extra.append(n)
    return [*stabilizer, *extra]
