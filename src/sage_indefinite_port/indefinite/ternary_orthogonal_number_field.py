r"""`O(M)` of an anisotropic ternary `O_K`-lattice `M`, `K` totally real, through its even Clifford algebra (#54).

Similitude. Diagonalize `h` over `K` by Gram-Schmidt: `b_1, b_2, b_3` with `h(b_i, b_i) = a_i`. In the even Clifford algebra,
`i = b_1 b_2`, `j = b_1 b_3` satisfy `i^2 = -a_1 a_2`, `j^2 = -a_1 a_3`, `ij = -ji`, so `C_0(M \otimes K) \cong Q = (-a_1 a_2, -a_1 a_3)_K`. On
the pure quaternions `Q^0`, `\mathrm{nrd}(x i + y j + z k) = a_1 a_2 x^2 + a_1 a_3 y^2 + a_1^2 a_2 a_3 z^2`, so
`\varphi(u_1 b_1 + u_2 b_2 + u_3 b_3) = u_1 k + u_2 a_2 j + u_3 a_3 i` satisfies `\mathrm{nrd}\, \varphi(x) = a_1 a_2 a_3\, h(x, x)`: a similitude
`M \otimes K \to Q^0`. Conjugation `x \mapsto c x c^{-1}` preserves `Q^0` and `\mathrm{nrd}`, and `c \mapsto \varphi^{-1} \circ \mathrm{conj}_c \circ \varphi`
is the classical isomorphism `Q^\times / K^\times \cong SO(M \otimes K)` (Voight, *Quaternion Algebras*, Prop. 4.5.10 and Ch. 22). `M`
anisotropic means `Q` is a division algebra.

Integral points. `SO(M)` is the image of `G = \{c : c \Lambda_0 c^{-1} = \Lambda_0\}`, `\Lambda_0 = \varphi(M)`. Every such `c` normalizes the ring
`R` generated by `O_K` and `\Lambda_0 \Lambda_0` (an order: products of the integral `x y`, `x, y \in \Lambda_0`, closed and tested integral), so
`G = \mathrm{Stab}_{N(R)}(\Lambda_0)`. `N(R)` preserves `R \cap Q^0`, which is commensurable with `\Lambda_0`, so the `N(R)`-orbit of `\Lambda_0`
is finite and Schreier generators of the stabilizer generate `G`. `N(R)` comes from
:func:`quaternion_orders_number_field.normalizer_generators` (units by :class:`QuaternionOrderVoronoi`, two-sided ideals by Eichler's
norm theorem). When `M` is definite at every real place but one, `Q` is Fuchsian and both come from
:class:`fuchsian_domain.FuchsianDomain`. Rank three is odd, so
`O(M) = SO(M) \times \{\pm 1\}`.
"""

from sage.algebras.quatalg.quaternion_algebra import QuaternionAlgebra
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ
from sage.rings.real_mpfr import RealField

from sage_indefinite_port.indefinite.fuchsian_domain import fuchsian_places
from sage_indefinite_port.indefinite.quaternion_orders_number_field import OrderLattices, maximal_orders_containing, normalizer_generators


class TernaryOrthogonalGroup:
    r"""`O(M)` for ``gram`` on `K^3` and the `O_K`-lattice `M` with `Z`-basis ``z_basis`` (module docstring)."""

    def __init__(self, field, gram, z_basis):
        assert field.is_totally_real()
        self.field, self.gram = field, matrix(field, gram)
        assert self.gram.nrows() == 3 and self.gram == self.gram.transpose()
        self.z_basis = [vector(field, x) for x in z_basis]
        rows = []
        for i in range(3):
            b = vector(field, [1 if l == i else 0 for l in range(3)])
            for c in rows:
                b = b - (self.h(b, c) / self.h(c, c)) * c
            rows.append(b)
        self.P = matrix(field, rows)
        self.a = [self.h(r, r) for r in rows]
        a1, a2, a3 = self.a
        self.algebra = QuaternionAlgebra(field, -a1 * a2, -a1 * a3)
        _one, i, j, k = self.algebra.basis()
        self.images = [k, a2 * j, a3 * i]
        det = a1 * a2 * a3
        assert all(self.phi(x).reduced_norm() == det * self.h(x, x) for x in self.z_basis)

    def h(self, x, y):
        return (matrix([x]) * self.gram * matrix([y]).transpose())[0, 0]

    def phi(self, x):
        u = self.P.solve_left(vector(self.field, x))
        return sum((c * q for c, q in zip(u, self.images)), self.algebra(0))

    def phi_inverse(self, q):
        c0, x, y, z = self.algebra(q).coefficient_tuple()
        assert c0 == 0
        u = vector(self.field, [z, y / self.a[1], x / self.a[2]])
        return u * self.P

    def conjugation(self, c):
        r"""Return the matrix of `\varphi^{-1} \circ \mathrm{conj}_c \circ \varphi` in the standard basis of `K^3`."""
        inverse = ~c
        columns = [self.phi_inverse(c * self.phi(vector(self.field, [1 if l == j else 0 for l in range(3)])) * inverse) for j in range(3)]
        return matrix(self.field, columns).transpose()

    def preserves(self, g):
        flat = matrix(QQ, [[c for entry in x for c in self.field(entry).list()] for x in self.z_basis])
        return all(
            all(c in ZZ for c in flat.solve_left(vector(QQ, [c for entry in g * x for c in self.field(entry).list()])))
            for x in self.z_basis
        )

    def proper_generators(self):
        r"""Return generators of `SO(M)` (module docstring)."""
        algebra = self.algebra
        if algebra.ramified_places(inf=True)[1] and fuchsian_places(algebra, RealField(64)) is None:
            raise NotImplementedError(
                f"SO(M) for the anisotropic ternary M with Gram {list(self.gram)} over {self.field}: C_0(M) = {algebra} ramifies at a real "
                f"place and is not split at exactly one real place (M definite at all, or indefinite at two or more and definite at some), "
                f"so neither Voronoi nor the Fuchsian domain gives the units and the two-sided ideal generators of its order (#54)"
            )
        lattices = OrderLattices(algebra)
        base = [self.phi(x) for x in self.z_basis]
        order = lattices.closure([x * y for x in base for y in base])
        assert order is not None
        primes = algebra.ramified_places(inf=False)
        reduced = ZZ(1)
        for prime in primes:
            reduced *= prime.norm()
        expected = abs(self.field.discriminant()) ** 4 * reduced**2
        maximal = maximal_orders_containing(algebra, order, expected)
        generators = normalizer_generators(algebra, order, maximal)

        def act(c):
            inverse = ~c
            return lattices.key([c * x * inverse for x in base])

        one = algebra(1)
        transversal = {act(one): one}
        queue, stabilizer = [one], []
        while queue:
            current = queue.pop(0)
            for g in generators:
                moved = g * current
                point = act(moved)
                if point in transversal:
                    stabilizer.append(~transversal[point] * moved)
                else:
                    transversal[point] = moved
                    queue.append(moved)
        identity = identity_matrix(self.field, 3)
        result = []
        for c in stabilizer:
            g = self.conjugation(c)
            assert g.transpose() * self.gram * g == self.gram and g.det() == 1 and self.preserves(g)
            if g != identity:
                result.append(g)
        return result

    def generators(self):
        return (-identity_matrix(self.field, 3), *self.proper_generators())
