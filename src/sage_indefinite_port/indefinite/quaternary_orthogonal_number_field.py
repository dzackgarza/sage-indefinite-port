r"""`SO(M)` and `O(M)` of an anisotropic quaternary `O_K`-lattice `M`, `K` totally real, through the even Clifford algebra (#54).

Clifford model. Diagonalize `h` over `K` by Gram-Schmidt: `b_1, \ldots, b_4`, `h(b_l, b_l) = a_l`, `\delta = a_1 a_2 a_3 a_4` the discriminant.
In the Clifford algebra `\omega = b_1 b_2 b_3 b_4` is central in `C_0` with `\omega^2 = \delta` (reversing four factors has sign `+1`). For
`\delta \notin K^{\times 2}`, `Z = K(\omega)` is a quadratic extension and `C_0 = D = (-a_1 a_2, -a_1 a_3)_Z` with `i = b_1 b_2`, `j = b_1 b_3`,
`k = ij = -a_1 b_2 b_3` (KMRT, *The Book of Involutions*, Sec. 15.B; Voight, *Quaternion Algebras*, Sec. 4.5 and Ch. 22). The map
`\psi(x) = b_1 x` identifies `M \otimes K` with the `K`-space spanned by `\psi(b_1) = a_1`, `\psi(b_2) = i`, `\psi(b_3) = j` and
`\psi(b_4) = b_1 b_4 = \omega k / (a_1 a_2 a_3)` (from `(b_2 b_3)\, \omega = -a_2 a_3\, b_1 b_4`). Conjugation by `b_1`, `\alpha`, is the
`\sigma`-semilinear automorphism of `D` with `\alpha(i) = -i`, `\alpha(j) = -j`, `\alpha(\omega) = -\omega`, and for `c` in the even Clifford group
`\psi(c x c^{-1}) = \alpha(c)\, \psi(x)\, c^{-1}`. The even Clifford group is `\{c \in D^\times : \mathrm{nrd}(c) \in K^\times\}` and it maps onto
`SO(M \otimes K)` with kernel `K^\times`.

Integral points. A `c` preserving `M` normalizes `C_0(M)`, the ring `R` generated by `O_K` and `x y = \alpha(\psi(x)) \psi(y)/a_1`, `x, y \in M`.
In `N(R)` (:func:`quaternion_orders_number_field.normalizer_generators`, Voronoi units over `Z`) the elements with `\mathrm{nrd}(c) \in K^\times Z^{\times 2}`
form a subgroup of finite index (Schreier generators, :func:`finite_preimage_generators`); such `c` is rescaled to `c / w`, `\mathrm{nrd}(c / w) \in K`:
with `t^2 = n / \sigma(n)`, `n = \mathrm{nrd}(c)`, `t \sigma(t) = 1`, Hilbert 90 gives `t = w / \sigma(w)`, `w = a + t \sigma(a)`, and
`n / w^2 = \sigma(n / w^2)`. Two rescalings differ by `z \in Z^\times` with `z^2 \in K`, acting by `\sigma(z)/z = \pm 1`. The resulting group of
isometries is commensurable with `SO(M)`, so the orbit of `\psi(M)` is finite and Schreier generators of its stabilizer, with `-1`,
generate `SO(M)`. `O(M) = O^+(M)` when `D` is a division algebra (KMRT Cor. 13.43, as in :mod:`clifford_commutant`).
"""

from sage.algebras.quatalg.quaternion_algebra import QuaternionAlgebra
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.integer_ring import ZZ
from sage.rings.polynomial.polynomial_ring_constructor import PolynomialRing
from sage.rings.rational_field import QQ
from sage_extensions.categories.lattice_centralizers import finite_preimage_generators

from sage_indefinite_port.indefinite.quaternion_orders_number_field import OrderLattices, maximal_orders_containing, normalizer_generators


class QuaternaryOrthogonalGroup:
    r"""`SO(M) = O(M)` for ``gram`` on `K^4` and the `O_K`-lattice with `Z`-basis ``z_basis`` (module docstring)."""

    def __init__(self, field, gram, z_basis):
        assert field.is_totally_real()
        self.field, self.gram = field, matrix(field, gram)
        assert self.gram.nrows() == 4 and self.gram == self.gram.transpose()
        self.z_basis = [vector(field, x) for x in z_basis]
        rows = []
        for i in range(4):
            b = vector(field, [1 if l == i else 0 for l in range(4)])
            for c in rows:
                b = b - (self.h(b, c) / self.h(c, c)) * c
            rows.append(b)
        self.P = matrix(field, rows)
        self.a = [self.h(r, r) for r in rows]
        a1, a2, a3, a4 = self.a
        self.delta = a1 * a2 * a3 * a4
        if self.delta.is_square():
            raise NotImplementedError(
                f"SO(M) for the anisotropic quaternary M with Gram {list(self.gram)} over {field}: the discriminant is a square, so "
                f"C_0(M) = B x B for a quaternion algebra B over K and SO(M) is commensurable with (B^1 x B^1)/(+-1); that product route is "
                f"not implemented (#54)"
            )
        x = PolynomialRing(field, "x").gen()
        relative = field.extension(x**2 - self.delta, "w")
        self.relative = relative
        self.center = relative.absolute_field("z")
        # structure() = (absolute -> relative, relative -> absolute)
        self._to, self._from = self.center.structure()
        self.omega = self._from(relative.gen())
        self.algebra = QuaternionAlgebra(self.center, self.lift(-a1 * a2), self.lift(-a1 * a3))
        _one, i, j, k = self.algebra.basis()
        self.images = [self.algebra(self.lift(a1)), i, j, self.omega * k / self.lift(a1 * a2 * a3)]

    def h(self, x, y):
        return (matrix([x]) * self.gram * matrix([y]).transpose())[0, 0]

    def lift(self, c):
        return self._from(self.relative(c))

    def sigma(self, z):
        p0, p1 = self._to(self.center(z)).list()
        return self._from(self.relative(p0) - self.relative(p1) * self.relative.gen())

    def down(self, z):
        p0, p1 = self._to(self.center(z)).list()
        assert p1 == 0
        return self.field(p0)

    def alpha(self, y):
        z0, z1, z2, z3 = self.algebra(y).coefficient_tuple()
        _one, i, j, k = self.algebra.basis()
        return self.sigma(z0) - self.sigma(z1) * i - self.sigma(z2) * j + self.sigma(z3) * k

    def psi(self, x):
        u = self.P.solve_left(vector(self.field, x))
        return sum((self.lift(c) * q for c, q in zip(u, self.images)), self.algebra(0))

    def psi_inverse(self, y):
        z0, z1, z2, z3 = self.algebra(y).coefficient_tuple()
        a1, a2, a3, _a4 = self.a
        u = vector(self.field, [self.down(z0 / self.lift(a1)), self.down(z1), self.down(z2), self.down(z3 * self.lift(a1 * a2 * a3) / self.omega)])
        return u * self.P

    def action(self, c):
        r"""Return the matrix of `x \mapsto \psi^{-1}(\alpha(c) \psi(x) c^{-1})` in the standard basis of `K^4`."""
        left, inverse = self.alpha(c), ~c
        columns = [self.psi_inverse(left * self.psi(vector(self.field, [1 if l == j else 0 for l in range(4)])) * inverse) for j in range(4)]
        return matrix(self.field, columns).transpose()

    def preserves(self, g):
        flat = matrix(QQ, [[c for entry in x for c in self.field(entry).list()] for x in self.z_basis])
        return all(
            all(c in ZZ for c in flat.solve_left(vector(QQ, [c for entry in g * x for c in self.field(entry).list()])))
            for x in self.z_basis
        )

    def _in_subgroup(self, n):
        r"""Decide `n \in K^\times Z^{\times 2}`: `n / \sigma(n) = t^2` with `t \sigma(t) = 1` (module docstring)."""
        ratio = self.center(n) / self.sigma(n)
        if not ratio.is_square():
            return False
        t = ratio.sqrt()
        return t * self.sigma(t) == 1

    def _rescaled(self, c):
        n = self.center(c.reduced_norm())
        t = (n / self.sigma(n)).sqrt()
        if t * self.sigma(t) != 1:
            t = -t
        assert t * self.sigma(t) == 1
        w = 1 + t
        if w == 0:
            w = self.omega + t * self.sigma(self.omega)
        result = c * self.algebra(~w)
        norm = self.center(result.reduced_norm())
        assert norm == self.sigma(norm)
        return result

    def generators(self):
        r"""Return generators of `O(M) = SO(M)` (module docstring)."""
        algebra = self.algebra
        if algebra.ramified_places(inf=True)[1]:
            raise NotImplementedError(
                f"O(M) for the anisotropic quaternary M with Gram {list(self.gram)} over {self.field}: C_0(M) = {algebra} ramifies at a real "
                f"place of Z, and the normalizer of its order needs generators of two-sided ideals beyond Eichler's norm theorem (#54)"
            )
        lattices = OrderLattices(algebra)
        base = [self.psi(x) for x in self.z_basis]
        a1 = self.lift(self.a[0])
        order = lattices.closure([self.alpha(x) * y / a1 for x in base for y in base])
        assert order is not None
        reduced = ZZ(1)
        for prime in algebra.ramified_places(inf=False):
            reduced *= prime.norm()
        expected = abs(self.center.discriminant()) ** 4 * reduced**2
        maximal = maximal_orders_containing(algebra, order, expected)
        normalizer = normalizer_generators(algebra, order, maximal)
        subgroup, _index = finite_preimage_generators(normalizer, lambda c: self.center(c.reduced_norm()), self._in_subgroup)
        actions = [self.action(self._rescaled(c)) for c in subgroup]
        assert all(g.transpose() * self.gram * g == self.gram for g in actions)

        identity = identity_matrix(self.field, 4)
        transversal = {self._lattice_key(identity): identity}
        queue, stabilizer = [identity], []
        while queue:
            current = queue.pop(0)
            for g in actions:
                moved = g * current
                point = self._lattice_key(moved)
                if point in transversal:
                    stabilizer.append(~transversal[point] * moved)
                else:
                    transversal[point] = moved
                    queue.append(moved)
        result = [-identity]
        for g in stabilizer:
            assert self.preserves(g) and g.transpose() * self.gram * g == self.gram
            if g != identity:
                result.append(g)
        return tuple(result)

    def _lattice_key(self, g):
        r"""Return the Hermite key of `g M` in `Q`-coordinates."""
        rows = matrix(QQ, [[c for entry in g * x for c in self.field(entry).list()] for x in self.z_basis])
        scale = rows.denominator()
        hermite = matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)
        return (scale, tuple(hermite.list()))
