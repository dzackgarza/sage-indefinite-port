r"""Unitary groups of anisotropic skew-Hermitian quaternion planes through the Clifford algebra (#54).

Let `A = M_2(D)`, `D` a quaternion division algebra over `Q`, be the commutant with the orthogonal involution `\sigma` (the adjoint of an
anisotropic skew-Hermitian form `h`), acting on `Q^r` with the lattice `Z^r`; `C(Z) = \{g \in A \cap GL_r(Z) : \sigma(g) g = 1\}`.

Clifford model (Knus, Merkurjev, Rost, Tignol, *The Book of Involutions*, Thm. 15.7, Cor. 15.12). `L = \mathrm{Skew}(A, \sigma)` is a
`6`-dimensional semisimple `Q`-Lie algebra of type `A_1 \times A_1`, `L \cong R_{Z/Q}(C^0)` for the Clifford algebra `C = C(A, \sigma)`, a
quaternion algebra over the discriminant field `Z = Q(\sqrt\delta)` (a field since `h` is anisotropic). The centroid of `L` (maps commuting
with every `\mathrm{ad}_x`) is `Z`; its traceless element `\Theta` has `\Theta^2 = \delta`, and over `Z` the idempotent `e = (1 + \Theta/\sqrt\delta)/2`
splits `L \otimes Z = I \oplus \tau(I)`. Then `C = Z + I \subset A \otimes Z`, `C' = \tau(C)` is its centralizer, `A \otimes Z = C \otimes_Z C'`, and
`\sigma|_C` is the canonical involution. For `c \in C^\times`, `\chi(c) = c \tau(c)` is `\tau`-invariant, so lies in `A`, and
`\sigma(\chi(c)) \chi(c) = N_{Z/Q}(\mathrm{nrd}\, c)`; `\chi` maps `SL_1(C)` onto `\mathrm{Spin} \to SO(A, \sigma)` with kernel `\pm 1`.

Integral points. `O_C = C \cap M_r(O_Z)` is an order and `\chi(SL_1(O_C)) \subseteq C(Z)`; `SL_1(O_C)` comes from
:class:`QuaternionOrderVoronoi`. A non-split `A` has only proper isometries: `O(A, \sigma) = O^+(A, \sigma)` (KMRT, Corollary (13.43), from Theorem (13.38): an improper
similitude `g` makes `A` Brauer-equivalent to `(Z, \mu(g))_Q`, split when `\mu(g) = 1`; first observed by Kneser). Improper similitudes with
`\mu \ne 1` may exist, but `C(Z)` consists of isometries, so every `g \in C(Z)` is proper and acts on
`C` by an inner automorphism `x \mapsto n x n^{-1}`, `n \in C^\times`, preserving `O_C` (conjugation by `g \in GL_r(Z)` preserves `M_r(O_Z)`);
then `g = \pm n \tau(n) / q`, `q^2 = N_{Z/Q}(\mathrm{nrd}\, n)`. For `O_C` maximal, `O_Z` principal and `C` without real ramification, the
normalizer is `N(O_C) = Z^\times O_C^\times \langle n_P \rangle`, `n_P` a generator of the two-sided prime ideal `\mathfrak P` over each finite
ramified `P` (Voight, *Quaternion Algebras*, Sec. 18.5 on two-sided ideals of maximal orders; `\mathfrak P` is principal by Eichler's norm theorem, Voight Ch. 28,
when `\mathrm{nrd}\, \mathfrak P = P` has a generator positive at the ramified real places; with real ramification `C` is Fuchsian and
its units and ideal generators come from :class:`fuchsian_domain.FuchsianDomain`), and `O_C^\times = SL_1(O_C) O_Z^\times \langle u_1, u_2 \rangle` for
units whose reduced norms represent `\mathrm{nrd}(O_C^\times) / (O_Z^\times)^2`. Hence `C(Z)` is generated by `\chi(SL_1(O_C))`, `-1` and the
integral ones among the finitely many `\pm \chi(u n_T)/q`, `u` a product of the `u_i`, `n_T = \prod_{P \in T} n_P`.
"""

