r"""Unitary groups of anisotropic skew-Hermitian quaternion planes through the Clifford algebra (#54).

Let `A = M_2(D)`, `D` a quaternion division algebra over `Q`, be the commutant with the orthogonal involution `\sigma` (the adjoint of an
anisotropic skew-Hermitian form `h`), acting on `Q^r` with the lattice `Z^r`; `C(Z) = \{g \in A \cap GL_r(Z) : \sigma(g) g = 1\}`.

Clifford model (Knus, Merkurjev, Rost, Tignol, *The Book of Involutions*, Thm. 15.7, Cor. 15.12). `L = \mathrm{Skew}(A, \sigma)` is a
`6`-dimensional semisimple `Q`-Lie algebra of type `A_1 \times A_1`, `L \cong R_{Z/Q}(C^0)` for the Clifford algebra `C = C(A, \sigma)`, a
quaternion algebra over the discriminant field `Z = Q(\sqrt\delta)` (a field since `h` is anisotropic). The centroid of `L` (maps commuting
with every `\mathrm{ad}_x`) is `Z`; its traceless element `\Theta` has `\Theta^2 = \delta`, and over `Z` the idempotent `e = (1 + \Theta/\sqrt\delta)/2`
splits `L \otimes Z = I \oplus \tau(I)`. Then `C = Z + I \subset A \otimes Z`, `C' = \tau(C)` is its centralizer, `A \otimes Z = C \otimes_Z C'`, and
`\sigma|_C` is the canonical involution. For `c \in C^\times`, `\chi(c) = c \tau(c)` is `\tau`-invariant, so lies in `A`, and
`\sigma(\chi(c)) \chi(c) = N_{Z/Q}(\mathrm{nrd}\, c)`; `\chi` maps `SL_1(C)` onto `\mathrm{Spin} \to SO(A, \sigma)` with kernel `\pm 1`.

Integral points. `O_C = C \cap M_r(O_Z)` is an order and `\chi(SL_1(O_C)) \subseteq C(Z)`; `SL_1(O_C)` comes from
:class:`QuaternionOrderVoronoi`. A non-split `A` has no improper similitudes (KMRT, Sec. 13.A), so every `g \in C(Z)` is proper and acts on
`C` by an inner automorphism `x \mapsto n x n^{-1}`, `n \in C^\times`, preserving `O_C` (conjugation by `g \in GL_r(Z)` preserves `M_r(O_Z)`);
then `g = \pm n \tau(n) / q`, `q^2 = N_{Z/Q}(\mathrm{nrd}\, n)`. For `O_C` maximal, `O_Z` principal and `C` without real ramification, the
normalizer is `N(O_C) = Z^\times O_C^\times \langle n_P \rangle`, `n_P` a generator of the two-sided prime ideal `\mathfrak P` over each finite
ramified `P` (Voight, *Quaternion Algebras*, Sec. 18.5 on two-sided ideals of maximal orders; `\mathfrak P` is principal by Eichler's norm theorem, Voight Ch. 28,
as `\mathrm{nrd}\, \mathfrak P = P` is principal and no real place ramifies), and `O_C^\times = SL_1(O_C) O_Z^\times \langle u_1, u_2 \rangle` for
units whose reduced norms represent `\mathrm{nrd}(O_C^\times) / (O_Z^\times)^2`. Hence `C(Z)` is generated by `\chi(SL_1(O_C))`, `-1` and the
integral ones among the finitely many `\pm \chi(u n_T)/q`, `u` a product of the `u_i`, `n_T = \prod_{P \in T} n_P`.
"""

from itertools import combinations

from sage.algebras.quatalg.quaternion_algebra import QuaternionAlgebra
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.finite_rings.finite_field_constructor import GF
from sage.rings.integer_ring import ZZ
from sage.rings.number_field.number_field import NumberField
from sage.rings.polynomial.polynomial_ring_constructor import PolynomialRing
from sage.rings.rational_field import QQ
from sage_extensions.algebras.isometry_commutant import _short_vectors
from sage_indefinite_port.indefinite.quaternion_voronoi_number_field import QuaternionOrderVoronoi


def _flat(x):
    return vector(QQ, matrix(QQ, x).list())


class CliffordModel:
    r"""The Clifford model of a commutant `M_2(D)` with the adjoint of an anisotropic skew-Hermitian form (module docstring)."""

    def __init__(self, commutant):
        self.commutant = commutant
        r = commutant.rank
        order = [m.change_ring(QQ) for m in commutant.order_basis]
        kernel = matrix(QQ, [_flat(commutant.adjoint(m) + m) for m in order]).left_kernel().basis()
        skew = [sum(QQ(c) * m for c, m in zip(k, order)) for k in kernel]
        assert len(skew) == 6, f"Skew(A, sigma) has dimension {len(skew)}, not 6"
        rows = matrix(QQ, [_flat(x) for x in skew])
        coordinates = lambda x: rows.solve_left(_flat(x))
        ads = [matrix(QQ, [coordinates(x * y - y * x) for y in skew]).transpose() for x in skew]
        units = []
        for a in range(6):
            for b in range(6):
                E = matrix(QQ, 6, 6)
                E[a, b] = 1
                units.append(E)
        equations = matrix(QQ, [[c for X in ads for c in (E * X - X * E).list()] for E in units])
        centroid = [sum(QQ(c) * E for c, E in zip(k, units)) for k in equations.left_kernel().basis()]
        assert len(centroid) == 2, f"the centroid of Skew(A, sigma) has dimension {len(centroid)}"
        E = next(E for E in centroid if not E.is_scalar())
        theta = E - (E.trace() / 6) * identity_matrix(QQ, 6)
        delta = (theta * theta)[0, 0]
        assert theta * theta == delta * identity_matrix(QQ, 6)
        assert not delta.is_square(), "the discriminant is a square: h is hyperbolic"
        self.field = NumberField(PolynomialRing(QQ, "x")([-delta, 0, 1]), "z")
        z = self.field.gen()
        self.tau = next(t for t in self.field.automorphisms() if t(z) == -z)
        ideal = []
        for col in range(6):
            image = sum(theta[row, col] * skew[row] for row in range(6))
            ideal.append((skew[col].change_ring(self.field) + image.change_ring(self.field) / z) / 2)
        one = identity_matrix(self.field, r)
        i = next(x for x in ideal if not x.is_zero())
        a = (i * i)[0, 0]
        assert i * i == a * one
        j = next(c for c in (i * y - y * i for y in ideal) if not c.is_zero())
        b = (j * j)[0, 0]
        assert j * j == b * one and i * j == -j * i
        self.frame = (one, i, j, i * j)
        self.algebra = QuaternionAlgebra(self.field, a, b)
        self._q_matrices = [z**p * f for f in self.frame for p in (0, 1)]
        self._q_elements = [z**p * g for g in self.algebra.basis() for p in (0, 1)]
        self._q_rows = matrix(QQ, [[c for x in M.list() for c in self.field(x).list()] for M in self._q_matrices])
        assert all(self._contains(x * y) for x in self.frame for y in self.frame)
        self.order_basis = self._integral_order()

    def to_matrix(self, q):
        return sum(c * f for c, f in zip(self.algebra(q).coefficient_tuple(), self.frame))

    def _contains(self, M):
        flat = vector(QQ, [c for x in M.list() for c in self.field(x).list()])
        return self._q_rows.stack(matrix(QQ, [flat])).rank() == self._q_rows.rank()

    def _integral_order(self):
        r"""Return a `Z`-basis of `O_C = C \cap M_r(O_Z)`: the dual of the lattice spanned by the `O_Z`-coordinate functionals of the entries."""
        integers = self.field.ring_of_integers()
        functionals = matrix(QQ, [[c for x in M.list() for c in integers.coordinates(x)] for M in self._q_matrices]).transpose()
        scale = functionals.denominator()
        span = matrix(QQ, matrix(ZZ, scale * functionals).hermite_form(include_zero_rows=False)) / scale
        assert span.nrows() == 8
        dual = span.inverse().transpose()
        return [sum((QQ(c) * q for c, q in zip(row, self._q_elements)), self.algebra(0)) for row in dual.rows()]

    def chi(self, n):
        r"""Return `n \tau(n)` as a rational matrix."""
        M = self.to_matrix(n)
        product = M * M.apply_map(self.tau)
        return matrix(QQ, [[QQ(x) for x in row] for row in product.rows()])

    def _ramified_generators(self, voronoi):
        r"""Return `n_P` with `\mathrm{nrd}(n_P) O_Z = P` for the finite ramified `P`, by enumeration in a positive form (terminates by Eichler)."""
        primes = self.algebra.ramified_places(inf=False)
        gram = voronoi.gram(self.algebra(1))
        result = []
        for prime in primes:
            bound, found = QQ(1), None
            while found is None:
                for v in _short_vectors(gram, bound):
                    x = voronoi.from_order(v)
                    if self.field.ideal(x.reduced_norm()) == prime:
                        found = x
                        break
                bound *= 2
            result.append(found)
        return primes, result

    def _check_maximal(self, voronoi, primes):
        gram = matrix(QQ, [[voronoi.trace(x * y) for y in voronoi.order] for x in voronoi.order])
        discriminant = self.field.discriminant()
        expected = abs(discriminant) ** 4 * _norm_product(primes) ** 2
        if abs(gram.det()) != expected:
            raise NotImplementedError(
                f"O_C = C cap M_r(O_Z) has discriminant {abs(gram.det())}, not that of a maximal order ({expected}); the "
                f"normalizer of a non-maximal order is not computed here (#54)"
            )

    def centralizer_generators(self):
        r"""Return generators of `C(Z)` (module docstring)."""
        if self.field.class_number() != 1:
            raise NotImplementedError(
                f"Z = {self.field} has class number {self.field.class_number()}: the normalizer generators n_P need the lift "
                f"through the class group of Z (#54)"
            )
        voronoi = QuaternionOrderVoronoi(self.algebra, self.order_basis)
        primes, ramified = self._ramified_generators(voronoi)
        self._check_maximal(voronoi, primes)
        units = self.field.unit_group()
        width = len(units.gens())
        reps, span = [], matrix(GF(2), 0, width)
        for u in voronoi.unit_generators():
            row = matrix(GF(2), [[x % 2 for x in units.log(self.field(u.reduced_norm()))]])
            if span.stack(row).rank() > span.rank():
                span = span.stack(row)
                reps.append(u)
        r = self.commutant.rank
        result = [-identity_matrix(QQ, r), *(self.chi(c) for c in voronoi.sl1_generators())]
        one = self.algebra(1)
        for k in range(len(reps) + 1):
            for chosen_units in combinations(reps, k):
                for t in range(len(ramified) + 1):
                    for chosen_primes in combinations(ramified, t):
                        n = one
                        for x in (*chosen_units, *chosen_primes):
                            n = n * x
                        norm = QQ(self.field(n.reduced_norm()).norm())
                        if norm <= 0 or not norm.is_square():
                            continue
                        g = self.chi(n) / norm.sqrt()
                        if all(c in ZZ for c in g.list()) and all(c in ZZ for c in g.inverse().list()):
                            result.extend([g, -g])
        assert all(self.commutant.is_centralizer_element(matrix(ZZ, g)) for g in result)
        return tuple(result)


def _norm_product(primes):
    result = ZZ(1)
    for prime in primes:
        result *= prime.norm()
    return result
