def _flat(x):
    return vector(QQ, matrix(QQ, x).list())


class CliffordModel:
    r"""The Clifford model of a commutant `M_2(D)` with the adjoint of an anisotropic skew-Hermitian form (module docstring)."""

    def __init__(self, commutant):
        self.commutant = commutant
        r = commutant.rank
        order = [m.change_ring(QQ) for m in commutant.order_basis]
        kernel = matrix(QQ, [_flat(commutant.adjoint(m) + m) for m in order]).left_kernel().basis()
        skew = [sum(QQ(c) * m for c, m in zip(k, order)) for k in kernel]
        assert len(skew) == 6, f"Skew(A, sigma) has dimension {len(skew)}, not 6"
        rows = matrix(QQ, [_flat(x) for x in skew])
        coordinates = lambda x: rows.solve_left(_flat(x))
        ads = [matrix(QQ, [coordinates(x * y - y * x) for y in skew]).transpose() for x in skew]
        units = []
        for a in range(6):
            for b in range(6):
                E = matrix(QQ, 6, 6)
                E[a, b] = 1
                units.append(E)
        equations = matrix(QQ, [[c for X in ads for c in (E * X - X * E).list()] for E in units])
        centroid = [sum(QQ(c) * E for c, E in zip(k, units)) for k in equations.left_kernel().basis()]
        assert len(centroid) == 2, f"the centroid of Skew(A, sigma) has dimension {len(centroid)}"
        E = next(E for E in centroid if not E.is_scalar())
        theta = E - (E.trace() / 6) * identity_matrix(QQ, 6)
        delta = (theta * theta)[0, 0]
        assert theta * theta == delta * identity_matrix(QQ, 6)
        assert not delta.is_square(), "the discriminant is a square: h is hyperbolic"
        self.delta = delta
        self.field = NumberField(PolynomialRing(QQ, "x")([-delta, 0, 1]), "z")
        z = self.field.gen()
        self.tau = next(t for t in self.field.automorphisms() if t(z) == -z)
        ideal = []
        for col in range(6):
            image = sum(theta[row, col] * skew[row] for row in range(6))
            ideal.append((skew[col].change_ring(self.field) + image.change_ring(self.field) / z) / 2)
        one = identity_matrix(self.field, r)
        i = next(x for x in ideal if not x.is_zero())
        a = (i * i)[0, 0]
        assert i * i == a * one
        j = next(c for c in (i * y - y * i for y in ideal) if not c.is_zero())
        b = (j * j)[0, 0]
        assert j * j == b * one and i * j == -j * i
        self.frame = (one, i, j, i * j)
        self.algebra = QuaternionAlgebra(self.field, a, b)
        self._q_matrices = [z**p * f for f in self.frame for p in (0, 1)]
        self._q_elements = [z**p * g for g in self.algebra.basis() for p in (0, 1)]
        self._q_rows = matrix(QQ, [[c for x in M.list() for c in self.field(x).list()] for M in self._q_matrices])
        assert all(self._contains(x * y) for x in self.frame for y in self.frame)
        self.order_basis = self._integral_order()

    def to_matrix(self, q):
        return sum(c * f for c, f in zip(self.algebra(q).coefficient_tuple(), self.frame))

    def _contains(self, M):
        flat = vector(QQ, [c for x in M.list() for c in self.field(x).list()])
        return self._q_rows.stack(matrix(QQ, [flat])).rank() == self._q_rows.rank()

    def _integral_order(self):
        r"""Return a `Z`-basis of `O_C = C \cap M_r(O_Z)`: the dual of the lattice spanned by the `O_Z`-coordinate functionals of the entries."""
        integers = self.field.ring_of_integers()
        functionals = matrix(QQ, [[c for x in M.list() for c in integers.coordinates(x)] for M in self._q_matrices]).transpose()
        scale = functionals.denominator()
        span = matrix(QQ, matrix(ZZ, scale * functionals).hermite_form(include_zero_rows=False)) / scale
        assert span.nrows() == 8
        dual = span.inverse().transpose()
        return [sum((QQ(c) * q for c, q in zip(row, self._q_elements)), self.algebra(0)) for row in dual.rows()]

    def chi(self, n):
        r"""Return `n \tau(n)` as a rational matrix."""
        M = self.to_matrix(n)
        product = M * M.apply_map(self.tau)
        return matrix(QQ, [[QQ(x) for x in row] for row in product.rows()])

    def voronoi(self):
        if not hasattr(self, "_voronoi"):
            self._voronoi = quaternion_unit_engine(self.algebra, self.order_basis)
        return self._voronoi

    def _generator(self, elements, target):
        return self.voronoi().norm_generator(elements, target)

    def expected_discriminant(self):
        primes = list(self.algebra.ramified_places(inf=False))
        return abs(self.field.discriminant()) ** 4 * _norm_product(primes) ** 2

    def is_maximal(self):
        voronoi = self.voronoi()
        gram = matrix(QQ, [[voronoi.trace(x * y) for y in voronoi.order] for x in voronoi.order])
        return abs(gram.det()) == self.expected_discriminant()

    def normalizer_representatives(self):
        r"""Return elements `n` of `C` whose classes generate `N(O_C) / (Z^\times SL_1(O_C))` together with `SL_1(O_C)`.

        Units: representatives of `\mathrm{nrd}(O_C^\times)` modulo `(O_Z^\times)^2`. Ramified part: for each set `T` of finite ramified primes,
        the two-sided ideal `\mathfrak P_T = \prod_{P \in T} \mathfrak P` times a central `\mathfrak b^{-1}` is principal exactly when
        `\mathrm{nrd} = \prod_T P \cdot \mathfrak b^{-2}` has a generator positive at the ramified real places (Eichler's norm theorem; Voight Sec. 28.5, the lift
        through the class group of `Z`); its generator is found in the lattice `\mathfrak b^{-1} O_C` with `\mathrm{nrd}` generating that ideal.
        """
        if hasattr(self, "_normalizer"):
            return self._normalizer
        voronoi = self.voronoi()
        primes = list(self.algebra.ramified_places(inf=False))
        if not self.is_maximal():
            raise NotImplementedError(
                f"normalizer coset representatives of the non-maximal O_C (used by transporters); its generators come from "
                f":func:`normalizer_generators` (#54)"
            )
        ramified_real = ramified_real_places(self.algebra, RealField(64))
        units = self.field.unit_group()
        width = len(units.gens())
        reps, span = [], matrix(GF(2), 0, width)
        for u in voronoi.unit_generators():
            row = matrix(GF(2), [[x % 2 for x in units.log(self.field(u.reduced_norm()))]])
            if span.stack(row).rank() > span.rank():
                span = span.stack(row)
                reps.append(u)
        classes = [c.ideal() for c in self.field.class_group()]
        ramified = []
        for t in range(1, len(primes) + 1):
            for chosen in combinations(primes, t):
                product_ideal = self.field.ideal(1)
                for prime in chosen:
                    product_ideal *= prime
                for central in classes:
                    if positive_generator(self.field, product_ideal / central**2, ramified_real) is None:
                        continue
                    elements = [self.algebra(g) * o for g in (central**-1).basis() for o in self.order_basis]
                    generator = self._generator(elements, product_ideal / central**2)
                    if generator is not None:
                        ramified.append(generator)
                        break
        one = self.algebra(1)
        result = []
        for k in range(len(reps) + 1):
            for chosen_units in combinations(reps, k):
                for extra in [one, *ramified]:
                    n = extra
                    for u in chosen_units:
                        n = u * n
                    result.append(n)
        self._normalizer = tuple(result)
        return self._normalizer

    def _nonmaximal_centralizer_generators(self):
        r"""Return generators of `C(Z)` for a non-maximal `O_C`.

        `N(O_C)` comes from :func:`normalizer_generators` over the maximal orders containing `O_C`. Its elements with
        `N_{Z/Q}(\mathrm{nrd}\, n)` a rational square form the preimage of a finite subgroup of `Q^\times / Q^{\times 2}` (the reduced norms of
        `N(O_C)` are supported on the primes of the discriminant), so Schreier generators give it; their images `\pm \chi(n)/q` generate a group
        containing `C(Z)` with finite index, and the commutant's Schreier descent to `O` returns `C(Z)`."""
        from sage_indefinite_port.indefinite.quaternion_orders_number_field import maximal_orders_containing, normalizer_generators

        maximal = maximal_orders_containing(self.algebra, self.order_basis, self.expected_discriminant())
        generators = normalizer_generators(self.algebra, self.order_basis, maximal)

        def square_class(n):
            norm = QQ(self.field(n.reduced_norm()).norm())
            return (norm.numerator() * norm.denominator()).squarefree_part()

        subgroup, _index = finite_preimage_generators(generators, square_class, lambda c: c == 1)
        r = self.commutant.rank
        moves = [-identity_matrix(QQ, r)]
        for n in subgroup:
            norm = QQ(self.field(n.reduced_norm()).norm())
            moves.append(self.chi(n) / norm.sqrt())
        return tuple(self.commutant._order_subgroup_generators(moves))

    def centralizer_generators(self):
        r"""Return generators of `C(Z)` (module docstring)."""
        if not self.is_maximal():
            return self._nonmaximal_centralizer_generators()
        voronoi = self.voronoi()
        r = self.commutant.rank
        result = [-identity_matrix(QQ, r), *(self.chi(c) for c in voronoi.sl1_generators())]
        for n in self.normalizer_representatives():
            norm = QQ(self.field(n.reduced_norm()).norm())
            if norm <= 0 or not norm.is_square():
                continue
            g = self.chi(n) / norm.sqrt()
            if all(c in ZZ for c in g.list()) and all(c in ZZ for c in g.inverse().list()):
                result.extend([g, -g])
        assert all(self.commutant.is_centralizer_element(matrix(ZZ, g)) for g in result)
        return tuple(result)


def _reduced_norm_ideal(field, elements):
    r"""Return the ideal generated by `\mathrm{nrd}` on the `Z`-span of ``elements`` (values and polarizations)."""
    values = [x.reduced_norm() for x in elements]
    values += [(x + y).reduced_norm() - x.reduced_norm() - y.reduced_norm() for x in elements for y in elements]
    return field.ideal([v for v in values if v != 0])


def _algebra_isomorphism(source_algebra, target_algebra):
    r"""Return the images `x, y` in ``target_algebra`` of the generators `i, j` of ``source_algebra`` (same centre), or ``None`` when the
    algebras are not isomorphic.

    Quaternion algebras over a number field are isomorphic exactly when they ramify at the same places (Albert-Brauer-Hasse-Noether;
    Voight, *Quaternion Algebras*, Main Theorem 14.6.1), which decides. Then `x` is a pure quaternion with `x^2 = a`, a null vector
    `(u, v, w, t)`, `t \ne 0`, of `\langle a', b', -a'b', -a \rangle`. Following Lam, *Introduction to Quadratic Forms over Fields*, I.3.4, it
    is a value `c = a' u^2 + b' v^2` represented by `\langle -a'b', -a \rangle`, i.e. a point of the conic `\langle -a'b', -a, c \rangle`, decided
    exactly by Sage's number-field conic for each `c`. Such `c` form a nonempty set open at finitely many places, so the enumeration of
    `(u, v) = (u_0, v_0) / m` over growing boxes of `O_Z` and growing denominators `m` (dense in every completion) ends. `t \ne 0` because the pure norm form of a division algebra is anisotropic. `y` lies in the
    plane of pure quaternions anticommuting with `x` with `y^2 = b`, a point of a ternary conic, decided exactly."""
    if set(source_algebra.ramified_places(inf=False)) != set(target_algebra.ramified_places(inf=False)) or sorted(
        source_algebra.ramified_places(inf=True)[1], key=str
    ) != sorted(target_algebra.ramified_places(inf=True)[1], key=str):
        return None
    field = source_algebra.base_ring()
    a, b = source_algebra.invariants()
    a2, b2 = target_algebra.invariants()
    _one, i2, j2, k2 = target_algebra.basis()
    integers = field.ring_of_integers().basis()
    x, bound = None, 1
    while x is None:
        box = [sum(c * g for c, g in zip(coefficients, integers)) for coefficients in product(range(-bound, bound + 1), repeat=len(integers))]
        pairs = ((u / m, v / m) for m in range(1, bound + 1) for u, v in product(box, repeat=2))
        for u, v in pairs:
            c = a2 * u**2 + b2 * v**2
            if c == 0:
                continue
            found, point = Conic(field, [-a2 * b2, -a, c]).has_rational_point(point=True)
            if not found:
                continue
            W, T, S = list(point)
            if T != 0:
                x = (S * u * i2 + S * v * j2 + W * k2) / T
                break
        bound += 1
    assert x * x == target_algebra(a)
    pure = [i2, j2, k2]
    equation = matrix(field, [[(x * p + p * x).coefficient_tuple()[0]] for p in pure])
    plane = [sum((c * p for c, p in zip(k, pure)), target_algebra(0)) for k in equation.left_kernel().basis()]
    assert len(plane) == 2
    y1, y2 = plane
    g11 = (y1 * y1).coefficient_tuple()[0]
    g12 = (y1 * y2 + y2 * y1).coefficient_tuple()[0] / 2
    w2 = y2 - (g12 / g11) * y1
    g22 = (w2 * w2).coefficient_tuple()[0]
    found, point = Conic(field, [g11, g22, -b]).has_rational_point(point=True)
    assert found, "isomorphic algebras: the anticommuting plane represents b"
    P, Q, T = list(point)
    assert T != 0
    y = (P * y1 + Q * w2) / T
    assert y * y == target_algebra(b) and x * y == -y * x
    return x, y


def clifford_transporter(source, start, square, target_gram, targets):
    r"""Return an integral transporter to ``(target_gram, targets)`` for an anisotropic skew-Hermitian commutant, or ``None`` as a proof.

    ``start`` is a rational intertwiner and ``square`` `= B^{-1} t_0^t B' t_0`. A transporter `t = t_0 b` makes `\mathrm{Int}(t)` an isomorphism
    `(A, \sigma) \to (A', \sigma')` carrying `M_r(Z) \cap A` onto `M_r(Z) \cap A'`, hence the Clifford data `(Z, C, O_C)` onto those of the target,
    composed with one of the two embeddings of the target discriminant field (the second swaps `C'` and `\tau(C')`). So: the discriminants
    agree; for each embedding, `C \cong C''` (:func:`_algebra_isomorphism`), corrected by the generator `\alpha` of the connecting ideal
    `\psi_0(O_C) O_{C''}` (Eichler, class number one) to an isomorphism of maximal orders; `b` is its unique lift to `A` up to `Q^\times`
    (Skolem-Noether over `Z`, with `b` rational), a similitude with `\sigma(b) s b = \mu`. A transporter is an isometry, and whether it carries `C` to `C'` or to `\tau(C')` is
    covered by the two embeddings, so no improper coset is missed. Every transporter is `\pm t_0 b \chi(n) / q` with `n`
    in the normalizer of `O_C`, `q^2 = \mu N(\mathrm{nrd}\, n)`, modulo `\chi(SL_1(O_C)) \subseteq C(Z)`, so the finite list of
    :meth:`CliffordModel.normalizer_representatives` decides."""
    commutant = source.commutant
    target = CliffordModel(IsometryCommutant(target_gram, targets))
    if not (target.delta / source.delta).is_square():
        return None
    if source.field.class_number() != 1:
        raise NotImplementedError(f"the connecting ideal over Z = {source.field} of class number > 1 need not be principal (#54)")
    inverse = start.inverse()
    r = commutant.rank
    basis = [m.change_ring(QQ) for m in commutant.order_basis]
    for embedding in target.field.embeddings(source.field):
        a2, b2 = target.algebra.invariants()
        algebra = QuaternionAlgebra(source.field, embedding(a2), embedding(b2))
        move = lambda q: algebra([embedding(c) for c in q.coefficient_tuple()])
        frame = [inverse * F.apply_map(embedding) * start for F in target.frame]
        order = [move(o) for o in target.order_basis]
        voronoi = quaternion_unit_engine(algebra, order)
        isomorphism = _algebra_isomorphism(source.algebra, algebra)
        if isomorphism is None:
            continue
        x, y = isomorphism
        psi0 = lambda q: sum((c * g for c, g in zip(q.coefficient_tuple(), (algebra(1), x, y, x * y))), algebra(0))
        connecting = [psi0(o) * o2 for o in source.order_basis for o2 in order]
        alpha = voronoi.norm_generator(connecting, _reduced_norm_ideal(source.field, connecting))
        assert alpha is not None, f"the connecting ideal over {source.field} is not principal (#54)"
        psi = lambda q: ~alpha * psi0(q) * alpha
        assert all(voronoi.in_order(psi(o)) for o in source.order_basis)
        image = lambda q: sum((c * F for c, F in zip(q.coefficient_tuple(), frame)), 0 * frame[0])
        _one, i, j, _k = source.algebra.basis()
        rows = []
        for m in basis:
            entries = []
            for generator, matrix_generator in ((i, source.frame[1]), (j, source.frame[2])):
                difference = m.change_ring(source.field) * matrix_generator - image(psi(generator)) * m.change_ring(source.field)
                entries.extend(c for e in difference.list() for c in source.field(e).list())
            rows.append(entries)
        kernel = matrix(QQ, rows).left_kernel().basis()
        assert len(kernel) == 1, f"the lift of the Clifford isomorphism is not unique up to Q^x: {len(kernel)}"
        b = sum(QQ(c) * m for c, m in zip(kernel[0], basis))
        assert b.det() != 0
        similitude = commutant.adjoint(b) * square * b
        mu = similitude[0, 0]
        assert similitude == mu * identity_matrix(QQ, r)
        for n in source.normalizer_representatives():
            multiplier = mu * QQ(source.field(n.reduced_norm()).norm())
            if multiplier <= 0 or not multiplier.is_square():
                continue
            candidate = start * b * source.chi(n) / multiplier.sqrt()
            for sign in (1, -1):
                found = _verified(commutant, sign * candidate, target_gram, targets)
                if found is not None:
                    return found
    return None


def _norm_product(primes):
    result = ZZ(1)
    for prime in primes:
        result *= prime.norm()
    return result
