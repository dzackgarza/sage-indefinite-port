"""Ar(Lattices): a sublattice I of L is the marked lattice (L, I -> L)."""

type Vector = Lattices.ElementMethods
type Flag = tuple[Vector, Parent]
"""A flag Zu < J < L: a primitive isotropic u and the totally isotropic plane J containing it, a subobject of L."""


class UnsupportedRankError(ValueError):
    """Totally isotropic sublattices of rank above 2 are outside the induction (map §13.5)."""


class IsotropicInduction:
    def __init__(self, recursion: EichlerRecursion) -> None:
        self.recursion = recursion
        self._line_classes: dict[int, tuple[Lattices.ParentMethods, tuple[Vector, ...]]] = {}
        self._candidates: dict[tuple[int, tuple[int, ...]], tuple[Lattices.ParentMethods, tuple[Flag, ...]]] = {}

    def isotropic_vector_classes(self, lattice: Lattices.ParentMethods) -> tuple[Vector, ...]:
        r"""One primitive isotropic vector per O(L)-orbit: none for definite L, marked cells for positive index 1, the recursion beyond.

        The representatives are computed once per lattice (the source's ListOrbit), so line,
        plane and flag classes of one lattice share them and the candidates built on them.
        """
        if id(lattice) not in self._line_classes:
            self._line_classes[id(lattice)] = (lattice, self._computed_isotropic_vector_classes(lattice))
        return self._line_classes[id(lattice)][1]

    def _computed_isotropic_vector_classes(self, lattice: Lattices.ParentMethods) -> tuple[Vector, ...]:
        profile = AttackProfile.from_lattice(lattice)
        match profile.positive_index:
            case 0:
                return ()
            case 1:
                if not lattice.is_isotropic():
                    return ()
                if int(lattice.rank()) == 2 and tuple(map(int, lattice.signature_pair())) == (1, 1):
                    return binary_split_primitive_vector_classes(lattice, 0)
                # CombinedAlgorithms.h:2483-2492 applies IndefiniteReduction
                # before the Lorentzian orbit dispatcher. The pinned
                # lorentzian_perfect.h:1625-1644 enumerates the TOTAL perfect
                # cells even for square zero, extracting their null vertices;
                # the isotropic-only perfect-cell mode is a different routine.
                # The integral isometry reduced -> lattice transports the
                # complete orbit representatives, as res.B.transpose() does.
                # CombinedAlgorithms.h:1702-1706 passes the signed attack
                # form to the Lorentzian dispatcher.  For signature (n, 1)
                # this is -L; isotropic vectors have the same coordinates,
                # but must be returned as elements of the original L.
                reduction = indefinite_reduced_presentation(profile.signed_view)
                orbits = MarkedCellOrbitAlgorithm(perfect_complex(reduction.reduced, NONNEGATIVE_SQUARES), 0).global_orbits()
                representatives = tuple(reduction.isometry(orbit[0]) for orbit in orbits)
                if profile.sign == 1:
                    return representatives
                return tuple(
                    lattice.linear_combination({label: representative.to_vector()(label) for label in lattice.module_generating_set()})
                    for representative in representatives
                )
            case _:
                return tuple(vector_class.representative for vector_class in self.recursion.primitive_vector_classes(lattice, 0))

    @staticmethod
    def reduction(lattice: Lattices.ParentMethods, *vectors: Vector) -> Parent:
        r"""The isotropic reduction I^perp/I of the primitive totally isotropic I spanned by the vectors."""
        return lattice.primitive_isotropic_subobject(*vectors).isotropic_reduction()

    @staticmethod
    def plane_vectors(plane: Parent) -> tuple[Vector, ...]:
        r"""A basis of the plane in the coordinate-label order used by its frame."""
        inclusion = plane.inclusion()
        domain = inclusion.domain()
        return tuple(inclusion(domain.module_generator(label)) for label in domain.module_generating_set())

    def line_isometry(self, source: Vector, target: Vector) -> LatticeIsometryMethods | None:
        r"""An isometry carrying Zu onto Zw: one carrying u to w or to -w."""
        isometry = self.recursion.pointed_isometry(source, target)
        return isometry if isometry is not None else self.recursion.pointed_isometry(source, -target)

    @staticmethod
    def _frame_lifts(reduction: Parent) -> tuple[tuple, dict]:
        r"""The labels of K = u^perp/u and their frame lifts into u^perp <= L, as the recursion's line action uses them."""
        perpendicular = reduction.orthogonal_complement().inclusion()
        frame = reduction.coordinate_frame()
        labels = tuple(reduction.quotient_lattice().module_generating_set())
        return labels, {label: perpendicular(frame(label)) for label in labels}

    @staticmethod
    def _lift(lattice: Lattices.ParentMethods, labels: tuple, lifts: dict, element: Vector) -> Vector:
        r"""The frame lift into u^perp of a vector of K (eRec.TheCompl * eRec.NSP applied to it)."""
        coordinates = element.to_vector()
        return sum((lattice.scalar_multiple(coordinates(label), lifts[label]) for label in labels if coordinates(label)), lattice.zero())

    @staticmethod
    def _integral_image(lattice: Lattices.ParentMethods, element: object, vector: Vector) -> Vector:
        r"""The image of a vector of L under a rational isometry that preserves u^perp, as a vector of L."""
        rational = lattice.base_change(lattice.base_ring().fraction_field_map())
        labels = tuple(lattice.module_generating_set())
        coordinates = vector.to_vector()
        rational_point = rational.linear_combination({label: rational.base_ring()(int(coordinates(label))) for label in labels if coordinates(label)})
        moved = element(rational_point).to_vector()
        if any(moved(label).denominator() != 1 for label in labels):
            raise ArithmeticError(f"{element} does not preserve u^perp integrally: it carries {vector} to a nonintegral vector")
        return lattice.linear_combination({label: lattice.base_ring()(int(moved(label))) for label in labels if moved(label)})

    def _plane_stabilizer_generators(self, reduction: Parent, line: Vector, isotropic: Vector) -> tuple:
        r"""Rational generators of V: the plane span(u, x~) stabilizer inside the line's rational group G.

        # source: CombinedAlgorithms.h:1975-2075 f_stab_plane_v, with :821-877
        # ExtendIsometryGroup_IsotropicOrth and :776-817 ExtendIsometryGroup_Triangular (sd = one
        # block of dimension 1), mapped by :496-534 MapOrthogonalSublatticeGroupUsingSublattice.
        Images of the basis (u, frame lifts) of N = u^perp: -Id_N; the extensions of Aut((K, x))
        (u fixed); the GL(1) block sign u -> -u; the shears frame_i -> frame_i + u. The source's
        third family, x~ -> x~ + u with a completion of (u, x~) fixed, is k -> k + phi(k) u for a
        functional phi of K with phi(x) = 1, a product of the frame shears, so it adds nothing.

        Deviation: the source lifts V with the Sublattice computed for G so that V lies in G. For
        a line the restriction G -> Aut(N) is injective: an isometry fixing N = u^perp pointwise
        sends u' (b(u, u') = 1) to u' + a u, and isotropy of the image gives 2a = 0. The
        extension of an N-automorphism to L tensor Q is therefore unique, extension is a
        homomorphism, and the extensions below lie in G = isotropic_stabilizer_action((u,), (-u,)),
        whose generators are extensions of generators of the same group of N-automorphisms: the
        O(K) generators, the sign of u and the frame shears generate every automorphism of N
        preserving Zu, and V's generators are such automorphisms.
        """
        lattice = line.parent()
        quotient = reduction.quotient_lattice()
        labels, lifts = self._frame_lifts(reduction)
        frame = tuple(lifts[label] for label in labels)
        basis = (line, *frame)
        families = [(-line, *(-lifted for lifted in frame))]
        for automorphism in self.recursion.pointed_automorphism_generators(isotropic):
            families.append((line, *(self._lift(lattice, labels, lifts, automorphism(quotient.module_generator(label))) for label in labels)))
        families.append((-line, *frame))
        for sheared in range(len(frame)):
            families.append((line, *(lifted + line if position == sheared else lifted for position, lifted in enumerate(frame))))
        return tuple(_extend_perpendicular_isometry(reduction, reduction, basis, images)[0] for images in families)

    def flags_through(self, lattice: Lattices.ParentMethods, line: Vector) -> Iterator[Flag]:
        r"""Flags (Zu, J) meeting every Aut((L, Zu))-orbit of isotropic planes J through u.

        # source: CombinedAlgorithms.h:2259-2377 SpanRepresentatives with :2076-2190
        # f_double_cosets (METHOD_GENERATION_DOUBLE_COSETS, the default of :2396-2402).
        For each isotropic class x of K = u^perp/u (ListOrbitF) with frame lift x~ in N = u^perp
        (eVectB = Embed^T eVect), G, the rational line group (IndefiniteForms.g:1060-1130),
        carries span(u, x~) onto every plane through u over the O(K)-orbit of x: such a plane is
        the preimage in N of its line in K. With G_L = Aut((L, Zu)) and V <= Stab_G(span(u, x~))
        (f_stab_plane_v), the double cosets V t G_L give G = union of G_L t^-1 V, so the planes
        span(u, t^-1(x~)) meet every G_L-orbit; the callers deduplicate by exact isometry, as the
        source's fInsert does. G preserves N integrally, so t^-1(x~) is in L.

        The source maps G and V with one Sublattice so that V lies in G
        (MapOrthogonalSublatticeGroupUsingSublattice). Here G is presented on the generators of
        the line action together with those of V; it is the same group (V lies in G, see
        _plane_stabilizer_generators), so the line action's stable containing module still
        bounds it, and V is a subgroup on selected generators of that presentation. The
        source's ExhaustiveMatrixRightCosetSimplifications and ExhaustiveVectorSimplification
        only shorten representatives and are not translated.
        """
        # The candidates through a line are data of (L, u); plane_classes and flag_classes both
        # read them, and building the line action and its cosets dominates their cost.
        coordinates = line.to_vector()
        key = (id(lattice), tuple(int(coordinates(label)) for label in lattice.module_generating_set()))
        if key not in self._candidates:
            reduction = self.reduction(lattice, line)
            quotient = reduction.quotient_lattice()
            labels, lifts = self._frame_lifts(reduction)
            line_action = self.recursion.isotropic_stabilizer_action((line,), ((-line,),))
            line_generators = tuple(line_action.rational_group().group_generators())
            ambient = line_action.rational_group().supergroup()
            candidates = []
            for isotropic in self.isotropic_vector_classes(quotient):
                lifted = self._lift(lattice, labels, lifts, isotropic)
                plane_generators = self._plane_stabilizer_generators(reduction, line, isotropic)
                group = ambient.subgroup((*line_generators, *plane_generators))
                action = IntegralStructureAction(group, line_action.lattice_inclusion()).with_stable_containing_bound(line_action.stable_containing_bound())
                double_cosets = action.double_cosets(group.subgroup(plane_generators))
                section = double_cosets.double_coset_section()
                candidates.extend((line, lattice.primitive_isotropic_subobject(line, self._integral_image(lattice, ~section(orbit), lifted))) for orbit in double_cosets)
            self._candidates[key] = (lattice, tuple(candidates))
        return iter(self._candidates[key][1])

    def flag_classes(self, lattice: Lattices.ParentMethods) -> tuple[Flag, ...]:
        r"""One flag per O(L)-orbit of isotropic flags of ranks (1, 2).

        # source: CombinedAlgorithms.h:2192-2394 INDEF_FORM_GetOrbit_IsotropicKstuff_Method with
        # sd = seq_dims_flag(2): fInsert (:2238-2258) keeps a candidate unless it is
        # flag-equivalent to a kept one (IndefiniteForms.g:1784-1799, :1887-1971). Flags whose
        # lines lie in different O(L)-orbits are never equivalent, so each candidate is compared
        # with the kept flags through its own line only. The invariant prefilter of fInsert
        # (INDEF_FORM_Invariant of the reduction) is the LatticePrefilter that
        # EichlerRecursion.isometry applies to the reductions inside flag_isometry.
        """
        # A rational totally isotropic plane exists exactly when the Witt
        # index is at least two.  In particular a Witt-index-one lattice
        # has no flags of ranks (1, 2), independently of its line orbits.
        if int(lattice.witt_index()) < 2:
            return ()
        kept: list[Flag] = []
        for line in self.isotropic_vector_classes(lattice):
            through: list[Flag] = []
            for flag in self.flags_through(lattice, line):
                if all(self.flag_isometry(other, flag) is None for other in through):
                    through.append(flag)
            kept.extend(through)
        return tuple(kept)

    def plane_classes(self, lattice: Lattices.ParentMethods) -> tuple[Parent, ...]:
        r"""One plane per O(L)-orbit of primitive totally isotropic planes.

        # source: CombinedAlgorithms.h:2192-2394 with sd = seq_dims_plane(2) (IndefiniteForms.g:
        # 1774-1883): every candidate of every line class, kept unless plane-equivalent to a kept plane.
        """
        if int(lattice.witt_index()) < 2:
            return ()
        kept: list[Parent] = []
        for line in self.isotropic_vector_classes(lattice):
            for _line, plane in self.flags_through(lattice, line):
                if all(self.plane_isometry(other, plane) is None for other in kept):
                    kept.append(plane)
        return tuple(kept)

    def flag_isometry(self, source: Flag, target: Flag) -> LatticeIsometryMethods | None:
        r"""An isometry carrying the line onto the line and the plane onto the plane, or None (f_equiv_flag).

        Bases (u, j) and (u', j') with the lines first; the correction group's action on J' is the
        stabilizer of Zu' in GL(J').
        """
        line, other = self.flag_basis(source)
        target_line, target_other = self.flag_basis(target)
        return self.recursion.isotropic_subspace_isometry(
            (line, other),
            (target_line, target_other),
            ((-target_line, target_other), (target_line, -target_other), (target_line, target_other + target_line)),
        )

    def plane_isometry(self, source: Parent, target: Parent) -> LatticeIsometryMethods | None:
        r"""An isometry carrying the plane J onto J', or None (f_equiv_plane): the correction group acts on J' through GL(J')."""
        first, second = self.plane_vectors(source)
        target_first, target_second = self.plane_vectors(target)
        return self.recursion.isotropic_subspace_isometry(
            (first, second),
            (target_first, target_second),
            ((target_second, target_first), (target_first + target_second, target_second), (-target_first, target_second)),
        )

    def _stabilizer_generators(self, isotropic: tuple[Vector, ...], radical_images: tuple[tuple[Vector, ...], ...]) -> tuple[LatticeIsometryMethods, ...]:
        # source: IndefiniteForms.g:1710-1723 INDEF_FORM_Stabilizer_IsotropicKstuff_Kernel, whose
        # MatrixIntegral_Stabilizer conjugates the generators back to integral matrices on Z^n
        # (GroupAction.g:869-886); the action reads each one on the basis of L once.
        action = self.recursion.isotropic_stabilizer_action(isotropic, radical_images)
        lattice = isotropic[0].parent()
        return tuple(lattice.integral_isometry(generator) for generator in action.stabilizer().group_generators())

    def line_automorphism_generators(self, lattice: Lattices.ParentMethods, line: Vector) -> tuple[LatticeIsometryMethods, ...]:
        r"""Aut((L, Zu)): Gamma = {+-1} on the line (IndefiniteForms.g:1711-1725 with k = 1)."""
        if line.parent() is not lattice:
            raise ValueError(f"{line} is not a vector of {lattice}")
        return self._stabilizer_generators((line,), ((-line,),))

    def plane_automorphism_generators(self, plane: Parent) -> tuple[LatticeIsometryMethods, ...]:
        r"""Aut((L, J)): Gamma = GL(J), generated by the swap, the elementary shear and a sign (IndefiniteForms.g:1711-1725)."""
        first, second = self.plane_vectors(plane)
        # Images of (first, second): the swap, the elementary shear and a sign generate GL(J).
        return self._stabilizer_generators((first, second), ((second, first), (first + second, second), (-first, second)))

    @staticmethod
    def flag_basis(flag: Flag) -> tuple[Vector, Vector]:
        r"""A basis (u, j) of J whose first vector is the flag's line vector u, primitive in J."""
        line, plane = flag
        inclusion = plane.inclusion()
        coordinates = inclusion.lift(line).to_vector()
        labels = tuple(inclusion.domain().module_generating_set())
        a, b = (int(coordinates(label)) for label in labels)
        gcd_value, c, d = xgcd(a, b)
        if abs(gcd_value) != 1:
            raise ValueError(f"{line} is not primitive in its plane")
        # a*c + b*d = gcd = +-1, so (a, b), (-d, c) is a basis; its second vector completes u.
        first, second = (inclusion(inclusion.domain().module_generator(label)) for label in labels)
        lattice = line.parent()
        ring = lattice.base_ring()
        return line, lattice.scalar_multiple(ring(int(-d)), first) + lattice.scalar_multiple(ring(int(c)), second)

    def flag_automorphism_generators(self, flag: Flag) -> tuple[LatticeIsometryMethods, ...]:
        r"""Aut of the flag Zu < J: Gamma = the stabilizer of Zu in GL(J), generated by two signs and the shear j -> j + u (f_stab_flag)."""
        line, other = self.flag_basis(flag)
        return self._stabilizer_generators(
            (line, other),
            ((-line, other), (line, -other), (line, other + line)),
        )


