r"""Voronoi's algorithm for unit groups of quaternion orders over a real quadratic field (#54).

Let `A = (a, b)_Z` be a quaternion algebra over a real quadratic field `Z`, `O` an order with a `Z`-basis `o_1, \ldots, o_8`, and
`\iota` a positive involution of `A` over `Q`, i.e. `(x, y) \mapsto \mathrm{Tr}_{A/Q}(x \iota(y))` is positive definite. By Albert's
classification a quaternion algebra over a totally real field has one exactly when it is totally definite (the canonical involution)
or totally indefinite (`x \mapsto t^{-1} \bar x t` for a pure `t`); one is searched and certified by the positive definiteness of that
trace form. `\mathrm{Herm} = \{s \in A : \iota(s) = s\}` is a `Q`-space with the positive definite pairing `\langle s, r \rangle = \mathrm{Tr}_{A/Q}(s r)`.

Forms. `s \in \mathrm{Herm}` defines `\varphi_s(x) = \mathrm{Tr}_{A/Q}(\iota(x) s x) = \langle s, x \iota(x) \rangle` on `O`; `s` is positive when `\varphi_s` is
positive definite. Its minimum `\mu(s)`, minimal vectors `\mathrm{Min}(s)` and Voronoi domain `\mathrm{cone}\{x \iota(x) : x \in \mathrm{Min}(s)\}`
are as in Voronoi's theory; `s` is perfect when the rays span `\mathrm{Herm}`. A unit `u` acts by `u \cdot s = \iota(u) s u`, with
`\varphi_{u \cdot s}(x) = \varphi_s(u x)` and `\mathrm{Min}(u \cdot s) = u^{-1} \mathrm{Min}(s)`. The Voronoi domains of perfect forms tile the
positive cone, there are finitely many perfect forms up to `O^\times` and positive scalars, and `O^\times` is generated by the stabilizers of
representatives together with the elements carrying each Voronoi neighbour to its representative (Braun, Coulangeon, Nebe,
Schoennenbeck, *Computing in arithmetic groups with Voronoi's algorithm*, J. Algebra 435 (2015), arXiv:1407.6234, Sec. 2-3; Opgenorth,
*Dual cones and the Voronoi algorithm*, Experiment. Math. 10 (2001); Koecher, Math. Ann. 141 (1960)).

Neighbours. For a facet of the Voronoi domain of a perfect `s` with inner normal `r` (`\langle r, x \iota(x) \rangle \ge 0` on the domain, `= 0` on
the facet), the neighbour is `s + \rho r` with the least `\rho > 0` at which a new minimal vector appears; `\rho` is found by Schuermann's
iteration (Schuermann, *Computational geometry of positive definite quadratic forms*, AMS Univ. Lecture Ser. 48 (2009), Alg. 2): shrink to
a positive form, then replace `\rho` by `\min (\varphi_s(x) - \mu) / (-\langle r, x \iota(x) \rangle)` over the vectors `x` with
`\varphi_{s + \rho r}(x) < \mu` until there are none. The same iteration with `r` orthogonal to the rays of a non-perfect `s` makes it perfect.

Equivalence. `u \cdot s = s'` forces `u x_0 \in \mathrm{Min}(s)` for a fixed `x_0 \in \mathrm{Min}(s')`, so `u = m x_0^{-1}` with `m \in \mathrm{Min}(s)`: a finite
test, and the same list gives the finite stabilizer.
"""

from itertools import product

from sage.geometry.polyhedron.constructor import Polyhedron
from sage.matrix.constructor import matrix
from sage.modules.free_module_element import vector
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ
from sage_extensions.algebras.isometry_commutant import _short_vectors


class QuaternionOrderVoronoi:
    r"""Perfect forms and Voronoi neighbours for an order ``order_basis`` of the quaternion algebra ``algebra`` over a real quadratic field."""

    def __init__(self, algebra, order_basis):
        self.algebra = algebra
        self.center = algebra.base_ring()
        assert self.center.degree() == 2 and self.center.is_totally_real()
        one = self.center.one()
        self._q_basis = [self.center.gen() ** p * g for g in algebra.basis() for p in (0, 1)]
        assert self._q_basis[0] == algebra(one)
        self.order = tuple(algebra(x) for x in order_basis)
        assert len(self.order) == 8
        self._order_rows = matrix(QQ, [self.coordinates(x) for x in self.order])
        assert self._order_rows.det() != 0
        self.involution = self._positive_involution()
        kernel = matrix(QQ, [self.coordinates(self.involution(q) - q) for q in self._q_basis]).left_kernel().basis()
        self.herm = [self.element(row) for row in (matrix(QQ, kernel) * matrix(QQ, [self.coordinates(q) for q in self._q_basis])).rows()]
        self._herm_rows = matrix(QQ, [self.coordinates(s) for s in self.herm])
        self._pairing = matrix(QQ, [[self.trace(s * r) for r in self.herm] for s in self.herm])
        assert self._pairing.is_positive_definite()

    # Coordinates over Q.
    def coordinates(self, x):
        return [c for a in self.algebra(x).coefficient_tuple() for c in self.center(a).list()]

    def element(self, coordinates):
        return sum((QQ(c) * q for c, q in zip(coordinates, self._q_basis)), self.algebra(0))

    def order_coordinates(self, x):
        r"""Return the coordinates of ``x`` in the order basis (rational; integral exactly when ``x`` is in the order)."""
        return self._order_rows.solve_left(vector(QQ, self.coordinates(x)))

    def in_order(self, x):
        return all(c in ZZ for c in self.order_coordinates(x))

    def from_order(self, coordinates):
        return sum((ZZ(c) * o for c, o in zip(coordinates, self.order)), self.algebra(0))

    def herm_coordinates(self, s):
        return self._herm_rows.solve_left(vector(QQ, self.coordinates(s)))

    def trace(self, x):
        return QQ(self.center(self.algebra(x).reduced_trace()).trace())

    def is_unit(self, x):
        return self.in_order(x) and self.in_order(~x)

    def _positive_involution(self):
        r"""Return a positive involution over `Q`: the canonical one, or `x \mapsto t^{-1} \bar x t` for a pure `t` (module docstring)."""
        candidates = [lambda x: x.conjugate()]
        _one, i, j, k = self.algebra.basis()
        scalars = [0, 1, -1, self.center.gen(), -self.center.gen()]
        for coefficients in product(scalars, repeat=3):
            t = coefficients[0] * i + coefficients[1] * j + coefficients[2] * k
            if t != 0:
                candidates.append(lambda x, t=t: ~t * x.conjugate() * t)
        for involution in candidates:
            gram = matrix(QQ, [[self.trace(x * involution(y)) for y in self._q_basis] for x in self._q_basis])
            if gram.is_positive_definite():
                return involution
        raise NotImplementedError(
            f"no positive involution of {self.algebra} over Q among the canonical one and x -> t^-1 conj(x) t for small pure t; "
            f"by Albert's classification there is none unless the algebra is totally definite or totally indefinite, and the "
            f"cone of Hermitian forms then needs a splitting field (#54)"
        )

    # Forms.
    def gram(self, s):
        r"""Return the Gram matrix of `\varphi_s` in the order basis."""
        iota = self.involution
        return matrix(
            QQ,
            [[(self.trace(iota(x) * s * y) + self.trace(iota(y) * s * x)) / 2 for y in self.order] for x in self.order],
        )

    def value(self, s, x):
        return self.trace(self.involution(x) * s * x)

    def ray(self, x):
        return self.herm_coordinates(x * self.involution(x))

    def pairing(self, s, x):
        r"""Return `\langle s, x \iota(x) \rangle = \varphi_s(x)` for ``s`` in `\mathrm{Herm}` (as an algebra element)."""
        return self.value(s, x)

    def is_positive(self, s):
        return self.gram(s).is_positive_definite()

    def _below(self, s, bound):
        r"""Return the order elements `x \ne 0` with `\varphi_s(x) < ` ``bound``, `s` positive."""
        gram = self.gram(s)
        return [self.from_order(v) for v in _short_vectors(gram, bound) if (v * gram * v) < bound]

    def minimum(self, s):
        gram = self.gram(s)
        bound = min(gram[i, i] for i in range(gram.nrows()))
        vectors = _short_vectors(gram, bound)
        mu = min(v * gram * v for v in vectors)
        return mu, [self.from_order(v) for v in vectors if v * gram * v == mu]

    def is_perfect(self, s):
        _mu, minimal = self.minimum(s)
        return matrix(QQ, [self.ray(x) for x in minimal]).rank() == len(self.herm)

    def _step(self, s, r):
        r"""Return the least `\rho > 0` at which `s + \rho r` has a new minimal vector (Schuermann, Alg. 2)."""
        mu, _minimal = self.minimum(s)
        low, high = QQ(0), QQ(1)
        while True:
            moved = s + high * r
            if not self.is_positive(moved):
                high = (low + high) / 2
                continue
            below = self._below(moved, mu)
            if below:
                break
            low, high = high, 2 * high
        while below:
            high = min((self.value(s, x) - mu) / (-self.value(r, x)) for x in below)
            below = self._below(s + high * r, mu)
        return high

    def _normalized(self, s):
        mu, _minimal = self.minimum(s)
        return s / mu

    def perfect_form(self):
        r"""Return a perfect form, from `s = 1` by moves orthogonal to the rays of the minimal vectors."""
        s = self.algebra(1)
        while not self.is_perfect(s):
            _mu, minimal = self.minimum(s)
            rays = matrix(QQ, [self.ray(x) for x in minimal])
            direction = (rays * self._pairing).right_kernel().basis()[0]
            r = sum((QQ(c) * h for c, h in zip(direction, self.herm)), self.algebra(0))
            if self.gram(r).is_positive_semidefinite():
                r = -r
            assert not self.gram(r).is_positive_semidefinite()
            s = self._normalized(s + self._step(s, r) * r)
        return self._normalized(s)

    def facet_normals(self, s):
        r"""Return the inner normals `r \in \mathrm{Herm}` of the facets of the Voronoi domain of the perfect ``s`` (exact ``ppl`` backend)."""
        _mu, minimal = self.minimum(s)
        cone = Polyhedron(rays=[self.ray(x) for x in minimal], base_ring=QQ, backend="ppl")
        assert cone.dim() == len(self.herm)
        inverse = self._pairing.inverse()
        normals = []
        for inequality in cone.inequalities():
            assert inequality.b() == 0
            coordinates = inverse * vector(QQ, inequality.A())
            normals.append(sum((QQ(c) * h for c, h in zip(coordinates, self.herm)), self.algebra(0)))
        return normals

    def neighbour(self, s, r):
        r"""Return the normalized Voronoi neighbour of the perfect ``s`` across the facet with inner normal ``r``."""
        if self.gram(r).is_positive_semidefinite():
            raise NotImplementedError(
                f"the facet normal {r} of the perfect form {s} is positive semidefinite: the facet lies on the boundary of the "
                f"cone, which happens only for a group of positive Q-rank; this order's unit group is not cocompact (#54)"
            )
        return self._normalized(s + self._step(s, r) * r)

    def transporter(self, source, target):
        r"""Return a unit `u` with `u \cdot` ``source`` `=` ``target`` (both normalized), or ``None`` (module docstring, Equivalence)."""
        _mu, minimal = self.minimum(source)
        _nu, target_minimal = self.minimum(target)
        if len(minimal) != len(target_minimal):
            return None
        x0 = target_minimal[0]
        for m in minimal:
            u = m * ~x0
            if self.is_unit(u) and self.involution(u) * source * u == target:
                return u
        return None

    def stabilizer(self, s):
        _mu, minimal = self.minimum(s)
        x0 = minimal[0]
        result = []
        for m in minimal:
            u = m * ~x0
            if self.is_unit(u) and self.involution(u) * s * u == s:
                result.append(u)
        return result

    def perfect_forms(self):
        r"""Return representatives of the perfect forms up to `O^\times`, with the transports of their neighbours."""
        if not hasattr(self, "_perfect"):
            forms, transports = [self.perfect_form()], []
            position = 0
            while position < len(forms):
                s = forms[position]
                position += 1
                for r in self.facet_normals(s):
                    neighbour = self.neighbour(s, r)
                    found = next(((k, u) for k, known in enumerate(forms) for u in [self.transporter(known, neighbour)] if u is not None), None)
                    if found is None:
                        forms.append(neighbour)
                    else:
                        transports.append(found[1])
            self._perfect = (tuple(forms), tuple(transports))
        return self._perfect[0]
