r"""The Bestvina-Savin ocean of an anisotropic binary Hermitian form over `Z[i]` (#59).

Source: M. Bestvina, G. Savin, *Geometry of integral binary Hermitian forms*, arXiv:1104.1474v2.
This module implements the coefficient ring `A = Z[i]`, discriminant `D = -4`.

Conventions follow section 3: `f(v) = v^T H \bar v` on column vectors `v \in A^2`, where
`H = [[a, \nu], [\bar\nu, c]]` has `a, c \in Z` and `\nu \in A^* = (1/2) A`, and
`\Delta = D (a c - N(\nu))`. A matrix `g \in GL_2(A)` acts on column vectors, and `g \in U(f)` when
`g^T H \bar g = H`. Since `N(\det g) = 1`, an element of `GL_2(A)` that multiplies `f` by a positive
scalar multiplies it by `1`. Hence `PU(f) = U(f) / \mu_4`, and each class has four integral lifts.

Spine (section 4 and the start of section 7), in terms of lax vectors, which are primitive vectors
of `A^2` up to `A^\times`:

- A 2-cell is a lax basis `{u, v}`.
- The edges of the cell `{u, v}` are the superbases `{u, v, u + i^k v}`.
- A vertex is a set of six lax vectors `{r, s} \cup {(1+i)/2 (r + i^k s)}`, where `r, s` span a
  submodule of index 2. Consecutive edges of `{u, v}` meet at the vertex with
  `{r, s} = {u + i^k v, u + i^{k+1} v}`.

The ocean (Definition 1) is the set of cells with `F(u) F(v) < 0`. The form is anisotropic exactly
when the quaternion algebra `(D, \Delta)` is division (section 3).

Generators. Theorem 5.1 gives finitely many orbits of cells and Theorem 6.1 makes the ocean a
connected surface, so cells adjacent across edges form a connected graph. Let `R` be orbit
representatives and, for each side of each representative, let `g` move the neighbouring cell to
a representative. Let `G` be generated by these `g` and the stabilizers of `R`. The set `G R` is
closed under adjacency: if `\tau` is the neighbour of `\sigma \in R` and `g \tau = \sigma'`, then
the neighbour `h \tau` of `h \sigma` equals `h g^{-1} \sigma'`. So `G R` is every cell. For `\gamma` in
`PU(f)` and `\sigma \in R` there is `h \in G` with `h \sigma = \gamma \sigma`, and `h^{-1} \gamma` stabilizes `\sigma`.
Thus `G = PU(f)`. By #59 section D, lifts together with `\mu_4` generate `U(f)`.

The paper's introduction places the algorithm in section 8, but the printed section 8 treats
`D = -3`. The construction for `D = -4` is section 7, with the computation in Example 7.1.
"""

from dataclasses import dataclass
from heapq import heappop, heappush
from itertools import combinations, count

from sage.arith.misc import hilbert_symbol, prime_divisors
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.rings.integer_ring import ZZ
from sage.rings.number_field.number_field import CyclotomicField
from sage.rings.rational_field import QQ

FIELD = CyclotomicField(4)
I = FIELD.gen()
UNITS = (FIELD.one(), I, -FIELD.one(), -I)


def _coordinates(element) -> tuple:
    return tuple(int(c) for c in element.list())


def _is_gaussian_integer(element) -> bool:
    return all(c.denominator() == 1 for c in element.list())


def discriminant(form) -> int:
    r"""Return `\Delta = D (a c - N(\nu))` with `D = -4`."""
    return ZZ(-4 * (form[0, 0] * form[1, 1] - form[0, 1] * form[0, 1].conjugate()))


def is_anisotropic(form) -> bool:
    r"""Return whether `f` does not represent 0, by the Hilbert symbols of `(-1, \Delta)` (section 3)."""
    delta = discriminant(form)
    return any(hilbert_symbol(-1, delta, p) == -1 for p in prime_divisors(2 * abs(delta)))


def _check_form(form) -> None:
    if form.nrows() != 2 or form.ncols() != 2 or form.base_ring() is not FIELD:
        raise ValueError("the form must be a 2 by 2 matrix over Q(i)")
    if form != form.conjugate_transpose():
        raise ValueError("the form must be Hermitian")
    if form[0, 0] not in QQ or form[1, 1] not in QQ:
        raise ValueError("the diagonal must be rational")
    if QQ(form[0, 0]) not in ZZ or QQ(form[1, 1]) not in ZZ or not _is_gaussian_integer(2 * form[0, 1]):
        raise ValueError("the form must be integral on Z[i]^2: a, c in Z and nu in (1/2) Z[i]")
    if discriminant(form) <= 0:
        raise ValueError("the form must be indefinite: the source requires Delta > 0")
    if not is_anisotropic(form):
        raise ValueError("the form represents 0: the ocean of the source requires an anisotropic form")


def _lax(a, b) -> tuple:
    r"""Return the canonical representative of the lax vector of `(a, b)`."""
    return min(((u * a, u * b) for u in UNITS), key=lambda v: _coordinates(v[0]) + _coordinates(v[1]))


def _det(u, v):
    return u[0] * v[1] - u[1] * v[0]


def _norm(element) -> int:
    return int(ZZ(element * element.conjugate()))


def _ordered(cell) -> tuple:
    return tuple(sorted(cell, key=lambda v: _coordinates(v[0]) + _coordinates(v[1])))


def cell_edges(cell) -> tuple:
    r"""Return the four edges `{u, v, u + i^k v}` of a cell, consecutively."""
    u, v = _ordered(cell)
    return tuple(frozenset((u, v, _lax(u[0] + w * v[0], u[1] + w * v[1]))) for w in UNITS)


def _vertex(r, s) -> frozenset:
    r"""Return the six lax vectors of the vertex with opposite pair `r, s`."""
    if _norm(_det(r, s)) != 2:
        raise ValueError("an opposite pair spans a submodule of index 2")
    half = (1 + I) / 2
    remaining = [(half * (r[0] + w * s[0]), half * (r[1] + w * s[1])) for w in UNITS]
    if not all(_is_gaussian_integer(x) and _is_gaussian_integer(y) for x, y in remaining):
        raise ValueError("the four remaining vectors of a vertex are integral")
    return frozenset((_lax(*r), _lax(*s), *(_lax(x, y) for x, y in remaining)))


def cell_vertices(cell) -> tuple:
    r"""Return the four vertices of a cell, in the cyclic order of its edges."""
    u, v = _ordered(cell)
    third = [(u[0] + w * v[0], u[1] + w * v[1]) for w in UNITS]
    return tuple(_vertex(third[k], third[(k + 1) % 4]) for k in range(4))


@dataclass(frozen=True)
class SidePairing:
    r"""The element `g` with `g \tau = ` cell orbit `target`, where `\tau` is across `side` of `source`."""

    source: int
    side: int
    target: int
    element: object


@dataclass(frozen=True)
class CellOrbit:
    r"""An orbit of a cell, edge or vertex: a representative, its label, and its stabilizer in `PU(f)`."""

    representative: frozenset
    label: tuple
    stabilizer: tuple


@dataclass(frozen=True)
class Reduction:
    r"""`g = (\prod_t p_t^{-1}) \cdot s \cdot i^m`, for the side pairings `p_t` of `word` in order."""

    word: tuple
    stabilizer: object
    scalar_power: int


class HermitianOcean:
    r"""The ocean of an integral indefinite anisotropic binary Hermitian form over `Z[i]`."""

    def __init__(self, form) -> None:
        form = matrix(FIELD, form)
        _check_form(form)
        self.form = form
        self.identity = identity_matrix(FIELD, 2)
        self._values: dict = {}
        self.cells: tuple = ()
        self.side_pairings: tuple = ()
        self._quotient()

    def value(self, v) -> int:
        r"""Return `F` of a lax vector, which equals `f(v)` since `A` is a principal ideal domain."""
        cached = self._values.get(v)
        if cached is not None:
            return cached
        H, (x, y) = self.form, v
        result = int(ZZ(H[0, 0] * x * x.conjugate() + H[0, 1] * x * y.conjugate()
                        + H[1, 0] * y * x.conjugate() + H[1, 1] * y * y.conjugate()))
        self._values[v] = result
        return result

    def is_ocean_cell(self, cell) -> bool:
        u, v = _ordered(cell)
        return self.value(u) * self.value(v) < 0

    def is_unitary(self, g) -> bool:
        r"""Return whether `g \in GL_2(A)` and `g^T H \bar g = H`."""
        integral = all(_is_gaussian_integer(c) for c in g.list())
        unit_determinant = integral and any(g.det() == w for w in UNITS)
        return unit_determinant and g.transpose() * self.form * g.apply_map(lambda c: c.conjugate()) == self.form

    def act(self, g, thing) -> frozenset:
        r"""Return the image of a cell, edge or vertex under `g`."""
        return frozenset(_lax(g[0, 0] * x + g[0, 1] * y, g[1, 0] * x + g[1, 1] * y) for x, y in thing)

    def _transporters(self, source, target) -> list:
        r"""Return one lift in `U(f)` of each element of `PU(f)` that moves `source` to `target`.

        The chosen lax basis `(p, q)` of `source` determines `g` modulo scalars from the lax images of
        `p, q` and the ratio of their units, so the enumeration below is exact and without repetition.
        """
        if sorted(self.value(v) for v in source) != sorted(self.value(v) for v in target):
            return []
        p, q = next(pair for pair in combinations(_ordered(source), 2) if _norm(_det(*pair)) == 1)
        inverse = matrix(FIELD, 2, 2, [p[0], q[0], p[1], q[1]]).inverse()
        members = _ordered(target)
        found = []
        for p_image in members:
            for q_image in members:
                if p_image == q_image or _norm(_det(p_image, q_image)) != 1:
                    continue
                for unit in UNITS:
                    g = matrix(FIELD, 2, 2, [p_image[0], unit * q_image[0], p_image[1], unit * q_image[1]]) * inverse
                    if self.is_unitary(g) and self.act(g, source) == target:
                        found.append(g)
        return found

    def _spine_start(self) -> frozenset:
        r"""Return an ocean cell by breadth-first search of the connected spine, from the standard cell."""
        start = frozenset((_lax(FIELD.one(), FIELD.zero()), _lax(FIELD.zero(), FIELD.one())))
        layer, seen = [start], {start}
        while True:
            following = []
            for cell in layer:
                if self.is_ocean_cell(cell):
                    return cell
                for edge in cell_edges(cell):
                    for pair in combinations(edge, 2):
                        neighbour = frozenset(pair)
                        if neighbour not in seen:
                            seen.add(neighbour)
                            following.append(neighbour)
            layer = following

    def neighbour(self, cell, side: int) -> frozenset:
        r"""Return the unique other ocean cell across an edge (Claim 5 of section 6)."""
        others = [frozenset(pair) for pair in combinations(cell_edges(cell)[side], 2)
                  if frozenset(pair) != cell and self.is_ocean_cell(frozenset(pair))]
        if len(others) != 1:
            raise ValueError("an edge of the ocean lies in exactly two ocean cells")
        return others[0]

    def _quotient(self) -> None:
        r"""Compute cell orbit representatives and side pairings; Theorem 5.1 gives termination."""
        cells = [self._spine_start()]
        pairings = []
        index = 0
        while index < len(cells):
            for side in range(4):
                neighbour = self.neighbour(cells[index], side)
                for target, representative in enumerate(cells):
                    transporters = self._transporters(neighbour, representative)
                    if transporters:
                        pairings.append(SidePairing(index, side, target, transporters[0]))
                        break
                else:
                    pairings.append(SidePairing(index, side, len(cells), self.identity))
                    cells.append(neighbour)
            index += 1
        self.side_pairings = tuple(pairings)
        self.cells = tuple(
            CellOrbit(cell, tuple(sorted(self.value(v) for v in cell)), tuple(self._transporters(cell, cell)))
            for cell in cells
        )

    def _orbits(self, things, label) -> tuple:
        representatives: list = []
        for thing in things:
            if not any(self._transporters(thing, r) for r in representatives):
                representatives.append(thing)
        return tuple(CellOrbit(r, label(r), tuple(self._transporters(r, r))) for r in representatives)

    def edge_orbits(self) -> tuple:
        r"""Return the edge orbits, labeled by `inv(e)`, the sum of `f` on the superbasis."""
        edges = [edge for orbit in self.cells for edge in cell_edges(orbit.representative)]
        return self._orbits(edges, lambda e: (sum(self.value(v) for v in e),))

    def vertex_invariant(self, vertex) -> int:
        r"""Return `inv(v) = f(r) + f(s)` for an opposite pair, independent of the pair by Prop. 7.1."""
        r, s = next(pair for pair in combinations(_ordered(vertex), 2) if _norm(_det(*pair)) == 2)
        return self.value(r) + self.value(s)

    def vertex_orbits(self) -> tuple:
        r"""Return the vertex orbits, labeled by `inv(v)`."""
        vertices = [vertex for orbit in self.cells for vertex in cell_vertices(orbit.representative)]
        return self._orbits(vertices, lambda v: (self.vertex_invariant(v),))

    def orbifold_euler_characteristic(self):
        r"""Return `\sum (-1)^{\dim \sigma} / |Stab(\sigma)|` over the orbits of cells, edges and vertices."""
        return (sum(QQ((1, len(o.stabilizer))) for o in self.vertex_orbits())
                - sum(QQ((1, len(o.stabilizer))) for o in self.edge_orbits())
                + sum(QQ((1, len(o.stabilizer))) for o in self.cells))

    def _projective_key(self, g) -> tuple:
        return min(tuple(_coordinates(u * c)[j] for c in g.list() for j in range(2)) for u in UNITS)

    def projective_generators(self) -> tuple:
        r"""Return one lift in `U(f)` of each generator of `PU(f)`: stabilizers and side pairings."""
        candidates = [g for orbit in self.cells for g in orbit.stabilizer]
        candidates += [pairing.element for pairing in self.side_pairings]
        scalar = self._projective_key(self.identity)
        result: dict = {}
        for g in candidates:
            key = self._projective_key(g)
            if key != scalar and key not in result and self._projective_key(g.inverse()) not in result:
                result[key] = g
        return tuple(result.values())

    def scalar_kernel(self):
        r"""Return `i I`, which generates the kernel `\mu_4` of `U(f) \to PU(f)`."""
        return I * self.identity

    def unitary_generators(self) -> tuple:
        r"""Return generators of `U(f)`: lifts of generators of `PU(f)` and the scalar kernel."""
        return (*self.projective_generators(), self.scalar_kernel())

    def determinant_image(self) -> tuple:
        r"""Return the subgroup `\det U(f) \subseteq \mu_4`, as a tuple of units."""
        image, frontier = {FIELD.one()}, [FIELD.one()]
        generators = [g.det() for g in self.unitary_generators()]
        while frontier:
            value = frontier.pop()
            for d in generators:
                if value * d not in image:
                    image.add(value * d)
                    frontier.append(value * d)
        return tuple(image)

    def special_unitary_generators(self) -> tuple:
        r"""Return Schreier generators of `SU(f)`, the kernel of `\det` on `U(f)`."""
        generators = self.unitary_generators()
        transversal = {FIELD.one(): self.identity}
        frontier = [FIELD.one()]
        while frontier:
            value = frontier.pop()
            for g in generators:
                image = value * g.det()
                if image not in transversal:
                    transversal[image] = transversal[value] * g
                    frontier.append(image)
        result: dict = {}
        for value, representative in transversal.items():
            for g in generators:
                candidate = representative * g * transversal[value * g.det()].inverse()
                if candidate != self.identity:
                    result[tuple(_coordinates(c)[j] for c in candidate.list() for j in range(2))] = candidate
        return tuple(result.values())

    def _distance(self, cell, target) -> int:
        return sum(_norm(_det(x, y)) for x in cell for y in target)

    def reduce(self, g) -> Reduction:
        r"""Return a word for `g \in U(f)` by walking the ocean from the first cell to its image.

        The walk is best-first on `\sum N(\det(x, y))` over `x` in the cell and `y` in the target. For
        each bound this value is below it on finitely many cells, so the search reaches the target
        of the connected surface. The element `s` is an element of the stabilizer of the first cell.
        """
        if not self.is_unitary(g):
            raise ValueError("g must lie in U(f)")
        start = self.cells[0].representative
        target = self.act(g, start)
        pairing = {(p.source, p.side): p for p in self.side_pairings}
        order = count()
        heap = [(self._distance(start, target), next(order), start, 0, self.identity, None)]
        seen = {start}
        while heap:
            _, _, cell, orbit, gamma, path = heappop(heap)
            if cell == target:
                return self._finish(g, gamma, path)
            for side in range(4):
                step = pairing[(orbit, side)]
                inverse = gamma * step.element.inverse()
                image = self.act(inverse, self.cells[step.target].representative)
                if image not in seen:
                    seen.add(image)
                    heappush(heap, (self._distance(image, target), next(order), image, step.target, inverse,
                                    ((orbit, side), path)))
        raise ValueError("the ocean walk exhausted its cells without reaching the target")

    def _finish(self, g, gamma, path) -> Reduction:
        word: list = []
        while path is not None:
            word.append(path[0])
            path = path[1]
        word.reverse()
        residual = gamma.inverse() * g
        for stabilizer in self.cells[0].stabilizer:
            for power, unit in enumerate(UNITS):
                if stabilizer * unit == residual:
                    return Reduction(tuple(word), stabilizer, power)
        raise ValueError("the residual element does not lie in the stabilizer of the first cell")

    def evaluate(self, reduction: Reduction):
        r"""Return the product that `reduction` records."""
        pairing = {(p.source, p.side): p for p in self.side_pairings}
        result = self.identity
        for step in reduction.word:
            result *= pairing[step].element.inverse()
        return result * reduction.stabilizer * UNITS[reduction.scalar_power]


def isometry(source, target):
    r"""Return `g \in GL_2(A)` with `g^T H' \bar g = H`, ``source`` `= H`, ``target`` `= H'`, or ``None``.

    An isometry `g` from `f` to `f'` (`f'(g v) = f(v)`) maps lax vectors to lax vectors with the same
    values, so it maps ocean cells of `f` (Definition 1) bijectively onto ocean cells of `f'`. Let `\tau`
    be one ocean cell of `f'`. Then `g^{-1} \tau` is an ocean cell of `f`, so `\gamma g^{-1} \tau` is a
    cell orbit representative `\rho` for some `\gamma \in U(f)` (Theorem 5.1), and `g \gamma^{-1}` maps `\rho`
    to `\tau`. Such a map is determined, up to `A^\times`, by the lax images of a lax basis of `\rho`, as in
    :meth:`HermitianOcean._transporters`. So the finite search below decides the isometry.
    """
    first, second = HermitianOcean(source), HermitianOcean(target)
    if discriminant(first.form) != discriminant(second.form):
        return None
    cell = _ordered(second.cells[0].representative)
    for orbit in first.cells:
        p, q = _ordered(orbit.representative)
        inverse = matrix(FIELD, 2, 2, [p[0], q[0], p[1], q[1]]).inverse()
        for p_image, q_image in ((cell[0], cell[1]), (cell[1], cell[0])):
            for unit in UNITS:
                g = matrix(FIELD, 2, 2, [p_image[0], unit * q_image[0], p_image[1], unit * q_image[1]]) * inverse
                if g.transpose() * second.form * g.apply_map(lambda c: c.conjugate()) == first.form:
                    return g
    return None
