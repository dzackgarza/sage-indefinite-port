r"""The unitary group of the hyperbolic plane over `Z[i]`, `Z[\omega]`, `Z[\sqrt{-2}]` (#51).

Let `J = [[0, 1], [1, 0]]` and let `\theta` generate the skew elements of `O`. The group is
generated by `T = [[1, \theta], [0, 1]]`, `W = [[0, 1], [1, 0]]` and `D_u = diag(u, conj(u)^{-1})`.
The first column of `g` is primitive and isotropic, so `a / c` is skew. Subtracting the nearest
multiple of `\theta` gives `|a'| <= |\theta| |c| / 2`, and `|\theta| / 2 < 1` in these orders, so `W`
lowers `|c|` strictly. A column with `c = 0` has `a` a unit, and the rest is a power of `T`.
"""

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.rings.number_field.number_field import QuadraticField


def field(d: int):
    r"""Return ``Q(sqrt(-d))`` for ``d`` in 1, 2, 3."""
    if d not in (1, 2, 3):
        raise ValueError(f"the Euclidean reduction needs d in 1, 2, 3, not {d}")
    return QuadraticField(-d, "a")


def theta(d: int):
    r"""Return the generator of the skew elements of the maximal order: `i`, `\sqrt{-2}`, `\sqrt{-3}`."""
    return field(d).gen()


def form(d: int):
    E = field(d)
    return matrix(E, 2, 2, [0, 1, 1, 0])


def generators(d: int) -> dict:
    r"""Return ``T``, ``W`` and one ``D_u`` per unit of the order."""
    E = field(d)
    table = {"T": matrix(E, 2, 2, [1, theta(d), 0, 1]), "W": matrix(E, 2, 2, [0, 1, 1, 0])}
    for k, unit in enumerate(E.roots_of_unity()):
        table[f"D{k}"] = matrix(E, 2, 2, [unit, 0, 0, ~unit.conjugate()])
    return table


def is_element(d: int, g) -> bool:
    order = field(d).ring_of_integers()
    return all(entry in order for entry in g.list()) and g.conjugate_transpose() * form(d) * g == form(d)


def evaluate(d: int, word):
    table = generators(d)
    result = identity_matrix(field(d), 2)
    for name, exponent in word:
        result = result * table[name] ** int(exponent)
    return result


def word(d: int, g):
    r"""Return a checked word in the generators for ``g``."""
    if not is_element(d, g):
        raise ValueError(f"{g} is not in U(1,1) over the maximal order of Q(sqrt(-{d}))")
    E = field(d)
    skew = theta(d)
    table = generators(d)
    prefix = []
    current = g
    while current[1, 0] != 0:
        ratio = current[0, 0] / current[1, 0]
        coefficient = QQ_of(ratio / skew)
        k = coefficient.round()
        shifted = table["T"] ** (-int(k)) * current
        if shifted[0, 0].norm() >= current[1, 0].norm():
            raise ArithmeticError("the Euclidean step did not lower the norm")
        prefix += [("T", int(k)), ("W", 1)]
        current = table["W"] * shifted
    unit = current[0, 0]
    index = next(i for i, u in enumerate(E.roots_of_unity()) if u == unit)
    reduced = ~table[f"D{index}"] * current
    power = reduced[0, 1] / skew
    result = [*prefix, (f"D{index}", 1), ("T", int(QQ_of(power)))]
    if evaluate(d, result) != g:
        raise ArithmeticError("the word does not evaluate to the given element")
    return tuple(result)


def QQ_of(value):
    r"""Return ``value`` as a rational, for an element of `Q` inside the field."""
    parts = value.vector()
    if parts[1] != 0:
        raise ArithmeticError(f"{value} is not rational")
    return parts[0]
