r"""`O(\Lambda)` for `\Lambda = U \perp M` over `O_K`, `M` anisotropic over a totally real `K` (Witt index one) (#54).

``gram`` is the Gram matrix in an `O_K`-basis `e, f, m_1, \ldots, m_k` with `h(e, f) = 1`, `h(e, e) = h(f, f) = 0` and `M = \langle e, f \rangle^\perp`.

Parabolic generators. `\mathrm{Stab}(e)` is generated by `O(M)` (acting on `M`, fixing `e, f`) and the integral Eichler transvections
`E(e, a)(x) = x - h(a, x) e + h(e, x) a - \tfrac12 h(a, a) h(e, x) e`, `a \in M_{ev} = \{a \in M : h(a, a) \in 2 O_K\}` (an element fixing `e`
sends `f` to an isotropic `f + a + c e` with `h(e, \cdot) = 1`, so `c = -h(a, a)/2`, and composing with `E(e, a)^{-1}` leaves an element
fixing `e, f`, i.e. of `O(M)`). `a \mapsto E(e, a)` is additive, so a `Z`-basis of `M_{ev}` suffices. Further generators: the Weyl element
`w` exchanging `e, f` and fixing `M`, the unit scalings `e \mapsto u e`, `f \mapsto u^{-1} f`, and `-1`.

Cusp transitivity by Euclid. For a primitive isotropic `v = x e + y f + m`: `E(e, a)` replaces `m` by `m + y a` and keeps `y`; `w` exchanges
`x` and `y`. With `z = m / y` and `m + y a = y (z + a)`, the new `x' = -h(m + ya, m + ya)/(2y)` has `|N(x')| = |N(y)| \cdot |N(h(z + a, z + a))| / 2^d`,
`d = [K : Q]`. If for every `z \in M \otimes R` some `a \in M_{ev}` has `|N(h(z + a, z + a))| < 2^d` (a covering certificate, decided by interval
bisection of the fundamental box of `M_{ev}`), `|N(y)|` strictly decreases to `y = 0`; then `h(m, m) = 0` forces `m = 0` (`M` anisotropic) and
`v = x e` with `x \in O_K^\times`. So the group generated is transitive on primitive isotropic vectors, and with `\mathrm{Stab}(e)` it is `O(\Lambda)`
(for `g \in O(\Lambda)`, a word `\gamma` with `\gamma g e = e` gives `\gamma g \in \mathrm{Stab}(e)`). No cusp links are needed then. Without the
certificate, cusp classes are not decided here and the module raises.

`O(M)` for totally definite `M` is the finite group of `Z`-automorphisms of `M_Z` preserving `\mathrm{Tr}(h)` and `\mathrm{Tr}(\omega h)` (these
determine `h`; such maps are `O_K`-linear by nondegeneracy), from PARI ``qfauto`` (Plesken-Souvignier); for rank one it is `\pm 1` at any
signs. The covering certificate and the reduction use only `|N(h)|` and the anisotropy of `M`, so they hold at any real signature. `O(M)` of
rank `\ge 2` that is not totally definite raises.
"""

from itertools import product

from sage.libs.pari import pari
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.finite_rings.finite_field_constructor import GF
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ
from sage.rings.real_mpfi import RealIntervalField

BOX_BUDGET = 200000


def _pairing(gram, x, y):
    return (matrix([x]) * gram * matrix([y]).transpose())[0, 0]


def eichler(gram, c, a):
    K = gram.base_ring()
    c, a = vector(K, c), vector(K, a)
    hc, ha = matrix(K, [c]) * gram, matrix(K, [a]) * gram
    n = gram.nrows()
    return identity_matrix(K, n) - c.column() * ha + a.column() * hc - (_pairing(gram, a, a) / 2) * c.column() * hc


def _basis_starting_at_one(order):
    r"""Return a `Z`-basis of ``order`` whose first element is `1`.

    `1` is primitive in the order, so its coordinate row `r` extends to a unimodular matrix: with `D = U r V` the Smith
    form, `D = (1, 0, \ldots, 0)`, and the rows of `V^{-1}` form a basis whose first row is `\pm r`.
    """
    basis = order.basis()
    row = matrix(ZZ, [order.coordinates(order(1))])
    D, U, V = row.smith_form()
    assert D[0, 0] == 1
    change = V.inverse() * U[0, 0]
    result = [sum((change[i, j] * basis[j] for j in range(len(basis))), order(0)) for i in range(len(basis))]
    assert result[0] == 1
    return result


class WittOneLattice:
    r"""`\Lambda = U \perp M` over `O_K` in the basis `e, f, m_1, \ldots, m_k` (module docstring)."""

    def __init__(self, field, gram):
        self.field, self.gram = field, matrix(field, gram)
        n = self.gram.nrows()
        assert self.gram.submatrix(0, 0, 2, 2) == matrix(field, [[0, 1], [1, 0]])
        assert self.gram.submatrix(0, 2, 2, n - 2).is_zero()
        self.k = n - 2
        self.inner = self.gram.submatrix(2, 2, self.k, self.k)
        self.integers = _basis_starting_at_one(field.ring_of_integers())
        self.embeddings = field.embeddings(RealIntervalField(200))
        self.signs = []
        for sigma in self.embeddings:
            eigen = self.inner.apply_map(lambda x: sigma(x).center()).change_ring(QQ)
            if eigen.is_positive_definite():
                self.signs.append(1)
            elif (-eigen).is_positive_definite():
                self.signs.append(-1)
            else:
                self.signs.append(0)
        self.m_basis = [vector(field, [0, 0, *(1 if i == j else 0 for i in range(self.k))]) for j in range(self.k)]
        self.z_basis = [w * m for m in self.m_basis for w in self.integers]
        self.even_basis = self._even_sublattice()

    def h(self, x, y):
        return _pairing(self.gram, x, y)

    def _even_sublattice(self):
        r"""Return a `Z`-basis of `M_{ev}`: the kernel of the additive map `a \mapsto h(a, a) \bmod 2 O_K` on `M_Z`."""
        integers = self.field.ring_of_integers()
        d = len(self.integers)
        size = len(self.z_basis)
        images = []
        for a in self.z_basis:
            images.append([ZZ(c) % 2 for c in integers.coordinates(self.h(a, a))])
        kernel = matrix(GF(2), images).left_kernel().basis()
        rows = [vector(ZZ, [ZZ(c) for c in k]) for k in kernel] + [2 * vector(ZZ, [1 if i == j else 0 for i in range(size)]) for j in range(size)]
        hermite = matrix(ZZ, rows).hermite_form(include_zero_rows=False)
        assert hermite.nrows() == size and d >= 1
        return [sum((c * b for c, b in zip(row, self.z_basis)), vector(self.field, self.k + 2)) for row in hermite.rows()]

    def _quadratic_intervals(self, basis):
        r"""Return, per real embedding, the real Gram matrix (intervals) of `h^\sigma` on the coordinates of ``basis``."""
        result = []
        for sigma in self.embeddings:
            result.append(matrix(sigma.codomain(), [[sigma(self.h(x, y)) for y in basis] for x in basis]))
        return result

    def covering_certificate(self):
        r"""Decide `\forall z \exists a \in M_{ev}: |N(h(z + a))| < 2^d` by bisection of `[0, 1]^{kd}` (module docstring); ``False`` if the budget ends."""
        basis = self.even_basis
        grams = self._quadratic_intervals(basis)
        field = grams[0].base_ring()
        dimension = len(basis)
        limit = field(2) ** len(self.embeddings)
        stack = [tuple((QQ(0), QQ(1)) for _ in range(dimension))]
        visited = 0
        while stack:
            box = stack.pop()
            visited += 1
            if visited > BOX_BUDGET:
                return False
            centre = [(a + b) / 2 for a, b in box]
            closed = False
            for shift in product((-1, 0, 1), repeat=dimension):
                translate = [field(a - (ZZ(round(c)) + s), b - (ZZ(round(c)) + s)) for (a, b), c, s in zip(box, centre, shift)]
                norm = field(1)
                for gram in grams:
                    value = sum(gram[i, j] * translate[i] * translate[j] for i in range(dimension) for j in range(dimension))
                    norm = norm * value
                if abs(norm).upper() < limit.lower():
                    closed = True
                    break
            if closed:
                continue
            k = max(range(dimension), key=lambda i: box[i][1] - box[i][0])
            middle = (box[k][0] + box[k][1]) / 2
            stack.append(tuple((box[i][0], middle) if i == k else box[i] for i in range(dimension)))
            stack.append(tuple((middle, box[i][1]) if i == k else box[i] for i in range(dimension)))
        return True

    def inner_automorphisms(self):
        r"""Return generators of `O(M)` as matrices on `\Lambda` fixing `e, f`.

        Rank one: `O(\langle c \rangle) = \{\pm 1\}` (`u^2 = 1`), whatever the signs of `c`. Totally definite `M` (all signs equal and nonzero):
        PARI ``qfauto`` on `\pm\mathrm{Tr}(h)` and `\mathrm{Tr}(\omega h)`. Otherwise `M` of rank `\ge 2` is indefinite or of mixed sign at the
        real places; rank two uses :class:`binary_orthogonal_number_field.BinaryOrthogonalGroup`; rank `\ge 3` is a cocompact group and raises."""
        if self.k == 1:
            minus = identity_matrix(self.field, 3)
            minus[2, 2] = -1
            return [minus]
        if self.k == 2 and (0 in self.signs or len(set(self.signs)) != 1):
            from sage_indefinite_port.indefinite.binary_orthogonal_number_field import BinaryOrthogonalGroup

            result = []
            for g in BinaryOrthogonalGroup(self.field, self.inner).generators():
                full = identity_matrix(self.field, 4)
                full.set_block(2, 2, g)
                result.append(full)
            return result
        if 0 in self.signs or len(set(self.signs)) != 1:
            raise NotImplementedError(
                f"O(M) for the anisotropic M = {list(self.inner)} of rank {self.k} over {self.field} with real signs {self.signs}: "
                f"rank >= 3 that is not totally definite is a cocompact "
                f"arithmetic group (even Clifford algebra and Voronoi) (#54)"
            )
        self.sign = self.signs[0]
        omega = self.field.gen()
        trace = lambda x: QQ(self.field(x).trace())
        first = matrix(QQ, [[self.sign * trace(self.h(x, y)) for y in self.z_basis] for x in self.z_basis])
        second = matrix(QQ, [[trace(omega * self.h(x, y)) for y in self.z_basis] for x in self.z_basis])
        scale = first.denominator() * second.denominator()
        found = pari([matrix(ZZ, scale * first), matrix(ZZ, scale * second)]).qfauto()
        result = []
        d = len(self.integers)
        for generator in found[1]:
            g = matrix(ZZ, generator.sage())
            images = []
            for j in range(self.k):
                column = g.column(j * d)
                images.append(sum((c * b for c, b in zip(column, self.z_basis)), vector(self.field, self.k + 2)))
            full = identity_matrix(self.field, self.k + 2)
            for j, image in enumerate(images):
                full.set_column(2 + j, image)
            assert full.transpose() * self.gram * full == self.gram
            result.append(full)
        return result

    def weyl(self):
        n = self.k + 2
        w = identity_matrix(self.field, n)
        w[0, 0] = w[1, 1] = 0
        w[0, 1] = w[1, 0] = 1
        return w

    def generators(self):
        if not self.covering_certificate():
            raise NotImplementedError(
                f"U + M with M = {list(self.inner)} over {self.field}: the Euclidean covering |N(h(z + a))| < 2^d by M_ev was not "
                f"certified within {BOX_BUDGET} boxes, so transitivity on primitive isotropic vectors is not proved; the cusp "
                f"classes and their links over O_K are needed (#54)"
            )
        n = self.k + 2
        e = vector(self.field, [1, 0, *([0] * self.k)])
        result = [-identity_matrix(self.field, n), self.weyl(), *self.inner_automorphisms()]
        result.extend(eichler(self.gram, e, a) for a in self.even_basis)
        for u in self.field.unit_group().gens():
            u = self.field(u)
            scaling = identity_matrix(self.field, n)
            scaling[0, 0], scaling[1, 1] = u, ~u
            result.append(scaling)
        integral = lambda g: all(c.is_integral() for c in g.list())
        assert all(integral(g) and g.transpose() * self.gram * g == self.gram for g in result)
        return tuple(result)

    def reduce_isotropic(self, v):
        r"""Return `g` in the generated group with `g v \in O_K^\times e`, for a primitive isotropic ``v`` (the Euclidean reduction)."""
        assert self.h(v, v) == 0
        e = vector(self.field, [1, 0, *([0] * self.k)])
        g = identity_matrix(self.field, self.k + 2)
        current = vector(self.field, v)
        coordinates_matrix = matrix(QQ, [[c for x in a[2:] for c in x.list()] for a in self.even_basis])
        while current[1] != 0:
            y = current[1]
            z = [c / y for c in current[2:]]
            flat = vector(QQ, [c for x in z for c in self.field(x).list()])
            coefficients = coordinates_matrix.solve_left(flat)
            best = None
            for shift in product((-1, 0, 1), repeat=len(coefficients)):
                a = -sum(((ZZ(round(c)) + s) * b for c, s, b in zip(coefficients, shift, self.even_basis)), vector(self.field, self.k + 2))
                moved = current[2:] + y * a[2:]
                value = abs(self.field(sum(moved[i] * self.inner[i, j] * moved[j] for i in range(self.k) for j in range(self.k))).norm())
                if best is None or value < best[0]:
                    best = (value, a)
            step = eichler(self.gram, e, best[1])
            current = self.weyl() * step * current
            g = self.weyl() * step * g
        assert current[2:] == 0 and current[0].is_unit()
        return g
