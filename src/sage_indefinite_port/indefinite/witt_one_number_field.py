r"""`O(\Lambda)` for `\Lambda = U \perp M` over `O_K`, `M` anisotropic over a totally real `K` (Witt index one) (#54).

`\Lambda` is a projective `O_K`-module, given by a pseudo-basis (Cohen, *Advanced Topics in Computational Number Theory*, §1.4;
O'Meara §81): ``gram`` is the Gram matrix in a `K`-basis `e, f, m_1, \ldots, m_k` and ``ideals`` are fractional ideals
`\mathfrak a_e, \mathfrak a_e^{-1}, \mathfrak a_1, \ldots, \mathfrak a_k` with
`\Lambda = \mathfrak a_e e \oplus \mathfrak a_e^{-1} f \oplus \mathfrak a_1 m_1 \oplus \cdots \oplus \mathfrak a_k m_k`, `h(e, f) = 1`,
`h(e, e) = h(f, f) = 0` and `M = \bigoplus \mathfrak a_i m_i = \langle e, f \rangle^\perp`. A matrix `g` in this basis preserves `\Lambda`
exactly when `g_{ij} \in \mathfrak a_i \mathfrak a_j^{-1}`. The `Z`-basis of `M` is the union of the `Z`-bases of the `\mathfrak a_i m_i`.

Parabolic generators. For a fractional ideal `\mathfrak c` let `P(\mathfrak c) = \{a \in \mathfrak c M : h(a, a) \in 2 \mathfrak c^2\}`.
The Eichler transvection `E(c, a)(x) = x - h(a, x) c + h(c, x) a - \tfrac12 h(a, a) h(c, x) c` preserves `\Lambda` for `c = e`,
`a \in P(\mathfrak a_e)` and for `c = f`, `a \in P(\mathfrak a_e^{-1})` (`h(e, \Lambda) = \mathfrak a_e^{-1}`, `h(\mathfrak c M, M) \subset \mathfrak c`).
`\mathrm{Stab}(\mathfrak a_e e)` is generated by `O(M)` (fixing `e, f`), the unit scalings `e \mapsto u e`, `f \mapsto u^{-1} f`, and the
`E(e, a)`, `a \in P(\mathfrak a_e)`: an element fixing `e` sends `f` to an isotropic `f + a + c e` with `h(e, \cdot) = 1`, and
`\mathfrak a_e^{-1}(f + a + c e) \subset \Lambda` forces `a \in \mathfrak a_e M` and `c = -h(a, a)/2 \in \mathfrak a_e^2`, i.e. `a \in P(\mathfrak a_e)`;
composing with `E(e, a)^{-1}` leaves an element of `O(M)`. `a \mapsto E(c, a)` is additive, so `Z`-bases of the `P` suffice. Further
generators: `-1` and, when `\mathfrak a_e^{-2} = \alpha O_K` is principal, the Weyl element `e \mapsto \alpha f`, `f \mapsto \alpha^{-1} e`.

Cusp transitivity by Euclid. For `g \in O(\Lambda)` write `v = g e = x e + y f + m`; then `x \in O_K`, `y \in \mathfrak a_e^{-2}`,
`x O_K = N_x` and `y \mathfrak a_e^2 = N_y` are integral ideals. `E(e, a)` replaces `m` by `m + y a`, keeps `y`, and the new
`x' = -h(m + ya, m + ya)/(2y)` has `|N(x')| = |N(y)| \cdot |N(h(z + a, z + a))| / 2^d`, `z = m/y`, `d = [K : Q]`; so
`|N(x')| < N(y \mathfrak a_e^2)` once `|N(h(z + a, z + a))| < 2^d N(\mathfrak a_e)^2`. Symmetrically `E(f, b)`, `b \in P(\mathfrak a_e^{-1})`,
makes `N(y' \mathfrak a_e^2) < |N(x)|` once `|N(h(z + b, z + b))| < 2^d N(\mathfrak a_e)^{-2}`, `z = m/x`. If both coverings hold for every
`z \in M \otimes R` (certificates decided by interval bisection of the fundamental boxes), applying the step at the larger of the two
positive integers `|N(x)|, N(y \mathfrak a_e^2)` strictly decreases the larger one until `x = 0` or `y = 0`. At `y = 0`, `h(m, m) = 0` forces
`m = 0` (`M` anisotropic) and `x \in O_K^\times` since `g \mathfrak a_e e` is primitive. At `x = 0`, `v = y f` and primitivity gives
`y \mathfrak a_e = \mathfrak a_e^{-1}`, so `\mathfrak a_e^{-2} = y O_K` is principal and the Weyl element returns `v` to `O_K^\times e`.
So the generated group moves `g \mathfrak a_e e` back to `\mathfrak a_e e`, and with the stabilizer it is `O(\Lambda)`. Without the
certificates, cusp classes are not decided here and the module raises.

`O(M)` for totally definite `M` is the finite group of `Z`-automorphisms of `M_Z` preserving `\mathrm{Tr}(h)` and `\mathrm{Tr}(\omega h)` (these
determine `h`; such maps are `O_K`-linear by nondegeneracy), from PARI ``qfauto`` (Plesken-Souvignier); for rank one it is `\pm 1` at any
signs. The covering certificates and the reduction use only `|N(h)|` and the anisotropy of `M`, so they hold at any real signature. `O(M)` of
rank `\ge 2` that is not totally definite raises.
"""

from itertools import product

from sage.libs.pari import pari
from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.finite_rings.finite_field_constructor import GF
from sage.rings.integer_ring import ZZ
from sage.rings.rational_field import QQ
from sage.rings.real_mpfi import RealIntervalField

BOX_BUDGET = 200000


def _pairing(gram, x, y):
    return (matrix([x]) * gram * matrix([y]).transpose())[0, 0]


def eichler(gram, c, a):
    K = gram.base_ring()
    c, a = vector(K, c), vector(K, a)
    hc, ha = matrix(K, [c]) * gram, matrix(K, [a]) * gram
    n = gram.nrows()
    return identity_matrix(K, n) - c.column() * ha + a.column() * hc - (_pairing(gram, a, a) / 2) * c.column() * hc


class WittOneLattice:
    r"""`\Lambda = \mathfrak a_e e \oplus \mathfrak a_e^{-1} f \oplus \bigoplus \mathfrak a_i m_i` over `O_K` (module docstring)."""

    def __init__(self, field, gram, ideals):
        self.field, self.gram = field, matrix(field, gram)
        n = self.gram.nrows()
        self.ideals = [field.ideal(a) for a in ideals]
        assert len(self.ideals) == n
        assert self.gram.submatrix(0, 0, 2, 2) == matrix(field, [[0, 1], [1, 0]])
        assert self.gram.submatrix(0, 2, 2, n - 2).is_zero()
        assert self.ideals[1] == self.ideals[0] ** -1
        self.k = n - 2
        self.inner = self.gram.submatrix(2, 2, self.k, self.k)
        self.embeddings = field.embeddings(RealIntervalField(200))
        self.signs = []
        for sigma in self.embeddings:
            eigen = self.inner.apply_map(lambda x: sigma(x).center()).change_ring(QQ)
            if eigen.is_positive_definite():
                self.signs.append(1)
            elif (-eigen).is_positive_definite():
                self.signs.append(-1)
            else:
                self.signs.append(0)
        self.e = vector(field, [1, 0, *([0] * self.k)])
        self.f = vector(field, [0, 1, *([0] * self.k)])
        self.m_basis = [vector(field, [0, 0, *(1 if i == j else 0 for i in range(self.k))]) for j in range(self.k)]
        self.z_basis = self._scaled_z_basis(field.ideal(1))
        self.even_e = self._even_parameters(self.ideals[0])
        self.even_f = self._even_parameters(self.ideals[1])

    def h(self, x, y):
        return _pairing(self.gram, x, y)

    def _scaled_z_basis(self, scale):
        r"""Return the `Z`-basis of `\mathfrak c M`: the union of the `Z`-bases of `\mathfrak c \mathfrak a_i m_i`."""
        return [w * m for m, a in zip(self.m_basis, self.ideals[2:]) for w in (scale * a).basis()]

    def _even_parameters(self, scale):
        r"""Return a `Z`-basis of `P(\mathfrak c)`: the kernel of the additive map `a \mapsto h(a, a) \bmod 2 \mathfrak c^2` on `\mathfrak c M`.

        Additivity: `h(a + b, a + b) - h(a, a) - h(b, b) = 2 h(a, b) \in 2 \mathfrak c^2`. The value is read in a `Z`-basis of `\mathfrak c^2`."""
        module = self._scaled_z_basis(scale)
        size = len(module)
        target = matrix(QQ, [self.field(t).list() for t in (scale**2).basis()])
        images = []
        for a in module:
            coordinates = target.solve_left(vector(QQ, self.field(self.h(a, a)).list()))
            assert all(c.is_integral() for c in coordinates)
            images.append([ZZ(c) % 2 for c in coordinates])
        kernel = matrix(GF(2), images).left_kernel().basis()
        rows = [vector(ZZ, [ZZ(c) for c in k]) for k in kernel] + [2 * vector(ZZ, [1 if i == j else 0 for i in range(size)]) for j in range(size)]
        hermite = matrix(ZZ, rows).hermite_form(include_zero_rows=False)
        assert hermite.nrows() == size
        return [sum((c * b for c, b in zip(row, module)), vector(self.field, self.k + 2)) for row in hermite.rows()]

    def preserves(self, g):
        r"""Return whether `g \Lambda \subset \Lambda`: `g_{ij} \in \mathfrak a_i \mathfrak a_j^{-1}`."""
        n = self.k + 2
        return all(
            g[i, j] == 0 or (self.field.ideal(g[i, j]) * self.ideals[j] / self.ideals[i]).is_integral() for i in range(n) for j in range(n)
        )

    def _quadratic_intervals(self, basis):
        r"""Return, per real embedding, the real Gram matrix (intervals) of `h^\sigma` on the coordinates of ``basis``."""
        result = []
        for sigma in self.embeddings:
            result.append(matrix(sigma.codomain(), [[sigma(self.h(x, y)) for y in basis] for x in basis]))
        return result

    def _covers(self, basis, bound):
        r"""Decide `\forall z \exists a \in \mathbb Z \text{basis}: |N(h(z + a))| < \text{bound}` by bisection of `[0, 1]^{kd}`; ``False`` if the budget ends."""
        grams = self._quadratic_intervals(basis)
        field = grams[0].base_ring()
        dimension = len(basis)
        limit = field(bound)
        stack = [tuple((QQ(0), QQ(1)) for _ in range(dimension))]
        visited = 0
        while stack:
            box = stack.pop()
            visited += 1
            if visited > BOX_BUDGET:
                return False
            centre = [(a + b) / 2 for a, b in box]
            closed = False
            for shift in product((-1, 0, 1), repeat=dimension):
                translate = [field(a - (ZZ(round(c)) + s), b - (ZZ(round(c)) + s)) for (a, b), c, s in zip(box, centre, shift)]
                norm = field(1)
                for gram in grams:
                    value = sum(gram[i, j] * translate[i] * translate[j] for i in range(dimension) for j in range(dimension))
                    norm = norm * value
                if abs(norm).upper() < limit.lower():
                    closed = True
                    break
            if closed:
                continue
            k = max(range(dimension), key=lambda i: box[i][1] - box[i][0])
            middle = (box[k][0] + box[k][1]) / 2
            stack.append(tuple((box[i][0], middle) if i == k else box[i] for i in range(dimension)))
            stack.append(tuple((middle, box[i][1]) if i == k else box[i] for i in range(dimension)))
        return True

    def covering_certificate(self):
        r"""Decide both Euclidean coverings of the module docstring: by `P(\mathfrak a_e)` below `2^d N(\mathfrak a_e)^2` and by
        `P(\mathfrak a_e^{-1})` below `2^d N(\mathfrak a_e)^{-2}`."""
        d = len(self.embeddings)
        norm = self.ideals[0].norm()
        if not self._covers(self.even_e, 2**d * norm**2):
            return False
        if self.ideals[0] == self.ideals[1]:
            return True
        return self._covers(self.even_f, 2**d * norm**-2)

    def inner_automorphisms(self):
        r"""Return generators of `O(M)` as matrices on `\Lambda` fixing `e, f`.

        Rank one: `O(\mathfrak a_1 m_1) = \{\pm 1\}` (`u^2 = 1`), whatever the signs of `c`. Totally definite `M` (all signs equal and nonzero):
        PARI ``qfauto`` on `\pm\mathrm{Tr}(h)` and `\mathrm{Tr}(\omega h)` on the `Z`-basis of `M`. Otherwise `M` of rank `\ge 2` is indefinite or
        of mixed sign at the real places; rank two with a free pseudo-basis uses
        :class:`binary_orthogonal_number_field.BinaryOrthogonalGroup`; rank `\ge 3` is a cocompact group and raises."""
        if self.k == 1:
            minus = identity_matrix(self.field, 3)
            minus[2, 2] = -1
            return [minus]
        if self.k == 2 and (0 in self.signs or len(set(self.signs)) != 1):
            one = self.field.ideal(1)
            if any(a != one for a in self.ideals[2:]):
                raise NotImplementedError(
                    f"O(M) for the anisotropic binary M = {list(self.inner)} over {self.field} on the pseudo-basis ideals {self.ideals[2:]}: "
                    f"the binary norm-one torus route takes a free O_K-basis of M (#54)"
                )
            from sage_indefinite_port.indefinite.binary_orthogonal_number_field import BinaryOrthogonalGroup

            result = []
            for g in BinaryOrthogonalGroup(self.field, self.inner).generators():
                full = identity_matrix(self.field, 4)
                full.set_block(2, 2, g)
                result.append(full)
            return result
        if 0 in self.signs or len(set(self.signs)) != 1:
            raise NotImplementedError(
                f"O(M) for the anisotropic M = {list(self.inner)} of rank {self.k} over {self.field} with real signs {self.signs}: "
                f"rank >= 3 that is not totally definite is a cocompact "
                f"arithmetic group (even Clifford algebra and Voronoi) (#54)"
            )
        self.sign = self.signs[0]
        omega = self.field.gen()
        trace = lambda x: QQ(self.field(x).trace())
        first = matrix(QQ, [[self.sign * trace(self.h(x, y)) for y in self.z_basis] for x in self.z_basis])
        second = matrix(QQ, [[trace(omega * self.h(x, y)) for y in self.z_basis] for x in self.z_basis])
        scale = first.denominator() * second.denominator()
        found = pari([matrix(ZZ, scale * first), matrix(ZZ, scale * second)]).qfauto()
        result = []
        d = len(self.embeddings)
        for generator in found[1]:
            g = matrix(ZZ, generator.sage())
            full = identity_matrix(self.field, self.k + 2)
            for j in range(self.k):
                # z_basis[j d] = w m_j with w the first Z-basis element of a_j; g is O_K-linear, so g m_j = g(w m_j) / w.
                w = self.z_basis[j * d][2 + j]
                column = g.column(j * d)
                image = sum((c * b for c, b in zip(column, self.z_basis)), vector(self.field, self.k + 2))
                full.set_column(2 + j, image / w)
            assert full.transpose() * self.gram * full == self.gram and self.preserves(full)
            result.append(full)
        return result

    def weyl(self):
        r"""Return `e \mapsto \alpha f`, `f \mapsto \alpha^{-1} e` for `\mathfrak a_e^{-2} = \alpha O_K`, or ``None`` when that class is not principal."""
        generator = (self.ideals[1] / self.ideals[0]).gens_reduced()
        if len(generator) != 1:
            return None
        alpha = generator[0]
        w = identity_matrix(self.field, self.k + 2)
        w[0, 0] = w[1, 1] = 0
        w[1, 0], w[0, 1] = alpha, ~alpha
        return w

    def generators(self):
        links = ()
        if not self.covering_certificate():
            from sage_indefinite_port.indefinite.genus_number_field import cusp_links

            links = cusp_links(self)
        n = self.k + 2
        weyl = self.weyl()
        result = [-identity_matrix(self.field, n), *([weyl] if weyl is not None else []), *self.inner_automorphisms()]
        result.extend(eichler(self.gram, self.e, a) for a in self.even_e)
        result.extend(eichler(self.gram, self.f, b) for b in self.even_f)
        for u in self.field.unit_group().gens():
            u = self.field(u)
            scaling = identity_matrix(self.field, n)
            scaling[0, 0], scaling[1, 1] = u, ~u
            result.append(scaling)
        result.extend(links)
        assert all(self.preserves(g) and g.transpose() * self.gram * g == self.gram for g in result)
        return tuple(result)

    def _nearest(self, current, pivot, basis):
        r"""Return `a \in` span``basis`` near `-m/\text{pivot}`, minimizing `|N(h(m + \text{pivot}\, a))|` over the neighbouring lattice points."""
        coordinates_matrix = matrix(QQ, [[c for x in a[2:] for c in self.field(x).list()] for a in basis])
        z = [c / pivot for c in current[2:]]
        flat = vector(QQ, [c for x in z for c in self.field(x).list()])
        coefficients = coordinates_matrix.solve_left(flat)
        best = None
        for shift in product((-1, 0, 1), repeat=len(coefficients)):
            a = -sum(((ZZ(round(c)) + s) * b for c, s, b in zip(coefficients, shift, basis)), vector(self.field, self.k + 2))
            moved = current[2:] + pivot * a[2:]
            value = abs(self.field(sum(moved[i] * self.inner[i, j] * moved[j] for i in range(self.k) for j in range(self.k))).norm())
            if best is None or value < best[0]:
                best = (value, a)
        return best[1]

    def reduce_isotropic(self, v):
        r"""Return `g` in the generated group with `g v \in O_K^\times e`, for ``v`` `= \gamma e`, `\gamma \in O(\Lambda)` (the Euclidean reduction)."""
        assert self.h(v, v) == 0
        g = identity_matrix(self.field, self.k + 2)
        current = vector(self.field, v)
        scale = self.ideals[0].norm() ** 2
        while current[0] != 0 and current[1] != 0:
            x, y = current[0], current[1]
            if abs(x.norm()) >= abs(y.norm()) * scale:
                step = eichler(self.gram, self.e, self._nearest(current, y, self.even_e))
            else:
                step = eichler(self.gram, self.f, self._nearest(current, x, self.even_f))
            current = step * current
            g = step * g
        if current[0] == 0:
            weyl = self.weyl()
            assert weyl is not None
            current = weyl * current
            g = weyl * g
        assert current[1:] == 0 and current[0].is_unit()
        return g
