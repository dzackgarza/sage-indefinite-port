r"""Anisotropic binary Hermitian forms through a quaternion order (#59).

Let `E = Q(i)` and `h = diag(1, -3)` on `Z[i]^2`. The form is anisotropic exactly when `3` is not
a norm from `E`, which holds at the prime `3`. A matrix `[[\alpha, 3 \bar\beta], [\beta, \bar\alpha]]` with
`\alpha, \beta \in Z[i]` and `|\alpha|^2 - 3 |\beta|^2 = 1` is the element `\alpha + \beta j` of the order
`Z<1, i, j, k>` of `(-1, 3)` of reduced norm one, and every element of `SU(h)` has this form. So the
Voronoi generators of the order give `SU(h)`. Since `det` maps `U(h)` onto the units of `Z[i]` and
`diag(u, 1)` lies in `U(h)` with determinant `u`, the group `U(h)` is generated by `SU(h)` and
those diagonal elements. The scalars of `U(h)` are `\mu_4`, the kernel of `U(h) \to PU(h)`.

This route is the quaternion model of the form, in place of the Bestvina-Savin ocean of the source.
"""

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.rings.number_field.number_field import CyclotomicField

from sage_indefinite_port.indefinite.quaternion_voronoi import QuaternionVoronoi

FIELD = CyclotomicField(4)
I = FIELD.gen()
FORM = matrix(FIELD, 2, 2, [1, 0, 0, -3])


def is_anisotropic() -> bool:
    r"""Return whether `h` has no isotropic vector, by the Hilbert symbol `(-1, 3)` at `3`."""
    from sage.arith.misc import hilbert_symbol

    return hilbert_symbol(-1, 3, 3) == -1


def _to_matrix(element):
    r"""Return the matrix of ``x + y i + z j + w k`` in `SU(h)`."""
    x, y, z, w = element.coefficient_tuple() if hasattr(element, "coefficient_tuple") else (element, 0, 0, 0)
    alpha = FIELD(x) + FIELD(y) * I
    beta = FIELD(z) - FIELD(w) * I
    return matrix(FIELD, 2, 2, [alpha, 3 * beta.conjugate(), beta, alpha.conjugate()])


def special_unitary_generators():
    r"""Return generators of `SU(h)`."""
    norm_one, central = QuaternionVoronoi(-1, 3).norm_one_generators()
    return tuple(_to_matrix(element) for element in (*norm_one, *central))


def unitary_generators():
    r"""Return generators of `U(h)`."""
    return (*special_unitary_generators(), matrix(FIELD, 2, 2, [I, 0, 0, 1]))


def scalar_kernel():
    r"""Return a generator of the kernel of `U(h) \to PU(h)`, which is multiplication by `i`."""
    return I * identity_matrix(FIELD, 2)


def is_element(g) -> bool:
    integral = all(c.denominator() == 1 for entry in g.list() for c in entry.vector())
    return integral and g.conjugate_transpose() * FORM * g == FORM
