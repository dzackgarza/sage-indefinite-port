CELL_BUDGET = 40000


def _interval_product(x, y):
    values = [x[0] * y[0], x[0] * y[1], x[1] * y[0], x[1] * y[1]]
    return (min(values), max(values))


def _interval_square(x):
    low, high = x
    if low <= 0 <= high:
        return (QQ(0), max(low * low, high * high))
    return (min(low * low, high * high), max(low * low, high * high))


def _form_enclosure(gram, intervals):
    r"""Return an exact rational enclosure of `y^t G y` over the box ``intervals``."""
    low, high = QQ(0), QQ(0)
    n = len(intervals)
    for i in range(n):
        for j in range(i, n):
            weight = gram[i, j] if i == j else 2 * gram[i, j]
            part = _interval_square(intervals[i]) if i == j else _interval_product(intervals[i], intervals[j])
            a, b = weight * part[0], weight * part[1]
            low, high = low + min(a, b), high + max(a, b)
    return low, high


def covering_certificate(gram, transforms):
    r"""Decide `\forall t \in [0, 1]^3\ \exists (T, m)`: `|Q(T t - m)| < 1`, `Q(y) = y^t G y`, `T \in` ``transforms``, `m \in Z^3`.

    Boxes are bisected along their widest side; a box is closed when for one `T` and one `m` near the image of its centre the exact
    interval enclosure of `Q(T t - m)` lies in `(-1, 1)`. Returns the closed boxes with their `(T, m)`, or ``None`` when the budget of
    :data:`CELL_BUDGET` boxes is exhausted (the certificate failed; it does not prove the covering false).
    """
    stack = [tuple((QQ(0), QQ(1)) for _ in range(3))]
    closed = []
    visited = 0
    while stack:
        box = stack.pop()
        visited += 1
        if visited > CELL_BUDGET:
            return None
        centre = vector(QQ, [(a + b) / 2 for a, b in box])
        witness = None
        for index, T in enumerate(transforms):
            image = T * centre
            for shift in product((-1, 0, 1), repeat=3):
                m = [ZZ(round(c)) + s for c, s in zip(image, shift)]
                intervals = []
                for i in range(3):
                    low = high = -QQ(m[i])
                    for j in range(3):
                        a, b = T[i, j] * box[j][0], T[i, j] * box[j][1]
                        low, high = low + min(a, b), high + max(a, b)
                    intervals.append((low, high))
                low, high = _form_enclosure(gram, intervals)
                if -1 < low and high < 1:
                    witness = (index, tuple(m))
                    break
            if witness is not None:
                break
        if witness is not None:
            closed.append((box, witness))
            continue
        k = max(range(3), key=lambda i: box[i][1] - box[i][0])
        middle = (box[k][0] + box[k][1]) / 2
        stack.append(tuple((box[i][0], middle) if i == k else box[i] for i in range(3)))
        stack.append(tuple((middle, box[i][1]) if i == k else box[i] for i in range(3)))
    return closed


def _mul(X, Y):
    return tuple(tuple(sum((X[i][k] * Y[k][j] for k in range(2)), X[0][0] * 0) for j in range(2)) for i in range(2))


def _star(X):
    return tuple(tuple(X[j][i].conjugate() for j in range(2)) for i in range(2))


def _apply(X, x):
    return tuple(X[i][0] * x[0] + X[i][1] * x[1] for i in range(2))


def _inverse(X):
    r"""Return the inverse of an invertible `2 \times 2` matrix over a division ring (block elimination)."""
    (p, q), (r, s) = X
    if p == 0:
        swapped = _inverse(((r, s), (p, q)))
        return tuple(tuple(swapped[i][1 - j] for j in range(2)) for i in range(2))
    pi = ~p
    schur = s - r * pi * q
    si = ~schur
    return ((pi + pi * q * si * r * pi, -pi * q * si), (-si * r * pi, si))


def _columns(v, f):
    return ((v[0], f[0]), (v[1], f[1]))


class QuaternionMatrixCommutant:
    r"""The identification `A \cong M_2(D)` of a centre-`Q` commutant of dimension `16`; see the module docstring."""

    def __init__(self, commutant):
        self.commutant = commutant
        r = commutant.rank
        self._r = r
        one = identity_matrix(QQ, r)
        order = [m.change_ring(QQ) for m in commutant.order_basis]
        self._order = order
        y = self._zero_divisor()
        ideal = [m * y for m in order]
        rows = matrix(QQ, [x.list() for x in ideal])
        span = [ideal[i] for i in rows.pivot_rows()]
        coefficient_rows = []
        target = []
        for x in span:
            products = [(x * b).list() for b in span]
            for position in range(r * r):
                coefficient_rows.append([p[position] for p in products])
                target.append(x.list()[position])
        solution = matrix(QQ, coefficient_rows).solve_right(vector(QQ, target))
        e = sum(c * b for c, b in zip(solution, span))
        assert e * e == e and e.rank() == r // 2
        complement = one - e
        e12 = next(x for x in (e * m * complement for m in order) if not x.is_zero())
        candidates = [complement * m * e for m in order]
        solution = matrix(QQ, [(e12 * x).list() for x in candidates]).solve_left(vector(QQ, e.list()))
        e21 = sum(c * x for c, x in zip(solution, candidates))
        assert e12 * e21 == e and e21 * e12 == complement
        self.rows, self.cols = (e, e12), (e, e21)
        self._frame_algebra(e, order)

    def _zero_divisor(self):
        candidates = [*self._order, *(x * y - y * x for x in self._order for y in self._order)]
        for y in candidates:
            for q, _m in y.minimal_polynomial().factor():
                if q.degree() < y.minimal_polynomial().degree():
                    value = q(y)
                    if not value.is_zero() and value.rank() == self._r // 2:
                        return value
        raise NotImplementedError(
            f"no zero divisor of rank r/2 in the commutant of {self.commutant.isometries}: it is not M_2(D), or the "
            f"order basis and its commutators have irreducible minimal polynomials (#54)"
        )

    def _frame_algebra(self, e, order):
        r = self._r
        corner = [e * m * e for m in order]
        trd = lambda x: 4 * x.trace() / r
        pure = lambda x: x - trd(x) / 2 * e
        first = next(pure(m) for m in corner if not pure(m).is_zero())
        first = first * first.denominator()
        second = next(c for c in (first * pure(m) - pure(m) * first for m in corner) if not c.is_zero())
        second = second * second.denominator()
        a, b = (first * first).trace() / e.trace(), (second * second).trace() / e.trace()
        assert first * first == a * e and second * second == b * e
        if a * b == 0:
            self.algebra = None
            return
        if a > 0 and b > 0:
            first, a = first * second, -a * b
        elif a > 0 > b:
            first, second, a, b = second, first, b, a
        self.a, self.b = ZZ(a), ZZ(b)
        self.algebra = QuaternionAlgebra(QQ, self.a, self.b)
        self.frame = (e, first, second, first * second)
        self._frame_rows = matrix(QQ, [m.list() for m in self.frame])

    def is_division(self):
        return self.algebra is not None and self.algebra.is_division_algebra()

    def quaternion(self, x):
        return self.algebra(list(self._frame_rows.solve_left(vector(QQ, x.list()))))

    def embed(self, d):
        return sum(QQ(c) * m for c, m in zip(list(d), self.frame))

    def block(self, a):
        return tuple(tuple(self.quaternion(self.rows[i] * a * self.cols[j]) for j in range(2)) for i in range(2))

    def element_of(self, X):
        return sum(self.cols[i] * self.embed(X[i][j]) * self.rows[j] for i in range(2) for j in range(2))

    def column(self, x):
        return tuple(self.quaternion(self.rows[i] * x) for i in range(2))

    def _flat(self, x):
        return [c for d in x for c in list(d)]

    def _hermitian_matrix(self):
        r"""Return `H_0` with `H_0 M(a^\dagger) = M(a)^* H_0` for the order basis, and its sign `\epsilon`, `H_0^* = \epsilon H_0`."""
        if hasattr(self, "_H0"):
            return self._H0
        A = self.algebra
        units = [A(1), *A.gens()]
        assert len(units) == 4
        zero = A(0)
        unknowns = []
        for i, j, d in product(range(2), range(2), units):
            unknowns.append(tuple(tuple(d if (k, l) == (i, j) else zero for l in range(2)) for k in range(2)))
        equations = []
        for m in self._order:
            left, right = self.block(self.commutant.adjoint(m)), _star(self.block(m))
            images = [[c for x in _difference(_mul(X, left), _mul(right, X)) for entry in x for c in list(entry)] for X in unknowns]
            equations.extend(zip(*images))
        kernel = matrix(QQ, equations).right_kernel().basis()
        assert len(kernel) == 1, f"the adjoint is not inner of a unique form: kernel dimension {len(kernel)}"
        c = kernel[0]
        H0 = tuple(tuple(sum((c[4 * (2 * i + j) + k] * units[k] for k in range(4)), zero) for j in range(2)) for i in range(2))
        star = _star(H0)
        sign = 1 if star == H0 else -1
        assert sign == 1 or star == tuple(tuple(-x for x in row) for row in H0)
        self._H0 = (H0, sign)
        return self._H0

    def h(self, x, y, middle):
        r"""Return `y^* H_0 M x` for columns ``x``, ``y`` and the `2 \times 2` matrix ``middle`` `= H_0 M`."""
        image = _apply(middle, x)
        return y[0].conjugate() * image[0] + y[1].conjugate() * image[1]

    # Lattices of D^2 and of D, as rational coordinate rows.
    def _lattice(self, elements):
        rows = matrix(QQ, [self._flat(self.column(m * self.rows[0])) for m in elements])
        scale = rows.denominator()
        hermite = matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)
        assert hermite.nrows() == 8
        return matrix(QQ, hermite) / scale

    def _vector(self, row):
        return (self.algebra(list(row[:4])), self.algebra(list(row[4:])))

    def _right_order(self, lattice):
        r"""Return a `Z`-basis of `\{d \in D : \Lambda d \subseteq \Lambda\}`."""
        A = self.algebra
        units = [A(1), *A.gens()]
        vectors = [self._vector(row) for row in lattice.rows()]
        inverse = lattice.inverse()
        rows = matrix(QQ, [[c for x in vectors for c in vector(QQ, self._flat((x[0] * d, x[1] * d))) * inverse] for d in units])
        scale = rows.denominator()
        saturated = matrix(ZZ, scale * rows).saturation()
        return [sum(QQ(c) * d for c, d in zip(rows.solve_left(vector(QQ, row)), units)) for row in saturated.rows()]

    def _units(self, order):
        r"""Return generators of `R^\times` and the norm-value search of :func:`_reduced_norm_point` for the order ``order``."""
        rows = matrix(QQ, [list(d) for d in order])
        if self.a < 0 < self.b:
            voronoi = QuaternionVoronoi(int(self.a), int(self.b), rows)
            return voronoi.unit_generators(), lambda elements, value: _reduced_norm_point(voronoi, elements, value)
        raise NotImplementedError(
            f"D = ({self.a}, {self.b})_Q is definite: the Levi units are finite, and the definite unit and norm search is not "
            f"implemented here (#54)"
        )

    def _ideal_generator(self, elements, order, search):
        r"""Return `j` with `j R =` the right ideal spanned by ``elements``, or ``None`` when it is not principal over `R`."""
        coordinates = matrix(QQ, [list(d) for d in elements])
        reference = matrix(QQ, [list(d) for d in order])
        ratio = abs(coordinates.det() / reference.det())
        if not ratio.is_square():
            return None
        norm = ratio.sqrt()
        found = search([d.conjugate() for d in elements], norm)
        if found is None:
            return None
        return found.conjugate()

    def hyperbolic_model(self, lattice, middle):
        r"""Return `(v, f, q)` with `\Lambda = v R \oplus f R` of Gram `q H` for `h(x, y) = y^*` ``middle`` `x`, or ``None`` if `\Lambda` is not of that type.

        ``None`` is a proof (module docstring) once the covering certificate of `R` holds.
        """
        A = self.algebra
        vectors = [self._vector(row) for row in lattice.rows()]
        order = self._right_order(lattice)
        search = self._units(order)[1]
        form = lambda x: QQ(list(self.h(x, x, middle))[0])
        gram = matrix(QQ, 8, 8)
        for i in range(8):
            for j in range(8):
                s = (vectors[i][0] + vectors[j][0], vectors[i][1] + vectors[j][1])
                gram[i, j] = (form(s) - form(vectors[i]) - form(vectors[j])) / 2
        found = qfsolve(gram)
        if found in ZZ:
            return None
        found = vector(QQ, found)
        found = found * found.denominator()
        v = tuple(sum((c * x[k] for c, x in zip(found, vectors)), A(0)) for k in range(2))
        units = [A(1), *A.gens()]
        inverse = lattice.inverse()
        rows = matrix(QQ, [list(vector(QQ, self._flat((v[0] * d, v[1] * d))) * inverse) for d in units])
        scale = rows.denominator()
        saturated = matrix(ZZ, scale * rows).saturation()
        ideal = [sum(QQ(c) * d for c, d in zip(rows.solve_left(vector(QQ, row)), units)) for row in saturated.rows()]
        j = self._ideal_generator(ideal, order, search)
        if j is None:
            raise NotImplementedError(f"the right R-ideal of the null vector {v} is not principal over its order (#54)")
        v = (v[0] * j, v[1] * j)
        pairing = [self.h(x, v, middle) for x in vectors]
        coordinates = matrix(QQ, [list(d) for d in pairing])
        reference = matrix(QQ, [list(d) for d in order])
        hermite = matrix(ZZ, coordinates.denominator() * coordinates).hermite_form(include_zero_rows=False) / coordinates.denominator()
        index = abs(matrix(QQ, hermite).det() / reference.det())
        if not index.is_nth_power(4):
            return None
        q = index.nth_root(4)
        if not self._same_lattice([q * d for d in order], [self.algebra(list(row)) for row in hermite.rows()]):
            return None
        target = vector(QQ, list(A(q)))
        equations = matrix(QQ, [list(d) for d in pairing]).transpose()
        denominator = equations.denominator() * target.denominator()
        solution = _integer_solution(matrix(ZZ, denominator * equations), vector(ZZ, denominator * target))
        assert solution is not None
        f = tuple(sum((c * x[k] for c, x in zip(solution, vectors)), A(0)) for k in range(2))
        height = QQ(list(self.h(f, f, middle))[0]) / q
        traces = matrix(ZZ, [[ZZ(d.reduced_trace())] for d in order]).transpose()
        if height not in ZZ:
            return None
        shift = _integer_solution(traces, vector(ZZ, [ZZ(height)]))
        if shift is None:
            return None
        t = sum((c * d for c, d in zip(shift, order)), A(0))
        f = (f[0] - v[0] * t, f[1] - v[1] * t)
        assert self.h(v, v, middle) == 0 and self.h(f, f, middle) == 0 and self.h(f, v, middle) == q
        return v, f, q, order

    def _same_lattice(self, first, second):
        a = matrix(QQ, [list(d) for d in first])
        b = matrix(QQ, [list(d) for d in second])
        return a.nrows() == b.nrows() == 4 and all(c in ZZ for c in (a * b.inverse()).list()) and abs((a * b.inverse()).det()) == 1

    def _model_generators(self, order, unit_generators):
        r"""Return `L(u)`, `n(s)`, `W` of `U(R^2, H)` after certifying the covering of `R^0` (module docstring)."""
        A = self.algebra
        one, zero = A(1), A(0)
        traces = matrix(ZZ, [[ZZ(d.reduced_trace())] for d in order])
        pure = [sum((c * d for c, d in zip(k, order)), zero) for k in traces.left_kernel().basis()]
        assert len(pure) == 3
        gram = matrix(QQ, 3, 3, lambda i, j: ((pure[i] + pure[j]).reduced_norm() - pure[i].reduced_norm() - pure[j].reduced_norm()) / 2)
        frame = matrix(QQ, [list(s) for s in pure])
        transforms = [identity_matrix(QQ, 3)]
        moves = [*unit_generators, *(~u for u in unit_generators)]
        for u in [*moves, *(x * y for x in moves for y in moves)]:
            transforms.append(matrix(QQ, [frame.solve_left(vector(QQ, list(u * s * u.conjugate()))) for s in pure]).transpose())
        for limit in (1, len(transforms)):
            if covering_certificate(gram, transforms[:limit]) is not None:
                break
        else:
            raise NotImplementedError(
                f"the covering bound |nrd(u xi conj(u) + s)| < 1, s in R^0, u in R^x, was not certified for the order "
                f"{[list(d) for d in order]} of ({self.a}, {self.b})_Q within {CELL_BUDGET} boxes; the height reduction of "
                f"U(R^2, H) is not proved for it (#54)"
            )
        result = [((u, zero), (zero, ~u.conjugate())) for u in unit_generators]
        result.extend(((one, s), (zero, one)) for s in pure)
        result.append(((zero, one), (one, zero)))
        return result

    def unitary_generators(self):
        if hasattr(self, "_unitary"):
            return self._unitary
        H0, sign = self._hermitian_matrix()
        if sign != 1:
            raise NotImplementedError(
                f"the adjoint of the commutant of {self.commutant.isometries} is the adjoint of a skew-Hermitian form over "
                f"({self.a}, {self.b})_Q; its unitary group is not generated here (#54)"
            )
        self._lattice_rows = self._lattice(self._order)
        found = self.hyperbolic_model(self._lattice_rows, H0)
        if found is None:
            raise NotImplementedError(
                f"the Hermitian Lambda over ({self.a}, {self.b})_Q of the commutant of {self.commutant.isometries} is not "
                f"v R + f R with Gram q H for a rational q; its unitary group is not generated here (#54)"
            )
        v, f, q, order = found
        units, _search = self._units(order)
        P = _columns(v, f)
        Pi = _inverse(P)
        moves = [self.element_of(_mul(_mul(P, g), Pi)) for g in self._model_generators(order, units)]
        one = identity_matrix(QQ, self._r)
        assert all(self.commutant.adjoint(m) * m == one for m in moves)
        self._model_data = (v, f, q)
        self._unitary = tuple(moves)
        return self._unitary

    def centralizer_generators(self):
        return self.commutant._order_subgroup_generators(list(self.unitary_generators()))

    def coset_representatives(self):
        if not hasattr(self, "_cosets"):
            representatives = [identity_matrix(QQ, self._r)]
            position = 0
            while position < len(representatives):
                current = representatives[position]
                position += 1
                for generator in self.unitary_generators():
                    moved = generator * current
                    if not any(self.commutant.in_order(known.inverse() * moved) for known in representatives):
                        representatives.append(moved)
            self._cosets = tuple(representatives)
        return self._cosets

    def equivariant_transporter(self, target_gram, targets):
        commutant = self.commutant
        if abs(target_gram.det()) != abs(commutant.gram.det()):
            return None
        start = rational_intertwiner(commutant.isometries, targets)
        if start is None:
            return None
        square = commutant.gram.change_ring(QQ).inverse() * start.transpose() * target_gram * start
        assert commutant.contains(square)
        self.unitary_generators()
        v, f, q = self._model_data
        H0, _sign = self._hermitian_matrix()
        twisted = _mul(H0, self.block(square))
        target = self.hyperbolic_model(self._lattice(solution_lattice(commutant, start)), twisted)
        if target is None:
            return None
        v2, f2, q2, _order = target
        if q2 == q:
            image = _columns(v2, f2)
        elif q2 == -q:
            image = _columns(v2, (-f2[0], -f2[1]))
        else:
            return None
        isometry = self.element_of(_mul(image, _inverse(_columns(v, f))))
        one = identity_matrix(QQ, commutant.rank)
        assert commutant.adjoint(isometry) * square * isometry == one
        for representative in self.coset_representatives():
            found = _verified(commutant, start * isometry * representative, target_gram, targets)
            if found is not None:
                return found
        return None


def _difference(X, Y):
    return tuple(tuple(X[i][j] - Y[i][j] for j in range(2)) for i in range(2))
