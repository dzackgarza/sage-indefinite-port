r"""Commutants `A \cong M_2(D)`, `D` a quaternion division algebra over `Q`, with a Hermitian adjoint (#54).

Recovery of `D` and the form. A proper zero divisor of `M_2(D)` has `D`-rank one, hence matrix rank `r/2` on `Q^r`; one is
`q(y)` for a rational factor `q` of a reducible minimal polynomial. In the left ideal `A y` a right identity `e` is an idempotent with
`A e = A y` (a linear equation). With `e_{12} \in e A (1 - e)` nonzero and `e_{21} \in (1 - e) A e` solving `e_{12} e_{21} = e`, the rows
`r = (e, e_{12})` and columns `c = (e, e_{21})` satisfy `r_i c_j = \delta_{ij} e` and `c_1 r_1 + c_2 r_2 = 1`, so `a \mapsto (r_i a c_j)` is an
isomorphism `A \to M_2(D)`, `D = e A e`, with inverse `M \mapsto \sum c_i M_{ij} r_j`. The left ideal `A e` is `D^2` by `x \mapsto (r_1 x, r_2 x)`, a
right `D`-module on which `A` acts by matrices. `D` is put in the form `(a, b)_Q` as in :class:`QuaternionCommutant`.

The adjoint is `M(a^\dagger) = H_0^{-1} M(a)^* H_0` for one `H_0 \in GL_2(D)` up to `Q^\times` (Skolem-Noether), `^*` the conjugate transpose for the
canonical involution, found as the kernel of `H_0 M(a^\dagger) = M(a)^* H_0`; `H_0^* = \pm H_0`. Then `a^\dagger a = 1` exactly when `a` preserves
`h(x, y) = y^* H_0 x` on `D^2`. `\Lambda = O e` is `O`-stable, `R = \{d : \Lambda d \subseteq \Lambda\}` is an order of `D`, and
`C(Z) = U(\Lambda, h) \cap O` has finite index in `U(\Lambda, h)`.

Hyperbolic model. For Hermitian `H_0`, `h(x, x) \in Q`. A null `v` of `\Lambda` (PARI ``qfsolve`` on the rational form), made primitive by a
generator `j` of the right `R`-ideal `\{d : v d \in \Lambda\}`, and `h(\Lambda, v) = q R` with `q \in Q` give `f_1` with `h(f_1, v) = q`; `f = f_1 - v t`
has `h(f, f) = h(f_1, f_1) - q\, \mathrm{trd}(t)`, and `f_1` is unique modulo `v R`. Then `\Lambda = v R \oplus f R` with Gram `q H`, `H = [[0, 1], [1, 0]]`.

Generation of `U(R^2, H)` (height reduction, after :mod:`eisenstein_hyperbolic_unitary`). Let `(x; y)` be a primitive null column. Null means
`\bar y x + \bar x y = 0`, so `\xi = x y^{-1}` is pure. `L(u) = diag(u, \bar u^{-1})`, `u \in R^\times`, sends `\xi` to `u \xi \bar u`; `n(s) = [[1, s], [0, 1]]`,
`s \in R^0 = \{s \in R : \mathrm{trd}\, s = 0\}`, sends `\xi` to `\xi + s`; `W = [[0, 1], [1, 0]]` exchanges `x, y`. By :func:`covering_certificate`, every `\xi`
has a translate in the fundamental parallelepiped of `R^0` and a unit `u` and `s` with `|\mathrm{nrd}(u \xi \bar u + s)| < 1`; then `W n(s) L(u) n(s_0)` lowers
the integer `|\mathrm{nrd}(y)|`. At `y = 0` the column is `(x; 0)`, `x \in R^\times`, and `L(x)^{-1}` makes it `e_1`. An element fixing `e_1` has second
column `(p; 1)` with `p + \bar p = 0`, so it is `n(p)`. Hence `U(R^2, H)` is generated by `L(u)` (`u` in generators of `R^\times`), `n(s)` (`s` in a
`Z`-basis of `R^0`) and `W`. Every indefinite division quaternion algebra over `Q` is norm-Euclidean (Cerri-Chaubert-Lezowski, Acta Arith. 165
(2014), Cor. 3.5); the covering of `R^0` needed here is a property of the order and is certified, not assumed.

Transporters. As in :meth:`CentralFieldCommutant.equivariant_transporter`, `t_0 a_1` with `a_1 : (\Lambda, h) \to (\Lambda', h_m)`. All primitive null
vectors of `\Lambda` lie in one `U`-orbit (the height reduction), so `\Lambda'` is `q' H` or no isometry exists; and `q' H \cong q H` exactly when `q' = \pm q`
(reduced norms of determinants), by `v \mapsto v'`, `f \mapsto \pm f'`.
"""

