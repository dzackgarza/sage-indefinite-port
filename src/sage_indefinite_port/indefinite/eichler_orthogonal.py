def hypotheses_failure(field, gram):
    r"""Return the precise failed hypothesis of the module, or ``None`` when all hold."""
    n = gram.nrows()
    if n < 4 or gram.submatrix(0, 0, 4, 4) != _hyperbolic(field, 2):
        return "the model Gram does not start with H + H"
    if not field.is_totally_real():
        return f"K = Q[x]/({field.polynomial()}) is not totally real"
    if field.class_number() != 1:
        return f"O_K has class number {field.class_number()}; GHS Prop. 3.3 over O_K is stated for principal O_K"
    if not all(c.is_integral() for c in gram.list()) or not all((gram[i, i] / 2).is_integral() for i in range(n)):
        return "Lambda is not even"
    for p in (2, 3):
        for prime, _e in field.ideal(p).factor():
            if prime.residue_class_degree() != 1:
                continue
            residue = prime.residue_field()
            rank = gram.apply_map(residue).rank()
            needed = 6 if p == 2 else 5
            if rank < needed:
                return f"the Kneser condition rank_pi(Lambda) >= {needed} fails at a prime over {p} (rank {rank})"
    return None


def _hyperbolic(field, planes):
    G = matrix(field, 2 * planes, 2 * planes)
    for i in range(planes):
        G[2 * i, 2 * i + 1] = G[2 * i + 1, 2 * i] = 1
    return G


def _pairing(gram, x, y):
    return (matrix([x]) * gram * matrix([y]).transpose())[0, 0]


def eichler(gram, c, a):
    r"""Return the matrix of `t(c, a)` in the basis of ``gram``."""
    K = gram.base_ring()
    c, a = vector(K, c), vector(K, a)
    hc, ha = matrix(K, [c]) * gram, matrix(K, [a]) * gram
    square = _pairing(gram, a, a)
    n = gram.nrows()
    return identity_matrix(K, n) - c.column() * ha + a.column() * hc - (square / 2) * c.column() * hc


def reflection(gram, v):
    K = gram.base_ring()
    v = vector(K, v)
    return identity_matrix(K, gram.nrows()) - (2 / _pairing(gram, v, v)) * v.column() * (matrix(K, [v]) * gram)


def _integral(g):
    return all(c.is_integral() for c in g.list())


def jordan_exponents(gram, prime):
    r"""Return the exponents `r_k` (with multiplicity) of a Jordan splitting of ``gram`` at a non-dyadic ``prime``.

    A diagonal entry of minimal valuation is a pivot (the other entries of its row are then divisible by it); when only an
    off-diagonal `G_{ij}` has minimal valuation, `x_i + x_j` has value `G_{ii} + 2 G_{ij} + G_{jj}` of that valuation.
    """
    G = matrix(gram.base_ring(), gram)
    exponents = []
    while G.nrows():
        n = G.nrows()
        valuations = {(i, j): G[i, j].valuation(prime) for i in range(n) for j in range(n) if G[i, j] != 0}
        least = min(valuations.values())
        pivot = next((i for i in range(n) if valuations.get((i, i)) == least), None)
        if pivot is None:
            i, j = next(key for key, value in valuations.items() if value == least)
            T = identity_matrix(G.base_ring(), n)
            T[j, i] = 1
            G = T.transpose() * G * T
            pivot = i
            assert G[i, i].valuation(prime) == least
        T = identity_matrix(G.base_ring(), n)
        for k in range(n):
            if k != pivot:
                T[pivot, k] = -G[pivot, k] / G[pivot, pivot]
        G = T.transpose() * G * T
        exponents.append(least)
        G = G.delete_rows([pivot]).delete_columns([pivot])
    return exponents


class _Classes:
    r"""Coordinates over `F_2` of `C = \langle O_K^\times, \pi_P : P \in S \rangle K^{\times 2}`."""

    def __init__(self, field, primes):
        self.field = field
        self.primes = list(primes)
        self.units = field.unit_group()

    def __call__(self, c):
        K = self.field
        c = K(c)
        rest = c
        parities = [c.valuation(P) % 2 for P in self.primes]
        for prime, exponent in K.ideal(c).factor():
            if prime not in self.primes and exponent % 2:
                raise AssertionError(f"spinor norm {c} has odd valuation outside S: the local bound is violated")
            rest = rest / prime.gens_reduced()[0] ** exponent
        assert K.ideal(rest) == K.ideal(1)
        units = [ZZ(x) % 2 for x in self.units.log(rest)]
        return vector(GF(2), units + parities)


# Spinor norm groups over dyadic completions (Beli).
#
# Reference: C. N. Beli, *Integral spinor norm groups over dyadic local fields and representations of quadratic lattices*,
# PhD thesis, Ohio State University (2001), Chapter 1 (published as J. Number Theory 102 (2003) 125-182). Page numbers below
# are the thesis pages. Notation: `F = K_P`, `e = \mathrm{ord}\, 2`, `d(\varepsilon) = \mathrm{ord}\, \mathcal D(\varepsilon)` the order of the quadratic
# defect of a unit, `N(a) = \{x : (a, x)_P = 1\}`, `(1 + p^k) F^{\times 2}` with `(1 + p^0) F^{\times 2} = F^\times` and `(1 + p^\infty) F^{\times 2} = F^{\times 2}`
# (p. 16). `\theta(\tau_u) = Q(u)`, `Q(x) = B(x, x)` (p. 6).


class LocalSquareClasses:
    r"""`F^\times / F^{\times 2}` for `F = K_P`, `P` dyadic, as `F_2^m`, `m = [F : Q_2] + 2`.

    The classes are generated by a uniformizer `\pi` and the units `1 + c \pi^j`, `1 \le j \le 2e`, `c` in lifts of an `F_2`-basis of the
    residue field (`(1 + p^j) / (1 + p^{j+1})` is the residue field, and `1 + p^{2e+1} \subseteq F^{\times 2}`). The Hilbert symbol is a
    nondegenerate pairing on `F^\times / F^{\times 2}` (p. 16), so `x \mapsto ((x, c)_P)_c` is injective; a basis `B` among the generators gives
    coordinates. Subgroups are `F_2`-subspaces.
    """

    def __init__(self, field, prime):
        self.field, self.prime = field, prime
        self.e = prime.ramification_index()
        self.pi = field.uniformizer(prime)
        residue = prime.residue_field()
        self._lifts = [field(residue.lift(residue.gen() ** i)) for i in range(prime.residue_class_degree())]
        generators = [self.pi, *(1 + c * self.pi**j for j in range(1, 2 * self.e + 1) for c in self._lifts)]
        self._probes = generators
        basis, rows = [], matrix(GF(2), 0, len(generators))
        for g in generators:
            stacked = rows.stack(matrix(GF(2), [self._symbols(g)]))
            if stacked.rank() > rows.rank():
                basis.append(g)
                rows = stacked
        self.dimension = len(basis)
        assert self.dimension == self.e * prime.residue_class_degree() + 2
        self._basis, self._rows = basis, rows
        self.space = VectorSpace(GF(2), self.dimension)

    def _symbols(self, x):
        return [0 if self.field.hilbert_symbol(x, c, self.prime) == 1 else 1 for c in self._probes]

    def __call__(self, x):
        r"""Return the coordinates of the class of ``x`` in the basis `B`."""
        return self._rows.solve_left(vector(GF(2), self._symbols(self.field(x))))

    def ord(self, x):
        return self.field(x).valuation(self.prime)

    def span(self, elements):
        return self.space.subspace([self(x) for x in elements])

    def trivial(self):
        return self.space.subspace([])

    def norms(self, a):
        r"""Return `N(a) = \{x : (a, x)_P = 1\}`."""
        functional = [0 if self.field.hilbert_symbol(a, b, self.prime) == 1 else 1 for b in self._basis]
        return matrix(GF(2), self.dimension, 1, functional).left_kernel()

    def one_plus(self, k):
        r"""Return `(1 + p^k) F^{\times 2}` (convention of p. 16)."""
        if k <= 0:
            return self.space
        if k > 2 * self.e:
            return self.trivial()
        return self.span([1 + c * self.pi**j for j in range(k, 2 * self.e + 1) for c in self._lifts])

    def units(self):
        return self.one_plus(1)

    def defect(self, unit):
        r"""Return `d(\varepsilon) \in \{1, 3, \ldots, 2e - 1, 2e, \infty\}` (p. 16): the largest `k` with `\varepsilon \in (1 + p^k) F^{\times 2}`."""
        assert self.ord(unit) == 0
        x = self(unit)
        if x.is_zero():
            return Infinity
        return max(k for k in range(1, 2 * self.e + 1) if x in self.one_plus(k))

    def split(self, a):
        r"""Return `(R, \varepsilon)` with `a = \pi^R \varepsilon`."""
        R = self.ord(a)
        return R, self.field(a) / self.pi**R

    def in_A(self, a):
        r"""Lemma 1.3.5 (p. 26): `a \in \mathcal A` iff `-a \notin F^{\times 2}` and `\mathcal D(-a) \subseteq O`, or `-a \in F^{\times 2}` and `\mathrm{ord}\, a \ge -2e`."""
        R, eps = self.split(a)
        if R % 2:
            return R > 0
        d = self.defect(-eps)
        if d == Infinity:
            return R >= -2 * self.e
        return R + d >= 0

    def G(self, a):
        r"""Definition 3 (p. 29); `\theta(O^+(\langle \alpha, \beta \rangle)) = G(\beta / \alpha)` for a binary BONG (Lemma 1.3.7, p. 30)."""
        assert self.in_A(a)
        e = self.e
        R, eps = self.split(a)
        if R == -2 * e and self(-4 * self.field(a)).is_zero():
            return self.units()
        d = self.defect(-eps)
        if R > 4 * e:
            return self.span([a])
        if R > 2 * e:
            if R % 2:
                return self.span([self.pi * eps]) + self.one_plus(R - 2 * e).intersection(self.norms(-self.pi * eps))
            if 2 * d <= 4 * e - R:
                return self.span([eps]) + self.one_plus(R + d - 2 * e).intersection(self.norms(-eps))
            return self.span([eps]) + self.one_plus(R // 2)
        if R % 2:
            return self.norms(-self.pi * eps)
        if 2 * d <= 2 * e - R:
            return self.norms(-eps)
        if 4 * d <= 6 * e - R:
            return self.one_plus(R // 2 + d - e).intersection(self.norms(-eps))
        return self.one_plus(e - (2 * e - R) // 4)


def _dyadic_blocks(gram, prime):
    r"""Return an orthogonal splitting of `\Lambda_P` into unary and modular binary blocks, as column bases in the coordinates of ``gram``.

    `m` is the least valuation of an entry (the scale). If a diagonal entry has valuation `m` (`n = s`) it is split off as a unary
    block; otherwise an off-diagonal `G_{ij}` of valuation `m` spans a `p^m`-modular binary block (`\mathrm{ord} \det = 2m`, the diagonals
    being of larger valuation) and the rest is projected away with the integral matrix `A^{-1} (G_{ik}, G_{jk})^t` (O'Meara 91:9, 93:15).
    """
    K = gram.base_ring()
    basis = identity_matrix(K, gram.nrows())
    blocks = []
    while basis.ncols():
        G = basis.transpose() * gram * basis
        n = G.nrows()
        valuations = {(i, j): G[i, j].valuation(prime) for i in range(n) for j in range(n) if G[i, j] != 0}
        least = min(valuations.values())
        pivot = next((i for i in range(n) if valuations.get((i, i)) == least), None)
        indices = [pivot] if pivot is not None else list(next(key for key, value in valuations.items() if value == least))
        A = G.matrix_from_rows_and_columns(indices, indices)
        rest = [k for k in range(n) if k not in indices]
        T = identity_matrix(K, n)
        for k in rest:
            shift = A.solve_right(G.matrix_from_rows_and_columns(indices, [k]))
            assert all(c.valuation(prime) >= 0 for c in shift.list())
            for row, index in enumerate(indices):
                T[index, k] = -shift[row, 0]
        basis = basis * T
        blocks.append(basis.matrix_from_columns(indices))
        basis = basis.matrix_from_columns(rest)
    return blocks


def _norm_generator(gram, block, prime):
    r"""Return a vector of the block spanned by the columns of ``block`` whose `Q` has the order of the block norm."""
    _r, u = _block_invariants(block.transpose() * gram * block, prime)
    columns = block.columns()
    candidates = [*columns, *([columns[0] + columns[1]] if len(columns) == 2 else [])]
    return next(x for x in candidates if (x * gram * x) != 0 and (x * gram * x).valuation(prime) == u)


def _exchange(gram, first, second, prime):
    r"""Lemma 1.4.5(i) (Beli thesis, p. 61): ``first`` binary `p^{r_1}`-modular with basis `x, y`, `\mathrm{ord} B(x, y) = r_1`,
    `sL_1 \supseteq sL_2` and `nL_1 \subset nL_2`. With `z` a norm generator of `L_2`, `L_1' = O(x + z) + O y` is `p^{r_1}`-modular and
    splits `L_1 \perp L_2 = L_1' \perp L_2'`, with `nL_1' = nL_2' = nL_2`. Returns the column bases of `L_1'` and `L_2'`."""
    x, y = first.columns()
    if (x * gram * y) == 0 or (x * gram * y).valuation(prime) != _block_invariants(first.transpose() * gram * first, prime)[0]:
        x, y = x + y, y
    z = _norm_generator(gram, second, prime)
    new_first = matrix(gram.base_ring(), [x + z, y]).transpose()
    A = new_first.transpose() * gram * new_first
    columns = []
    for w in second.columns():
        shift = A.solve_right(new_first.transpose() * gram * w)
        assert all(c.valuation(prime) >= 0 for c in shift)
        columns.append(w - new_first * shift)
    return new_first, matrix(gram.base_ring(), columns).transpose()


def _dual(gram, block):
    return block * (block.transpose() * gram * block).inverse()


def maximal_norm_splitting(gram, prime):
    r"""Return a maximal norm splitting of `\Lambda_P` (Definition 7, Beli thesis p. 51) as column bases, scales non-decreasing.

    Lemma 1.4.6 (p. 62): starting from any splitting into unary and modular binary blocks, a pair `i < j` with `u_j < u_i` is repaired by
    Lemma 1.4.5(i) on `(L_i, L_j)`, and a pair with `u_j - 2 r_j > u_i - 2 r_i` by Lemma 1.4.5(ii), i.e. 1.4.5(i) on the duals `(L_j^\#, L_i^\#)`
    (`\mathrm{ord}\, n L^\# = u - 2r`). Each step keeps scales and ranks and lowers the number of blocks with `nL_k \subset nL^{sL_k}`.
    (Xu's minimal norm Jordan splitting, Pacific J. Math. 167 (1995) 385-398, Thm. 1.1, is existential; Beli's exchange is the construction.)
    """
    blocks = _dyadic_blocks(gram, prime)
    while True:
        blocks.sort(key=lambda b: _block_invariants(b.transpose() * gram * b, prime)[0])
        invariants = [_block_invariants(b.transpose() * gram * b, prime) for b in blocks]
        pair = next(
            (
                (i, j)
                for i in range(len(blocks))
                for j in range(i + 1, len(blocks))
                if not 0 <= invariants[j][1] - invariants[i][1] <= 2 * (invariants[j][0] - invariants[i][0])
            ),
            None,
        )
        if pair is None:
            return blocks
        i, j = pair
        (ri, ui), (rj, uj) = invariants[i], invariants[j]
        if uj < ui:
            blocks[i], blocks[j] = _exchange(gram, blocks[i], blocks[j], prime)
        else:
            assert uj - 2 * rj > ui - 2 * ri
            dual_j, dual_i = _exchange(gram, _dual(gram, blocks[j]), _dual(gram, blocks[i]), prime)
            blocks[i], blocks[j] = _dual(gram, dual_i), _dual(gram, dual_j)


def _block_invariants(block, prime):
    r"""Return `(r, u)`: the orders of the scale and the norm of a unary or modular binary block Gram."""
    n = block.nrows()
    entries = [block[i, j] for i in range(n) for j in range(n) if block[i, j] != 0]
    norms = [block[i, i] for i in range(n) if block[i, i] != 0] + [2 * block[i, j] for i in range(n) for j in range(n) if i != j and block[i, j] != 0]
    return min(x.valuation(prime) for x in entries), min(x.valuation(prime) for x in norms)


def _block_bong(block, prime):
    r"""Return the lengths of a BONG of one block: a norm generator `x_1` and `\det / Q(x_1)` (Lemma 1.2.1, p. 19)."""
    if block.nrows() == 1:
        return [block[0, 0]]
    alpha, beta, gamma = block[0, 0], block[0, 1], block[1, 1]
    _r, u = _block_invariants(block, prime)
    first = next(x for x in (alpha, gamma, alpha + 2 * beta + gamma) if x != 0 and x.valuation(prime) == u)
    return [first, block.det() / first]


def good_bong(gram, prime):
    r"""Return the lengths `a_1, \ldots, a_n` of a good BONG of `\Lambda_P` and whether `\Lambda_P` has property A.

    Property A (Definition 6, p. 51): a Jordan splitting with components of rank `\le 2` and `0 < u_j - u_i < 2 (r_j - r_i)` for `i < j`.
    For such `\Lambda_P` every Jordan splitting is a maximal norm splitting (note to Definition 7, p. 51), so the test on the Jordan
    splitting grouped from :func:`maximal_norm_splitting` decides the property. A maximal norm splitting gives a BONG by concatenating block
    BONGs (Lemma 1.4.1(i), p. 51), and it is good (Corollary 1.4.2(ii), Definition 8, p. 55).
    """
    blocks = [b.transpose() * gram * b for b in maximal_norm_splitting(gram, prime)]
    invariants = [_block_invariants(b, prime) for b in blocks]
    components = {}
    for (r, u), b in zip(invariants, blocks):
        rank, norm = components.get(r, (0, u))
        components[r] = (rank + b.nrows(), min(norm, u))
    scales = sorted(components)
    property_a = all(components[r][0] <= 2 for r in scales) and all(
        0 < components[s][1] - components[r][1] < 2 * (s - r) for k, r in enumerate(scales) for s in scales[k + 1 :]
    )
    lengths = [a for b in blocks for a in _block_bong(b, prime)]
    orders = [a.valuation(prime) for a in lengths]
    assert all(orders[i] <= orders[i + 2] for i in range(len(orders) - 2))
    assert not property_a or all(orders[i] < orders[i + 2] for i in range(len(orders) - 2))
    return lengths, property_a


def spinor_norm_group(field, gram, prime, classes=None):
    r"""Return `\theta(O^+(\Lambda_P))` as a subspace of :class:`LocalSquareClasses`, `P` dyadic.

    Property A: Theorem 1 (p. 70), `\theta(O^+(L)) = G(a_2/a_1) \cdots G(a_n/a_{n-1}) (1 + p^\alpha) F^{\times 2}`,
    `\alpha = \min_{1 \le i \le n-2} [(R_{i+2} - R_i)/2]` (`\alpha = \infty` for `n \le 2`). Otherwise `\theta(O^+(L))` is `F^\times` or
    `O^\times F^{\times 2}` (Sec. 1.7, p. 105), and Theorem 3 (p. 112) decides: `\theta(O^+(L)) \subseteq O^\times F^{\times 2}` iff every
    `G(a_{i+1}/a_i) \subseteq O^\times F^{\times 2}` and `(R_{i+1} - R_i)/2 \equiv e \pmod 2` whenever `R_i = R_{i+2}`.
    """
    classes = classes or LocalSquareClasses(field, prime)
    lengths, property_a = good_bong(gram, prime)
    n = len(lengths)
    orders = [classes.ord(a) for a in lengths]
    ratios = [lengths[i + 1] / lengths[i] for i in range(n - 1)]
    assert all(classes.in_A(x) for x in ratios)
    groups = [classes.G(x) for x in ratios]
    if property_a:
        result = classes.trivial()
        for g in groups:
            result = result + g
        if n >= 3:
            result = result + classes.one_plus(min((orders[i + 2] - orders[i]) // 2 for i in range(n - 2)))
        return result
    units = classes.units()
    contained = all(g.is_subspace(units) for g in groups) and all(
        ((orders[i + 1] - orders[i]) // 2 - classes.e) % 2 == 0 for i in range(n - 2) if orders[i] == orders[i + 2]
    )
    return units if contained else classes.space


def dyadic_parity_free(field, gram, prime):
    r"""Return whether `O(\Lambda_P)` has an element `g` with `v_P(c(g))` odd (module docstring)."""
    classes = LocalSquareClasses(field, prime)
    theta = spinor_norm_group(field, gram, prime, classes)
    n = gram.nrows()
    norm_order = min(
        [gram[i, i].valuation(prime) for i in range(n) if gram[i, i] != 0]
        + [(2 * gram[i, j]).valuation(prime) for i in range(n) for j in range(n) if i != j and gram[i, j] != 0]
    )
    return not theta.is_subspace(classes.units()) or (classes.e + norm_order) % 2 == 1


def _unbounded_primes(field, gram):
    r"""Return the primes `S` of the module docstring: non-dyadic with an odd Jordan exponent, or dyadic outside O'Meara-Pollak with
    free parity (:func:`dyadic_parity_free`)."""
    two = field.ideal(2)
    unramified = all(e == 1 for _p, e in two.factor())
    result = []
    for prime, _e in field.ideal(2 * gram.det()).factor():
        if prime.is_coprime(two):
            if any(r % 2 for r in jordan_exponents(gram, prime)):
                result.append(prime)
        elif (not unramified or gram.det().valuation(prime) != 0) and dyadic_parity_free(field, gram, prime):
            result.append(prime)
    return result


def generators(field, gram):
    r"""Return generators of `O(\Lambda)` as matrices in the basis of ``gram``; raise when a hypothesis fails."""
    failure = hypotheses_failure(field, gram)
    if failure is not None:
        raise NotImplementedError(f"O(Lambda) for Lambda = H + H + L_0 over O_K: {failure} (#54)")
    n = gram.nrows()
    basis = [vector(field, [1 if i == k else 0 for i in range(n)]) for k in range(n)]
    e, f = basis[0], basis[1]
    integers = field.ring_of_integers().basis()
    result = [eichler(gram, c, k * b) for c in (e, f) for b in basis[2:] for k in integers]
    units = [field(u) for u in field.unit_group().gens()]
    result.extend(reflection(gram, e - u * f) for u in [field.one(), *units])
    odd = _unbounded_primes(field, gram)
    if odd:
        classes = _Classes(field, odd)
        width = len(field.unit_group().gens())
        found = matrix(GF(2), 0, len(odd))
        zbasis = [k * b for b in basis for k in integers]
        bound = 1
        while found.rank() < len(odd):
            for coefficients in product(range(-bound, bound + 1), repeat=len(zbasis)):
                if max(abs(c) for c in coefficients) != bound:
                    continue
                v = sum(c * x for c, x in zip(coefficients, zbasis))
                norm = _pairing(gram, v, v)
                if norm == 0:
                    continue
                g = reflection(gram, v)
                if not _integral(g):
                    continue
                image = classes(-2 * norm)[width:]
                stacked = found.stack(matrix(GF(2), [image]))
                if stacked.rank() > found.rank():
                    found = stacked
                    result.append(g)
                    if found.rank() == len(odd):
                        break
            bound += 1
    assert all(_integral(g) and g.transpose() * gram * g == gram for g in result)
    return tuple(result)
