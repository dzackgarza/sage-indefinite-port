r"""Generators of `O(\Lambda)` for an even `\Lambda = U \perp U_1 \perp L_0` over a principal totally real `O_K` (#54).

``gram`` is the Gram matrix `G_{ij} = h(b_i, b_j)` of a symmetric `O_K`-bilinear form `h` in an `O_K`-basis
`e, f, e_1, f_1, b_4, \ldots` of `\Lambda` with `G = H \oplus H \oplus G_0`, `H = [[0, 1], [1, 0]]`, and `h(x, x) \in 2 O_K`.

Eichler transvections. For `c \in \{e, f\}` and `a \in L_1 = U_1 \perp L_0`,
`t(c, a)(x) = x - h(a, x) c + h(c, x) a - \tfrac12 h(a, a) h(c, x) c` is integral (`h(a, a) \in 2 O_K`), and `a \mapsto t(c, a)` is
additive, so `E_U(L_1) = \langle t(c, a) \rangle` is generated by `a` in a `Z`-basis of `L_1`.

Theorem (Gritsenko-Hulek-Sankaran, *Abelianisation of orthogonal groups and the fundamental group of modular varieties*,
J. Algebra 322 (2009), arXiv:0810.1614, Prop. 3.3, valid over a principal ideal domain `O_K` by Sec. 4.2, proof of Thm. 4.2):
(i) primitive `u, v` with `h(u, u) = h(v, v)` and `u^* \equiv v^* \bmod \Lambda` are `E_U(L_1)`-equivalent (Eichler criterion,
Eichler 1952 Satz 10.4); (ii) `E(\Lambda) = E_U(L_1)`; (iv) for every `r` with `h(r, r) = -2`, `\sigma_r = \rho \sigma_{e - f}`, `\rho \in E_U(L_1)`.
Theorem (Kneser 1956, Satz 4; GHS Thm. 4.1 over `O_K`): under the Kneser conditions (`\Lambda` even, represents `-2`,
a real place of Witt index `\ge 2`, `\mathrm{rank}_\pi \Lambda \ge 5` (`\ge 6`) at primes with residue field `F_3` (`F_2`)),
`O'(\Lambda) = SO(\Lambda) \cap \ker \theta` is generated by `\sigma_a \sigma_b`, `h(a, a) = h(b, b) = -2`. With (iv), `O'(\Lambda) \subseteq E_U(L_1)`.

So `O(\Lambda) / E_U(L_1)` is a quotient of `O(\Lambda) / O'(\Lambda)`, which `\kappa = (\det, \theta)` embeds in
`\{\pm 1\} \times K^\times / K^{\times 2}`, `\theta(\sigma_v) = h(v, v)`. Generators are `E_U(L_1)` and elements realizing a basis of
`\kappa(O(\Lambda))`.

Bound on `\kappa(O(\Lambda))`. Put `c(g) = \theta(g) (-2)^{[\det g = -1]}`. At each prime `P`, `g \in O(\Lambda_P)`:

- `P` non-dyadic: `O(\Lambda_P)` is generated by symmetries (Kneser 1956; O'Meara, *Introduction to Quadratic Forms*, Sec. 92).
  In a Jordan splitting `\perp \pi^{r_k} J_k` with every `r_k` even, an integral symmetry `\sigma_v`, `v` primitive, has
  `h(v, v) \mid 2 h(v, \Lambda)`; with `v_k` the valuation of the `J_k`-part of `v`, `v(h(v, v)) \ge m = \min_k (r_k + 2 v_k)` and
  `v(h(v, \Lambda)) \le \min_k (r_k + v_k) \le m`, so `v(h(v, v))` equals `m = r_{k_0}` (with `v_{k_0} = 0`), which is even. Hence `v_P(c(g))` is even.
- `P` dyadic, `\Lambda_P` even unimodular, `2` unramified: `O(\Lambda_P)` is generated by symmetries and Eichler transformations
  (O'Meara-Pollak, *Generation of local integral orthogonal groups* I, II, Math. Z. 87 (1965), 93 (1966)). An integral symmetry of a
  primitive `v` has `h(v, v) \mid 2` and `h(v, v) \in 2 O_P`, so `h(v, v) \in 2 O_P^\times`; Eichler transformations have `\theta = 1`.
  Hence `v_P(c(g))` is even.
- `P` dyadic otherwise (`2` ramified, or `\Lambda_P` not unimodular): the parity of `v_P(c(g))` is decided exactly by Beli's spinor norm
  groups (:func:`spinor_norm_group`). `c(O^+(\Lambda_P)) = \theta(O^+(\Lambda_P))` and, `\sigma_{x_1}` being integral for a norm generator `x_1`,
  `c(O^-(\Lambda_P)) = -2 Q(x_1) \theta(O^+(\Lambda_P))`. So odd `v_P(c(g))` occurs exactly when `\theta(O^+(\Lambda_P)) \not\subseteq O_P^\times F_P^{\times 2}`
  or `e_P + \mathrm{ord}_P\, n\Lambda_P` is odd; otherwise `P` leaves `S`.

As `O_K` is principal, `c(g)` lies in `C = \langle O_K^\times, \pi_P : P \in S \rangle K^{\times 2}`, where `S` consists of the non-dyadic
`P \mid \det G` with an odd Jordan exponent and the dyadic `P` of the last case whose parity is free. For `P \in S` the parity is realized by
an element of `O(\Lambda_P)`; integral reflections of `\Lambda` realizing the free parities are enumerated by height (shells of growing
coefficient bound in a `Z`-basis of `\Lambda`) until their classes span the parity coordinates of `S`. The enumeration is unbounded: it ends
when integral reflections realize every free parity. Eichler transvections have trivial spinor norm and products of found elements add
nothing to the `F_2`-span, so reflections are the only candidates this enumeration needs.
`\kappa(\sigma_{e - f}) = (-1, -2)`, `c(\sigma_{e-f} \sigma_{e - \varepsilon f}) = \varepsilon` for units `\varepsilon`; for `P \in S`
a reflection `\sigma_v` with `v_P(-2 h(v, v))` odd is searched in a box. When the found classes span `C`, the generators below generate `O(\Lambda)`.
"""

