r"""Generators of `O(\Lambda)` for an even `\Lambda = U \perp U_1 \perp L_0` over a principal totally real `O_K` (#54).

``gram`` is the Gram matrix `G_{ij} = h(b_i, b_j)` of a symmetric `O_K`-bilinear form `h` in an `O_K`-basis
`e, f, e_1, f_1, b_4, \ldots` of `\Lambda` with `G = H \oplus H \oplus G_0`, `H = [[0, 1], [1, 0]]`, and `h(x, x) \in 2 O_K`.

Eichler transvections. For `c \in \{e, f\}` and `a \in L_1 = U_1 \perp L_0`,
`t(c, a)(x) = x - h(a, x) c + h(c, x) a - \tfrac12 h(a, a) h(c, x) c` is integral (`h(a, a) \in 2 O_K`), and `a \mapsto t(c, a)` is
additive, so `E_U(L_1) = \langle t(c, a) \rangle` is generated by `a` in a `Z`-basis of `L_1`.

Theorem (Gritsenko-Hulek-Sankaran, *Abelianisation of orthogonal groups and the fundamental group of modular varieties*,
J. Algebra 322 (2009), arXiv:0810.1614, Prop. 3.3, valid over a principal ideal domain `O_K` by Sec. 4.2, proof of Thm. 4.2):
(i) primitive `u, v` with `h(u, u) = h(v, v)` and `u^* \equiv v^* \bmod \Lambda` are `E_U(L_1)`-equivalent (Eichler criterion,
Eichler 1952 Satz 10.4); (ii) `E(\Lambda) = E_U(L_1)`; (iv) for every `r` with `h(r, r) = -2`, `\sigma_r = \rho \sigma_{e - f}`, `\rho \in E_U(L_1)`.
Theorem (Kneser 1956, Satz 4; GHS Thm. 4.1 over `O_K`): under the Kneser conditions (`\Lambda` even, represents `-2`,
a real place of Witt index `\ge 2`, `\mathrm{rank}_\pi \Lambda \ge 5` (`\ge 6`) at primes with residue field `F_3` (`F_2`)),
`O'(\Lambda) = SO(\Lambda) \cap \ker \theta` is generated by `\sigma_a \sigma_b`, `h(a, a) = h(b, b) = -2`. With (iv), `O'(\Lambda) \subseteq E_U(L_1)`.

So `O(\Lambda) / E_U(L_1)` is a quotient of `O(\Lambda) / O'(\Lambda)`, which `\kappa = (\det, \theta)` embeds in
`\{\pm 1\} \times K^\times / K^{\times 2}`, `\theta(\sigma_v) = h(v, v)`. Generators are `E_U(L_1)` and elements realizing a basis of
`\kappa(O(\Lambda))`.

Bound on `\kappa(O(\Lambda))`. Put `c(g) = \theta(g) (-2)^{[\det g = -1]}`. At each prime `P`, `g \in O(\Lambda_P)`:

- `P` non-dyadic: `O(\Lambda_P)` is generated by symmetries (Kneser 1956; O'Meara, *Introduction to Quadratic Forms*, Sec. 92).
  In a Jordan splitting `\perp \pi^{r_k} J_k` with every `r_k` even, an integral symmetry `\sigma_v`, `v` primitive, has
  `h(v, v) \mid 2 h(v, \Lambda)`; with `v_k` the valuation of the `J_k`-part of `v`, `v(h(v, v)) \ge m = \min_k (r_k + 2 v_k)` and
  `v(h(v, \Lambda)) \le \min_k (r_k + v_k) \le m`, so `v(h(v, v))` equals `m = r_{k_0}` (with `v_{k_0} = 0`), which is even. Hence `v_P(c(g))` is even.
- `P` dyadic, `\Lambda_P` even unimodular, `2` unramified: `O(\Lambda_P)` is generated by symmetries and Eichler transformations
  (O'Meara-Pollak, *Generation of local integral orthogonal groups* I, II, Math. Z. 87 (1965), 93 (1966)). An integral symmetry of a
  primitive `v` has `h(v, v) \mid 2` and `h(v, v) \in 2 O_P`, so `h(v, v) \in 2 O_P^\times`; Eichler transformations have `\theta = 1`.
  Hence `v_P(c(g))` is even.
- `P` dyadic otherwise (`2` ramified, or `\Lambda_P` not unimodular): no parity bound is used, so `v_P(c(g))` is unrestricted.

As `O_K` is principal, `c(g)` lies in `C = \langle O_K^\times, \pi_P : P \in S \rangle K^{\times 2}`, where `S` consists of the non-dyadic
`P \mid \det G` with an odd Jordan exponent and the dyadic `P` of the last case. This bound holds without any dyadic hypothesis; it is
sharp at a dyadic `P` exactly when a reflection realizes its class, which the search below certifies.
`\kappa(\sigma_{e - f}) = (-1, -2)`, `c(\sigma_{e-f} \sigma_{e - \varepsilon f}) = \varepsilon` for units `\varepsilon`; for `P \in S`
a reflection `\sigma_v` with `v_P(-2 h(v, v))` odd is searched in a box. When the found classes span `C`, the generators below generate `O(\Lambda)`.
"""

from itertools import product

from sage.matrix.constructor import matrix
from sage.matrix.special import identity_matrix
from sage.modules.free_module_element import vector
from sage.rings.finite_rings.finite_field_constructor import GF
from sage.rings.integer_ring import ZZ


def hypotheses_failure(field, gram):
    r"""Return the precise failed hypothesis of the module, or ``None`` when all hold."""
    n = gram.nrows()
    if n < 4 or gram.submatrix(0, 0, 4, 4) != _hyperbolic(field, 2):
        return "the model Gram does not start with H + H"
    if not field.is_totally_real():
        return f"K = Q[x]/({field.polynomial()}) is not totally real"
    if field.class_number() != 1:
        return f"O_K has class number {field.class_number()}; GHS Prop. 3.3 over O_K is stated for principal O_K"
    if not all(c.is_integral() for c in gram.list()) or not all((gram[i, i] / 2).is_integral() for i in range(n)):
        return "Lambda is not even"
    for p in (2, 3):
        for prime, _e in field.ideal(p).factor():
            if prime.residue_class_degree() != 1:
                continue
            residue = prime.residue_field()
            rank = gram.apply_map(residue).rank()
            needed = 6 if p == 2 else 5
            if rank < needed:
                return f"the Kneser condition rank_pi(Lambda) >= {needed} fails at a prime over {p} (rank {rank})"
    return None


def _hyperbolic(field, planes):
    G = matrix(field, 2 * planes, 2 * planes)
    for i in range(planes):
        G[2 * i, 2 * i + 1] = G[2 * i + 1, 2 * i] = 1
    return G


def _pairing(gram, x, y):
    return (matrix([x]) * gram * matrix([y]).transpose())[0, 0]


def eichler(gram, c, a):
    r"""Return the matrix of `t(c, a)` in the basis of ``gram``."""
    K = gram.base_ring()
    c, a = vector(K, c), vector(K, a)
    hc, ha = matrix(K, [c]) * gram, matrix(K, [a]) * gram
    square = _pairing(gram, a, a)
    n = gram.nrows()
    return identity_matrix(K, n) - c.column() * ha + a.column() * hc - (square / 2) * c.column() * hc


def reflection(gram, v):
    K = gram.base_ring()
    v = vector(K, v)
    return identity_matrix(K, gram.nrows()) - (2 / _pairing(gram, v, v)) * v.column() * (matrix(K, [v]) * gram)


def _integral(g):
    return all(c.is_integral() for c in g.list())


def jordan_exponents(gram, prime):
    r"""Return the exponents `r_k` (with multiplicity) of a Jordan splitting of ``gram`` at a non-dyadic ``prime``.

    A diagonal entry of minimal valuation is a pivot (the other entries of its row are then divisible by it); when only an
    off-diagonal `G_{ij}` has minimal valuation, `x_i + x_j` has value `G_{ii} + 2 G_{ij} + G_{jj}` of that valuation.
    """
    G = matrix(gram.base_ring(), gram)
    exponents = []
    while G.nrows():
        n = G.nrows()
        valuations = {(i, j): G[i, j].valuation(prime) for i in range(n) for j in range(n) if G[i, j] != 0}
        least = min(valuations.values())
        pivot = next((i for i in range(n) if valuations.get((i, i)) == least), None)
        if pivot is None:
            i, j = next(key for key, value in valuations.items() if value == least)
            T = identity_matrix(G.base_ring(), n)
            T[j, i] = 1
            G = T.transpose() * G * T
            pivot = i
            assert G[i, i].valuation(prime) == least
        T = identity_matrix(G.base_ring(), n)
        for k in range(n):
            if k != pivot:
                T[pivot, k] = -G[pivot, k] / G[pivot, pivot]
        G = T.transpose() * G * T
        exponents.append(least)
        G = G.delete_rows([pivot]).delete_columns([pivot])
    return exponents


class _Classes:
    r"""Coordinates over `F_2` of `C = \langle O_K^\times, \pi_P : P \in S \rangle K^{\times 2}`."""

    def __init__(self, field, primes):
        self.field = field
        self.primes = list(primes)
        self.units = field.unit_group()

    def __call__(self, c):
        K = self.field
        c = K(c)
        rest = c
        parities = [c.valuation(P) % 2 for P in self.primes]
        for prime, exponent in K.ideal(c).factor():
            if prime not in self.primes and exponent % 2:
                raise AssertionError(f"spinor norm {c} has odd valuation outside S: the local bound is violated")
            rest = rest / prime.gens_reduced()[0] ** exponent
        assert K.ideal(rest) == K.ideal(1)
        units = [ZZ(x) % 2 for x in self.units.log(rest)]
        return vector(GF(2), units + parities)


def _unbounded_primes(field, gram):
    r"""Return the primes `S` of the module docstring: non-dyadic with an odd Jordan exponent, or dyadic outside O'Meara-Pollak."""
    two = field.ideal(2)
    unramified = all(e == 1 for _p, e in two.factor())
    result = []
    for prime, _e in field.ideal(2 * gram.det()).factor():
        if prime.is_coprime(two):
            if any(r % 2 for r in jordan_exponents(gram, prime)):
                result.append(prime)
        elif not unramified or gram.det().valuation(prime) != 0:
            result.append(prime)
    return result


def generators(field, gram):
    r"""Return generators of `O(\Lambda)` as matrices in the basis of ``gram``; raise when a hypothesis fails."""
    failure = hypotheses_failure(field, gram)
    if failure is not None:
        raise NotImplementedError(f"O(Lambda) for Lambda = H + H + L_0 over O_K: {failure} (#54)")
    n = gram.nrows()
    basis = [vector(field, [1 if i == k else 0 for i in range(n)]) for k in range(n)]
    e, f = basis[0], basis[1]
    integers = field.ring_of_integers().basis()
    result = [eichler(gram, c, k * b) for c in (e, f) for b in basis[2:] for k in integers]
    units = [field(u) for u in field.unit_group().gens()]
    result.extend(reflection(gram, e - u * f) for u in [field.one(), *units])
    odd = _unbounded_primes(field, gram)
    if odd:
        classes = _Classes(field, odd)
        width = len(field.unit_group().gens())
        found = matrix(GF(2), 0, len(odd))
        zbasis = [k * b for b in basis[2:] for k in integers]
        for coefficients in product((-1, 0, 1), repeat=len(zbasis)):
            if found.rank() == len(odd):
                break
            v = sum(c * x for c, x in zip(coefficients, zbasis))
            norm = _pairing(gram, v, v)
            if norm == 0:
                continue
            g = reflection(gram, v)
            if not _integral(g):
                continue
            image = classes(-2 * norm)[width:]
            stacked = found.stack(matrix(GF(2), [image]))
            if stacked.rank() > found.rank():
                found = stacked
                result.append(g)
        if found.rank() < len(odd):
            raise NotImplementedError(
                f"O(Lambda) for Lambda = H + H + L_0 over O_K: the spinor-norm classes of the primes {odd} are allowed by "
                f"the local bound but no integral reflection of L_1 with coefficients in {{-1, 0, 1}} realizes them; at a "
                f"dyadic prime the bound may be strict, and deciding it needs the dyadic spinor norms of Beli, J. Number "
                f"Theory 102 (2003) (#54)"
            )
    assert all(_integral(g) and g.transpose() * gram * g == gram for g in result)
    return tuple(result)
