r"""Pointwise and setwise stabilizers and transporters of equivariant markings (#61, items 5 and 7).

Let `L` be a nondegenerate integral lattice with Gram matrix `B`, let `F_i` be isometries of
`L`, and let `X : S \to L` be a primitive injective integral matrix with `F_i X = X E_i`.
Because `X` is primitive and `F_i` is invertible on `L`, each `E_i` lies in `GL(S)`. No
hypothesis on the `F_i` is made: they may be unipotent, of infinite order, and need not
commute. The group is `Stab = \{g \in C : g X = X\}`, for `C` the simultaneous centralizer in
`O(L)`. Centralizers and equivariant transporters of the `F_i` on nondegenerate lattices come
from :mod:`commutant_groups` (#54).

This module uses three complete routes for markings, and it raises ``NotImplementedError`` outside them.

Nondegenerate source. If `A = X^t B X` is nonsingular, `L \otimes Q` is `XS \oplus K` with
`K = (XS)^\perp`, and the `F_i` preserve `K`. An element of `Stab` is `1 \oplus h` with `h` in
the centralizer `C_K` of the `F_i|_K` in `O(K)`. Conversely, `1 \oplus h` preserves `L` exactly
when `h` fixes the finite group `P / K` pointwise, for `P` the projection of `L` to
`K \otimes Q`. So `Stab` has finite index in `C_K`, and Schreier's lemma on the finite orbit
of the generators of `P / K` gives its generators. A transporter to `Y` is `1 \oplus t h` with
`t : (K, F|_K) \to (K', F|_{K'})` one equivariant isometry onto `K' = (YS)^\perp` and
`h \in C_K`; integrality depends only on the point `h p_K` of the same finite orbit. The
setwise stabilizer is the subgroup of `C_{O(S)}(E) \times C_K` that preserves `L`, of finite
index, with Schreier generators.

Unipotent centralizer. If `A / rad A = Q` for the commutant on `L`, then `C = \pm \exp(\Lambda)`
for a lattice `\Lambda` in the abelian skew radical. For nilpotent `x`, `\exp(x) - 1` is `x`
times a unit commuting with it, so `\exp(x) X = X` exactly when `x X = 0`, and `-\exp(x)` has
no eigenvalue `1`. Hence `Stab = \exp(\Lambda \cap \mathrm{Ann}(X))`.

Radical parabolic. If `A` is singular, `R = X(\mathrm{rad} A)` is a primitive, totally isotropic,
`F`-stable sublattice, and every `g \in C` with `g X = X` or `g X S = X S` preserves `R`. When the
extension `0 \to R^\perp_Q \to L_Q \to L_Q / R^\perp \to 0` splits as `F`-modules, there is an
`F`-stable Witt frame `L_Q = R \oplus M' \oplus R'` with `R'` isotropic and dual to `R`
(:class:`_RadicalParabolic`). The stabilizer of `R` in `C(Q)` is then the Levi group
`C_{GL(R)}(F|_R) \times C_{O(M')}(F|_{M'})` times the unipotent group `U_R \cap C`, where `U_R` acts
trivially on `R` and `R^\perp / R`. The lattice `M = R^\perp_L / R` carries the nondegenerate
marking `\bar X` of `S / \mathrm{rad}`. An element fixing `X` has Levi part `(1, h)`, `h` in the
stabilizer of `\bar X` in `C_{O(M)}(\bar F)`, computed by the nondegenerate route, and its unipotent
part fixes `X`. The integral Levi image has finite index in the Levi group, so Schreier's
lemma on the liftability of the Levi generators gives it, and the unipotent kernel is generated by
the provider's Mal'cev frame (:class:`_ParabolicKernel`). A transporter matches the radicals and the
quotient markings by one equivariant isometry `M_X \to M_Y` and a quotient transporter, corrects the
`R`-components by one rational unipotent element, and decides the integral point of the remaining
unipotent coset over each left coset of the integral Levi image.

Finite orbit. If the image of `C` on the `Q`-span of the orbit of `X` is finite, then the orbit
is finite and Schreier's lemma applies. The finiteness is decided by GAP. This route serves the
degenerate sources whose radical extension does not split.

Lines. Otherwise, for such sources, the stabilizer `G` in `C` of the lines `Q x_j` and `Q(x_1 + x_j)` acts on
`X S` by `\pm 1`, and the pointwise stabilizer is the kernel of that character (:meth:`EquivariantMarking._line_stabilizer`).
The transporter of an infinite orbit with a non-split radical extension raises ``NotImplementedError``.

:class:`CentralizerTupleOrbit` reduces a tuple of vectors to the marking of the saturated
`Q\langle F \rangle`-span of the tuple: `g` commutes with every word in the `F_i`, so it fixes
the tuple exactly when it fixes that span pointwise.
"""

