def _schreier(generators, base, action, one):
    r"""Return a transversal of the finite orbit of ``base`` and Schreier generators of its stabilizer.

    Reference: Schreier's lemma, as in Holt-Eick-O'Brien, *Handbook of Computational Group
    Theory*, Theorem 4.13. ``action`` returns the canonical form of a point.
    """
    start = action(one, base)
    transversal = {start.str(): (one, start)}
    frontier = [start.str()]
    stabilizer = {}
    while frontier:
        element, point = transversal[frontier.pop()]
        for generator in generators:
            image = action(generator, point)
            label = image.str()
            product = generator * element
            if label not in transversal:
                transversal[label] = (product, image)
                frontier.append(label)
                continue
            schreier = transversal[label][0].inverse().change_ring(ZZ) * product
            if schreier != one:
                stabilizer[schreier.str()] = schreier
    return transversal, tuple(stabilizer.values())


def _is_finite(generators):
    r"""Decide finiteness of the group generated by integer matrices."""
    return not generators or MatrixGroup([matrix(ZZ, g) for g in generators]).is_finite()


def _logarithm(element):
    r"""Return the logarithm of a unipotent matrix."""
    nilpotent = element.change_ring(QQ) - 1
    power = nilpotent
    total = 0 * nilpotent
    degree = 1
    while not power.is_zero():
        total += (-1) ** (degree + 1) * power / degree
        power *= nilpotent
        degree += 1
    return total


def _glue_action(element, point):
    r"""Act on the columns of ``point``, reduced modulo the integers."""
    return (element.change_ring(QQ) * point).apply_map(lambda entry: entry - entry.floor())


def _diagonal(blocks):
    r"""Return the block-diagonal rational matrix of ``blocks``; a block may be empty."""
    size = sum(b.nrows() for b in blocks)
    result = matrix(QQ, size, size)
    offset = 0
    for block in blocks:
        n = block.nrows()
        if n:
            result.set_block(offset, offset, block.change_ring(QQ))
        offset += n
    return result


def _general_linear_generators(size):
    r"""Return the elementary transvections and one sign, which generate `GL_k(\mathbb Z)`."""
    result = []
    for i in range(size):
        for j in range(size):
            if i != j:
                move = identity_matrix(QQ, size)
                move[i, j] = 1
                result.append(move)
    sign = identity_matrix(QQ, size)
    sign[0, 0] = -1
    result.append(sign)
    return result


def _commutative_unit_generators(order_basis, size):
    r"""Return generators of `O^\times` for an order `O` (Z-basis ``order_basis``) of a commutative semisimple `A \subseteq M_k(Q)`.

    A primitive element `\theta \in O` gives `A = Q[x]/(f) = \prod_i K_i` with `f = \prod_i f_i` squarefree. The unit group
    of the maximal order `\prod_i O_{K_i}` is generated by the Dirichlet units and roots of unity of each factor
    (Dirichlet's unit theorem; Neukirch, *Algebraic Number Theory*, I.7.4), embedded by the Chinese remainder theorem.
    `O^\times = O \cap \prod_i O_{K_i}^\times` (the inverse of a unit is a polynomial in it with integral coefficients,
    by Cayley-Hamilton), and it has finite index, so it is the Schreier preimage of the integral matrices.
    """
    dimension = len(order_basis)
    theta = None
    for coefficients in product(range(-2, 3), repeat=dimension):
        candidate = sum((c * m.change_ring(QQ) for c, m in zip(coefficients, order_basis)), matrix(QQ, size, size))
        polynomial = candidate.minimal_polynomial()
        if polynomial.degree() == dimension and polynomial.is_squarefree():
            theta = candidate
            break
    assert theta is not None, f"no primitive element of the commutative order {order_basis} in the height box"
    factors = [f for f, _e in polynomial.factor()]
    ring = polynomial.parent()
    one = identity_matrix(QQ, size)
    generators = [-one]
    for i, factor in enumerate(factors):
        if factor.degree() == 1:
            units = [-1]
        else:
            field = NumberField(factor, "a")
            units = [field(u) for u in field.unit_group().gens_values()]
        for unit in units:
            residue = ring(unit.polynomial().list()) if factor.degree() > 1 else ring(unit)
            residues = [residue if j == i else ring(1) for j in range(len(factors))]
            lifted = CRT_list(residues, factors)
            generators.append(lifted(theta))
    assert all(g.det() != 0 and all(g * m == m * g for m in order_basis) for g in generators)
    found, _index = finite_preimage_generators([*generators, one], lambda g: g, lambda g: g.denominator() == 1)
    return tuple(matrix(ZZ, g) for g in found) or (identity_matrix(ZZ, size),)


def _endomorphism_unit_generators(actions, size):
    r"""Return generators of `C_{GL_k(Z)}(E_1, \dots, E_s)`, the unit group of `O = \{a \in M_k(Z) : a E_i = E_i a\}`.

    The order has no involution constraint. For `A = M_k(Q)` it is `GL_k(Z)`, generated by elementary transvections and one
    sign (Hua-Reiner). For commutative semisimple `A` it is :func:`_commutative_unit_generators`. Every other `A` is reduced
    to a centralizer of isometries (:func:`_hyperbolic_unit_generators`).
    """
    if size == 0:
        return ()
    rows = []
    for E in actions:
        E = matrix(ZZ, E)
        for i in range(size):
            for j in range(size):
                row = [0] * size**2
                for k in range(size):
                    row[k * size + j] -= E[i, k]
                    row[i * size + k] += E[k, j]
                rows.append(row)
    equations = matrix(ZZ, rows) if rows else matrix(ZZ, 0, size**2)
    order_basis = tuple(matrix(ZZ, size, size, list(v)) for v in equations.right_kernel().basis())
    if len(order_basis) == size**2:
        return tuple(matrix(ZZ, g) for g in _general_linear_generators(size))
    commutative = all(x * y == y * x for x in order_basis for y in order_basis)
    form = matrix(QQ, [[(x * y).trace() for y in order_basis] for x in order_basis])
    if commutative and form.det() != 0:
        return _commutative_unit_generators(order_basis, size)
    return _hyperbolic_unit_generators(actions, size)


def _hyperbolic_unit_generators(actions, size):
    r"""Return generators of `C_{GL_k(Z)}(E_1, \dots, E_s)` as the centralizer of isometries of a hyperbolic lattice.

    On `H = Z^k \oplus Z^k` with Gram matrix `\begin{pmatrix} 0 & 1 \\ 1 & 0 \end{pmatrix}`, the isometries preserving
    both Lagrangians `V_1 = Z^k \oplus 0` and `V_2 = 0 \oplus Z^k` are exactly `a \oplus a^{-t}` with `a \in GL_k(Z)`,
    and `a \oplus a^{-t}` commutes with `E_i \oplus E_i^{-t}` exactly when `a E_i = E_i a`. So the group is the
    centralizer in `O(H)` of the `E_i \oplus E_i^{-t}` and of the stabilizers of `V_1, V_2`, the unit group of the
    adjoint-stable order `\{a \oplus b^t\}` of :class:`_SubspaceCommutant`, on which the adjoint is the exchange
    involution of `End(E) \times End(E)^{op}` (Knus-Merkurjev-Rost-Tignol, *The Book of Involutions*, Prop. 2.14;
    its unitary group is `GL_1(End(E))`). The centralizer routes of :mod:`commutant_groups` decide it, including a
    radical (Levi quotient and unipotent kernel), and raise for a factor outside their proved domain.
    """
    one, zero = identity_matrix(ZZ, size), matrix(ZZ, size, size)
    gram = block_matrix(ZZ, [[zero, one], [one, zero]], subdivide=False)
    doubled = [_diagonal([matrix(ZZ, E), matrix(ZZ, E).inverse().transpose()]).change_ring(ZZ) for E in actions]
    first = block_matrix(QQ, [[one], [zero]], subdivide=False)
    second = block_matrix(QQ, [[zero], [one]], subdivide=False)
    commutant = _SubspaceCommutant(gram, doubled, [first, second])
    result = []
    for g in _commutant_groups().centralizer_generators(commutant):
        g = matrix(ZZ, g)
        assert g.submatrix(0, size, size, size).is_zero() and g.submatrix(size, 0, size, size).is_zero()
        a = g.submatrix(0, 0, size, size)
        assert a.det() in (1, -1) and all(a * matrix(ZZ, E) == matrix(ZZ, E) * a for E in actions)
        result.append(a)
    return tuple(result) or (one,)


class _SubspaceCommutant(IsometryCommutant):
    r"""The commutant of the `F_i` cut down to the elements that preserve each subspace `V_j` and its orthogonal `V_j^\perp`.

    For a subspace `V` (columns `X`) with orthogonal `V^\perp` (columns `Y`), `a V \subseteq V` and
    `a V^\perp \subseteq V^\perp` are the linear conditions `Y^t B a X = 0` and `X^t B a Y = 0`. `V` may be
    degenerate. The algebra `P = \{a \in A : a V \subseteq V,\ a V^\perp \subseteq V^\perp\}` is stable under the
    adjoint, because `b(a^\dagger x, v) = b(x, a v)` gives `a V \subseteq V \Rightarrow a^\dagger V^\perp \subseteq V^\perp`
    and `a V^\perp \subseteq V^\perp \Rightarrow a^\dagger V \subseteq V` (`V^{\perp\perp} = V`). An isometry preserves `V`
    exactly when it preserves `V^\perp`, so the unit group of the order `P \cap M_n(Z)` is
    `C(F) \cap \bigcap_j \mathrm{Stab}(V_j)`. For nondegenerate `V` the conditions say that `a` commutes with the
    orthogonal projection onto `V`. The centralizer routes of :mod:`commutant_groups` then apply, a radical of
    `P` included (the parabolic `P` of a degenerate `V` has one).
    """

    def __init__(self, gram, isometries, subspaces):
        self.subspaces = tuple(matrix(QQ, X) for X in subspaces)
        super().__init__(gram, isometries)

    def _pairs(self):
        B = self.gram.change_ring(QQ)
        for X in self.subspaces:
            Y = (X.transpose() * B).right_kernel_matrix().transpose()
            yield X, Y

    def _defects(self, element):
        B = self.gram.change_ring(QQ)
        element = matrix(QQ, element)
        return [c for X, Y in self._pairs() for block in (Y.transpose() * B * element * X, X.transpose() * B * element * Y) for c in block.list()]

    def _integral_basis(self):
        base = super()._integral_basis()
        rows = matrix(QQ, [self._defects(m) for m in base])
        if rows.ncols() == 0:
            return base
        kernel = matrix(ZZ, rows.denominator() * rows).left_kernel().basis()
        return tuple(sum((c * m for c, m in zip(v, base)), matrix(ZZ, self.rank, self.rank)) for v in kernel)

    def contains(self, element):
        return super().contains(element) and all(c == 0 for c in self._defects(element))


def _liftable_subgroup(generators, lifts):
    r"""Return generators of `\{h \in \langle generators \rangle : h` lifts`\}`, a subgroup of finite index.

    Schreier's lemma on the right cosets, decided by ``lifts`` (Holt-Eick-O'Brien, Thm. 4.13).
    """
    generators = tuple(generators)
    if all(lifts(h) is not None for h in generators):
        return generators
    image, _index = finite_preimage_generators(generators, lambda element: element, lambda element: lifts(element) is not None)
    return image


def _left_cosets(generators, lifts, one):
    r"""Return representatives of the left cosets `x \Gamma` in `\langle generators \rangle`, for `\Gamma` the liftable subgroup."""
    representatives = [one]
    position = 0
    while position < len(representatives):
        current = representatives[position]
        position += 1
        for generator in generators:
            moved = generator * current
            if not any(lifts(known.inverse() * moved) is not None for known in representatives):
                representatives.append(moved)
    return representatives


class _ParabolicKernel(IsometryCommutant):
    r"""The commutant of the `F_i`, with the nilpotent ideal of the parabolic of `R` in place of the radical.

    For an `F`-stable isotropic `R` and columns `Z \subseteq R^\perp`, the space
    `\mathfrak a = \{x \in A : x R = 0,\ x R^\perp \subseteq R,\ x L \subseteq R^\perp,\ x Z = 0\}` is closed under
    products, with `\mathfrak a^3 = 0`. Its skew elements are the Lie algebra of `U_R \cap C \cap \mathrm{Stab}(Z)`:
    `\exp(x) Z = Z + x Z` since `x^2 Z \subseteq x R = 0`. The provider's Mal'cev frame reads only
    :meth:`radical_basis`, its powers and the adjoint, so :meth:`unipotent_kernel_generators` generates that
    integral group and :meth:`_integral_point` decides an integral point of a rational coset of it
    (Segal, *Polycyclic Groups*, Ch. 6, Thm. 2).
    """

    def __init__(self, gram, isometries, radical, perp, fixed):
        super().__init__(gram, isometries)
        B = self.gram.change_ring(QQ)
        radical, perp, fixed = radical.change_ring(QQ), perp.change_ring(QQ), fixed.change_ring(QQ)
        rows = []
        for m in self.order_basis:
            x = m.change_ring(QQ)
            blocks = (x * radical, perp.transpose() * B * x * perp, radical.transpose() * B * x, x * fixed)
            rows.append([c for block in blocks for c in block.list()])
        kernel = matrix(QQ, rows).left_kernel().basis()
        self._nilpotent = tuple(sum(c * m.change_ring(QQ) for c, m in zip(v, self.order_basis)) for v in kernel)

    def radical_basis(self):
        return self._nilpotent

    def skew_basis(self):
        r"""Return a `Q`-basis of the skew elements of `\mathfrak a`."""
        if not self._nilpotent:
            return ()
        equations = matrix(QQ, [(x + self.adjoint(x)).list() for x in self._nilpotent])
        return tuple(sum(c * x for c, x in zip(v, self._nilpotent)) for v in equations.left_kernel().basis())


class _RadicalParabolic:
    r"""An `F`-stable rational Witt frame `[R \mid M \mid R']` for a primitive `F`-stable isotropic `R \subseteq L`.

    `R^\perp_L` is projected to `M' = (R + R')^\perp` along `R`; the image `M` is a lattice isometric to
    `R^\perp_L / R`, with integral Gram matrix and integral actions `\bar F_i`. The basis of `R'` is dual to
    the basis of `R`, so `(a, h) \mapsto a \oplus h \oplus a^{-t}` is an isometry of the frames.
    """

    def __init__(self, gram, actions, radical, dual, levi):
        self.gram, self.actions = gram, actions
        self.radical, self.dual, self.levi = radical, dual, levi
        self.radical_rank, self.levi_rank = radical.ncols(), levi.ncols()
        self.frame = radical.augment(levi).augment(dual)
        self.levi_gram = matrix(ZZ, levi.transpose() * gram * levi)
        self.levi_actions = tuple(matrix(ZZ, levi.solve_right(F * levi)) for F in actions)
        self.perp = matrix(ZZ, radical.transpose() * gram).right_kernel().basis_matrix().transpose()

    @staticmethod
    def of(gram, actions, radical):
        r"""Return the frame, or ``None`` when `L_Q \to L_Q / R^\perp` has no `F`-equivariant section.

        A section is `C = C_0 + R^\perp T` with `F C = C D_F`, a linear (Sylvester) system in `T`.
        The isotropic correction `C - \tfrac12 R (P^t)^{-1} C^t B C`, `P = R^t B C`, is `F`-stable,
        because the map it subtracts is `F`-equivariant.
        """
        B = gram.change_ring(QQ)
        R = radical.change_ring(QQ)
        k = R.ncols()
        perp = matrix(ZZ, radical.transpose() * gram).right_kernel().basis_matrix().transpose().change_ring(QQ)
        start = B.inverse() * R
        pairing = R.transpose() * B * start
        width = perp.ncols()
        unknowns = [(a, b) for a in range(width) for b in range(k)]
        columns, targets = [], []
        for F in actions:
            F = F.change_ring(QQ)
            D = pairing.inverse() * R.transpose() * B * F * start
            G = perp.solve_right(F * perp)
            targets.extend(perp.solve_right(F * start - start * D).list())
            columns.append([(matrix(QQ, width, k, {(a, b): 1}) * D - G * matrix(QQ, width, k, {(a, b): 1})).list() for a, b in unknowns])
        if columns:
            system = matrix(QQ, columns[0]).transpose()
            for c in columns[1:]:
                system = system.stack(matrix(QQ, c).transpose())
            target = vector(QQ, targets)
            if target not in system.column_space():
                return None
            solution = system.solve_right(target)
            section = start + perp * matrix(QQ, width, k, list(solution))
        else:
            section = start
        square = R.transpose() * B * section
        section = section - R * square.transpose().inverse() * (section.transpose() * B * section) / 2
        assert all(section.augment(F * section).rank() == k for F in actions), "the isotropic section is not F-stable"
        dual = section * (R.transpose() * B * section).inverse()
        projected = perp - R * (dual.transpose() * B * perp)
        scale = projected.denominator()
        levi = matrix(ZZ, scale * projected).transpose().hermite_form(include_zero_rows=False).transpose() / scale
        assert levi.ncols() == gram.nrows() - 2 * k
        return _RadicalParabolic(B, tuple(F.change_ring(QQ) for F in actions), R, dual, levi)

    def levi_coordinates(self, columns):
        r"""Return the coordinates in `M` of the projection of columns of `R^\perp_L`."""
        columns = columns.change_ring(QQ)
        projected = columns - self.radical * (self.dual.transpose() * self.gram * columns)
        return matrix(ZZ, self.levi.solve_right(projected))

    def levi_commutant(self):
        return IsometryCommutant(self.levi_gram, self.levi_actions)

    def lift(self, a, h, onto):
        r"""Return `a \oplus h \oplus a^{-t}` from this frame to the frame ``onto``."""
        return onto.frame * _diagonal([a, h, a.transpose().inverse()]) * self.frame.inverse()

    def kernel(self, fixed):
        return _ParabolicKernel(self.gram.change_ring(ZZ), [F.change_ring(ZZ) for F in self.actions], self.radical, self.perp, fixed)


class EquivariantMarking:
    r"""A primitive injective `X : S \to L` with `F_i X = X E_i`, on column vectors."""

    def __init__(self, gram, marking, ambient_actions, source_actions):
        self.gram = matrix(ZZ, gram)
        self.marking = matrix(ZZ, marking)
        self.ambient_actions = tuple(matrix(ZZ, F) for F in ambient_actions)
        self.source_actions = tuple(matrix(ZZ, E) for E in source_actions)
        self.rank = self.gram.nrows()
        self.source_rank = self.marking.ncols()
        assert len(self.ambient_actions) == len(self.source_actions)
        assert self.marking.rank() == self.source_rank, f"{self.marking} is not injective"
        assert all(d in (0, 1) for d in self.marking.elementary_divisors()), f"{self.marking} is not primitive"
        assert all(
            F * self.marking == self.marking * E
            for F, E in zip(self.ambient_actions, self.source_actions, strict=True)
        ), "the marking is not equivariant for the given actions"
        self._commutant = IsometryCommutant(self.gram, self.ambient_actions)
        self._one = identity_matrix(ZZ, self.rank)
        self.source_gram = self.marking.transpose() * self.gram * self.marking

    def _is_stabilizer_element(self, element, target):
        return self._commutant.is_centralizer_element(element) and element * self.marking == target

    def _orthogonal(self, marking):
        r"""Return a basis of `K = (X S)^\perp`, its Gram matrix and the restrictions of the `F_i` to it."""
        basis = (marking.transpose() * self.gram).right_kernel().basis_matrix().transpose()
        gram_k = basis.transpose() * self.gram * basis
        restricted = tuple(matrix(ZZ, basis.change_ring(QQ).solve_right(F * basis)) for F in self.ambient_actions)
        return basis, gram_k, restricted

    def _complement(self):
        r"""Return the matrices of the nondegenerate-source decomposition.

        These are a basis of `K`, the `C_K` generators, the projections of the standard basis
        of `L` to `S` and to `K`, and the frame `[X \mid K]`.
        """
        basis, gram_k, restricted = self._orthogonal(self.marking)
        if basis.ncols() == 0:
            return basis, (), None, None, self.marking.change_ring(QQ)
        generators = _commutant_groups().centralizer_generators(IsometryCommutant(gram_k, restricted))
        frame = block_matrix(QQ, [[self.marking, basis]], subdivide=False)
        coordinates = frame.inverse()
        return basis, generators, coordinates[: self.source_rank], coordinates[self.source_rank :], frame

    def _lift(self, frame, source_part, complement_part):
        block = block_matrix(QQ, [[source_part, 0], [0, complement_part]], subdivide=False)
        element = frame * block * frame.inverse()
        assert element.denominator() == 1, f"{element} is not integral"
        return matrix(ZZ, element)

    def _nondegenerate_stabilizer(self):
        basis, generators, _to_source, to_complement, frame = self._complement()
        if basis.ncols() == 0:
            return ()
        identity_k = identity_matrix(ZZ, basis.ncols())
        _transversal, stabilizer = _schreier(generators, to_complement, _glue_action, identity_k)
        one_s = identity_matrix(QQ, self.source_rank)
        return tuple(self._lift(frame, one_s, h.change_ring(QQ)) for h in stabilizer)

    def _is_unipotent_type(self):
        radical = self._commutant.radical_basis()
        return bool(radical) and self._commutant.dimension() - len(radical) == 1

    def _span_restriction(self, generators):
        r"""Return the restriction of ``generators`` to the saturated span of the orbit of `X`."""
        rows = self.marking.transpose().change_ring(QQ).echelon_form()
        while True:
            enlarged = rows.stack(matrix(QQ, [(g * v).list() for g in generators for v in rows.rows()]))
            enlarged = enlarged.echelon_form()
            enlarged = enlarged[: enlarged.rank()]
            if enlarged.nrows() == rows.nrows():
                break
            rows = enlarged
        scale = rows.denominator()
        lattice = matrix(ZZ, scale * rows).saturation().transpose()
        return [matrix(ZZ, lattice.change_ring(QQ).solve_right(g * lattice)) for g in generators]

    def _finite_orbit(self):
        r"""Return the transversal and stabilizer of `X` under `C`, or ``None`` when the orbit is infinite."""
        generators = _commutant_groups().centralizer_generators(self._commutant)
        if not _is_finite(self._span_restriction(generators)):
            return None
        return _schreier(generators, self.marking, lambda g, p: g * p, self._one)

    def _subspace_stabilizer(self, subspaces):
        r"""Return generators of `C(F) \cap \bigcap_j \mathrm{Stab}(V_j)` for the rational column spaces `V_j`."""
        commutant = _SubspaceCommutant(self.gram, self.ambient_actions, subspaces)
        result = tuple(matrix(ZZ, g) for g in _commutant_groups().centralizer_generators(commutant))
        assert all(commutant.contains(g) for g in result)
        return result

    def _line_stabilizer(self):
        r"""Return generators of the pointwise stabilizer of `X` through the stabilizer of the lines of its columns.

        Let `G = C(F) \cap \bigcap \mathrm{Stab}(\ell)` over the lines `\ell = Q x_j` and `Q (x_1 + x_j)`. An element
        of `G` maps `x_j \mapsto \lambda_j x_j` and `x_1 + x_j \mapsto \mu (x_1 + x_j)`, so `\lambda_j = \lambda_1` for all `j`:
        `G` acts on `X S_Q` by a scalar, which is `\pm 1` because `X` is primitive and `g` is integral and invertible.
        Every `g` with `g X = X` lies in `G`, so the pointwise stabilizer is the kernel of the character
        `G \to \{\pm 1\}`, of index at most two, with Schreier generators (Holt-Eick-O'Brien, Thm. 4.13). This
        route needs no splitting of the radical extension and no finiteness of the orbit.
        """
        columns = [self.marking.matrix_from_columns([j]) for j in range(self.source_rank)]
        lines = [*columns, *(columns[0] + c for c in columns[1:])]
        generators = self._subspace_stabilizer(lines)
        found, _index = finite_preimage_generators(
            [*generators, self._one], lambda g: g, lambda g: matrix(ZZ, g) * self.marking == self.marking
        )
        return tuple(matrix(ZZ, g) for g in found)

    def _source_frame(self):
        r"""Return a unimodular `T` whose first `k` columns are a basis of `\mathrm{rad} A`, and `k`."""
        kernel = self.source_gram.right_kernel_matrix()
        _diagonal_form, _left, right = kernel.smith_form()
        return right.inverse().transpose(), kernel.nrows()

    def _parabolic(self, marking):
        r"""Return the radical frame of ``marking`` and its columns on the complement of `\mathrm{rad} A`.

        The frame is ``None`` when `X(\mathrm{rad} A)` is not primitive (then ``marking`` is not an image
        of `X`) or when its radical extension does not split.
        """
        frame, k = self._source_frame()
        radical = marking * frame.matrix_from_columns(range(k))
        rest = marking * frame.matrix_from_columns(range(k, self.source_rank))
        if any(d != 1 for d in radical.elementary_divisors()):
            return None, rest
        return _RadicalParabolic.of(self.gram, self.ambient_actions, radical), rest

    def _source_blocks(self):
        r"""Return the actions of the `E_i` on `\mathrm{rad} A` and on `S / \mathrm{rad} A`."""
        frame, k = self._source_frame()
        adapted = [frame.inverse() * E * frame for E in self.source_actions]
        assert all(m.submatrix(k, 0, self.source_rank - k, k).is_zero() for m in adapted)
        on_radical = tuple(matrix(ZZ, m.submatrix(0, 0, k, k)) for m in adapted)
        on_quotient = tuple(matrix(ZZ, m.submatrix(k, k)) for m in adapted)
        return on_radical, on_quotient

    def _quotient_marking(self, parabolic, quotient):
        return EquivariantMarking(parabolic.levi_gram, quotient, parabolic.levi_actions, self._source_blocks()[1])

    def _quotient_stabilizer(self, parabolic, quotient):
        r"""Return generators of the stabilizer of `\bar X` in `C_{O(M)}(\bar F)`."""
        if parabolic.levi_rank == 0:
            return ()
        if quotient.ncols() == 0:
            return _commutant_groups().centralizer_generators(parabolic.levi_commutant())
        return self._quotient_marking(parabolic, quotient).pointwise_stabilizer_generators()

    def _parabolic_stabilizer(self, parabolic, rest):
        r"""Return the unipotent kernel and integral lifts of the liftable Levi stabilizer of `\bar X`."""
        kernel = parabolic.kernel(self.marking)
        one = identity_matrix(QQ, parabolic.radical_rank)
        lifts = lambda h: kernel._integral_point(parabolic.lift(one, h.change_ring(QQ), parabolic), 1)
        levi = _liftable_subgroup(self._quotient_stabilizer(parabolic, parabolic.levi_coordinates(rest)), lifts)
        return (*kernel.unipotent_kernel_generators(), *(lifts(h) for h in levi))

    def _parabolic_transporter(self, parabolic, rest, target):
        r"""Return `g \in C` with `g X = Y` through the radical frames of `X` and `Y`, or ``None``.

        `g` maps `R_X \to R_Y` by `X|_{rad} \mapsto Y|_{rad}` and induces an equivariant isometry
        `\bar g : M_X \to M_Y` with `\bar g \bar X = \bar Y`; these are `t_0 s \Gamma`-cosets for one
        transporter `t_0` of the quotient lattices and one quotient-marking transporter `s`. The frame
        lift of `\bar g` differs from `Y` by columns of `R_Y`, removed by `\exp(x_0)` for a skew `x_0`
        of the target ideal, a linear equation independent of the coset; the remaining solutions are
        the coset `\exp(x_0) \hat g\, U_X(Q)`.
        """
        target_parabolic, target_rest = self._parabolic(target)
        if target_parabolic is None:
            return None
        k = parabolic.radical_rank
        one = identity_matrix(QQ, k)
        kernel = parabolic.kernel(self.marking)
        lifts = lambda h: kernel._integral_point(parabolic.lift(one, h.change_ring(QQ), parabolic), 1)
        if parabolic.levi_rank == 0:
            moves = [matrix(QQ, 0, 0)]
        else:
            if (parabolic.levi_gram, parabolic.levi_actions) == (target_parabolic.levi_gram, target_parabolic.levi_actions):
                start = identity_matrix(ZZ, parabolic.levi_rank)
            else:
                start = _commutant_groups().equivariant_transporter(
                    parabolic.levi_commutant(), target_parabolic.levi_gram, target_parabolic.levi_actions
                )
            if start is None:
                return None
            start = start.change_ring(QQ)
            quotient = parabolic.levi_coordinates(rest)
            middle = identity_matrix(QQ, parabolic.levi_rank)
            if quotient.ncols():
                moved = start.inverse() * target_parabolic.levi_coordinates(target_rest).change_ring(QQ)
                found = self._quotient_marking(parabolic, quotient).transporter(matrix(ZZ, moved))
                if found is None:
                    return None
                middle = found.change_ring(QQ)
            stabilizer = [h.change_ring(QQ) for h in self._quotient_stabilizer(parabolic, quotient)]
            moves = [start * middle * c for c in _left_cosets(stabilizer, lifts, identity_matrix(QQ, parabolic.levi_rank))]
        correction = target_parabolic.kernel(matrix(ZZ, self.rank, 0))
        directions = correction.skew_basis()
        for move in moves:
            rational = parabolic.lift(one, move, target_parabolic)
            image = rational * self.marking
            defect = target.change_ring(QQ) - image
            if not defect.is_zero():
                if not directions:
                    return None
                system = matrix(QQ, [(x * image).list() for x in directions]).transpose()
                values = vector(QQ, defect.list())
                if values not in system.column_space():
                    return None
                coefficients = system.solve_right(values)
                rational = correction._exp(sum(c * x for c, x in zip(coefficients, directions))) * rational
            assert rational * self.marking == target
            found = kernel._integral_point(rational, 1)
            if found is not None:
                return found
        return None

    def _parabolic_setwise(self, parabolic, rest):
        r"""Return generators of the setwise stabilizer of `X S` for a singular `A`.

        With `W = X S_Q = R \oplus (W \cap M')`, the stabilizer of `W` in the stabilizer of `R` is
        `(C_{GL(R)}(F|_R) \times \mathrm{Stab}_{C_{O(M)}(\bar F)}(\bar X \bar S)) \ltimes (U_R \cap C)`, since
        `x W \subseteq R` for `x` in the unipotent ideal. Its integral group is generated by the unipotent
        kernel and integral lifts of the liftable Levi subgroup (Schreier). In the basis `X|_{rad}` of `R`,
        `F X|_{rad} = X|_{rad} E_R`, so `C_{GL(R)}(F|_R)` is the unit group of the commutant of the `E_R`
        (:func:`_endomorphism_unit_generators`).
        """
        k = parabolic.radical_rank
        on_radical, _on_quotient = self._source_blocks()
        radical_units = _endomorphism_unit_generators(on_radical, k)
        quotient = parabolic.levi_coordinates(rest)
        m = parabolic.levi_rank
        if m == 0:
            levi = ()
        elif quotient.ncols() == 0:
            levi = _commutant_groups().centralizer_generators(parabolic.levi_commutant())
        else:
            levi = self._quotient_marking(parabolic, quotient).setwise_stabilizer_generators()
        one_k, one_m = identity_matrix(QQ, k), identity_matrix(QQ, m)
        pairs = [_diagonal([a.change_ring(QQ), one_m]) for a in radical_units]
        pairs.extend(_diagonal([one_k, h.change_ring(QQ)]) for h in levi)
        kernel = parabolic.kernel(matrix(ZZ, self.rank, 0))
        lifts = lambda p: kernel._integral_point(
            parabolic.lift(p.submatrix(0, 0, k, k), p.submatrix(k, k), parabolic), 1
        )
        return (*kernel.unipotent_kernel_generators(), *(lifts(p) for p in _liftable_subgroup(pairs, lifts)))

    def pointwise_stabilizer_generators(self):
        r"""Return integer matrices generating `\{g \in C(F_1, \dots, F_s) : g X = X\}`.

        Domain: `A = X^t B X` nonsingular with `C_K` in the implemented commutant types; or
        `A / rad A = Q` with abelian skew radical; or singular `A` whose radical extension splits,
        with `C_M` in the implemented commutant types; otherwise the finite-orbit or line route.
        An unimplemented commutant type raises from the commutant.
        """
        if self.source_gram.det() != 0:
            result = self._nondegenerate_stabilizer()
        elif self._is_unipotent_type():
            result = self._unipotent_stabilizer()
        else:
            parabolic, rest = self._parabolic(self.marking)
            if parabolic is not None:
                result = self._parabolic_stabilizer(parabolic, rest)
            else:
                orbit = self._finite_orbit()
                result = self._line_stabilizer() if orbit is None else orbit[1]
        assert all(self._is_stabilizer_element(g, self.marking) for g in result)
        return result

    def _unipotent_stabilizer(self):
        generators = self._commutant.unipotent_kernel_generators()
        logarithms = [_logarithm(g) for g in generators]
        images = matrix(QQ, [(x * self.marking).list() for x in logarithms])
        if images.nrows() == 0:
            return ()
        exponents = matrix(ZZ, images.denominator() * images).left_kernel().basis()
        return tuple(self._power_product(generators, row) for row in exponents)

    def _power_product(self, generators, exponents):
        result = self._one
        for generator, exponent in zip(generators, exponents, strict=True):
            result = result * generator ** int(exponent)
        return result

    def _nondegenerate_transporter(self, target):
        r"""Return `g \in C` with `g X = Y`, or ``None`` as a proof of absence, for nonsingular `X^t B X`.

        `g = 1 \oplus k` on the frames `[X \mid K] \to [Y \mid K']`, with `k = t h` for one equivariant
        isometry `t : K \to K'` (:func:`commutant_groups.equivariant_transporter`) and `h \in C_K`.
        `g` is integral exactly when `Y p_S + K' t h p_K` is, which depends only on `h p_K` modulo
        `K`, a point of the finite orbit of `p_K` under `C_K`.
        """
        basis, generators, to_source, to_complement, frame = self._complement()
        if basis.ncols() == 0:
            candidate = target.change_ring(QQ) * frame.inverse()
            return matrix(ZZ, candidate) if candidate.denominator() == 1 else None
        target_basis, target_gram, target_actions = self._orthogonal(target)
        _basis, gram_k, restricted = self._orthogonal(self.marking)
        start = _commutant_groups().equivariant_transporter(IsometryCommutant(gram_k, restricted), target_gram, target_actions)
        if start is None:
            return None
        start = start.change_ring(QQ)
        transversal, _stabilizer = _schreier(generators, to_complement, _glue_action, identity_matrix(ZZ, basis.ncols()))
        for element, _point in transversal.values():
            candidate = target * to_source + target_basis * start * element.change_ring(QQ) * to_complement
            if candidate.denominator() == 1:
                return matrix(ZZ, candidate)
        return None

    def setwise_stabilizer_generators(self):
        r"""Return generators of `\{g \in C(F_1, \dots, F_s) : g X S = X S\}`.

        A singular `X^t B X` uses the radical parabolic (:meth:`_parabolic_setwise`). When its radical extension
        does not split, `X` is primitive, so `g X S = X S` exactly when `g` preserves `X S_Q`, and the group is the
        centralizer of :class:`_SubspaceCommutant` on `X S_Q`.

        Such `g` is `a \oplus h` on `[X \mid K]`, with `a \in O(A)` commuting with the `E_i` (from
        `F_i g X = g X E_i`) and `h \in C_K`. Conversely `a \oplus h` lies in `O(L)` exactly when it is
        integral, a condition on the finite group `L / (XS + K)`, so the stabilizer has finite
        index in `C_{O(A)}(E) \times C_K` and Schreier's lemma gives generators.
        """
        if self.source_gram.det() == 0:
            parabolic, rest = self._parabolic(self.marking)
            if parabolic is None:
                result = self._subspace_stabilizer([self.marking])
            else:
                result = self._parabolic_setwise(parabolic, rest)
            module = self.marking.column_module()
            assert all(
                self._commutant.is_centralizer_element(g) and (g * self.marking).column_module() == module for g in result
            )
            return result
        commutants = _commutant_groups()
        source = tuple(
            matrix(QQ, a) for a in commutants.centralizer_generators(IsometryCommutant(self.source_gram, self.source_actions))
        )
        basis, generators, _to_source, _to_complement, frame = self._complement()
        size = basis.ncols()
        one_s, one_k = identity_matrix(QQ, self.source_rank), identity_matrix(QQ, size)
        diagonal = lambda a, h: a if size == 0 else block_matrix(QQ, [[a, 0], [0, h]], subdivide=False)
        blocks = [diagonal(a, one_k) for a in source]
        blocks.extend(diagonal(one_s, h.change_ring(QQ)) for h in generators)
        blocks.append(identity_matrix(QQ, self.rank))
        inverse = frame.inverse()
        integral = lambda m: (frame * m * inverse).denominator() == 1
        schreier, _index = finite_preimage_generators(blocks, lambda m: m, integral)
        result = tuple(matrix(ZZ, frame * m * inverse) for m in schreier)
        module = self.marking.column_module()
        assert all(
            self._commutant.is_centralizer_element(g) and (g * self.marking).column_module() == module for g in result
        )
        return result

    def _unipotent_transporter(self, target):
        r"""Return `\pm \exp(x)`, `x \in \Lambda`, with value ``target`` on `X`, or ``None`` as a proof of absence.

        `\Lambda = \bigoplus Z x_i` is abelian, so `\exp(\sum n_i x_i) = \prod g_i^{n_i}` and the `x_i` generate a
        commutative nilpotent ideal `I`. Put `W_k = I^k X`, a decreasing filtration ending at `0`. Lifting
        `\exp(x) X = \pm Y` along it is linear at each step (solving along a central series, as in
        Baumslag-Cannonito-Robinson-Segal, *J. Algebra* 142 (1991), Section 3; Segal, *Polycyclic Groups*, Ch. 6).
        With `\Lambda_0 = \Lambda`, `X_0 = X`, at step `k \ge 1` the remaining solutions are `\exp(\Lambda_{k-1}) X_{k-1}`,
        where `x X \in W_k` for `x \in \Lambda_{k-1}`. Then `\exp(x) X_{k-1} \equiv X_{k-1} + x X \pmod{W_{k+1}}`, since
        `x^2 X \in x W_k` and `x (X_{k-1} - X) \in I W_k`. So `x X \equiv \pm Y - X_{k-1}` is an integral linear system
        on `\Lambda_{k-1}`: no solution proves absence; a solution `n_k` gives `X_k = \exp(n_k) X_{k-1}`, and its integral
        kernel is `\Lambda_k`. At `W_{k+1} = 0` the congruence is the equation.
        """
        generators = self._commutant.unipotent_kernel_generators()
        logarithms = [_logarithm(g) for g in generators]
        assert all(x * y == y * x for x in logarithms for y in logarithms), "the skew radical is not abelian"
        flat = lambda m: vector(QQ, m.list())
        size = self.rank * self.source_rank
        filtration, level = [], list(logarithms)
        while True:
            level = [m for m in level if not (m * self.marking).is_zero()]
            if not level:
                break
            filtration.append([flat(m * self.marking) for m in level])
            level = [x * m for x in logarithms for m in level]
        spans = [matrix(QQ, [r for later in filtration[k:] for r in later]) for k in range(len(filtration))]
        zero = matrix(QQ, self.rank, self.rank)
        for sign in (1, -1):
            wanted = sign * target.change_ring(QQ)
            basis = identity_matrix(ZZ, len(generators))
            current, element = self.marking.change_ring(QQ), self._one
            solvable = True
            for k in range(len(spans)):
                quotient = spans[k + 1].right_kernel_matrix() if k + 1 < len(spans) else identity_matrix(QQ, size)
                images = [flat(sum((c * x for c, x in zip(b, logarithms)), zero) * self.marking) for b in basis.rows()]
                equations = quotient * (matrix(QQ, images).transpose() if images else matrix(QQ, size, 0))
                values = quotient * flat(wanted - current)
                if equations.ncols() == 0:
                    solvable = values.is_zero()
                    if not solvable:
                        break
                    continue
                scale = lcm([equations.denominator(), values.denominator()])
                integral = matrix(ZZ, scale * equations)
                solution = _integer_solution(integral, vector(ZZ, scale * values))
                if solution is None:
                    solvable = False
                    break
                step = self._power_product(generators, list(vector(ZZ, solution) * basis))
                current, element = step * current, step * element
                basis = integral.right_kernel_matrix() * basis
            if solvable and current == wanted:
                return sign * element
        return None

    def transporter(self, target):
        r"""Return `g \in C(F_1, \dots, F_s)` with `g X = Y`, or ``None``, for a marking `Y`.

        `Y` has the same source and the same actions, so `F_i Y = Y E_i` is required. The domain
        is the one of :meth:`pointwise_stabilizer_generators`.
        """
        target = matrix(ZZ, target)
        assert all(
            F * target == target * E for F, E in zip(self.ambient_actions, self.source_actions, strict=True)
        ), "the target is not equivariant for the given actions"
        if target.transpose() * self.gram * target != self.source_gram:
            return None
        if self.source_gram.det() != 0:
            result = self._nondegenerate_transporter(target)
        elif self._is_unipotent_type():
            result = self._unipotent_transporter(target)
        elif (split := self._parabolic(self.marking))[0] is not None:
            result = self._parabolic_transporter(*split, target)
        else:
            orbit = self._finite_orbit()
            if orbit is None:
                raise NotImplementedError(
                    "the transporter of a marking whose radical extension does not split and whose orbit under the "
                    "centralizer is infinite (#53)"
                )
            transversal, _stabilizer = orbit
            found = transversal.get(target.str())
            result = found[0] if found is not None else None
        assert result is None or self._is_stabilizer_element(result, target)
        return result


def _module_words(isometries, columns):
    r"""Return pairs `(w, j)` of words in the `F_i` and columns with `w x_j` a basis of the `Q\langle F \rangle`-span of the `x_j`."""
    one = identity_matrix(QQ, columns.nrows())
    pairs, span = [], matrix(QQ, 0, columns.nrows())
    for j in range(columns.ncols()):
        stacked = span.stack(matrix(QQ, [columns.column(j)]))
        if stacked.rank() > span.rank():
            pairs.append((one, j))
            span = stacked
    position = 0
    while position < len(pairs):
        word, j = pairs[position]
        position += 1
        for F in isometries:
            moved = F.change_ring(QQ) * word
            stacked = span.stack(matrix(QQ, [moved * columns.column(j)]))
            if stacked.rank() > span.rank():
                pairs.append((moved, j))
                span = stacked
    return pairs


class CentralizerTupleOrbit:
    r"""The orbit of a tuple `x_1, \dots, x_k` of vectors of `L` under `C = C_{O(L)}(F_1, \dots, F_s)`.

    `g \in C` commutes with every word `w` in the `F_i`, so `g x_j = y_j` for all `j` exactly when
    `g W = W'` for `W = [w x_j]` and `W' = [w y_j]` on the pairs of :func:`_module_words`. With the
    primitive basis `X = W C^{-1}` of the saturated span `M`, `F_i X = X E_i`, and `g X = Y = W' C^{-1}`.
    Conversely `g X = Y` gives `g x = y` when `x = X c` and `y = Y c`, which is checked. So the
    stabilizer and transporter are those of the equivariant marking `X` (:class:`EquivariantMarking`).
    Vectors are integer columns.
    """

    def __init__(self, gram, isometries, columns):
        self.gram = matrix(ZZ, gram)
        self.isometries = tuple(matrix(ZZ, F) for F in isometries)
        self.columns = matrix(ZZ, columns)
        assert self.columns.nrows() == self.gram.nrows() and not self.columns.is_zero()
        self.pairs = _module_words(self.isometries, self.columns)
        spanning = self._words(self.columns)
        saturated = matrix(ZZ, spanning.denominator() * spanning.transpose()).saturation().transpose()
        self._change = saturated.change_ring(QQ).solve_right(spanning)
        self._coefficients = saturated.change_ring(QQ).solve_right(self.columns.change_ring(QQ))
        actions = tuple(matrix(ZZ, saturated.change_ring(QQ).solve_right(F * saturated)) for F in self.isometries)
        self.marking = EquivariantMarking(self.gram, saturated, self.isometries, actions)

    def _words(self, columns):
        return matrix(QQ, [w * columns.column(j) for w, j in self.pairs]).transpose()

    def target_marking(self, columns):
        r"""Return `Y` with `g X = Y` for every `g \in C` taking the tuple to ``columns``, or ``None`` when no linear map does."""
        columns = matrix(ZZ, columns)
        target = self._words(columns) * self._change.inverse()
        if target.denominator() != 1:
            return None
        target = matrix(ZZ, target)
        if target * self._coefficients != columns:
            return None
        if any(F * target != target * E for F, E in zip(self.isometries, self.marking.source_actions, strict=True)):
            return None
        return target

    def stabilizer_generators(self):
        r"""Return generators of `\{g \in C : g x_j = x_j\}`."""
        result = self.marking.pointwise_stabilizer_generators()
        assert all(g * self.columns == self.columns for g in result)
        return result

    def transporter(self, columns):
        r"""Return `g \in C` with `g x_j = y_j`, or ``None`` as a proof that none exists."""
        target = self.target_marking(columns)
        if target is None:
            return None
        found = self.marking.transporter(target)
        assert found is None or found * self.columns == matrix(ZZ, columns)
        return found

    def setwise_stabilizer_generators(self):
        r"""Return generators of `\{g \in C : g \Lambda = \Lambda\}` for `\Lambda` the span of the tuple, a basis.

        Write `A` for the Gram matrix of the tuple. When `A` is definite, the induced action on `\Lambda`
        lies in the finite `O(A)`, with kernel the pointwise stabilizer, so the pointwise generators
        and one transporter `x \mapsto x a` for each realized `a \in O(A)` generate. Otherwise, when
        `\Lambda_Q` is `F`-invariant, `g \Lambda = \Lambda` gives `g M = M` for the saturation `M` of
        `\Lambda`, the equivariant marking, so the stabilizer is the subgroup of
        :meth:`EquivariantMarking.setwise_stabilizer_generators` that preserves `\Lambda`. That subgroup
        contains the kernel of the action on `M / e M`, `e` the exponent of `M / \Lambda`, so it has finite
        index, and Schreier's lemma gives it. A singular `A` uses the radical parabolic of `M`. When `\Lambda_Q`
        is not `F`-invariant, degenerate or not, the stabilizer of `\Lambda_Q` is the unit group of the commutant of
        the `F_i` cut down to the elements preserving `\Lambda_Q` and `\Lambda_Q^\perp` (:meth:`_subspace_setwise`).
        """
        assert self.columns.rank() == self.columns.ncols(), "the tuple is not a basis of its span"
        source_gram = self.columns.transpose() * self.gram * self.columns
        source = Lattices(ZZ)([[int(c) for c in row] for row in source_gram])
        module = self.columns.column_module()
        if source.is_definite():
            frame = tuple(source.module_generators())
            result = list(self.stabilizer_generators())
            for automorphism in source.O():
                a = matrix(ZZ, [[int(c) for c in automorphism(v)] for v in frame]).transpose()
                witness = self.transporter(self.columns * a)
                if witness is not None:
                    result.append(witness)
        elif self.marking.source_rank == self.columns.ncols():
            saturated = self.marking.setwise_stabilizer_generators()
            if self.marking.marking.column_module() == module:
                result = list(saturated)
            else:
                preserves = lambda g: (matrix(ZZ, g) * self.columns).column_module() == module
                found, _index = finite_preimage_generators([*saturated, self.marking._one], lambda g: g, preserves)
                result = [matrix(ZZ, g) for g in found]
        else:
            result = self._subspace_setwise(module)
        assert all((g * self.columns).column_module() == module for g in result)
        return tuple(result)


    def _subspace_setwise(self, module):
        r"""Return the setwise stabilizer of `\Lambda` in `C(F)` for `\Lambda_Q` not `F`-invariant.

        `g \in O(L)` preserves `\Lambda_Q` exactly when it preserves `\Lambda_Q` and `\Lambda_Q^\perp`, so
        `C(F) \cap \mathrm{Stab}(\Lambda_Q)` is the centralizer of :class:`_SubspaceCommutant` (#54); `A` may be
        singular. Such `g` preserves the saturation `\Lambda_Q \cap L`, which contains `\Lambda` with finite index
        `e`; the stabilizer of `\Lambda` contains the kernel of the action on
        `(\Lambda_Q \cap L) / e (\Lambda_Q \cap L)`, so it has finite index, and Schreier's lemma gives it.
        """
        commutant = _SubspaceCommutant(self.gram, self.isometries, [self.columns])
        generators = [matrix(ZZ, g) for g in _commutant_groups().centralizer_generators(commutant)]
        assert all(commutant.contains(g) for g in generators)
        preserves = lambda g: (matrix(ZZ, g) * self.columns).column_module() == module
        found, _index = finite_preimage_generators([*generators, self.marking._one], lambda g: g, preserves)
        return [matrix(ZZ, g) for g in found]


def _right_orbit_restriction(marking, generators):
    r"""Return the integral matrices of `x \mapsto x a^{-1}` on the saturated span of the orbit of ``marking``."""
    flat = lambda m: vector(QQ, m.change_ring(QQ).list())
    shape = (marking.nrows(), marking.ncols())
    act = lambda r, a: flat(matrix(QQ, shape[0], shape[1], list(r)) * a.inverse())
    if marking.is_zero():
        return []
    rows = matrix(QQ, [flat(marking)])
    while True:
        enlarged = rows.stack(matrix(QQ, [act(r, a) for a in generators for r in rows.rows()])) if generators else rows
        enlarged = enlarged.echelon_form()[: enlarged.rank()]
        if enlarged.nrows() == rows.nrows():
            break
        rows = enlarged
    lattice = matrix(ZZ, rows.denominator() * rows).saturation().change_ring(QQ)
    return [matrix(ZZ, [lattice.solve_left(act(r, a)) for r in lattice.rows()]) for a in generators]


def source_automorphism_kernel_generators(marking, source_generators):
    r"""Return generators of the kernel of the projection of a diagram stabilizer to the ambient group.

    For `X : S \to L` not assumed injective and a finite group `J \le GL(S)`, the diagram
    stabilizer is `\{(g, a) \in \Gamma \times J : g X = X a\}`. Its projection to `\Gamma` has
    kernel `\{(1, a) : X a = X\}`, the source automorphisms invisible to `L`. A vertex with no
    arrow to `L` is modelled by zero columns of `X`, and a nonzero kernel shows that the
    diagram stabilizer is not the ambient stabilizer.

    `J` may be infinite. `J` acts on integral matrices by `x \mapsto x a^{-1}`; the saturated `Z`-span `M` of the
    orbit of `X` is `J`-stable, and the orbit is finite exactly when the image of `J` in `GL(M)` is finite (the
    orbit spans `M_Q` and consists of integral points). Then Schreier's lemma on the orbit gives the kernel
    (Holt-Eick-O'Brien, Thm. 4.13). An infinite orbit means the kernel has infinite index in `J`; for the source
    groups `J = GL_k(\mathbb Z)` and `J = O(A)` of the diagram stabilizer the kernel is
    :func:`invisible_source_automorphism_generators`, and for other `J` this raises.
    """
    marking = matrix(ZZ, marking)
    generators = tuple(matrix(ZZ, a) for a in source_generators)
    if not _is_finite(_right_orbit_restriction(marking, generators)):
        raise NotImplementedError(
            "the orbit of the marking under the source group given by generators is infinite, so the kernel is an "
            "intersection of infinite subgroups; for J = O(A) or GL_k(Z) use orthogonal_source_kernel_generators"
        )
    one = identity_matrix(ZZ, marking.ncols())
    _transversal, kernel = _schreier(generators, marking, lambda a, x: x * a.inverse().change_ring(ZZ), one)
    assert all(marking * a == marking for a in kernel)
    return kernel


def orthogonal_source_kernel_generators(gram, marking):
    r"""Return generators of `\{a \in J : X a = X\}` for `J = O(A)`, `A = X^t B X`, or `J = GL_k(\mathbb Z)`.

    `X a = X` gives `a^t A a = X^t B X = A`, so `\{a \in GL_k(\mathbb Z) : X a = X\} \subseteq O(A)` and both kernels
    are that group, whatever the orbit of `X` under `J`; it is :func:`invisible_source_automorphism_generators`.
    """
    marking = matrix(ZZ, marking)
    source_gram = marking.transpose() * matrix(ZZ, gram) * marking
    result = invisible_source_automorphism_generators(marking)
    assert all(a.transpose() * source_gram * a == source_gram and marking * a == marking for a in result)
    return result


def invisible_source_automorphism_generators(marking):
    r"""Return generators of `\{a \in GL_k(\mathbb Z) : X a = X\}` for an integral `X : \mathbb Z^k \to L`.

    This is the kernel of the projection of the diagram stabilizer to the ambient group when the
    source group `J` is `GL_k(\mathbb Z)`, and also when `J = O(A)` for `A = X^t B X`, since
    `X a = X` gives `a^t A a = A`. The group can be infinite. Choose a basis of `\mathbb Z^k`
    whose first `m` vectors span `K = \ker X`, which is saturated. Then `a` fixes `\mathbb Z^k / K`
    and preserves `K`, so in that basis `a = \begin{pmatrix} D & S \\ 0 & 1 \end{pmatrix}` with
    `D \in GL_m(\mathbb Z)` and `S` integral. Elementary matrices and one sign generate
    `GL_m(\mathbb Z)`, and the unit shears generate the `S` part.
    """
    marking = matrix(ZZ, marking)
    size = marking.ncols()
    kernel = marking.right_kernel_matrix()
    rank = kernel.nrows()
    if rank == 0:
        return ()
    _form, _left, right = kernel.smith_form()
    basis = right.inverse().transpose()  # Columns: a basis of Z^k whose first `rank` columns span K.
    unit = lambda i, j: matrix(ZZ, size, size, {(i, j): 1})
    one = identity_matrix(ZZ, size)
    adapted = [one + unit(i, j) for i in range(rank) for j in range(rank) if i != j]
    adapted.append(one - 2 * unit(0, 0))
    adapted.extend(one + unit(i, j) for i in range(rank) for j in range(rank, size))
    generators = tuple(matrix(ZZ, basis * a * basis.inverse()) for a in adapted)
    assert all(marking * a == marking for a in generators)
    return generators
