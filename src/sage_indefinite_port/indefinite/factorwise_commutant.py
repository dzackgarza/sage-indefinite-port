r"""Centralizers and transporters of a semisimple commutant whose centre is not a field (#54).

Let `A` be the commutant of the isometries `F_k` of `(L = Z^r, B)`, semisimple with centre `Z(A) = \prod_i Z_i`. Its primitive central
idempotents `e_i` (from the factorization of the minimal polynomial of a generic central element and the Chinese remainder theorem) split
`Q^r = \bigoplus e_i Q^r`. The adjoint `\dagger` permutes the `e_i`: if `e_i^\dagger = e_i`, the summand is `B`-orthogonal to the others; if
`e_i^\dagger = e_j \ne e_i`, the pair `e_i + e_j` is one orthogonal summand of GL type: `X = L \cap e_i Q^r` and `Y = L \cap e_j Q^r` are totally
isotropic, paired by `B`, and its unitary group is `GL_1` of the order of `\mathrm{End}_F(X)` acting on `X` and contragrediently on `Y`
(:func:`_pair_generators`); its transporter decides the `Z[F]`-lattice isomorphism `X \cong X'` by the ideal class and a finite unit quotient (:func:`_pair_transporter`). Group the idempotents into these `\dagger`-orbits
`\epsilon_1, \ldots, \epsilon_s`; then `L_i = L \cap \epsilon_i Q^r` are orthogonal, `L \supseteq \bigoplus L_i` with finite glue, and every
`F_k` preserves each `L_i`.

Centralizer. An element of `C(Z)` preserves each `\epsilon_i Q^r` (it commutes with the centre), so it restricts to `c_i \in C_i`, the centralizer
of the factor; conversely `\oplus c_i` lies in `C(Z)` exactly when it maps `L` to `L`, a subgroup of finite index of `\prod C_i`, whose Schreier
generators (membership: integrality on `Z^r`) generate `C(Z)`.

Transporter. A rational intertwiner `t_0` carries the `\epsilon_i` to the target's `\epsilon_i' = t_0 \epsilon_i t_0^{-1}`, so an integral transporter `t`
restricts to factor transporters `t_i : L_i \to L_i'`, and `t_i \in t_i^0 C_i` for one factor transporter `t_i^0` (``None`` for one factor is a
proof for `L`). `\oplus t_i` maps `L` onto `L'` exactly when its action on `\bigoplus L_i^\sharp / L_i` carries the glue of `L` to that of `L'`, which
depends on each `c_i` only through its image in the finite group `\mathrm{Aut}(L_i^\sharp / L_i)`. So `t_i = t_i^0 c_i` with `c_i` over a transversal
of `C_i` modulo the kernel of that action decides, through :func:`_verified`.
"""

from itertools import product

from sage.arith.functions import lcm

from sage.libs.pari import pari
from sage.matrix.constructor import block_matrix, matrix
from sage.matrix.special import identity_matrix
from sage.rings.integer_ring import ZZ
from sage.rings.polynomial.polynomial_ring_constructor import PolynomialRing
from sage.rings.rational_field import QQ
from sage_extensions.algebras.isometry_commutant import IsometryCommutant
from sage_extensions.categories.lattice_centralizers import finite_preimage_generators


def central_idempotents(commutant):
    r"""Return the primitive central idempotents of the semisimple commutant (module docstring)."""
    center = [c.change_ring(QQ) for c in commutant._center_basis()]
    ring = PolynomialRing(QQ, "x")
    for coefficients in product(range(1, len(center) + 3), repeat=len(center)):
        x = sum(c * z for c, z in zip(coefficients, center))
        minimal = ring(x.minimal_polynomial())
        if minimal.degree() == len(center) and minimal.is_squarefree():
            break
    else:
        raise AssertionError("no central element generates the centre")
    result = []
    for factor, _e in minimal.factor():
        cofactor = minimal // factor
        idempotent = ((cofactor * cofactor.inverse_mod(factor)) % minimal)(x)
        result.append(idempotent)
    one = identity_matrix(QQ, commutant.rank)
    assert sum(result) == one and all(e * e == e for e in result)
    return result


def adjoint_orbits(commutant, idempotents):
    r"""Group the idempotents into `\dagger`-orbits: ``(e,)`` for a fixed one, ``(e, e^\dagger)`` for a swapped pair."""
    remaining = list(idempotents)
    result = []
    while remaining:
        e = remaining.pop(0)
        image = commutant.adjoint(e)
        if image == e:
            result.append((e,))
            continue
        assert image in remaining
        remaining.remove(image)
        result.append((e, image))
    return result


def _pair_generators(gram, isometries, pair):
    r"""Return the basis `[X | Y]` of a GL-type summand and generators `\mathrm{diag}(a, b)` of its unitary group in that basis.

    `X = L \cap e Q^r` and `Y = L \cap e^\dagger Q^r` are totally isotropic and paired by `B_{XY}`. The unitary group of the summand is
    `\{(a, B_{XY}^{-1} a^{-t} B_{XY})\}` for `a` in the units of `\mathrm{End}_F(X)`, generated by :func:`_endomorphism_unit_generators`; the
    finite-index subgroup preserving `L` is cut out afterwards."""
    from sage_indefinite_port.indefinite.equivariant_markings import _endomorphism_unit_generators

    e, image = pair
    X, Y = _summand_basis(e), _summand_basis(image)
    pairing = (X.transpose() * gram * Y).change_ring(QQ)
    actions = [_restrict(X.change_ring(QQ), F.change_ring(QQ)) for F in isometries]
    basis = block_matrix(ZZ, [[X, Y]], subdivide=False)
    result = []
    for a in _endomorphism_unit_generators(actions, X.ncols()):
        a = matrix(QQ, a)
        b = pairing.inverse() * a.inverse().transpose() * pairing
        result.append(block_matrix(QQ, [[a, matrix(QQ, a.nrows(), b.ncols())], [matrix(QQ, b.nrows(), a.ncols()), b]], subdivide=False))
    return basis, result


def _summand_basis(projector):
    r"""Return an integral basis matrix (columns) of `\mathrm{image}(\epsilon) \cap Z^r`."""
    r = projector.nrows()
    complement = identity_matrix(QQ, r) - projector
    scale = complement.denominator()
    return matrix(ZZ, scale * complement).right_kernel_matrix().transpose()


def _restrict(basis, element):
    return basis.solve_right(element * basis)


def _factor(gram, isometries, projector):
    basis = _summand_basis(projector)
    factor_gram = basis.transpose() * gram * basis
    factor_isometries = [matrix(ZZ, _restrict(basis.change_ring(QQ), F.change_ring(QQ))) for F in isometries]
    return basis, matrix(ZZ, factor_gram), factor_isometries


def factorwise_centralizer_generators(commutant, centralizer_generators):
    r"""Return generators of `C(Z)` (module docstring, Centralizer); ``centralizer_generators`` is the dispatcher for the factors."""
    orbits = adjoint_orbits(commutant, central_idempotents(commutant))
    r = commutant.rank
    bases, moves = [], []
    for orbit in orbits:
        if len(orbit) == 2:
            basis, pair_moves = _pair_generators(commutant.gram, commutant.isometries, orbit)
            bases.append(basis)
            moves.extend((len(bases) - 1, c) for c in pair_moves)
            continue
        basis, gram, isometries = _factor(commutant.gram, commutant.isometries, orbit[0])
        bases.append(basis)
        for c in centralizer_generators(IsometryCommutant(gram, isometries)):
            moves.append((len(bases) - 1, matrix(QQ, c)))
    frame = block_matrix(QQ, [[b.change_ring(QQ) for b in bases]], subdivide=False)
    assert frame.is_square() and frame.det() != 0
    sizes = [b.ncols() for b in bases]

    def embed(index, c):
        blocks = [c if i == index else identity_matrix(QQ, sizes[i]) for i in range(len(sizes))]
        return frame * block_matrix(QQ, [[blocks[i] if i == j else matrix(QQ, sizes[i], sizes[j]) for j in range(len(sizes))] for i in range(len(sizes))], subdivide=False) * frame.inverse()

    embedded = [embed(i, c) for i, c in moves] + [-identity_matrix(QQ, r)]
    integral = lambda g: all(x in ZZ for x in g.list())
    subgroup, _index = finite_preimage_generators(embedded, lambda g: g, integral)
    result = tuple(matrix(ZZ, g) for g in subgroup)
    assert all(commutant.is_centralizer_element(g) for g in result)
    return result


def _discriminant_transversal(gram, generators):
    r"""Return a transversal of the group generated by ``generators`` modulo the kernel of its action on `L^\sharp / L`."""
    dual = gram.change_ring(QQ).inverse()
    one = identity_matrix(QQ, gram.nrows())
    same = lambda x, y: all(c in ZZ for c in ((~x * y - one) * dual).list())
    reps, position = [one], 0
    while position < len(reps):
        current = reps[position]
        position += 1
        for g in generators:
            moved = matrix(QQ, g) * current
            if not any(same(known, moved) for known in reps):
                reps.append(moved)
    return reps


def _number_field(polynomial):
    from sage.rings.number_field.number_field import NumberField

    return NumberField(polynomial.change_ring(QQ), "theta")


def _pair_transversal(gram, basis, moves):
    r"""Return a transversal of the group generated by ``moves`` (in the basis ``basis`` of the summand `N`) modulo the elements that preserve
    `N` and act trivially on `N^\sharp / N`."""
    local = (basis.transpose() * gram * basis).change_ring(QQ)
    dual = local.inverse()
    one = identity_matrix(QQ, local.nrows())

    def same(x, y):
        z = ~x * y
        return all(c in ZZ for c in z.list()) and z.det() in (1, -1) and all(c in ZZ for c in ((z - one) * dual).list())

    reps, position = [one], 0
    while position < len(reps):
        current = reps[position]
        position += 1
        for g in moves:
            moved = g * current
            if not any(same(known, moved) for known in reps):
                reps.append(moved)
    return reps


def _pair_transporter(commutant, target_gram, targets, start, pair):
    r"""Return ``(basis, target_basis, t0, cosets)`` for a GL-type summand, or ``None`` as a proof that no transporter exists.

    The `Z[F]`-lattices `X` and `X'` (pulled back to `X \otimes Q` by `t_0`) are isomorphic exactly when one maps onto the other by `\alpha(F)`,
    `\alpha` a unit of the etale algebra `A = Q[F]|_X` when it has dimension `\dim X`; :class:`_EtaleModel` decides this for any multiplier
    ring through the maximal order and a finite unit quotient (Eick, Hofmann, O'Brien, J. LMS 2019, arXiv:1811.06190, Sec. 3). The `Y`-part
    is the contragredient `B_{X'Y'}^{-1} \alpha_X^{-t} B_{XY}`. All pair transporters are `t_0 \cdot \mathrm{diag}(a, b)` over the unitary group of the summand; the
    cosets modulo the elements preserving `X + Y` and trivial on its discriminant group decide integrality with the other factors."""
    e, image = pair
    X, Y = _summand_basis(e), _summand_basis(image)
    target_e, target_image = start * e * start.inverse(), start * image * start.inverse()
    X2, Y2 = _summand_basis(target_e), _summand_basis(target_image)
    if X.ncols() != X2.ncols() or Y.ncols() != Y2.ncols():
        return None
    k = X.ncols()
    actions = [_restrict(X.change_ring(QQ), F.change_ring(QQ)) for F in commutant.isometries]
    alpha0 = X2.change_ring(QQ).solve_right(start * X.change_ring(QQ))
    source_columns, target_columns = identity_matrix(QQ, k).columns(), alpha0.inverse().columns()
    algebra = _etale_model(actions, k)
    if algebra is not None:
        alpha = algebra.isomorphism(source_columns, target_columns)
        if alpha is None:
            return None
        action = algebra.action(alpha)
    else:
        model = _dedekind_model(actions, k)
        if model is None:
            raise NotImplementedError(
                f"GL-type summand of the commutant of {commutant.isometries}: Q[F] acting on X (x) Q is not commutative, so its Wedderburn "
                f"components M_n(K) with n > 1 need explicit matrix units (a splitting of each component) before the Morita reduction of "
                f"Eick-Hofmann-O'Brien (arXiv:1811.06190, Sec. 4) to O_K-lattices; that splitting is not implemented (#54)"
            )
        action = model.isomorphism(source_columns, target_columns)
        if action is None:
            return None
    alpha_x = alpha0 * action
    pairing = (X.transpose() * commutant.gram * Y).change_ring(QQ)
    target_pairing = (X2.transpose() * target_gram * Y2).change_ring(QQ)
    beta = target_pairing.inverse() * alpha_x.inverse().transpose() * pairing
    zero = lambda a, b: matrix(QQ, a, b)
    t0 = block_matrix(QQ, [[alpha_x, zero(k, Y.ncols())], [zero(Y.ncols(), k), beta]], subdivide=False)
    basis, moves = _pair_generators(commutant.gram, commutant.isometries, pair)
    target_basis = block_matrix(ZZ, [[X2, Y2]], subdivide=False)
    return basis, target_basis, t0, _pair_transversal(commutant.gram, basis, moves)


class _EtaleModel:
    r"""`A = Q[\Theta] \cong Q[x]/(f) \cong \prod_i K_i` acting on `Q^k` through a cyclic vector `v` (`p(x) \mapsto p(\Theta) v`), with lattices
    in `Q^k` read as `Z`-lattices of `A`, i.e. tuples `(a_i) \in \prod K_i`.

    Isomorphism (Eick, Hofmann, O'Brien, *The conjugacy problem in GL(n, Z)*, J. LMS 2019, arXiv:1811.06190, Sec. 3). `Z[F]`-lattices
    `X, X'` in the same rational module are isomorphic exactly when `\alpha X = X'` for some `\alpha \in A^\times` (an `A`-linear map of the
    rank-one free module `A`). Then `O_A X' = \alpha O_A X`, so in each factor the colon ideal
    `(O_A X')_i (O_A X)_i^{-1}` is principal, generated by `\alpha_{0,i}`, and `\alpha \in \alpha_0 O_A^\times`. `u \mapsto u X` depends only on the
    class of `u` modulo `\mathrm{Stab}(X) = R(X)^\times`, the units of the multiplier ring, which contains `(Z + m O_A)^\times` for
    `m O_A \subseteq R(X)`, so `O_A^\times / \mathrm{Stab}(X)` is finite (it embeds in `(O_A / \mathfrak f)^\times / (R(X)/\mathfrak f)^\times`). A
    transversal, by orbit enumeration from generators of `O_A^\times = \prod O_{K_i}^\times`, decides: `X \cong X'` exactly when `\alpha_0 u X = X'`
    for one of its elements `u`."""

    def __init__(self, theta, vector_, polynomial):
        k = theta.nrows()
        self.theta, self.polynomial = theta, polynomial
        self.krylov_inverse = block_matrix(QQ, [[theta**i * vector_ for i in range(k)]], subdivide=False).inverse()
        self.factors = [factor for factor, _e in polynomial.factor()]
        self.fields = [_number_field(factor) for factor in self.factors]

    def element(self, column):
        coefficients = list(self.krylov_inverse * column)
        return tuple(sum((QQ(c) * K.gen() ** i for i, c in enumerate(coefficients)), K(0)) for K in self.fields)

    def _flat(self, x):
        return [c for a, K in zip(x, self.fields) for c in K(a).list()]

    def _contains(self, lattice, elements):
        rows = matrix(QQ, [self._flat(y) for y in lattice])
        return all(all(c in ZZ for c in rows.solve_left(matrix(QQ, [self._flat(x)])).list()) for x in elements)

    def _times(self, u, lattice):
        return [tuple(a * b for a, b in zip(u, x)) for x in lattice]

    def _maps_onto(self, u, source, target):
        inverse = tuple(~a for a in u)
        return self._contains(target, self._times(u, source)) and self._contains(source, self._times(inverse, target))

    def isomorphism(self, source_columns, target_columns):
        r"""Return `\alpha` with `\alpha X = X'` for the lattices spanned by the columns, or ``None`` (class docstring)."""
        source = [self.element(c) for c in source_columns]
        target = [self.element(c) for c in target_columns]
        alpha0 = []
        for index, K in enumerate(self.fields):
            colon = K.ideal([x[index] for x in target]) / K.ideal([x[index] for x in source])
            if not colon.is_principal():
                return None
            alpha0.append(K(colon.gens_reduced()[0]))
        alpha0 = tuple(alpha0)
        one = tuple(K(1) for K in self.fields)
        generators = []
        for index, K in enumerate(self.fields):
            for u in K.unit_group().gens_values():
                generators.append(tuple(K(u) if i == index else L(1) for i, L in enumerate(self.fields)))
        stabilizes = lambda u: self._maps_onto(u, source, source)
        divide = lambda x, y: tuple(a / b for a, b in zip(x, y))
        transversal, position = [one], 0
        while position < len(transversal):
            current = transversal[position]
            position += 1
            for g in generators:
                moved = tuple(a * b for a, b in zip(current, g))
                if not any(stabilizes(divide(moved, known)) for known in transversal):
                    transversal.append(moved)
        for u in transversal:
            alpha = tuple(a * b for a, b in zip(alpha0, u))
            if self._maps_onto(alpha, source, target):
                return alpha
        return None

    def action(self, alpha):
        r"""Return the matrix of multiplication by ``alpha`` on `Q^k`: `p_\alpha(\Theta)`, `p_\alpha` by the Chinese remainder theorem."""
        from sage.arith.misc import CRT_list

        ring = self.polynomial.parent()
        residues = [ring(K(a).polynomial().list()) for a, K in zip(alpha, self.fields)]
        p = CRT_list(residues, list(self.factors)) if len(residues) > 1 else residues[0]
        k = self.theta.nrows()
        return sum((QQ(c) * self.theta**i for i, c in enumerate(p.list())), matrix(QQ, k, k))


def _etale_model(actions, k):
    r"""Return the :class:`_EtaleModel` of the algebra generated by ``actions`` on `Q^k` when it is commutative of dimension `k`, else ``None``.

    Then it is etale (the commutant is semisimple), equal to `Q[\Theta]` for any `\Theta` in it with squarefree characteristic polynomial of
    degree `k`, and the elements failing that lie in finitely many proper subspaces, so a growing search of integer combinations of the
    ``actions`` finds one; a vector `v` with invertible Krylov matrix is cyclic."""
    one = identity_matrix(QQ, k)
    if not all(x * y == y * x for x in actions for y in actions):
        return None
    span = [one]
    frontier = [one]
    flat = lambda m: m.list()
    while frontier:
        current = frontier.pop()
        for F in actions:
            moved = F * current
            if matrix(QQ, [flat(m) for m in span + [moved]]).rank() > len(span):
                span.append(moved)
                frontier.append(moved)
    if len(span) != k:
        return None
    bound = 1
    while True:
        for coefficients in product(range(-bound, bound + 1), repeat=len(actions)):
            theta = sum((c * F for c, F in zip(coefficients, actions)), matrix(QQ, k, k))
            polynomial = theta.charpoly()
            if polynomial.is_squarefree():
                for column in [*one.columns(), sum(one.columns())]:
                    v = matrix(QQ, k, 1, list(column))
                    if block_matrix(QQ, [[theta**i * v for i in range(k)]], subdivide=False).det() != 0:
                        return _EtaleModel(theta, v, polynomial)
                for coefficients_v in product(range(-bound, bound + 1), repeat=k):
                    v = matrix(QQ, k, 1, list(coefficients_v))
                    if block_matrix(QQ, [[theta**i * v for i in range(k)]], subdivide=False).det() != 0:
                        return _EtaleModel(theta, v, polynomial)
        bound += 1


class _DedekindModel:
    r"""`V = X \otimes Q` as a module over the commutative etale `A = Q[F]|_X = Q[\Theta] = \prod_i K_i` of dimension `< \dim V`:
    `V = \bigoplus_i V_i`, `V_i = e_i V \cong K_i^{d_i}`, `e_i = e_i(\Theta)` from the Chinese remainder theorem.

    Isomorphism (Eick, Hofmann, O'Brien, arXiv:1811.06190, Sec. 4, the reduction to modules over Dedekind domains). When `X` is an
    `O_A`-module, `X = \bigoplus_i e_i X` with `e_i X` a projective `O_{K_i}`-module of rank `d_i`, so `e_i X \cong O_{K_i}^{d_i - 1} \oplus
    \mathfrak a_i` (Steinitz; Cohen, *Advanced Topics*, Thm. 1.2.19), with the class of `\mathfrak a_i` its only invariant. PARI ``nfhnf`` gives a
    pseudo-basis and ``rnfsteinitz`` puts it in the form `(v_1, \ldots, v_d; O, \ldots, O, \mathfrak a)`. With `\mathfrak a' = \gamma \mathfrak a`, the
    `K_i`-linear `g_i : v_j \mapsto v'_j` (`j < d`), `v_d \mapsto \gamma v'_d` maps `e_i X` onto `e_i X'`; when some class differs there is
    none. A lattice `X` with a non-maximal multiplier ring is decided through `O_A X` and a finite orbit (:meth:`isomorphism`)."""

    def __init__(self, theta, polynomial):
        self.theta = theta
        k = theta.nrows()
        self.factors = [factor for factor, _e in polynomial.factor()]
        self.fields = [_number_field(factor) for factor in self.factors]
        evaluate = lambda q: sum((QQ(c) * theta**i for i, c in enumerate(q.list())), matrix(QQ, k, k))
        self.evaluate = evaluate
        self.idempotents, self.frames = [], []
        for factor in self.factors:
            cofactor = polynomial // factor
            idempotent = evaluate((cofactor * cofactor.inverse_mod(factor)) % polynomial)
            self.idempotents.append(idempotent)
            degree = factor.degree()
            columns, frame = [], []
            for w in idempotent.columns():
                w = matrix(QQ, k, 1, list(w))
                block = [theta**j * w for j in range(degree)]
                if matrix(QQ, [list(c.column(0)) for c in columns + block]).rank() == len(columns) + degree:
                    columns.extend(block)
                    frame.append(w)
            assert len(columns) == idempotent.rank()
            self.frames.append((frame, block_matrix(QQ, [columns], subdivide=False)))

    def _coordinates(self, index, column):
        r"""Return the `K_i`-coordinates of ``column`` `\in V_i` on the frame `w_1, \ldots, w_{d_i}`."""
        K = self.fields[index]
        frame, basis = self.frames[index]
        degree = self.factors[index].degree()
        c = basis.solve_right(matrix(QQ, len(column), 1, list(column))).column(0)
        return [sum((c[l * degree + j] * K.gen() ** j for j in range(degree)), K(0)) for l in range(len(frame))]

    def _maximal_span(self, columns):
        r"""Return a `Z`-basis (columns) of `O_A X` for `X` spanned by ``columns``."""
        generated = []
        for index, K in enumerate(self.fields):
            for w in K.ring_of_integers().basis():
                operator = self.evaluate(self.factors[index].parent()(K(w).polynomial().list())) * self.idempotents[index]
                generated.extend(operator * matrix(QQ, len(c), 1, list(c)) for c in columns)
        return _lattice_basis([list(g.column(0)) for g in generated])

    def _steinitz(self, index, columns):
        r"""Return ``(vectors, ideal)``: `K_i`-coordinate columns `v_1, \ldots, v_d` and `\mathfrak a` with `e_i M = \bigoplus_{j<d} O v_j \oplus \mathfrak a v_d`
        for the `O_A`-module `M` spanned by ``columns``."""
        K = self.fields[index]
        nf = K.pari_nf()
        projected = [self._coordinates(index, (self.idempotents[index] * matrix(QQ, len(c), 1, list(c))).column(0)) for c in columns]
        d = len(projected[0])
        generators = pari.matrix(d, len(projected), [projected[j][i].__pari__() for i in range(d) for j in range(len(projected))])
        hnf = nf.nfhnf([generators, pari([1] * len(projected))])
        steinitz = nf.rnfsteinitz(hnf)
        to_field = lambda c: K(nf.nfbasistoalg(c))
        vectors = matrix(K, d, d, [to_field(steinitz[0][i, j]) for i in range(d) for j in range(d)])
        ideals = []
        for j in range(d):
            hermite = nf.idealhnf(steinitz[1][j])
            ideals.append(K.ideal([to_field(hermite[i]) for i in range(len(hermite))]))
        assert all(ideal == K.ideal(1) for ideal in ideals[:-1])
        return vectors, ideals[-1]

    def _rational(self, index, g):
        r"""Return the matrix on `V` of the `K_i`-linear map with frame matrix ``g`` on `V_i`, the identity on the other `V_j`."""
        k = self.theta.nrows()
        images, bases = [], []
        for other, (frame, basis) in enumerate(self.frames):
            bases.append(basis)
            if other != index:
                images.append(basis)
                continue
            K, ring, degree = self.fields[index], self.factors[index].parent(), self.factors[index].degree()
            columns = []
            for l in range(len(frame)):
                image = sum((self.evaluate(ring(K(g[m, l]).polynomial().list())) * frame[m] for m in range(len(frame))), matrix(QQ, k, 1))
                columns.extend(self.theta**j * image for j in range(degree))
            images.append(block_matrix(QQ, [columns], subdivide=False))
        return block_matrix(QQ, [images], subdivide=False) * block_matrix(QQ, [bases], subdivide=False).inverse()

    def _automorphism_generators(self, pseudo):
        r"""Return generators of `\mathrm{Aut}_{O_A}(M)` on `V`, ``pseudo[i] = (vectors, \mathfrak a)`` the Steinitz pseudo-basis of `e_i M`.

        In the pseudo-basis `(v_j; \mathfrak a_j)` an automorphism of `e_i M` is a matrix with entries `g_{jl} \in \mathfrak a_j \mathfrak a_l^{-1}` and
        unit determinant. `\mathrm{SL}` is generated by the elementary `1 + b E_{jl}`, `b \in \mathfrak a_j \mathfrak a_l^{-1}` (Bass, Milnor, Serre,
        Publ. IHES 33 (1967), for `d \ge 3`; Vaserstein, Ann. Math. 96 (1972), for `d = 2` and `O_K^\times` infinite; for `d = 2` with finitely many
        units, i.e. `K = Q` (Euclidean) or imaginary quadratic, Cohn, Publ. IHES 30 (1966): only the Euclidean imaginary quadratic rings),
        and `\mathrm{GL}` by these with `\mathrm{diag}(1, \ldots, u, \ldots, 1)` for generators `u` of `O_K^\times`. A `Z`-basis of
        `\mathfrak a_j \mathfrak a_l^{-1}` suffices, since `1 + (b + b') E_{jl} = (1 + b E_{jl})(1 + b' E_{jl})`."""
        result = []
        for index, K in enumerate(self.fields):
            vectors, last = pseudo[index]
            d = vectors.nrows()
            if d == 2 and K.degree() <= 2 and not K.is_totally_real() and abs(K.discriminant()) not in (3, 4, 7, 8, 11):
                raise NotImplementedError(
                    f"GL_2 of the order of {K}, imaginary quadratic and not Euclidean, is not generated by elementary and diagonal "
                    f"matrices (Cohn 1966); its generators (Swan, Adv. Math. 6 (1971)) are not implemented (#54)"
                )
            ideals = [K.ideal(1)] * (d - 1) + [last]
            frame = lambda g: vectors * g * vectors.inverse()
            for j in range(d):
                for u in K.unit_group().gens_values():
                    g = matrix.identity(K, d)
                    g[j, j] = K(u)
                    result.append(self._rational(index, frame(g)))
                for l in range(d):
                    if l == j:
                        continue
                    for b in (ideals[j] / ideals[l]).basis():
                        g = matrix.identity(K, d)
                        g[j, l] = K(b)
                        result.append(self._rational(index, frame(g)))
        return result

    def isomorphism(self, source_columns, target_columns):
        r"""Return the matrix on `V` of an `A`-linear `g` with `g X = X'` for the lattices spanned by the columns, or ``None``.

        `M = O_A X`, `M' = O_A X'`. An isomorphism `X \to X'` extends to one `M \to M'`, so the Steinitz classes of the `e_i M` and `e_i M'` agree
        (class docstring), giving `\varphi_0 : M \to M'`. Every isomorphism is `\varphi_0 g`, `g \in \mathrm{Aut}_{O_A}(M)`, and it maps `X` onto
        `X'` exactly when `g X = \varphi_0^{-1} X'`. With `m M \subseteq X` and `m M \subseteq \varphi_0^{-1} X'`, `g X` depends only on `g` modulo
        `m \mathrm{End}(M)`, so the orbit of the finite submodule `X / m M \subseteq M / m M` under the generators of
        :meth:`_automorphism_generators` is finite and its search decides (Eick, Hofmann, O'Brien, arXiv:1811.06190, Sec. 4)."""
        source = matrix(QQ, source_columns).transpose()
        target = matrix(QQ, target_columns).transpose()
        maximal = self._maximal_span(source_columns)
        target_maximal = self._maximal_span(target_columns)
        pseudo, phi0 = [], []
        for index, K in enumerate(self.fields):
            vectors, ideal = self._steinitz(index, maximal.columns())
            target_vectors, target_ideal = self._steinitz(index, target_maximal.columns())
            ratio = target_ideal / ideal
            if not ratio.is_principal():
                return None
            gamma = K(ratio.gens_reduced()[0])
            d = vectors.nrows()
            scale = matrix(K, d, d, lambda i, j: (gamma if i == d - 1 else K(1)) if i == j else K(0))
            phi0.append(self._rational(index, target_vectors * scale * vectors.inverse()))
            pseudo.append((vectors, ideal))
        transport = matrix.identity(QQ, source.nrows())
        for g in phi0:
            transport = g * transport
        moved = target_maximal.solve_right(transport * maximal)
        assert all(c in ZZ for c in moved.list()) and moved.det() in (1, -1)
        pulled = transport.inverse() * target
        exponent = lcm([source.solve_right(maximal).denominator(), pulled.solve_right(maximal).denominator()])

        def key(lattice):
            coordinates = maximal.solve_right(lattice)
            assert all(c in ZZ for c in coordinates.list())
            rows = matrix(ZZ, coordinates.transpose()).stack(exponent * matrix.identity(ZZ, maximal.ncols()))
            return tuple(rows.hermite_form(include_zero_rows=False).list())

        goal = key(pulled)
        one = matrix.identity(QQ, source.nrows())
        orbit = {key(source): one}
        if goal in orbit:
            return transport
        generators = self._automorphism_generators(pseudo)
        frontier = [one]
        while frontier:
            current = frontier.pop()
            for g in generators:
                element = g * current
                point = key(element * source)
                if point in orbit:
                    continue
                orbit[point] = element
                if point == goal:
                    action = transport * element
                    image = target.solve_right(action * source)
                    assert all(c in ZZ for c in image.list()) and image.det() in (1, -1)
                    return action
                frontier.append(element)
        return None


def _lattice_basis(vectors):
    r"""Return the Hermite basis (columns) of the `Z`-span of the rational ``vectors``."""
    rows = matrix(QQ, vectors)
    scale = rows.denominator()
    hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
    return hermite.transpose()


def _dedekind_model(actions, k):
    r"""Return the :class:`_DedekindModel` when ``actions`` generate a commutative algebra on `Q^k`, else ``None``; `\Theta` is an integer
    combination with squarefree minimal polynomial of degree the dimension of the algebra (a primitive element of the etale algebra)."""
    if not all(x * y == y * x for x in actions for y in actions):
        return None
    one = identity_matrix(QQ, k)
    span, frontier = [one], [one]
    while frontier:
        current = frontier.pop()
        for F in actions:
            moved = F * current
            if matrix(QQ, [m.list() for m in span + [moved]]).rank() > len(span):
                span.append(moved)
                frontier.append(moved)
    bound = 1
    while True:
        for coefficients in product(range(-bound, bound + 1), repeat=len(actions)):
            theta = sum((c * F for c, F in zip(coefficients, actions)), matrix(QQ, k, k))
            polynomial = theta.minimal_polynomial()
            if polynomial.degree() == len(span) and polynomial.is_squarefree():
                return _DedekindModel(theta, polynomial)
        bound += 1


def factorwise_transporter(commutant, target_gram, targets, start, transporter, centralizer_generators):
    r"""Return an integral transporter to ``(target_gram, targets)`` or ``None`` as a proof (module docstring, Transporter)."""
    from sage_indefinite_port.indefinite.commutant_groups import _verified

    orbits = adjoint_orbits(commutant, central_idempotents(commutant))
    factors = []
    for orbit in orbits:
        if len(orbit) == 2:
            pair = _pair_transporter(commutant, target_gram, targets, start, orbit)
            if pair is None:
                return None
            factors.append(pair)
            continue
        projector = orbit[0]
        basis, gram, isometries = _factor(commutant.gram, commutant.isometries, projector)
        image = start * projector * start.inverse()
        target_basis, factor_target_gram, factor_targets = _factor(target_gram, targets, image)
        if abs(gram.det()) != abs(factor_target_gram.det()):
            return None
        factor_commutant = IsometryCommutant(gram, isometries)
        t0 = transporter(factor_commutant, factor_target_gram, factor_targets)
        if t0 is None:
            return None
        cosets = _discriminant_transversal(gram, centralizer_generators(factor_commutant))
        factors.append((basis, target_basis, matrix(QQ, t0), cosets))
    frame = block_matrix(QQ, [[f[0].change_ring(QQ) for f in factors]], subdivide=False)
    target_frame = block_matrix(QQ, [[f[1].change_ring(QQ) for f in factors]], subdivide=False)
    sizes = [f[0].ncols() for f in factors]
    for choice in product(*(f[3] for f in factors)):
        blocks = [f[2] * c for f, c in zip(factors, choice)]
        diagonal = block_matrix(
            QQ,
            [[blocks[i] if i == j else matrix(QQ, sizes[i], sizes[j]) for j in range(len(sizes))] for i in range(len(sizes))],
            subdivide=False,
        )
        candidate = target_frame * diagonal * frame.inverse()
        found = _verified(commutant, candidate, target_gram, targets)
        if found is not None:
            return found
    return None
