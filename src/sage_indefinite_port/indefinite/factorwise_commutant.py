def central_idempotents(commutant):
    r"""Return the primitive central idempotents of the semisimple commutant (module docstring)."""
    center = [c.change_ring(QQ) for c in commutant._center_basis()]
    ring = PolynomialRing(QQ, "x")
    for coefficients in product(range(1, len(center) + 3), repeat=len(center)):
        x = sum(c * z for c, z in zip(coefficients, center))
        minimal = ring(x.minimal_polynomial())
        if minimal.degree() == len(center) and minimal.is_squarefree():
            break
    else:
        raise AssertionError("no central element generates the centre")
    result = []
    for factor, _e in minimal.factor():
        cofactor = minimal // factor
        idempotent = ((cofactor * cofactor.inverse_mod(factor)) % minimal)(x)
        result.append(idempotent)
    one = identity_matrix(QQ, commutant.rank)
    assert sum(result) == one and all(e * e == e for e in result)
    return result


def adjoint_orbits(commutant, idempotents):
    r"""Group the idempotents into `\dagger`-orbits: ``(e,)`` for a fixed one, ``(e, e^\dagger)`` for a swapped pair."""
    remaining = list(idempotents)
    result = []
    while remaining:
        e = remaining.pop(0)
        image = commutant.adjoint(e)
        if image == e:
            result.append((e,))
            continue
        assert image in remaining
        remaining.remove(image)
        result.append((e, image))
    return result


def _pair_generators(gram, isometries, pair):
    r"""Return the basis `[X | Y]` of a GL-type summand and generators `\mathrm{diag}(a, b)` of its unitary group in that basis.

    `X = L \cap e Q^r` and `Y = L \cap e^\dagger Q^r` are totally isotropic and paired by `B_{XY}`. The unitary group of the summand is
    `\{(a, B_{XY}^{-1} a^{-t} B_{XY})\}` for `a` in the units of `\mathrm{End}_F(X)`, generated by :func:`_pair_unit_generators`; the
    finite-index subgroup preserving `L` is cut out afterwards."""
    e, image = pair
    X, Y = _summand_basis(e), _summand_basis(image)
    pairing = (X.transpose() * gram * Y).change_ring(QQ)
    actions = [_restrict(X.change_ring(QQ), F.change_ring(QQ)) for F in isometries]
    basis = block_matrix(ZZ, [[X, Y]], subdivide=False)
    result = []
    for a in _pair_unit_generators(actions, X.ncols()):
        a = matrix(QQ, a)
        b = pairing.inverse() * a.inverse().transpose() * pairing
        result.append(block_matrix(QQ, [[a, matrix(QQ, a.nrows(), b.ncols())], [matrix(QQ, b.nrows(), a.ncols()), b]], subdivide=False))
    return basis, result


def _pair_unit_generators(actions, k):
    r"""Return generators of `\mathrm{End}_F(X)^\times`, `\mathrm{End}_F(X) = \{a \in M_k(Z) : a F = F a\}`, for the integral ``actions`` `F` on `X = Z^k`.

    `A = \mathrm{End}_F(X) \otimes Q` is the commutant of the semisimple `B = Q[F]|_X`, so it is semisimple. `A = M_k(Q)`: `GL_k(Z)`
    (Hua-Reiner). `A` etale: Dirichlet units with the Chinese remainder theorem and Schreier (:func:`_commutative_unit_generators`).
    Otherwise the Morita reduction of :class:`_DedekindModel`: `\mathrm{End}_F(X)^\times` is the stabilizer of `X` in `\mathrm{Aut}_B(M)`,
    `M = \Gamma X` (a `B`-linear `g` with `g X = X` has `g M = \Gamma g X = M`), generated by elementary and diagonal units in the Steinitz
    pseudo-basis (:meth:`_DedekindModel._automorphism_generators`); with `m M \subseteq X` it contains the congruence subgroup modulo `m`, so it has
    finite index and is the Schreier preimage of the integral matrices (:func:`finite_preimage_generators`). No route passes through a
    centralizer of isometries, so none returns to :func:`factorwise_centralizer_generators`."""
    from sage_indefinite_port.indefinite.equivariant_markings import (
        _commutative_unit_generators,
        _endomorphism_order_basis,
        _general_linear_generators,
        _is_etale_order,
    )

    order_basis = _endomorphism_order_basis(actions, k)
    if len(order_basis) == k**2:
        return tuple(matrix(ZZ, g) for g in _general_linear_generators(k))
    if _is_etale_order(order_basis):
        return _commutative_unit_generators(order_basis, k)
    model = _dedekind_model(actions, k)
    maximal = model._maximal_span(identity_matrix(QQ, k).columns())
    pseudo = [model._steinitz(index, maximal.columns()) for index in range(len(model.fields))]
    one = identity_matrix(QQ, k)
    generators = [*model._automorphism_generators(pseudo), -one]
    assert all(g * F == F * g for g in generators for F in actions)
    found, _index = finite_preimage_generators(generators, lambda g: g, lambda g: g.denominator() == 1)
    result = tuple(matrix(ZZ, g) for g in found)
    assert all(g.det() in (1, -1) for g in result)
    return result or (identity_matrix(ZZ, k),)


def _summand_basis(projector):
    r"""Return an integral basis matrix (columns) of `\mathrm{image}(\epsilon) \cap Z^r`."""
    r = projector.nrows()
    complement = identity_matrix(QQ, r) - projector
    scale = complement.denominator()
    return matrix(ZZ, scale * complement).right_kernel_matrix().transpose()


def _restrict(basis, element):
    return basis.solve_right(element * basis)


def _factor(gram, isometries, projector):
    basis = _summand_basis(projector)
    factor_gram = basis.transpose() * gram * basis
    factor_isometries = [matrix(ZZ, _restrict(basis.change_ring(QQ), F.change_ring(QQ))) for F in isometries]
    return basis, matrix(ZZ, factor_gram), factor_isometries


def factorwise_centralizer_generators(commutant, centralizer_generators):
    r"""Return generators of `C(Z)` (module docstring, Centralizer); ``centralizer_generators`` is the dispatcher for the factors."""
    orbits = adjoint_orbits(commutant, central_idempotents(commutant))
    r = commutant.rank
    bases, moves = [], []
    for orbit in orbits:
        if len(orbit) == 2:
            basis, pair_moves = _pair_generators(commutant.gram, commutant.isometries, orbit)
            bases.append(basis)
            moves.extend((len(bases) - 1, c) for c in pair_moves)
            continue
        basis, gram, isometries = _factor(commutant.gram, commutant.isometries, orbit[0])
        bases.append(basis)
        for c in centralizer_generators(IsometryCommutant(gram, isometries)):
            moves.append((len(bases) - 1, matrix(QQ, c)))
    frame = block_matrix(QQ, [[b.change_ring(QQ) for b in bases]], subdivide=False)
    assert frame.is_square() and frame.det() != 0
    sizes = [b.ncols() for b in bases]

    def embed(index, c):
        blocks = [c if i == index else identity_matrix(QQ, sizes[i]) for i in range(len(sizes))]
        return frame * block_matrix(QQ, [[blocks[i] if i == j else matrix(QQ, sizes[i], sizes[j]) for j in range(len(sizes))] for i in range(len(sizes))], subdivide=False) * frame.inverse()

    embedded = [embed(i, c) for i, c in moves] + [-identity_matrix(QQ, r)]
    integral = lambda g: all(x in ZZ for x in g.list())
    subgroup, _index = finite_preimage_generators(embedded, lambda g: g, integral)
    result = tuple(matrix(ZZ, g) for g in subgroup)
    assert all(commutant.is_centralizer_element(g) for g in result)
    return result


def _discriminant_transversal(gram, generators):
    r"""Return a transversal of the group generated by ``generators`` modulo the kernel of its action on `L^\sharp / L`."""
    dual = gram.change_ring(QQ).inverse()
    one = identity_matrix(QQ, gram.nrows())
    same = lambda x, y: all(c in ZZ for c in ((~x * y - one) * dual).list())
    reps, position = [one], 0
    while position < len(reps):
        current = reps[position]
        position += 1
        for g in generators:
            moved = matrix(QQ, g) * current
            if not any(same(known, moved) for known in reps):
                reps.append(moved)
    return reps


def _number_field(polynomial):
    from sage.rings.number_field.number_field import NumberField

    return NumberField(polynomial.change_ring(QQ), "theta")


def _pair_transversal(gram, basis, moves):
    r"""Return a transversal of the group generated by ``moves`` (in the basis ``basis`` of the summand `N`) modulo the elements that preserve
    `N` and act trivially on `N^\sharp / N`."""
    local = (basis.transpose() * gram * basis).change_ring(QQ)
    dual = local.inverse()
    one = identity_matrix(QQ, local.nrows())

    def same(x, y):
        z = ~x * y
        return all(c in ZZ for c in z.list()) and z.det() in (1, -1) and all(c in ZZ for c in ((z - one) * dual).list())

    reps, position = [one], 0
    while position < len(reps):
        current = reps[position]
        position += 1
        for g in moves:
            moved = g * current
            if not any(same(known, moved) for known in reps):
                reps.append(moved)
    return reps


def _pair_transporter(commutant, target_gram, targets, start, pair):
    r"""Return ``(basis, target_basis, t0, cosets)`` for a GL-type summand, or ``None`` as a proof that no transporter exists.

    The `Z[F]`-lattices `X` and `X'` (pulled back to `X \otimes Q` by `t_0`) are isomorphic exactly when one maps onto the other by `\alpha(F)`,
    `\alpha` a unit of the etale algebra `A = Q[F]|_X` when it has dimension `\dim X`; :class:`_EtaleModel` decides this for any multiplier
    ring through the maximal order and a finite unit quotient (Eick, Hofmann, O'Brien, J. LMS 2019, arXiv:1811.06190, Sec. 3). Otherwise
    `A` is semisimple, commutative or not, and :class:`_DedekindModel` decides by the Morita reduction to `O_{K_i}`-lattices (Sec. 4). The `Y`-part
    is the contragredient `B_{X'Y'}^{-1} \alpha_X^{-t} B_{XY}`. All pair transporters are `t_0 \cdot \mathrm{diag}(a, b)` over the unitary group of the summand; the
    cosets modulo the elements preserving `X + Y` and trivial on its discriminant group decide integrality with the other factors."""
    e, image = pair
    X, Y = _summand_basis(e), _summand_basis(image)
    target_e, target_image = start * e * start.inverse(), start * image * start.inverse()
    X2, Y2 = _summand_basis(target_e), _summand_basis(target_image)
    if X.ncols() != X2.ncols() or Y.ncols() != Y2.ncols():
        return None
    k = X.ncols()
    actions = [_restrict(X.change_ring(QQ), F.change_ring(QQ)) for F in commutant.isometries]
    alpha0 = X2.change_ring(QQ).solve_right(start * X.change_ring(QQ))
    source_columns, target_columns = identity_matrix(QQ, k).columns(), alpha0.inverse().columns()
    algebra = _etale_model(actions, k)
    if algebra is not None:
        alpha = algebra.isomorphism(source_columns, target_columns)
        if alpha is None:
            return None
        action = algebra.action(alpha)
    else:
        model = _dedekind_model(actions, k)
        action = model.isomorphism(source_columns, target_columns)
        if action is None:
            return None
    alpha_x = alpha0 * action
    pairing = (X.transpose() * commutant.gram * Y).change_ring(QQ)
    target_pairing = (X2.transpose() * target_gram * Y2).change_ring(QQ)
    beta = target_pairing.inverse() * alpha_x.inverse().transpose() * pairing
    zero = lambda a, b: matrix(QQ, a, b)
    t0 = block_matrix(QQ, [[alpha_x, zero(k, Y.ncols())], [zero(Y.ncols(), k), beta]], subdivide=False)
    basis, moves = _pair_generators(commutant.gram, commutant.isometries, pair)
    target_basis = block_matrix(ZZ, [[X2, Y2]], subdivide=False)
    return basis, target_basis, t0, _pair_transversal(commutant.gram, basis, moves)


class _EtaleModel:
    r"""`A = Q[\Theta] \cong Q[x]/(f) \cong \prod_i K_i` acting on `Q^k` through a cyclic vector `v` (`p(x) \mapsto p(\Theta) v`), with lattices
    in `Q^k` read as `Z`-lattices of `A`, i.e. tuples `(a_i) \in \prod K_i`.

    Isomorphism (Eick, Hofmann, O'Brien, *The conjugacy problem in GL(n, Z)*, J. LMS 2019, arXiv:1811.06190, Sec. 3). `Z[F]`-lattices
    `X, X'` in the same rational module are isomorphic exactly when `\alpha X = X'` for some `\alpha \in A^\times` (an `A`-linear map of the
    rank-one free module `A`). Then `O_A X' = \alpha O_A X`, so in each factor the colon ideal
    `(O_A X')_i (O_A X)_i^{-1}` is principal, generated by `\alpha_{0,i}`, and `\alpha \in \alpha_0 O_A^\times`. `u \mapsto u X` depends only on the
    class of `u` modulo `\mathrm{Stab}(X) = R(X)^\times`, the units of the multiplier ring, which contains `(Z + m O_A)^\times` for
    `m O_A \subseteq R(X)`, so `O_A^\times / \mathrm{Stab}(X)` is finite (it embeds in `(O_A / \mathfrak f)^\times / (R(X)/\mathfrak f)^\times`). A
    transversal, by orbit enumeration from generators of `O_A^\times = \prod O_{K_i}^\times`, decides: `X \cong X'` exactly when `\alpha_0 u X = X'`
    for one of its elements `u`."""

    def __init__(self, theta, vector_, polynomial):
        k = theta.nrows()
        self.theta, self.polynomial = theta, polynomial
        self.krylov_inverse = block_matrix(QQ, [[theta**i * vector_ for i in range(k)]], subdivide=False).inverse()
        self.factors = [factor for factor, _e in polynomial.factor()]
        self.fields = [_number_field(factor) for factor in self.factors]

    def element(self, column):
        coefficients = list(self.krylov_inverse * column)
        return tuple(sum((QQ(c) * K.gen() ** i for i, c in enumerate(coefficients)), K(0)) for K in self.fields)

    def _flat(self, x):
        return [c for a, K in zip(x, self.fields) for c in K(a).list()]

    def _contains(self, lattice, elements):
        rows = matrix(QQ, [self._flat(y) for y in lattice])
        return all(all(c in ZZ for c in rows.solve_left(matrix(QQ, [self._flat(x)])).list()) for x in elements)

    def _times(self, u, lattice):
        return [tuple(a * b for a, b in zip(u, x)) for x in lattice]

    def _maps_onto(self, u, source, target):
        inverse = tuple(~a for a in u)
        return self._contains(target, self._times(u, source)) and self._contains(source, self._times(inverse, target))

    def isomorphism(self, source_columns, target_columns):
        r"""Return `\alpha` with `\alpha X = X'` for the lattices spanned by the columns, or ``None`` (class docstring)."""
        source = [self.element(c) for c in source_columns]
        target = [self.element(c) for c in target_columns]
        alpha0 = []
        for index, K in enumerate(self.fields):
            colon = K.ideal([x[index] for x in target]) / K.ideal([x[index] for x in source])
            if not colon.is_principal():
                return None
            alpha0.append(K(colon.gens_reduced()[0]))
        alpha0 = tuple(alpha0)
        one = tuple(K(1) for K in self.fields)
        generators = []
        for index, K in enumerate(self.fields):
            for u in K.unit_group().gens_values():
                generators.append(tuple(K(u) if i == index else L(1) for i, L in enumerate(self.fields)))
        stabilizes = lambda u: self._maps_onto(u, source, source)
        divide = lambda x, y: tuple(a / b for a, b in zip(x, y))
        transversal, position = [one], 0
        while position < len(transversal):
            current = transversal[position]
            position += 1
            for g in generators:
                moved = tuple(a * b for a, b in zip(current, g))
                if not any(stabilizes(divide(moved, known)) for known in transversal):
                    transversal.append(moved)
        for u in transversal:
            alpha = tuple(a * b for a, b in zip(alpha0, u))
            if self._maps_onto(alpha, source, target):
                return alpha
        return None

    def action(self, alpha):
        r"""Return the matrix of multiplication by ``alpha`` on `Q^k`: `p_\alpha(\Theta)`, `p_\alpha` by the Chinese remainder theorem."""
        from sage.arith.misc import CRT_list

        ring = self.polynomial.parent()
        residues = [ring(K(a).polynomial().list()) for a, K in zip(alpha, self.fields)]
        p = CRT_list(residues, list(self.factors)) if len(residues) > 1 else residues[0]
        k = self.theta.nrows()
        return sum((QQ(c) * self.theta**i for i, c in enumerate(p.list())), matrix(QQ, k, k))


def _etale_model(actions, k):
    r"""Return the :class:`_EtaleModel` of the algebra generated by ``actions`` on `Q^k` when it is commutative of dimension `k`, else ``None``.

    Then it is etale (the commutant is semisimple), equal to `Q[\Theta]` for any `\Theta` in it with squarefree characteristic polynomial of
    degree `k`, and the elements failing that lie in finitely many proper subspaces, so a growing search of integer combinations of the
    ``actions`` finds one; a vector `v` with invertible Krylov matrix is cyclic."""
    one = identity_matrix(QQ, k)
    if not all(x * y == y * x for x in actions for y in actions):
        return None
    span = [one]
    frontier = [one]
    flat = lambda m: m.list()
    while frontier:
        current = frontier.pop()
        for F in actions:
            moved = F * current
            if matrix(QQ, [flat(m) for m in span + [moved]]).rank() > len(span):
                span.append(moved)
                frontier.append(moved)
    if len(span) != k:
        return None
    bound = 1
    while True:
        for coefficients in product(range(-bound, bound + 1), repeat=len(actions)):
            theta = sum((c * F for c, F in zip(coefficients, actions)), matrix(QQ, k, k))
            polynomial = theta.charpoly()
            if polynomial.is_squarefree():
                for column in [*one.columns(), sum(one.columns())]:
                    v = matrix(QQ, k, 1, list(column))
                    if block_matrix(QQ, [[theta**i * v for i in range(k)]], subdivide=False).det() != 0:
                        return _EtaleModel(theta, v, polynomial)
                for coefficients_v in product(range(-bound, bound + 1), repeat=k):
                    v = matrix(QQ, k, 1, list(coefficients_v))
                    if block_matrix(QQ, [[theta**i * v for i in range(k)]], subdivide=False).det() != 0:
                        return _EtaleModel(theta, v, polynomial)
        bound += 1


class _DedekindModel:
    r"""`V = X \otimes Q` as a module over the semisimple `B = Q[F]|_X` with centre `Q[\Theta] = \prod_i K_i`: `V = \bigoplus_i V_i`,
    `V_i = \epsilon_i V`, `\epsilon_i = \epsilon_i(\Theta)` from the Chinese remainder theorem, `B_i = \epsilon_i B \cong M_{n_i}(K_i)` with matrix
    units `e_{ab}` (:meth:`_split`; `e_{11} = \epsilon_i` when `B_i = K_i`).

    Morita reduction (Eick, Hofmann, O'Brien, *The conjugacy problem in GL(n, Z)*, J. LMS 2019, arXiv:1811.06190, Sec. 4).
    `\Gamma = \bigoplus_{i, a, b} O_{K_i} e_{ab}` is an order (a maximal one, `\cong \prod M_{n_i}(O_{K_i})`), and `M = \Gamma X` is a
    `\Gamma`-lattice with `M = \bigoplus_{i, a} e_{a1} N_i`, `N_i = e_{11} M` an `O_{K_i}`-lattice in the `K_i`-space `e_{11} V_i \cong K_i^{d_i}`.
    `\mathrm{End}_B(V_i) \cong \mathrm{End}_{K_i}(e_{11} V_i)` by `h \mapsto (e_{a1} w \mapsto e_{a1} h w)`, and a `B`-linear `g` maps `M` onto `M'`
    exactly when its restrictions map `N_i` onto `N'_i`. So `N_i \cong O_{K_i}^{d_i - 1} \oplus \mathfrak a_i` (Steinitz; Cohen, *Advanced
    Topics*, Thm. 1.2.19), the class of `\mathfrak a_i` its only invariant. PARI ``nfhnf`` gives a pseudo-basis and ``rnfsteinitz`` puts it in
    the form `(v_1, \ldots, v_d; O, \ldots, O, \mathfrak a)`. With `\mathfrak a' = \gamma \mathfrak a`, the `K_i`-linear `v_j \mapsto v'_j`
    (`j < d`), `v_d \mapsto \gamma v'_d` maps `N_i` onto `N'_i`; when some class differs there is none. A lattice `X \subsetneq M` is decided
    through a finite orbit (:meth:`isomorphism`). A quaternion division component `B_i = D` with `V_i \cong D` contributes a maximal order `O`
    of `D` to `\Gamma` and is decided by the left `O`-ideal `W^{-1}(\epsilon_i M)` (:meth:`_division_transport`)."""

    def __init__(self, theta, polynomial, algebra_basis):
        self.theta = theta
        k = theta.nrows()
        self.factors = [factor for factor, _e in polynomial.factor()]
        self.fields = [_number_field(factor) for factor in self.factors]
        evaluate = lambda q: sum((QQ(c) * theta**i for i, c in enumerate(q.list())), matrix(QQ, k, k))
        self.evaluate = evaluate
        self.idempotents, self.units, self.frames, self.division = [], [], [], {}
        for index, factor in enumerate(self.factors):
            cofactor = polynomial // factor
            self.idempotents.append(evaluate((cofactor * cofactor.inverse_mod(factor)) % polynomial))
            self.units.append(self._split(index, algebra_basis))
            if index in self.division:
                self.frames.append(None)
                continue
            first = self.units[index][0][0]
            degree = factor.degree()
            columns, frame = [], []
            for w in first.columns():
                w = matrix(QQ, k, 1, list(w))
                block = [theta**j * w for j in range(degree)]
                if matrix(QQ, [list(c.column(0)) for c in columns + block]).rank() == len(columns) + degree:
                    columns.extend(block)
                    frame.append(w)
            assert len(columns) == first.rank()
            self.frames.append((frame, block_matrix(QQ, [columns], subdivide=False)))

    def _embed(self, index, c):
        r"""Return the matrix of `c \in K_i` on `V`: `c(\Theta) \epsilon_i`."""
        K, ring = self.fields[index], self.factors[index].parent()
        return self.evaluate(ring(K(c).polynomial().list())) * self.idempotents[index]

    def _solve(self, index, y, elements):
        r"""Return `c_s \in K_i` with `y = \sum_s c_s m_s` for the ``elements`` `m_s \in B_i` (an exact solution is asserted)."""
        K, degree = self.fields[index], self.factors[index].degree()
        columns = matrix(QQ, [(self.theta**j * m).list() for m in elements for j in range(degree)]).transpose()
        solution = columns.solve_right(vector(QQ, y.list()))
        assert columns * solution == vector(QQ, y.list())
        return [sum((solution[s * degree + j] * K.gen() ** j for j in range(degree)), K(0)) for s in range(len(elements))]

    def _split(self, index, algebra_basis):
        r"""Return matrix units `[[e_{ab}]]` of `B_i \cong M_n(K_i)`.

        `n = 1`: `e_{11} = \epsilon_i`. `n = 2`: a noncentral `a` satisfies `a^2 = t a - s` over `K = K_i`, so `i = a - t/2` has `i^2 = \alpha \in K`;
        for `x` with `j = x - i x i^{-1} \ne 0`, `ij = -ji` and `j^2 = \beta \in K`, so `B_i = (\alpha, \beta)_K`. It is split exactly when the conic
        `\alpha x^2 + \beta y^2 = z^2` has a `K`-point (Voight, *Quaternion Algebras*, Thm. 5.4.4); otherwise it is a division algebra, recorded by
        :meth:`_quaternion`, and ``None`` is returned. When split, `w = x i + y j` has `w^2 = z^2`, and
        `u = w + z \ne 0` is a zero divisor (`u (w - z) = 0`). Some `p = u y`, `y` in `\{1, i, j, ij\}` or the `Q`-basis of `B_i`, has nonzero
        reduced trace `\tau` (the trace form is nondegenerate and the `Q`-basis spans `B_i`) and reduced rank one, so `p^2 = \tau p` and `e_{11} = p / \tau` is a rank-one idempotent; `e_{22} = 1 - e_{11}`,
        `e_{12} = e_{11} x e_{22} \ne 0`, `f = e_{22} x' e_{11} \ne 0`, `e_{12} f = c e_{11}`, `e_{21} = c^{-1} f`."""
        from sage.schemes.plane_conics.constructor import Conic

        K, degree, idempotent = self.fields[index], self.factors[index].degree(), self.idempotents[index]
        rows = matrix(QQ, [(idempotent * b).list() for b in algebra_basis]).row_space().basis()
        k = idempotent.nrows()
        component = [matrix(QQ, k, k, list(r)) for r in rows]
        assert len(component) % degree == 0 and ZZ(len(component) // degree).is_square()
        n = ZZ(len(component) // degree).isqrt()
        if n == 1:
            return [[idempotent]]
        if n == 3:
            return self._split_cubic(index, component)
        if n > 3:
            raise NotImplementedError(
                f"Wedderburn component of dimension {n}^2 over {K}: explicit matrix units of a central simple algebra of degree n >= 4 need the "
                f"splitting algorithm of Ivanyos, Ronyai and Schicho (J. Algebra 2012), which is not implemented (#54)"
            )
        a = next(b for b in component if any(b * c != c * b for c in component))
        t, s = self._solve(index, a * a, [a, idempotent])
        i = a - self._embed(index, t / 2)
        (alpha,) = self._solve(index, i * i, [idempotent])
        i_inverse = self._embed(index, ~alpha) * i
        j = next(m for m in (x - i * x * i_inverse for x in component) if not m.is_zero())
        (beta,) = self._solve(index, j * j, [idempotent])
        found, point = Conic(K, [alpha, beta, -1]).has_rational_point(point=True)
        if not found:
            self._quaternion(index, alpha, beta, i, j)
            return None
        x, y, z = (K(c) for c in point)
        u = self._embed(index, x) * i + self._embed(index, y) * j + self._embed(index, z)
        first = None
        for factor in (idempotent, i, j, i * j, *component):
            p = u * factor
            if p.is_zero():
                continue
            (tau,) = self._solve(index, p * p, [p])
            if tau != 0:
                first = self._embed(index, ~tau) * p
                break
        assert first is not None, f"no u y with nonzero reduced trace for the zero divisor u of ({alpha}, {beta})_{K}"
        second = idempotent - first
        upper = next(m for m in (first * b * second for b in component) if not m.is_zero())
        lower = next(m for m in (second * b * first for b in component) if not m.is_zero())
        (c,) = self._solve(index, upper * lower, [first])
        lower = self._embed(index, ~c) * lower
        units = [[first, upper], [lower, second]]
        assert all(units[p][q] * units[q2][r] == (units[p][r] if q == q2 else 0 * idempotent) for p in range(2) for q in range(2) for q2 in range(2) for r in range(2))
        return units

    def _k_rank(self, index, elements):
        r"""Return the `K_i`-dimension of the `K_i`-span of the ``elements`` of `B_i`."""
        degree = self.factors[index].degree()
        if not elements:
            return 0
        return matrix(QQ, [(self.theta**j * m).list() for m in elements for j in range(degree)]).rank() // degree

    def _k_minimal_polynomial(self, index, x):
        r"""Return the minimal polynomial over `K_i` of ``x`` `\in B_i`."""
        K = self.fields[index]
        ring = PolynomialRing(K, "y")
        powers = [self.idempotents[index]]
        while self._k_rank(index, powers + [powers[-1] * x]) > len(powers):
            powers.append(powers[-1] * x)
        coefficients = self._solve(index, powers[-1] * x, powers)
        return ring.gen() ** len(powers) - sum(c * ring.gen() ** s for s, c in enumerate(coefficients))

    def _field_matrix(self, index, x, value):
        r"""Return the matrix of ``value`` `\in L = K_i[x]` (coefficients over `K_i` in the powers of the generator) at ``x``."""
        result, power = 0 * x, self.idempotents[index]
        for c in value.list():
            result += self._embed(index, c) * power
            power = power * x
        return result

    def _units_from_zero_divisor(self, index, z, component, n):
        r"""Return matrix units of `B_i \cong M_n(K_i)` from a zero divisor `z \ne 0`.

        `B_i` is von Neumann regular, so `z y z = z` has a solution `y` (linear over `Q`) and `e = z y` is an idempotent with `e B_i = z B_i`,
        of reduced rank `r = \dim_K e B_i / n`. For `n = 3` one of `e, 1 - e` has reduced rank one. For a rank-one `e`, `e B e = K e`, and the pairing
        `e B \times B e \to K e` is perfect; with `K`-bases `r_a` of `e B` and `c_b` of `B e`, `r_a c_b = G_{ab} e`, and the dual basis `c'_b = \sum_s
        c_s (G^{-1})_{sb}`, the `e_{ab} = c'_a r_b` are matrix units (`e_{ab} e_{cd} = c'_a (r_b c'_c) r_d = \delta_{bc} e_{ad}`, as `e r_d = r_d`)."""
        idempotent = self.idempotents[index]
        K = self.fields[index]
        columns = matrix(QQ, [(z * b * z).list() for b in component]).transpose()
        solution = columns.solve_right(vector(QQ, z.list()))
        e = z * sum((c * b for c, b in zip(solution, component)), 0 * z)
        assert e * e == e and e * z == z
        if self._k_rank(index, [e * b for b in component]) != n:
            e = idempotent - e
        assert self._k_rank(index, [e * b for b in component]) == n
        rows, cols = [e], []
        for b in component:
            if len(rows) < n and self._k_rank(index, rows + [e * b]) > len(rows):
                rows.append(e * b)
            if len(cols) < n and self._k_rank(index, cols + [b * e]) > len(cols):
                cols.append(b * e)
        assert len(rows) == n and len(cols) == n
        gram = matrix(K, n, n, [self._solve(index, r * c, [e])[0] for r in rows for c in cols])
        inverse = gram.inverse()
        duals = [sum((self._embed(index, inverse[s, b]) * cols[s] for s in range(n)), 0 * z) for b in range(n)]
        units = [[duals[a] * rows[b] for b in range(n)] for a in range(n)]
        assert sum(units[a][a] for a in range(n)) == idempotent
        assert all(units[a][b] * units[c][d] == (units[a][d] if b == c else 0 * z) for a in range(n) for b in range(n) for c in range(n) for d in range(n))
        return units

    def _split_cubic(self, index, component):
        r"""Return matrix units of a degree-three component `B_i`, or raise when it is a division algebra or no cyclic maximal subfield is found.

        For `x \in B_i` with minimal polynomial `f` over `K = K_i`: a reducible `f = g h` gives the zero divisor `g(x)`. An irreducible cubic `f`
        gives the maximal subfield `L = K(x)`; when `L / K` is cyclic (`f` has three roots in `L`), `\sigma(x) = s(x)` for a root `s \ne x`, and
        Skolem-Noether gives `u` with `u x = s(x) u` (a linear equation). Then `B_i = (L/K, \sigma, a)` with `a = u^3 \in K`, which splits exactly
        when `a = N_{L/K}(y)` (Pierce, *Associative Algebras*, Sec. 15.1), decided by PARI ``rnfisnorm``. Then `w = y^{-1} u` has
        `w^3 = N(y)^{-1} a = 1` and `w \notin K`, so `w - 1` is a zero divisor (:meth:`_units_from_zero_divisor`). The trial elements are the
        `Q`-basis of `B_i`, their pairwise sums and their products."""
        K = self.fields[index]
        candidates = [*component, *(b + c for s, b in enumerate(component) for c in component[s + 1 :]), *(b * c for b in component for c in component)]
        for x in candidates:
            if all(x * b == b * x for b in component):
                continue
            f = self._k_minimal_polynomial(index, x)
            factors = f.factor()
            if len(factors) > 1 or factors[0][1] > 1:
                z = self._field_matrix(index, x, factors[0][0])
                return self._units_from_zero_divisor(index, z, component, 3)
            L = K.extension(f, "l")
            roots = [r for r, _m in f.change_ring(L).roots() if r != L.gen()]
            if len(roots) != 2:
                continue
            sigma = self._field_matrix(index, x, roots[0])
            equations = matrix(QQ, [(b * x - sigma * b).list() for b in component])
            kernel = equations.left_kernel().basis()
            u = sum((c * b for c, b in zip(kernel[0], component)), 0 * x)
            (a,) = self._solve(index, u * u * u, [self.idempotents[index]])
            found, y = K(a).is_norm(L, element=True)
            if not found:
                raise NotImplementedError(
                    f"Wedderburn component (L/K, sigma, {a}) with L = {L} is a cubic division algebra over {K}: lattices over its orders "
                    f"are not classified by this route (#54)"
                )
            w = self._field_matrix(index, x, ~L(y)) * u
            return self._units_from_zero_divisor(index, w - self.idempotents[index], component, 3)
        raise NotImplementedError(
            f"no cyclic maximal subfield of the degree-three component over {K} among the trial elements: explicit matrix units need the "
            f"splitting algorithm of Ivanyos, Ronyai and Schicho (J. Algebra 2012), which is not implemented (#54)"
        )

    def _quaternion(self, index, alpha, beta, i, j):
        r"""Record the division component `B_i = D = (\alpha, \beta)_K` (:meth:`_split`): the Sage algebra with integral `c^2 \alpha, c'^2 \beta`
        for `c i, c' j`, a maximal order `O` containing `O_K \langle 1, ci, c'j, cc'ij \rangle`
        (:func:`~sage_indefinite_port.indefinite.quaternion_orders_number_field.maximal_orders_containing`, discriminant `|d_K|^4 N(\mathfrak D)^2`)
        and `W : D \to V_i`, `b \mapsto b w`, an isomorphism of left `D`-modules when `V_i \cong D` (`d = 1`)."""
        from sage.algebras.quatalg.quaternion_algebra import QuaternionAlgebra
        from sage_indefinite_port.indefinite.quaternion_orders_number_field import OrderLattices, maximal_orders_containing

        K, degree, idempotent = self.fields[index], self.factors[index].degree(), self.idempotents[index]
        if idempotent.rank() != 4 * degree:
            raise NotImplementedError(
                f"X (x) Q contains D^d, d = {idempotent.rank() // (4 * degree)} >= 2, for the quaternion division component ({alpha}, {beta})_{K}: "
                f"deciding O X = O X' needs an explicit decomposition O X = O^(d-1) + I over the maximal order O (Eichler cancellation), "
                f"which is not implemented (#54)"
            )
        c, c2 = alpha.denominator(), beta.denominator()
        i, j = self._embed(index, K(c)) * i, self._embed(index, K(c2)) * j
        algebra = QuaternionAlgebra(K, c**2 * alpha, c2**2 * beta)
        units = [idempotent, i, j, i * j]
        lattices = OrderLattices(algebra)
        gens = [algebra(1), *algebra.gens()]
        order = [algebra(K(w)) * g for w in K.ring_of_integers().basis() for g in gens]
        norm = ZZ(1)
        for prime in algebra.ramified_places(inf=False):
            norm *= ZZ(prime.norm())
        maximal = maximal_orders_containing(algebra, order, abs(ZZ(K.discriminant())) ** 4 * norm**2)[0]
        k = idempotent.nrows()
        w = next(matrix(QQ, k, 1, list(v)) for v in idempotent.columns() if not v.is_zero())
        self.division[index] = (algebra, lattices, maximal, units, w, None)
        image = block_matrix(QQ, [[self._quaternion_matrix(index, q) * w for q in lattices._q_basis]], subdivide=False)
        assert image.rank() == 4 * degree
        self.division[index] = (algebra, lattices, maximal, units, w, image)

    def _quaternion_matrix(self, index, x):
        r"""Return the matrix on `V` of `x \in D` (left multiplication on `V_i`, zero on the other `V_j`)."""
        algebra, _lattices, _maximal, units, _w, _image = self.division[index]
        return sum((self._embed(index, c) * u for c, u in zip(algebra(x).coefficient_tuple(), units)), 0 * units[0])

    def _ideal(self, index, columns):
        r"""Return a `Z`-basis of `I = W^{-1}(\epsilon_i M) \subset D` for `M` spanned by the columns of ``columns``, a left `O`-ideal."""
        _algebra, lattices, _maximal, _units, _w, image = self.division[index]
        coordinates = image.solve_right(self.idempotents[index] * columns)
        return lattices.basis([lattices.element(c) for c in coordinates.columns()])

    def _right_multiplication(self, index, delta):
        r"""Return the `B`-linear map of `V` that is `W (b \mapsto b \delta) W^{-1}` on `V_i` and the identity on the other `V_j`."""
        _algebra, lattices, _maximal, _units, w, image = self.division[index]
        moved = block_matrix(QQ, [[self._quaternion_matrix(index, q * delta) * w for q in lattices._q_basis]], subdivide=False)
        epsilon = self.idempotents[index]
        return identity_matrix(QQ, epsilon.nrows()) - epsilon + moved * image.solve_right(epsilon)

    def _division_transport(self, index, maximal, target_maximal):
        r"""Return ``(phi, generators)`` for a division component with `d = 1`, or ``None`` when `\epsilon_i M \not\cong \epsilon_i M'`.

        `\mathrm{End}_D(D) = D^{op}`, so the `B`-linear maps of `V_i` are `W (b \mapsto b \delta) W^{-1}`, and `\epsilon_i M \cong \epsilon_i M'` exactly
        when `I' = I \delta` for the left `O`-ideals `I, I'` (:meth:`_ideal`). Then `\delta` lies in the colon `(I : I') = \{x : I x \subseteq I'\} =
        I^{-1} I'`, an invertible left `O_R(I)`-ideal of reduced norm `\mathrm{nrd}(I') \mathrm{nrd}(I)^{-1}`, and any element of that reduced norm
        generates it (Voight, *Quaternion Algebras*, Sec. 16.6, 17.4), so `I x = I I^{-1} I' = I'`. ``norm_generator`` of the unit engine of the
        maximal order `O_R(I)` finds such an element or proves there is none. `\mathrm{Aut}_O(I)` is right multiplication by `O_R(I)^\times`."""
        from sage_indefinite_port.indefinite.clifford_commutant import _reduced_norm_ideal
        from sage_indefinite_port.indefinite.fuchsian_domain import quaternion_unit_engine

        algebra, lattices, _maximal, _units, _w, _image = self.division[index]
        K = self.fields[index]
        source, target = self._ideal(index, maximal), self._ideal(index, target_maximal)
        inverse = matrix(QQ, [lattices.coordinates(b) for b in target]).inverse()
        rows = []
        for b in source:
            rows.extend((matrix(QQ, [lattices.coordinates(b * q) for q in lattices._q_basis]) * inverse).columns())
        colon = lattices._dual(matrix(QQ, rows))
        engine = quaternion_unit_engine(algebra, lattices.right_order(source))
        delta = engine.norm_generator(colon, _reduced_norm_ideal(K, target) / _reduced_norm_ideal(K, source))
        if delta is None:
            return None
        assert lattices.key([b * delta for b in source]) == lattices.key(target)
        return self._right_multiplication(index, delta), [self._right_multiplication(index, u) for u in engine.unit_generators()]

    def _component_basis(self, index, vectors):
        r"""Return the columns `\Theta^j e_{a1} v_l` (`a, l, j`) spanning `V_i` for a `K_i`-basis ``vectors`` of `e_{11} V_i`."""
        degree = self.factors[index].degree()
        columns = [self.theta**j * row[0] * v for row in self.units[index] for v in vectors for j in range(degree)]
        return block_matrix(QQ, [columns], subdivide=False)

    def _coordinates(self, index, column):
        r"""Return the `K_i`-coordinates of ``column`` `\in e_{11} V_i` on the frame `w_1, \ldots, w_{d_i}`."""
        K = self.fields[index]
        frame, basis = self.frames[index]
        degree = self.factors[index].degree()
        c = basis.solve_right(matrix(QQ, len(column), 1, list(column))).column(0)
        return [sum((c[l * degree + j] * K.gen() ** j for j in range(degree)), K(0)) for l in range(len(frame))]

    def _maximal_span(self, columns):
        r"""Return a `Z`-basis (columns) of `M = \Gamma X` for `X` spanned by ``columns``."""
        generated = []
        for index, K in enumerate(self.fields):
            if index in self.division:
                operators = [self._quaternion_matrix(index, o) for o in self.division[index][2]]
            else:
                operators = [self._embed(index, w) * unit for w in K.ring_of_integers().basis() for row in self.units[index] for unit in row]
            for operator in operators:
                generated.extend(operator * matrix(QQ, len(c), 1, list(c)) for c in columns)
        return _lattice_basis([list(g.column(0)) for g in generated])

    def _steinitz(self, index, columns):
        r"""Return ``(vectors, ideal)``: `K_i`-coordinate columns `v_1, \ldots, v_d` and `\mathfrak a` with `N_i = \bigoplus_{j<d} O v_j \oplus \mathfrak a v_d`
        for the `\Gamma`-module `M` spanned by ``columns``."""
        K = self.fields[index]
        nf = K.pari_nf()
        first = self.units[index][0][0]
        projected = [self._coordinates(index, (first * matrix(QQ, len(c), 1, list(c))).column(0)) for c in columns]
        d = len(projected[0])
        generators = pari.matrix(d, len(projected), [projected[j][i].__pari__() for i in range(d) for j in range(len(projected))])
        hnf = nf.nfhnf([generators, pari([1] * len(projected))])
        steinitz = nf.rnfsteinitz(hnf)
        to_field = lambda c: K(nf.nfbasistoalg(c))
        vectors = matrix(K, d, d, [to_field(steinitz[0][i, j]) for i in range(d) for j in range(d)])
        ideals = []
        for j in range(d):
            hermite = nf.idealhnf(steinitz[1][j])
            ideals.append(K.ideal([to_field(hermite[i]) for i in range(len(hermite))]))
        assert all(ideal == K.ideal(1) for ideal in ideals[:-1])
        return vectors, ideals[-1]

    def _rational(self, index, g):
        r"""Return the matrix on `V` of the `B`-linear map restricting to the `K_i`-linear map with frame matrix ``g`` on `e_{11} V_i`, the
        identity on the other `V_j`."""
        k = self.theta.nrows()
        frame, _basis = self.frames[index]
        basis = self._component_basis(index, frame)
        mapped = [sum((self._embed(index, g[m, l]) * frame[m] for m in range(len(frame))), matrix(QQ, k, 1)) for l in range(len(frame))]
        epsilon = self.idempotents[index]
        return identity_matrix(QQ, k) - epsilon + self._component_basis(index, mapped) * basis.solve_right(epsilon)

    def _automorphism_generators(self, index, vectors, last):
        r"""Return generators of `\mathrm{Aut}_{O_{K_i}}(N_i)` on `V`, ``(vectors, last)`` the Steinitz pseudo-basis of `N_i`.

        In the pseudo-basis `(v_j; \mathfrak a_j)` an automorphism of `e_i M` is a matrix with entries `g_{jl} \in \mathfrak a_j \mathfrak a_l^{-1}` and
        unit determinant. `\mathrm{SL}` is generated by the elementary `1 + b E_{jl}`, `b \in \mathfrak a_j \mathfrak a_l^{-1}` (Bass, Milnor, Serre,
        Publ. IHES 33 (1967), for `d \ge 3`; Vaserstein, Ann. Math. 96 (1972), for `d = 2` and `O_K^\times` infinite; for `d = 2` with finitely many
        units, i.e. `K = Q` (Euclidean) or imaginary quadratic, Cohn, Publ. IHES 30 (1966): only the Euclidean imaginary quadratic rings),
        and `\mathrm{GL}` by these with `\mathrm{diag}(1, \ldots, u, \ldots, 1)` for generators `u` of `O_K^\times`. A `Z`-basis of
        `\mathfrak a_j \mathfrak a_l^{-1}` suffices, since `1 + (b + b') E_{jl} = (1 + b E_{jl})(1 + b' E_{jl})`."""
        result = []
        K = self.fields[index]
        d = vectors.nrows()
        if d == 2 and K.degree() <= 2 and not K.is_totally_real() and abs(K.discriminant()) not in (3, 4, 7, 8, 11):
            raise NotImplementedError(
                f"GL_2 of the order of {K}, imaginary quadratic and not Euclidean, is not generated by elementary and diagonal "
                f"matrices (Cohn 1966); its generators (Swan, Adv. Math. 6 (1971)) are not implemented (#54)"
            )
        ideals = [K.ideal(1)] * (d - 1) + [last]
        frame = lambda g: vectors * g * vectors.inverse()
        for j in range(d):
            for u in K.unit_group().gens_values():
                g = matrix.identity(K, d)
                g[j, j] = K(u)
                result.append(self._rational(index, frame(g)))
            for l in range(d):
                if l == j:
                    continue
                for b in (ideals[j] / ideals[l]).basis():
                    g = matrix.identity(K, d)
                    g[j, l] = K(b)
                    result.append(self._rational(index, frame(g)))
        return result

    def isomorphism(self, source_columns, target_columns):
        r"""Return the matrix on `V` of an `A`-linear `g` with `g X = X'` for the lattices spanned by the columns, or ``None``.

        `M = O_A X`, `M' = O_A X'`. An isomorphism `X \to X'` extends to one `M \to M'`, so the Steinitz classes of the `e_i M` and `e_i M'` agree
        (class docstring), giving `\varphi_0 : M \to M'`. Every isomorphism is `\varphi_0 g`, `g \in \mathrm{Aut}_{O_A}(M)`, and it maps `X` onto
        `X'` exactly when `g X = \varphi_0^{-1} X'`. With `m M \subseteq X` and `m M \subseteq \varphi_0^{-1} X'`, `g X` depends only on `g` modulo
        `m \mathrm{End}(M)`, so the orbit of the finite submodule `X / m M \subseteq M / m M` under the generators of
        :meth:`_automorphism_generators` and :meth:`_division_transport` is finite and its search decides (Eick, Hofmann, O'Brien, arXiv:1811.06190, Sec. 4)."""
        source = matrix(QQ, source_columns).transpose()
        target = matrix(QQ, target_columns).transpose()
        maximal = self._maximal_span(source_columns)
        target_maximal = self._maximal_span(target_columns)
        phi0, generators = [], []
        for index, K in enumerate(self.fields):
            if index in self.division:
                found = self._division_transport(index, maximal, target_maximal)
                if found is None:
                    return None
                phi0.append(found[0])
                generators.extend(found[1])
                continue
            vectors, ideal = self._steinitz(index, maximal.columns())
            target_vectors, target_ideal = self._steinitz(index, target_maximal.columns())
            ratio = target_ideal / ideal
            if not ratio.is_principal():
                return None
            gamma = K(ratio.gens_reduced()[0])
            d = vectors.nrows()
            scale = matrix(K, d, d, lambda i, j: (gamma if i == d - 1 else K(1)) if i == j else K(0))
            phi0.append(self._rational(index, target_vectors * scale * vectors.inverse()))
            generators.extend(self._automorphism_generators(index, vectors, ideal))
        transport = matrix.identity(QQ, source.nrows())
        for g in phi0:
            transport = g * transport
        moved = target_maximal.solve_right(transport * maximal)
        assert all(c in ZZ for c in moved.list()) and moved.det() in (1, -1)
        pulled = transport.inverse() * target
        exponent = lcm([source.solve_right(maximal).denominator(), pulled.solve_right(maximal).denominator()])

        def key(lattice):
            coordinates = maximal.solve_right(lattice)
            assert all(c in ZZ for c in coordinates.list())
            rows = matrix(ZZ, coordinates.transpose()).stack(exponent * matrix.identity(ZZ, maximal.ncols()))
            return tuple(rows.hermite_form(include_zero_rows=False).list())

        goal = key(pulled)
        one = matrix.identity(QQ, source.nrows())
        orbit = {key(source): one}
        if goal in orbit:
            return transport
        frontier = [one]
        while frontier:
            current = frontier.pop()
            for g in generators:
                element = g * current
                point = key(element * source)
                if point in orbit:
                    continue
                orbit[point] = element
                if point == goal:
                    action = transport * element
                    image = target.solve_right(action * source)
                    assert all(c in ZZ for c in image.list()) and image.det() in (1, -1)
                    return action
                frontier.append(element)
        return None


def _lattice_basis(vectors):
    r"""Return the Hermite basis (columns) of the `Z`-span of the rational ``vectors``."""
    rows = matrix(QQ, vectors)
    scale = rows.denominator()
    hermite = matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale
    return hermite.transpose()


def _dedekind_model(actions, k):
    r"""Return the :class:`_DedekindModel` of the semisimple algebra `B` generated by ``actions`` on `Q^k`. Its centre is the kernel of
    `z \mapsto ([z, F])_F` on a `Q`-basis of `B`, and `\Theta` is an integer combination of a centre basis with squarefree minimal polynomial of
    degree the dimension of the centre (a primitive element of the etale centre)."""
    one = identity_matrix(QQ, k)
    span, frontier = [one], [one]
    while frontier:
        current = frontier.pop()
        for F in actions:
            moved = F * current
            if matrix(QQ, [m.list() for m in span + [moved]]).rank() > len(span):
                span.append(moved)
                frontier.append(moved)
    commutators = matrix(QQ, len(span), len(actions) * k * k, [c for m in span for F in actions for c in (m * F - F * m).list()])
    center = [sum((c * m for c, m in zip(v, span)), matrix(QQ, k, k)) for v in commutators.left_kernel().basis()]
    bound = 1
    while True:
        for coefficients in product(range(-bound, bound + 1), repeat=len(center)):
            theta = sum((c * z for c, z in zip(coefficients, center)), matrix(QQ, k, k))
            polynomial = theta.minimal_polynomial()
            if polynomial.degree() == len(center) and polynomial.is_squarefree():
                return _DedekindModel(theta, polynomial, span)
        bound += 1


def factorwise_transporter(commutant, target_gram, targets, start, transporter, centralizer_generators):
    r"""Return an integral transporter to ``(target_gram, targets)`` or ``None`` as a proof (module docstring, Transporter)."""
    from sage_indefinite_port.indefinite.commutant_groups import _verified

    orbits = adjoint_orbits(commutant, central_idempotents(commutant))
    factors = []
    for orbit in orbits:
        if len(orbit) == 2:
            pair = _pair_transporter(commutant, target_gram, targets, start, orbit)
            if pair is None:
                return None
            factors.append(pair)
            continue
        projector = orbit[0]
        basis, gram, isometries = _factor(commutant.gram, commutant.isometries, projector)
        image = start * projector * start.inverse()
        target_basis, factor_target_gram, factor_targets = _factor(target_gram, targets, image)
        if abs(gram.det()) != abs(factor_target_gram.det()):
            return None
        factor_commutant = IsometryCommutant(gram, isometries)
        t0 = transporter(factor_commutant, factor_target_gram, factor_targets)
        if t0 is None:
            return None
        cosets = _discriminant_transversal(gram, centralizer_generators(factor_commutant))
        factors.append((basis, target_basis, matrix(QQ, t0), cosets))
    frame = block_matrix(QQ, [[f[0].change_ring(QQ) for f in factors]], subdivide=False)
    target_frame = block_matrix(QQ, [[f[1].change_ring(QQ) for f in factors]], subdivide=False)
    sizes = [f[0].ncols() for f in factors]
    for choice in product(*(f[3] for f in factors)):
        blocks = [f[2] * c for f, c in zip(factors, choice)]
        diagonal = block_matrix(
            QQ,
            [[blocks[i] if i == j else matrix(QQ, sizes[i], sizes[j]) for j in range(len(sizes))] for i in range(len(sizes))],
            subdivide=False,
        )
        candidate = target_frame * diagonal * frame.inverse()
        found = _verified(commutant, candidate, target_gram, targets)
        if found is not None:
            return found
    return None
