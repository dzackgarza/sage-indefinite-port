r"""Generators of `\mathrm{GL}_2(O_K)` and of `\mathrm{GL}(O_K \oplus \mathfrak a)` for `K` imaginary quadratic (#54).

Swan's method (R. G. Swan, *Generators and relations for certain special linear groups*, Adv. Math. 6 (1971) 1-77; as implemented by
Rahm and Fuchs, *Bianchi.gp*, and described in A. D. Rahm, *Higher torsion in the Abelianization of the full Bianchi groups*, LMS J. Comput.
Math. 16 (2013)). `H^3 = C \times R_{>0}`. A unimodular pair `(\mu, \lambda)`, `(\mu, \lambda) = O`, `\mu \ne 0`, gives the hemisphere
`S_{\mu, \lambda}` of centre `\lambda / \mu` and radius `1 / |\mu|`, the isometric sphere of `g_{\mu,\lambda} = [[\lambda^*, \nu], [-\mu, \lambda]]`
(`\lambda \lambda^* + \nu \mu = 1`). `B` is the set of points on or above every hemisphere; its part over a fundamental domain `P` of the
translations `O` is a fundamental domain of `\mathrm{SL}_2(O)` modulo the stabilizer of `\infty`, and `\mathrm{SL}_2(O)` is generated by that
stabilizer and the `g_{\mu,\lambda}` of the hemispheres bounding `B` (Swan, Sec. 2-4).

Coordinates. `O = Z + Z \omega`, `\omega = (D + \sqrt D) / 2`, `D` the discriminant, embedded with `\sqrt D \mapsto i \sqrt{|D|}`, so
`a + b \omega \mapsto (a + b D / 2, b \sqrt{|D|} / 2)`. `P` is the parallelogram `\{p + q \omega : 0 \le p, q \le 1\}`.

Singular points. `s \in K` is strictly below `S_{\mu', \lambda'}` exactly when `|\mu' s - \lambda'| < 1`. Write `s = \lambda / \mu` with
`\mathfrak a = (\lambda, \mu)`; then `\mu' s - \lambda' = \nu / \mu` with `\nu = \mu' \lambda - \lambda' \mu`, and as `(\mu', \lambda')` runs over
the unimodular pairs, `\nu` runs over the nonzero elements of `\mathfrak a` that are the second entry of a generating pair of `\mathfrak a`
(the bottom row of `g \in \mathrm{SL}_2(O)` applied to `(\lambda, \mu)`), i.e. over every nonzero `\nu \in \mathfrak a`. So `s` is not strictly covered
(singular) exactly when `\mathfrak a` is not principal and `N(\mu) = \min_{0 \ne \nu \in \mathfrak a} N(\nu)` (Swan, Sec. 3). Normalizing
`\mathfrak a` to a fixed integral representative of its class, the singular points modulo `O` are the `\lambda / \mu` with `\mu` of minimal norm
in `\mathfrak a` and `\lambda \in \mathfrak a / \mu O`, `(\lambda, \mu) = \mathfrak a` (:meth:`BianchiGroup.singular_points`).

Covering (Swan's termination criterion). The hemispheres with `N(\mu) \le b` are enumerated for `b = 1, 2, \ldots` until every point of `P`
lies strictly below one of them or is singular. The decision is exact, by interval arithmetic (``RealIntervalField``): a closed box of `P`
is certified by a hemisphere with `\sup_{z} |z - c|^2 < r^2` over the box; a singular point `s` is certified by the hemispheres through `s`
(`|\mu s - \lambda| = 1`), which contain `s + t w` for `0 < t < 2 \mathrm{Re}(w \bar v) / |w|^2`, `v = c - s`; a lower bound `\rho_s > 0` of
`\max_v 2 \mathrm{Re}(w \bar v) / |w|^2` over the directions `w` on the unit square in `(p, q)` certifies the punctured square of half-width `\rho_s`
(:meth:`BianchiGroup._punctured_radius`), and boxes inside it are accepted. Boxes are bisected up to a depth growing with `b`; a failure
only raises `b`.

Completion. A certified box also bounds the height of the floor of `B_S` (points on or above the hemispheres found) from below by
`h^2 \ge r^2 - \sup |z - c|^2`. A hemisphere `S'` touching `B \subseteq B_S` over such a box has radius at least that height, so
`N(\mu') \le 1 / h^2`: every hemisphere with `N(\mu) \le \max(b, 1 / h_{\min}^2)` is included, and their matrices, the translations, the
units and `\mathrm{diag}(1, -1)` generate `\mathrm{GL}_2(O)`. Near a singular point `B` is bounded by the hemispheres through it (Swan, Sec. 5),
which are among those found.

`\mathrm{GL}(O \oplus \mathfrak a)`, the stabilizer in `\mathrm{GL}_2(K)` of `M = O \oplus \mathfrak a` (:func:`steinitz_general_linear_generators`).
For `\mathfrak a` integral and `\alpha \in \mathfrak a`, `\Lambda_0 = O \oplus \alpha O` has `\alpha M \subseteq \Lambda_0 \subseteq M`, and its
stabilizer is `G_0 = D \mathrm{GL}_2(O) D^{-1}`, `D = \mathrm{diag}(1, \alpha)`. `H = G \cap G_0` is the stabilizer of `M` in `G_0`, of finite index
(it contains the congruence kernel modulo `\alpha`); its Schreier generators come from :func:`finite_preimage_generators`. `G / H` is the
`G`-orbit of `\Lambda_0`, a set of free `O`-lattices `\Lambda'` with `\alpha M \subseteq \Lambda' \subseteq M` of index `[M : \Lambda_0]`. For each such
`\Lambda' = W O^2` put `g_1 = W D^{-1}` (`g_1 \Lambda_0 = \Lambda'`); every `g \in \mathrm{GL}_2(K)` with `g \Lambda_0 = \Lambda'` is `g_1 h`, `h \in G_0`,
and it lies in `G` exactly when `h M = g_1^{-1} M`. The `G_0`-orbit of `M` is finite (lattices between `\Lambda_0` and `\alpha^{-1} \Lambda_0`), so a
search with transporters decides, and the found `g_1 h` form a transversal: `G = \langle H, g_1 h \rangle`."""

