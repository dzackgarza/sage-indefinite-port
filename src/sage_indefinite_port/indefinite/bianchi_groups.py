from sage.rings.rational_field import QQ
from sage.rings.real_mpfi import RealIntervalField
from sage_extensions.categories.lattice_centralizers import finite_preimage_generators

_RIF = RealIntervalField(128)


class BianchiGroup:
    r"""Swan's fundamental domain data and generators of `\mathrm{GL}_2(O_K)` (module docstring)."""

    def __init__(self, K):
        assert K.degree() == 2 and not K.is_totally_real(), f"{K} is not imaginary quadratic"
        self.field = K
        D = K.discriminant()
        self.discriminant = D
        self.omega = (K(D) + K(D).sqrt()) / 2
        assert self.omega.is_integral() and self.omega.minpoly().degree() == 2
        self._to_basis = matrix(QQ, [list(K(1)), list(self.omega)]).inverse()
        self._half_d = QQ(D) / 2
        self._root = _RIF(-D).sqrt() / 2

    def coordinates(self, x):
        r"""Return `(a, b) \in Q^2` with `x = a + b \omega`."""
        a, b = matrix(QQ, [list(self.field(x))]) * self._to_basis
        return QQ(a), QQ(b)

    def element(self, a, b):
        return self.field(a) + self.field(b) * self.omega

    def short_elements(self, basis, bound):
        r"""Return the nonzero `x e_1 + y e_2` of norm at most ``bound`` for a `Z`-basis ``basis`` of a fractional ideal: the norm form has Gram
        `G` and `|x_i| \le \sqrt{b (G^{-1})_{ii}}` by Cauchy-Schwarz."""
        e1, e2 = basis
        g11, g22 = e1.norm(), e2.norm()
        g12 = ((e1 + e2).norm() - g11 - g22) / 2
        inverse = matrix(QQ, [[g11, g12], [g12, g22]]).inverse()
        bx = ZZ(floor(bound * inverse[0, 0])).isqrt() + 1
        by = ZZ(floor(bound * inverse[1, 1])).isqrt() + 1
        result = []
        for x in range(-bx, bx + 1):
            for y in range(-by, by + 1):
                e = x * e1 + y * e2
                if e != 0 and e.norm() <= bound:
                    result.append(e)
        return result

    def _reduce(self, x):
        r"""Return the representative of `x` modulo `O` with coordinates in `[0, 1)^2`, and the translation removed."""
        a, b = self.coordinates(x)
        shift = self.element(floor(a), floor(b))
        return x - shift, shift

    def singular_points(self):
        r"""Return the singular points of `P` (module docstring), as elements of `K` with coordinates in `[0, 1]^2`."""
        K = self.field
        representatives = []
        for c in K.class_group():
            ideal = c.ideal()
            if ideal.is_principal():
                continue
            representatives.append(ideal)
        reduced = set()
        for ideal in representatives:
            basis = ideal.basis()
            elements = self.short_elements(basis, min(e.norm() for e in basis))
            least = min(e.norm() for e in elements)
            for mu in (e for e in elements if e.norm() == least):
                m = ZZ(least / ideal.norm())
                for x, y in product(range(m), repeat=2):
                    lam = x * basis[0] + y * basis[1]
                    if K.ideal([lam, mu]) != ideal:
                        continue
                    s, _shift = self._reduce(lam / mu)
                    reduced.add(s)
        points = set()
        for s in reduced:
            a, b = self.coordinates(s)
            for i, j in product((0, 1), repeat=2):
                if a + i <= 1 and b + j <= 1:
                    points.add(s + self.element(i, j))
        return sorted(points, key=self.coordinates)

    def _hemisphere_representatives(self, bound):
        r"""Return one unimodular pair `(\mu, \lambda)` per hemisphere with `N(\mu) \le` ``bound`` and centre in `[0, 1)^2` modulo `O`."""
        K = self.field
        one = K.ideal(1)
        found = {}
        for mu in self.short_elements([K(1), self.omega], bound):
            m = ZZ(mu.norm())
            for x, y in product(range(m), repeat=2):
                lam = self.element(x, y)
                if K.ideal([lam, mu]) != one:
                    continue
                centre, shift = self._reduce(lam / mu)
                key = (self.coordinates(centre), m)
                if key not in found:
                    found[key] = (mu, lam - mu * shift)
        return list(found.values())

    def _hemispheres(self, representatives):
        r"""Return ``(mu, lam, a, b, r2)`` for the translates by `i + j \omega`, `|i|, |j| \le 1`, of the ``representatives``."""
        result = []
        for mu, lam in representatives:
            for i, j in product((-1, 0, 1), repeat=2):
                moved = lam + mu * self.element(i, j)
                a, b = self.coordinates(moved / mu)
                result.append((mu, moved, a, b, 1 / QQ(mu.norm())))
        result.sort(key=lambda h: -h[4])
        return result

    def _gap(self, box, hemisphere):
        r"""Return a lower bound of `r^2 - |z - c|^2` over the closed ``box`` `[p_0, p_1] \times [q_0, q_1]`."""
        p0, p1, q0, q1 = box
        _mu, _lam, a, b, r2 = hemisphere
        P, Q = _RIF(p0, p1), _RIF(q0, q1)
        dx = (P - a) + (Q - b) * self._half_d
        dy = (Q - b) * self._root
        return (r2 - (dx * dx + dy * dy)).lower()

    def _punctured_radius(self, s, hemispheres, depth):
        r"""Return a rational `\rho > 0` such that every `z \ne s` with `|p - p_s|, |q - q_s| \le \rho` is strictly below a hemisphere through `s`,
        or ``None`` (module docstring, Covering)."""
        sp, sq = self.coordinates(s)
        through = [h for h in hemispheres if (h[0] * s - h[1]).norm() == 1]
        vectors = [((_RIF(a - sp) + _RIF(b - sq) * self._half_d), _RIF(b - sq) * self._root) for _mu, _lam, a, b, _r2 in through]
        if not vectors:
            return None
        edges = (
            lambda U: (_RIF(1), U),
            lambda U: (_RIF(-1), U),
            lambda U: (U, _RIF(1)),
            lambda U: (U, _RIF(-1)),
        )
        stack = [(edge, QQ(-1), QQ(1), 0) for edge in edges]
        rho = None
        while stack:
            edge, u0, u1, level = stack.pop()
            wp, wq = edge(_RIF(u0, u1))
            wx, wy = wp + wq * self._half_d, wq * self._root
            norm = wx * wx + wy * wy
            best = max((2 * (wx * vx + wy * vy) / norm).lower() for vx, vy in vectors)
            if best > 0:
                rho = best if rho is None else min(rho, best)
                continue
            if level == depth:
                return None
            middle = (u0 + u1) / 2
            stack.extend([(edge, u0, middle, level + 1), (edge, middle, u1, level + 1)])
        return rho.exact_rational() / 2

    def _cover(self, hemispheres, squares, depth):
        r"""Return a positive rational lower bound of the squared floor height over the boxes certified by a hemisphere, when `P` is covered,
        or ``None``."""
        stack = [(QQ(0), QQ(1), QQ(0), QQ(1), 0)]
        floor_height = None
        while stack:
            p0, p1, q0, q1, level = stack.pop()
            if any(sp - rho <= p0 and p1 <= sp + rho and sq - rho <= q0 and q1 <= sq + rho for (sp, sq), rho in squares):
                continue
            box = (p0, p1, q0, q1)
            gap = max(self._gap(box, h) for h in hemispheres)
            if gap > 0:
                gap = gap.exact_rational()
                floor_height = gap if floor_height is None else min(floor_height, gap)
                continue
            if level == depth:
                return None
            pm, qm = (p0 + p1) / 2, (q0 + q1) / 2
            stack.extend(
                [(p0, pm, q0, qm, level + 1), (pm, p1, q0, qm, level + 1), (p0, pm, qm, q1, level + 1), (pm, p1, qm, q1, level + 1)]
            )
        return floor_height

    @property
    def covering_bound(self):
        r"""Return ``(b, h2)``: the least `b` whose hemispheres cover `P` (Swan's criterion) and the floor-height lower bound `h^2`."""
        if hasattr(self, "_covering"):
            return self._covering
        singular = self.singular_points()
        bound = 1
        while True:
            hemispheres = self._hemispheres(self._hemisphere_representatives(bound))
            depth = 8 + bound
            squares = []
            for s in singular:
                rho = self._punctured_radius(s, hemispheres, depth)
                if rho is None:
                    break
                squares.append((self.coordinates(s), rho))
            if len(squares) == len(singular):
                floor_height = self._cover(hemispheres, squares, depth)
                if floor_height is not None:
                    self._covering = (bound, floor_height)
                    return self._covering
            bound += 1

    def hemisphere_matrices(self):
        r"""Return `g_{\mu, \lambda} = [[\lambda^*, \nu], [-\mu, \lambda]]` for one hemisphere per translation class with
        `N(\mu) \le \max(b, 1 / h^2)` (module docstring, Completion). A translate `\lambda + \mu t` gives `g_{\mu,\lambda} T^{-t}`."""
        K = self.field
        bound, floor_height = self.covering_bound
        complete = max(bound, floor(1 / floor_height))
        result = []
        for mu, lam in self._hemisphere_representatives(complete):
            if lam == 0:
                star, nu = K(0), 1 / mu
            else:
                a = K.ideal(lam).element_1_mod(K.ideal(mu))
                star, nu = a / lam, (1 - a) / mu
            g = matrix(K, [[star, nu], [-mu, lam]])
            assert g.det() == 1 and all(x.is_integral() for x in g.list())
            result.append(g)
        return result

    def generators(self):
        r"""Return generators of `\mathrm{GL}_2(O_K)`: translations by `1, \omega`, the hemisphere matrices, `\mathrm{diag}(u, 1)` for generators `u`
        of `O_K^\times`, and `\mathrm{diag}(1, -1)`."""
        K = self.field
        result = [matrix(K, [[1, 1], [0, 1]]), matrix(K, [[1, self.omega], [0, 1]])]
        result.extend(self.hemisphere_matrices())
        result.extend(matrix(K, [[K(u), 0], [0, 1]]) for u in K.unit_group().gens_values())
        result.append(matrix(K, [[1, 0], [0, -1]]))
        return result


@lru_cache(maxsize=None)
def bianchi_generators(K):
    r"""Return generators of `\mathrm{GL}_2(O_K)` for the imaginary quadratic ``K`` (:class:`BianchiGroup`)."""
    return tuple(BianchiGroup(K).generators())


class _ModuleLattices:
    r"""`O`-lattices in `K^2`, given by `O`-generators, with canonical keys (the Hermite basis of the `Z`-span in the coordinates `(1, \omega)`)."""

    def __init__(self, group):
        self.group = group
        self.field = group.field

    def rows(self, vectors):
        return [[c for x in v for c in self.group.coordinates(b * x)] for v in vectors for b in (self.field(1), self.group.omega)]

    def vectors(self, rows):
        return [(self.group.element(r[0], r[1]), self.group.element(r[2], r[3])) for r in rows]

    def basis(self, vectors):
        rows = matrix(QQ, self.rows(vectors))
        scale = rows.denominator()
        return matrix(QQ, matrix(ZZ, scale * rows).hermite_form(include_zero_rows=False)) / scale

    def key(self, vectors):
        return tuple(self.basis(vectors).list())

    def act(self, g, vectors):
        return [tuple((g * matrix(self.field, 2, 1, list(v))).column(0)) for v in vectors]

    def free_basis(self, vectors):
        r"""Return `W \in \mathrm{GL}_2(K)` with `W O^2` the lattice, or ``None`` when its Steinitz class is not trivial (PARI ``nfhnf``, ``rnfsteinitz``)."""
        K = self.field
        nf = K.pari_nf()
        generators = pari.matrix(2, len(vectors), [vectors[j][i].__pari__() for i in range(2) for j in range(len(vectors))])
        hnf = nf.nfhnf([generators, pari([1] * len(vectors))])
        steinitz = nf.rnfsteinitz(hnf)
        to_field = lambda c: K(nf.nfbasistoalg(c))
        W = matrix(K, 2, 2, [to_field(steinitz[0][i, j]) for i in range(2) for j in range(2)])
        ideals = []
        for j in range(2):
            hermite = nf.idealhnf(steinitz[1][j])
            ideals.append(K.ideal([to_field(hermite[i]) for i in range(len(hermite))]))
        assert ideals[0] == K.ideal(1)
        if not ideals[1].is_principal():
            return None
        beta = K(ideals[1].gens_reduced()[0])
        W = W * matrix(K, [[1, 0], [0, beta]])
        assert self.key([tuple(c) for c in W.columns()]) == self.key(vectors)
        return W


def _hnf_matrices(n, size):
    r"""Yield the integral upper-triangular Hermite matrices of determinant ``n`` (entries above the pivot `d_j` in `[0, d_j)`)."""
    for diagonal in product(ZZ(n).divisors(), repeat=size):
        if prod(diagonal) != n:
            continue
        slots = [(i, j) for j in range(size) for i in range(j)]
        for values in product(*(range(diagonal[j]) for _i, j in slots)):
            h = matrix(ZZ, size, size)
            for t in range(size):
                h[t, t] = diagonal[t]
            for (i, j), v in zip(slots, values):
                h[i, j] = v
            yield h


def steinitz_general_linear_generators(K, ideal):
    r"""Return generators of `\mathrm{GL}(O_K \oplus \mathfrak a) \subset \mathrm{GL}_2(K)` for the fractional ``ideal`` `\mathfrak a` (module docstring)."""
    base = bianchi_generators(K)
    if ideal.is_principal():
        gamma = K(ideal.gens_reduced()[0])
        D = matrix(K, [[1, 0], [0, gamma]])
        return [D * g * D.inverse() for g in base]
    integral, denominator = ideal.integral_split()
    E = matrix(K, [[1, 0], [0, 1 / K(denominator)]])
    return [E * g * E.inverse() for g in _integral_steinitz_generators(K, integral, base)]


def _integral_steinitz_generators(K, ideal, base):
    group = BianchiGroup(K)
    lattices = _ModuleLattices(group)
    basis = ideal.basis()
    elements = group.short_elements(basis, min(e.norm() for e in basis))
    alpha = min(elements, key=lambda e: e.norm())
    D = matrix(K, [[1, 0], [0, alpha]])
    M = [(K(1), K(0))] + [(K(0), K(g)) for g in basis]
    key_M = lattices.key(M)
    conjugated = [D * g * D.inverse() for g in base]
    member = lambda g: lattices.key(lattices.act(g, M)) == key_M
    stabilizer, _index = finite_preimage_generators(conjugated, lambda g: g, member)
    one = matrix.identity(K, 2)
    orbit = {key_M: one}
    frontier = [one]
    while frontier:
        current = frontier.pop()
        for g in conjugated:
            element = g * current
            point = lattices.key(lattices.act(element, M))
            if point not in orbit:
                orbit[point] = element
                frontier.append(element)
    M_basis = lattices.basis(M)
    alpha_rows = matrix(QQ, lattices.rows([(alpha * x, alpha * y) for x, y in M]))
    omega_vectors = lambda vs: [(group.omega * x, group.omega * y) for x, y in vs]
    index = ZZ(alpha.norm() / ideal.norm())
    transversal = []
    for h in _hnf_matrices(index, M_basis.nrows()):
        rows = h * M_basis
        candidate = lattices.vectors(rows.rows())
        if not all(c in ZZ for c in rows.solve_left(alpha_rows).list()):
            continue
        if not all(c in ZZ for c in rows.solve_left(matrix(QQ, lattices.rows(omega_vectors(candidate)))).list()):
            continue
        W = lattices.free_basis(candidate)
        if W is None:
            continue
        g1 = W * D.inverse()
        target = lattices.key(lattices.act(g1.inverse(), M))
        if target not in orbit:
            continue
        g = g1 * orbit[target]
        assert member(g)
        transversal.append(g)
    result = [*stabilizer, *transversal]
    assert all(member(g) for g in result)
    return result
