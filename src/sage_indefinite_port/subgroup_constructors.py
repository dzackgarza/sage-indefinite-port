def double_coset_simplification(equiv, G_gens, H_gens, max_iter=100):
    """
    Simplify an equivalence matrix using double coset decomposition.

    Given equiv, find equiv_red = h1 * equiv * h2 with h1 in G, h2 in H
    such that equiv_red is simpler (smaller entries).

    Port of ExhaustiveMatrixDoubleCosetSimplifications from
    CombinedAlgorithms.h.

    INPUT:
    - equiv: Sage integer matrix
    - G_gens: list of Sage integer matrices (generators of left group)
    - H_gens: list of Sage integer matrices (generators of right group)
    - max_iter: maximum iterations

    OUTPUT:
    - dict with 'equiv' (simplified matrix), 'left_coset', 'right_coset'
    """
    n = equiv.nrows()
    best = equiv
    best_complexity = _matrix_complexity(equiv)

    for _ in range(max_iter):
        improved = False

        # Try left multiplication by G generators
        for g in G_gens:
            candidate = g * best
            c = _matrix_complexity(candidate)
            if c < best_complexity:
                best = candidate
                best_complexity = c
                improved = True
                break

        if improved:
            continue

        # Try right multiplication by H generators
        for h in H_gens:
            candidate = best * h
            c = _matrix_complexity(candidate)
            if c < best_complexity:
                best = candidate
                best_complexity = c
                improved = True
                break

        if not improved:
            break

    return {
        "equiv": best,
        "left_coset": identity_matrix(ZZ, n),
        "right_coset": identity_matrix(ZZ, n),
    }


def _matrix_complexity(M):
    """Compute complexity measure of a matrix (sum of absolute entries)."""
    n = M.nrows()
    m = M.ncols()
    return sum(abs(M[i, j]) for i in range(n) for j in range(m))


